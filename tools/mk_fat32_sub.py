#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""mk_fat32_sub.py —— 动态字幕 / 音随图切 的全链路仿真卡镜像

复用 mk_fat32_img.py 的 MBR/BPB/BMP/目录项生成，只换文件清单：
    IMG01..IMG04.BMP   320×240 纯色（红/绿/蓝/黄，与 fat32_4img 一致）
    IMG01.TXT          短字幕（GB2312 + ASCII）          ← 排在 IMG01.WAV 前
    IMG01.WAV          假 wav
    IMG02.WAV          假 wav
    IMG02.TXT          长字幕（> 64 字，走懒加载）        ← 排在 IMG02.WAV 后
    IMG03 / IMG04      没有 TXT、没有 WAV（换过去字幕应清空、音乐不动）

另外生成 <out>_sub.vh 给 tb 用：每份 TXT 的期望字符数和首字符码、WAV 扇区号。
用法：
    python tools/mk_fat32_sub.py --out sim_data/fat32_sub.img --check
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mk_fat32_img as mk  # noqa: E402

TXT1 = '图一字幕ABC'
TXT2 = '第二张图片的长字幕用于测试懒加载滚动显示效果' * 3 + 'END'   # 66 汉字 + 3 ASCII


def codes(text):
    """按 sub_loader 的解析规则算出字符码表（单行，最多 256 个）。"""
    out = []
    for ch in text:
        b = ch.encode('gb2312')
        out.append(b[0] << 8 | b[1] if len(b) == 2 else b[0])
    return out[:256]


TXT5 = '第五张'
TXT9 = 'NINE 九'


def build(out, nimg=4, fill=0):
    """nimg=4：基本剧本；nimg=10 + fill：窗口一路滑动 + 大目录（match 扫描要走很多扇区）。"""
    files = []
    for i in range(nimg):
        data = mk.bmp24(320, 240, mk.COLORS[i], i + 1)
        files.append(('IMG%02d' % (i + 1), 'BMP', 0x20, data, 320, 240, mk.COLORS[i]))
    # 填充项：0 字节的 .DAT，夹在图片和 TXT/WAV 之间，match 扫描必须翻过它们
    for k in range(fill):
        files.append(('F%03d' % k, 'DAT', 0x20, b'', 0, 0, (0, 0, 0)))
    txts = {1: TXT1, 2: TXT2}
    files.append(('IMG01', 'TXT', 0x20, TXT1.encode('gb2312') + b'\r\n', 0, 0, (0, 0, 0)))
    files.append(('IMG01', 'WAV', 0x20, b'RIFF' + b'\x01' * 2044, 0, 0, (0, 0, 0)))
    files.append(('IMG02', 'WAV', 0x20, b'RIFF' + b'\x02' * 2044, 0, 0, (0, 0, 0)))
    files.append(('IMG02', 'TXT', 0x20, TXT2.encode('gb2312') + b'\r\n', 0, 0, (0, 0, 0)))
    if nimg >= 10:
        txts.update({5: TXT5, 9: TXT9})
        files.append(('IMG05', 'TXT', 0x20, TXT5.encode('gb2312') + b'\r\n', 0, 0, (0, 0, 0)))
        files.append(('IMG06', 'WAV', 0x20, b'RIFF' + b'\x06' * 2044, 0, 0, (0, 0, 0)))
        files.append(('IMG09', 'TXT', 0x20, TXT9.encode('gb2312') + b'\r\n', 0, 0, (0, 0, 0)))

    clus = 3
    plan = []
    for (nm, ext, attr, data, w, h, rgb) in files:
        nclus = (len(data) + mk.SPC * mk.SEC - 1) // (mk.SPC * mk.SEC)
        plan.append((nm, ext, attr, data, clus if nclus else 0, nclus, w, h, rgb))
        clus += nclus
    assert len(plan) < mk.SPC * mk.SEC // 32, 'root dir is a single cluster (128 entries)'

    img = bytearray(mk.TOTAL_SEC * mk.SEC)
    img[0:mk.SEC] = mk.mbr()
    img[mk.PART_LBA * mk.SEC:(mk.PART_LBA + 1) * mk.SEC] = mk.bpb()
    img[(mk.PART_LBA + 6) * mk.SEC:(mk.PART_LBA + 7) * mk.SEC] = mk.bpb()

    fat = bytearray(mk.FATSZ * mk.SEC)
    struct.pack_into('<I', fat, 0, 0x0FFFFFF8)
    struct.pack_into('<I', fat, 4, 0x0FFFFFFF)
    struct.pack_into('<I', fat, 8, 0x0FFFFFFF)
    for (_, _, _, _, start, nclus, _, _, _) in plan:
        for k in range(nclus):
            c = start + k
            struct.pack_into('<I', fat, c * 4, 0x0FFFFFFF if k == nclus - 1 else c + 1)
    for i in range(mk.NFAT):
        o = (mk.PART_LBA + mk.RSVD + i * mk.FATSZ) * mk.SEC
        img[o:o + len(fat)] = fat

    ents = b''
    for (nm, ext, attr, data, start, nclus, w, h, rgb) in plan:
        ents += mk.short_name(nm, ext, attr, start, len(data))
    ents += b'\x00' * 32
    root_off = (mk.DATA_LBA + (mk.ROOT_CLUS - 2) * mk.SPC) * mk.SEC
    img[root_off:root_off + len(ents)] = ents

    def off_of(p):
        return (mk.DATA_LBA + (p[4] - 2) * mk.SPC) * mk.SEC

    for p in plan:
        img[off_of(p):off_of(p) + len(p[3])] = p[3]

    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    with open(out, 'wb') as f:
        f.write(img)

    base = os.path.splitext(out)[0]
    with open(base + '.map', 'w', encoding='ascii') as f:
        f.write('# name off size w h r g b\n')
        for p in plan:
            f.write('%s.%s %d %d %d %d %d %d %d\n'
                    % (p[0], p[1], off_of(p), len(p[3]), p[6], p[7], p[8][0], p[8][1], p[8][2]))
    with open(base + '_map.vh', 'w', encoding='ascii') as f:
        f.write('// auto-generated by tools/mk_fat32_sub.py\ninitial begin\n')
        f.write('    map_n = %d;\n' % len(plan))
        for i, p in enumerate(plan):
            f.write('    map_off[%d] = %d; map_size[%d] = %d; map_name[%d] = "%s.%s";\n'
                    % (i, off_of(p), i, len(p[3]), i, p[0], p[1]))
        f.write('end\n')

    sec = {('%s.%s' % (p[0], p[1])): off_of(p) // mk.SEC for p in plan}
    c1, c2 = codes(TXT1), codes(TXT2)
    with open(base + '_sub.vh', 'w', encoding='ascii') as f:
        f.write('// auto-generated by tools/mk_fat32_sub.py: subtitle / music expectations\n')
        f.write('localparam integer SUB_LEN1 = %d;\n' % len(c1))
        f.write('localparam [15:0]  SUB_C1_0 = 16\'h%04X;\n' % c1[0])
        f.write('localparam integer SUB_LEN2 = %d;\n' % len(c2))
        f.write('localparam [15:0]  SUB_C2_0 = 16\'h%04X;\n' % c2[0])
        f.write('localparam [15:0]  SUB_C2_64 = 16\'h%04X;\n' % c2[64])
        f.write('localparam [22:0]  TXT1_SEC = 23\'d%d;\n' % sec['IMG01.TXT'])
        f.write('localparam [22:0]  TXT2_SEC = 23\'d%d;\n' % sec['IMG02.TXT'])
        f.write('localparam [22:0]  WAV1_SEC = 23\'d%d;\n' % sec['IMG01.WAV'])
        f.write('localparam [22:0]  WAV2_SEC = 23\'d%d;\n' % sec['IMG02.WAV'])
        # per-image expectations (index = image number - 1): subtitle length, WAV sector (0 = none)
        f.write('localparam integer NIMG = %d;\n' % nimg)
        f.write('integer exp_len [0:15];\ninteger exp_wav [0:15];\ninitial begin\n')
        for i in range(1, nimg + 1):
            n = len(codes(txts[i])) if i in txts else 0
            f.write('    exp_len[%d] = %d; exp_wav[%d] = %d;\n'
                    % (i - 1, n, i - 1, sec.get('IMG%02d.WAV' % i, 0)))
        f.write('end\n')
    return plan, len(c1), len(c2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='sim_data/fat32_sub.img')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--nimg', type=int, default=4, help='number of BMPs (4 or 10)')
    ap.add_argument('--fill', type=int, default=0, help='zero-byte filler entries in the root dir')
    args = ap.parse_args()
    plan, n1, n2 = build(args.out, args.nimg, args.fill)
    print('镜像：%s  TXT1=%d 字  TXT2=%d 字' % (args.out, n1, n2))
    for p in plan:
        print('  %-6s %-4s clus=%d size=%d' % (p[0], p[1], p[4], len(p[3])))
    if args.check:
        errs, ents = mk.check(args.out)
        print('  校验：%s（目录项 %d 个）' % ('通过' if not errs else '失败', len(ents)))
        for e in errs:
            print('   !!', e)
        return 1 if errs else 0
    return 0


if __name__ == '__main__':
    sys.exit(main())
