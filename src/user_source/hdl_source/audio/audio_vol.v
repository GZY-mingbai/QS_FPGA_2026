//=============================================================================
//  audio_vol.v —— 数字音量（24bit × 9bit，四舍五入，100% 逐位直通）
//=============================================================================
//
//  【为什么不用 24×9 的推断乘法】
//  DSP 只有 18×18。写成 `x * g9` 的话，赋值上下文会把两个操作数都拉到 33 位，
//  TD 按 33×33 综合 ⇒ 4 个 DSP/声道。同一个坑在 osd_menu 的 tween 上踩过
//  （25×25 白吃 4 个 DSP）。所以这里显式例化 EG_PHY_MULT18，并且**分时复用**：
//  一个 DSP 分 4 拍算完 L/R 的高低两段，总共只占 **1 个 DSP**。
//
//  【24 位怎么塞进 18×18】
//      x = x_hi · 2^18 + x_lo     （x_hi = x[23:18] 有符号 6 位，x_lo = x[17:0] 无符号）
//      x · g = x_lo·g + (x_hi·g) << 18
//  x_lo 用无符号模式（18 位能装下 0..262143），x_hi 用有符号模式（signeda 每拍切换）。
//  两个乘积的低 27 位都落在 mpy[26:0] 里，且都装得下：
//      x_lo·g ≤ 262143×256 = 67,108,608 < 2^26   ⇒ 27 位有符号也能表示（正数）
//      x_hi·g ≤ 32×256 = 8192                    ⇒ 14 位
//
//  【音质（逐条，这是本模块的存在理由）】
//    1. **不截位**：输入 24 位全参与乘法，不是先砍成 16 位再乘。
//    2. **四舍五入**：out = (x·g + 128) >> 8。截断（直接 >>8）会给所有样本
//       一个 -0.5LSB 的直流偏置 + 低电平谐波失真；四舍五入没有这个问题。
//       实现上不额外加一个 33 位加法器：把 +128 折成 `P[26:8] + P[7]`
//       （P = x_lo·g），因为 (P+128)>>8 ≡ P[26:8] + P[7]。
//    3. **100% 时逐位直通**：g9 = 256 时 (x·256+128)>>8 = x（对正负数都成立，
//       因为补码右移就是向下取整）。所以满音量下输出与输入**逐位相同**，
//       不是"差 0.4%"（用 255 当单位增益就会差 -0.034dB）。
//    4. **不需要饱和**：增益 ≤ 1，|x·g| ≤ |x|·256 = 2^31，永远不溢出 ⇒
//       没有削波失真，也不需要饱和逻辑（省 24 个 LUT）。
//
//  【增益映射】g9 = round(vol × 2.5625)，vol ∈ 0..100
//      41 = 32+8+1 ⇒ 两次移位相加；2.5625 = 41/16
//      vol=100 → 4100 → 256.75 → **256**（单位增益，逐位直通）
//      其余档位误差 ≤ 0.5 LSB/256 = 0.017dB（比滑块 5% 一档的 0.42dB 小得多）
//
//  【延迟】每样本 6 拍（IDLE→LO_L→HI_L→LO_R→HI_R→FIN），25MHz 下 240ns，
//  而采样间隔 20.8µs ⇒ 绰绰有余。ACR 只统计 valid 个数，固定延迟不影响。
//=============================================================================
module audio_vol (
    input  wire        clk,             // video_clk 25MHz
    input  wire        rst,             // 高有效
    input  wire        valid,           // 48kHz 采样节拍（单拍）
    input  wire [6:0]  vol,             // 0..100

    input  wire [23:0] l_in,            // 24bit 有符号
    input  wire [23:0] r_in,

    output reg  [23:0] l_out,
    output reg  [23:0] r_out,
    output reg         o_valid          // 与输入 valid 一一对应（晚 6 拍）
);

//-----------------------------------------------------------------------------
//  增益：g9 = round(vol × 41 / 16)，vol ≤ 100 ⇒ g9 ≤ 256
//-----------------------------------------------------------------------------
//  ★ 写成显式移位相加，不写 `vol * 41` —— 常数乘法虽然一般落 LUT，
//    但 TD 对 14 位以上的常数乘也可能拉一个 DSP 进来，这里直接断掉这个可能。
wire [12:0] v41 = ({6'd0, vol} << 5) + ({6'd0, vol} << 3) + {6'd0, vol};
//  (v41 + 8) >> 4 ≡ v41[12:4] + v41[3]（v41 = 16q+r 时，(r+8)>>4 就是 r≥8）
wire [8:0]  g9  = v41[12:4] + {8'd0, v41[3]};

//-----------------------------------------------------------------------------
//  乘法器（1 个 DSP，4 拍分时）
//-----------------------------------------------------------------------------
reg  [17:0] m_a;
reg         m_sgn;                  // 1 = 有符号（算 x_hi 时）
//  ★ 必须是 wire：mpy 由 EG_PHY_MULT18 的 .p 驱动（模块输出口）。
//    写成 reg 会被 TD 判 "concurrent assignment to a non-net"（iverilog 不报，上综合才炸）。
wire [35:0] mpy;

EG_PHY_MULT18 #(
    .INPUTREGA ("DISABLE"),         // 组合：操作数每拍现给，靠 FSM 打拍
    .INPUTREGB ("DISABLE"),
    .OUTPUTREG ("DISABLE"),
    .SRMODE    ("ASYNC"),
    .MODE      ("MULT18X18C")
) u_mult (
    .acout   (),
    .bcout   (),
    .p       (mpy),
    .signeda (m_sgn),
    .signedb (1'b0),                // g9 恒为正 ⇒ 无符号
    .a       (m_a),
    .b       ({9'd0, g9}),
    .acin    (18'd0),
    .bcin    (18'd0),
    .cea     (1'b1),
    .ceb     (1'b1),
    .cepd    (1'b1),
    .clk     (clk),
    .rstan   (1'b1),
    .rstbn   (1'b1),
    .rstpdn  (1'b1),
    .sourcea (1'b1),                // ★ 1 = 选 a（0 会选 acin，乘出 0）
    .sourceb (1'b1)
);

//-----------------------------------------------------------------------------
//  状态机
//-----------------------------------------------------------------------------
localparam [2:0] S_IDLE = 3'd0,
                 S_LOL  = 3'd1,     // 左 · 低 18 位
                 S_HIL  = 3'd2,     // 左 · 高 6 位
                 S_LOR  = 3'd3,     // 右 · 低 18 位
                 S_HIR  = 3'd4,     // 右 · 高 6 位
                 S_FIN  = 3'd5;     // 拼装 + 输出

reg [2:0]  st;
reg [23:0] xl, xr;
reg [26:0] plo_l, plo_r;            // x_lo · g（无符号 27 位）
reg signed [13:0] phi_l, phi_r;     // x_hi · g（有符号 14 位）

// 组合：把当前 mpy 结果按目标截到对应位宽
wire [26:0]        m_lo = mpy[26:0];
wire signed [13:0] m_hi = mpy[13:0];

//-----------------------------------------------------------------------------
//  拼装：out = (x_lo·g) 的高位 + (x_hi·g) << 10，并把 +128 折进最低位
//-----------------------------------------------------------------------------
//  推导：out = (x·g + 128) >> 8
//            = ((x_lo·g + 128) >> 8) + x_hi·g·2^10
//      而 (P + 128) >> 8 ≡ P[26:8] + P[7]   （P = x_lo·g）
//  ⇒ 只需两个小加法器，不需要 33 位全宽累加 + 33 位舍入加法器。
//  ★ 时序：四个乘积分别在 S_LOL/S_HIL/S_LOR/S_HIR 结束时落进 plo_*/phi_*，
//    所以到 S_FIN 时四个都齐了，这里组合拼装即可。
//  ★ 声明必须放在 always 之前 —— iverilog 对"先用后声明"直接报错。
wire [19:0] plo_l_r = plo_l[26:8] + {19'd0, plo_l[7]};
wire [19:0] plo_r_r = plo_r[26:8] + {19'd0, plo_r[7]};

//  {phi[13:0], 10'd0} 是 24 位、bit23 就是符号位 ⇒ $signed 之后直接参与有符号加法
wire signed [23:0] out_l_w = $signed({phi_l[13:0], 10'd0}) + $signed({4'd0, plo_l_r});
wire signed [23:0] out_r_w = $signed({phi_r[13:0], 10'd0}) + $signed({4'd0, plo_r_r});

always @(posedge clk or posedge rst) begin
    if (rst) begin
        st      <= S_IDLE;
        xl      <= 24'd0;
        xr      <= 24'd0;
        plo_l   <= 27'd0;
        plo_r   <= 27'd0;
        phi_l   <= 14'sd0;
        phi_r   <= 14'sd0;
        m_a     <= 18'd0;
        m_sgn   <= 1'b0;
        l_out   <= 24'sd0;
        r_out   <= 24'sd0;
        o_valid <= 1'b0;
    end else begin
        o_valid <= 1'b0;

        //  【操作数时序】m_a/m_sgn 用非阻塞赋值 ⇒ 在**下一拍**才有效。
        //  所以每个状态里"取本拍乘积 + 给下一拍备料"，乘积与 m_a 差一拍，
        //  但两者在同一状态里一进一出，6 拍正好走完 4 个乘积。
        case (st)
        S_IDLE: begin
            if (valid) begin
                xl    <= l_in;
                xr    <= r_in;
                m_a   <= {1'b0, l_in[17:0]};      // 左 · 低（下一拍 S_LOL 有效）
                m_sgn <= 1'b0;
                st    <= S_LOL;
            end
        end

        S_LOL: begin
            plo_l <= m_lo;                        // 本拍乘积 = 左·低
            m_a   <= {{12{xl[23]}}, xl[23:18]};   // 备料：左·高
            m_sgn <= 1'b1;
            st    <= S_HIL;
        end

        S_HIL: begin
            phi_l <= m_hi;                        // 本拍乘积 = 左·高
            m_a   <= {1'b0, xr[17:0]};            // 备料：右·低
            m_sgn <= 1'b0;
            st    <= S_LOR;
        end

        S_LOR: begin
            plo_r <= m_lo;
            m_a   <= {{12{xr[23]}}, xr[23:18]};   // 备料：右·高
            m_sgn <= 1'b1;
            st    <= S_HIR;
        end

        S_HIR: begin
            phi_r <= m_hi;
            st    <= S_FIN;
        end

        S_FIN: begin
            // 四个乘积在 S_HIR 结束时已全部到位 ⇒ 这里组合拼装即可
            l_out   <= out_l_w;
            r_out   <= out_r_w;
            o_valid <= 1'b1;
            st      <= S_IDLE;
        end

        default: st <= S_IDLE;
        endcase
    end
end


endmodule
