//=============================================================================
//  spec_fft.v —— 频谱条后端：÷4 抽取 + Hann 窗 + 128 点 FFT + 16 段对数条高
//=============================================================================
//
//  方案见 FFT_Plan.md。与原方案的差异（都是为了更省面积 / 更稳）：
//
//  1. **不单独放条高表 BRAM**（原 §5.1 的 BRAM #3 取消）。
//     FFT + 分段只在**垂直消隐**里跑（≈5.3k 拍，消隐 ≥ 11k 拍），有效显示期间
//     本模块只"写"（采样），读口空闲 ⇒ 读口在有效期直接借给扫描侧，
//     16 个条高就存在工作 RAM 的 128..143。
//     ⇒ BRAM 3 → 2；没有 commit 阶段；条高只在消隐里变 ⇒ 天然无撕裂。
//  2. **幅度用 DSP 算 re²+im²**（分段阶段 DSP 本来空闲），取代 α-max-β-min：
//     省掉两个求绝对值、比较器、两个加法器；结果是精确功率。
//  3. **log2 用串行归一化**（acc 左移直到 bit28=1，最多 28 拍），
//     取代 29 位优先编码器 + 3 个 29:1 尾数选择器。时间不要钱。
//  4. **Hann 窗**取代三角窗：窗系数放在 ROM 128..255，零逻辑。
//  5. **段边界**放在 ROM 64..127（只用到 bit8），"每段取最大"而非求和
//     （对数分段下高频段 bin 多，求和会让高频虚高）。
//     ★ 2026-11-03：低 8 位原来放「每段偏置」44,42,…,14（每段 −2）。那等价于给
//       16 条各做一次归一化：音乐本来 55 个 lg 单位的自然斜率被压成 25，
//       各段 p99 全被抬到 114…127 ⇒ 所有条同时顶格、看起来"起伏一样"。
//       现在把 16 段的偏置统一改成 48（=18dB 的单一全局刻度），
//       条高 = sat127(8·log2(P) − 48)。**只改 ROM 常量，RTL 结构一字未动**，
//       所以面积与 2026-11-03 13:20 那版逐位相同（那版 slice 4876/4900）。
//       实测 1.wav：条高均值 94…43、p99 116…72、左右落差 51px、无削顶。
//       若要更省面积，可再删峰值保持/看门狗/抽取器（约 −50 LE），但会改行为。
//  6. 位反转：采样写地址直接 {n[0],n[1],..,n[6]}，纯连线，零 LUT。
//
//  【时钟域】全部在 video_clk（25MHz），与音频样本、像素同域 ⇒ 无 CDC。
//
//  【一帧的节奏】（vbl = 最后一个有效行结束的单拍，来自 spec_bar_ovl）
//      vbl ─► S_FFT（7 级 × 64 蝶形 × 7 拍 = 3136 拍）
//          ─► S_BAND（63 bin × ≤35 拍 ≈ 2.2k 拍，更新 16 个条高）
//          ─► S_CAP（采 128 个 12kHz 样本 = 10.67ms）
//          ─► S_WAIT（等下一个 vbl）
//      10.67ms < 16.67ms ⇒ 稳定 60fps。FFT/BAND 全在消隐内完成。
//
//  【看门狗】S_CAP 里连续收到 2 个 vbl 还没采满（音频停了 / valid 不来）
//      ⇒ 以"本帧输入为 0"走一遍 S_BAND，条按 DECAY 自然落回 0。
//
//  【定点】（每级 /2 缩放，幅度不增长，16 位容器有充足余量）
//      输入   : smp[23:8] 16 位；4 点求和 >>2 仍是 16 位
//      加窗   : x16 × hann(u16) >> 17       ⇒ |x| < 2^14
//      蝶形   : X = (A ± W·B) >> 1，W 为 Q1.15 ⇒ 复数模不增长，分量 < 2^14
//      功率   : re² + im² < 2^29            ⇒ acc[28] 为最高位
//      对数   : L = {e[4:0], m[2:0]} ≈ 8·log2(P)，1 单位 = 0.376dB
//      条高   : h = sat127(L_band_max − 48)，16 段同一个 48（单一全局刻度）
//      满幅正弦：|X| = 2^14·128/2·0.5/128 = 2^12 ⇒ P = 2^24 ⇒ L = 192 ⇒ h = 144（顶格）
//
//  【资源】1 × EG_PHY_MULT18（显式例化，分时复用：加窗 / 复乘 4 拍 / 功率 2 拍），
//          2 × BRAM9k（工作 RAM 256×32、常数 ROM 256×32，均声明满 256 深、地址
//          8 位全部真实使用 ⇒ 不会被裁成浅表触发 SYN-5042）。
//
//  【ROM 内容】由 tools/gen_spec_rom.py 生成并写进本文件 ROM_INIT 区段，
//          改窗 / 改分段 / 改偏置都只需重跑脚本。
//=============================================================================
module spec_fft #(
    parameter [6:0] DECAY = 7'd2            // 峰值保持后每帧下落像素数
)(
    input  wire        clk,                 // video_clk 25MHz
    input  wire        rst,                 // 高有效

    input  wire        smp_valid,           // 48kHz 采样节拍（单拍）
    input  wire [23:0] smp,                 // 24bit 有符号（取 src_l_w：不受音量/静音/提示音影响）

    input  wire        vbl,                 // 垂直消隐开始（单拍，spec_bar_ovl 给）

    // ---- 扫描侧读口（有效显示期间借用工作 RAM 读口）----
    input  wire [3:0]  scan_idx,            // 下一拍像素所在条号
    output wire [6:0]  scan_h               // 该条高度 0..127（同步读，晚 1 拍）
);

//-----------------------------------------------------------------------------
//  状态
//-----------------------------------------------------------------------------
localparam [1:0] S_CAP  = 2'd0,             // 采样（抽取 + 加窗 → 位反转写入）
                 S_WAIT = 2'd1,             // 等 vbl
                 S_FFT  = 2'd2,             // 7 级蝶形
                 S_BAND = 2'd3;             // 功率 → log2 → 分段最大 → 峰值保持

reg  [1:0]  st;
reg  [2:0]  ph;                             // 步内拍号
reg  [6:0]  c7;                             // S_CAP: 样本号 n；S_FFT: 蝶形号 b；S_BAND: bin 号
reg  [3:0]  bk;                             // 段号 0..15
reg  [6:0]  h1;                             // 当前级 one-hot：2^s
reg  [5:0]  msk;                            // 当前级温度计码：2^s − 1
reg  [5:0]  tw;                             // 旋转因子下标（mod 64 累加）
reg  [1:0]  dc;                             // 抽取计数
reg         cap_go;                         // 抽取出一个样本的下一拍：加窗 + 写入
reg         wd;                             // 看门狗：S_CAP 里已经过了 1 个 vbl
reg         starve;                         // 本轮按"输入为 0"处理
reg         bfirst;                         // 下一个 bin 是本段第一个

wire is_cap  = (st == S_CAP);
wire is_fft  = (st == S_FFT);
wire is_band = (st == S_BAND);

//-----------------------------------------------------------------------------
//  存储（★ 两块都声明 256 深，并且 8 位地址都被真实使用）
//-----------------------------------------------------------------------------
//  wmem:   0..127  FFT 工作区 {re[15:0], im[15:0]}（位反转输入，自然序输出）
//        128..143  16 个条高（低 7 位），扫描侧在有效期读
//  rom:    0..63   W^k = {cos, −sin}·32767（Q1.15）
//         64..127  bin → {[8]=本段最后一个 bin, [7:0]=本段偏置 off}
//        128..255  Hann 窗 u16（低 16 位）
reg [31:0] wmem [0:255];   /* fehdl force_ram=1, ram_style="bram" */
reg [31:0] rom  [0:255];   /* fehdl force_ram=1, ram_style="bram" */

reg [31:0] rd;                              // wmem 同步读出
reg [31:0] rq;                              // rom  同步读出

wire [15:0] rd_re = rd[31:16];
wire [15:0] rd_im = rd[15:0];
wire [15:0] rq_hi = rq[31:16];
wire [15:0] rq_lo = rq[15:0];

//-----------------------------------------------------------------------------
//  蝶形地址（无桶形移位器：one-hot + 温度计码逐位选择）
//-----------------------------------------------------------------------------
//  i0 = 在 b 的第 s 位插入一个 0：
//      k < s : b[k]      k == s : 0      k > s : b[k−1]
//  i1 = i0 | 2^s
wire [5:0] b6 = c7[5:0];
wire [6:0] i0;
assign i0[0] = msk[0] & b6[0];
genvar gk;
generate
    for (gk = 1; gk < 6; gk = gk + 1) begin : g_i0
        assign i0[gk] = msk[gk] ? b6[gk] : (h1[gk] ? 1'b0 : b6[gk-1]);
    end
endgenerate
assign i0[6] = h1[6] ? 1'b0 : b6[5];
wire [6:0] i1 = i0 | h1;

//  旋转因子步长 = 2^(6−s) mod 64 —— 就是 h1 的位反转（纯连线）
wire [5:0] tw_step = {h1[1], h1[2], h1[3], h1[4], h1[5], h1[6]};

//  采样写地址：位反转（纯连线）
wire [6:0] n_rev = {c7[0], c7[1], c7[2], c7[3], c7[4], c7[5], c7[6]};

//-----------------------------------------------------------------------------
//  乘法器（1 个 DSP，分时）
//-----------------------------------------------------------------------------
//    S_CAP  cap_go : a = 抽取样本           b = Hann（无符号，零扩展）
//    S_FFT  ph1    : a = B.re  b = W.re  → acc  = p
//           ph2    : a = B.im  b = W.im  → acc −= p   ⇒ t_re
//           ph3    : a = B.re  b = W.im  → acc  = p
//           ph4    : a = B.im  b = W.re  → acc += p   ⇒ t_im
//    S_BAND ph1    : a = b = X.re        → acc  = p
//           ph2    : a = b = X.im        → acc += p   ⇒ 功率
//  B 一直留在 rd 里（ph0..ph3 读地址保持 i1），W 一直留在 rq 里 ⇒ 不用另存。
reg  [17:0] d4;                             // 抽取累加（4 × 16 位）
wire        asel = (ph == 3'd2) | (ph == 3'd4);     // 取虚部
wire        bsel = (ph == 3'd2) | (ph == 3'd3);     // 取 W.im
wire [15:0] a16  = is_cap ? d4[17:2] : (asel ? rd_im : rd_re);
wire [17:0] m_a  = {{2{a16[15]}}, a16};
wire [15:0] b16  = (bsel | is_cap) ? rq_lo : rq_hi;
wire [17:0] m_b  = is_band ? m_a :
                   is_cap  ? {2'b00, b16} :         // Hann 0..65535，正数
                             {{2{b16[15]}}, b16};

//  ★ 必须是 wire：由 EG_PHY_MULT18 的 .p 驱动（见 audio_vol.v 的说明）
wire [35:0] mpy;

EG_PHY_MULT18 #(
    .INPUTREGA ("DISABLE"),
    .INPUTREGB ("DISABLE"),
    .OUTPUTREG ("DISABLE"),
    .SRMODE    ("ASYNC"),
    .MODE      ("MULT18X18C")
) u_cmul (
    .acout   (),
    .bcout   (),
    .p       (mpy),
    .signeda (1'b1),
    .signedb (1'b1),
    .a       (m_a),
    .b       (m_b),
    .acin    (18'd0),
    .bcin    (18'd0),
    .cea     (1'b1),
    .ceb     (1'b1),
    .cepd    (1'b1),
    .clk     (clk),
    .rstan   (1'b1),
    .rstbn   (1'b1),
    .rstpdn  (1'b1),
    .sourcea (1'b1),                        // ★ 1 = 选 a（0 会选 acin，乘出 0）
    .sourceb (1'b1)
);

//-----------------------------------------------------------------------------
//  累加器（复乘 / 功率共用；分段阶段兼作 log2 归一化移位器）
//-----------------------------------------------------------------------------
reg  signed [30:0] acc;
reg         [15:0] t_re;                    // W·B 的实部（ph3 锁存）
reg          [4:0] ncnt;                    // log2 指数（从 28 往下数）

wire signed [30:0] pp       = $signed(mpy[30:0]);
wire               acc_ld   = (ph == 3'd1) | (is_fft & (ph == 3'd3));
wire               acc_sub  =  is_fft & (ph == 3'd2);
wire               acc_en   = (is_fft  & (ph != 3'd0) & (ph <= 3'd4)) |
                              (is_band & ((ph == 3'd1) | (ph == 3'd2)));
wire signed [30:0] acc_base = acc_ld ? 31'sd0 : acc;
wire signed [30:0] acc_sum  = acc_sub ? (acc_base - pp) : (acc_base + pp);

wire               nrm_done = acc[28] | (ncnt == 5'd0);
wire               nrm_sh   = is_band & (ph == 3'd3) & ~nrm_done;

//-----------------------------------------------------------------------------
//  蝶形加减：ph5 写 X1 = (A − t) >> 1 到 i1，ph6 写 X0 = (A + t) >> 1 到 i0
//-----------------------------------------------------------------------------
//  rd 在 ph5、ph6 都是 A（ph4/ph5 读地址 = i0，i0 在 ph6 才写）
wire        bf_sub = (ph == 3'd5);
wire [15:0] t_im   = acc[30:15];
wire [16:0] a_re17 = {rd_re[15], rd_re};
wire [16:0] a_im17 = {rd_im[15], rd_im};
wire [16:0] t_re17 = {t_re[15],  t_re};
wire [16:0] t_im17 = {t_im[15],  t_im};
wire [16:0] s_re   = bf_sub ? (a_re17 - t_re17) : (a_re17 + t_re17);
wire [16:0] s_im   = bf_sub ? (a_im17 - t_im17) : (a_im17 + t_im17);

//-----------------------------------------------------------------------------
//  分段：log2 → 段内取最大 → 偏置 / 饱和 → 峰值保持
//-----------------------------------------------------------------------------
reg  [7:0] bmax;
wire [7:0] lg      = {ncnt, acc[27:25]};    // ≈ 8·log2(P)
wire       b_last  = rq[8];                 // 本 bin 是本段最后一个
// ★ 2026-11-03 [AREA]：16 段偏置都是 48（ROM 64..127 低 8 位全是 0x30），
//   直接减常数 ⇒ 省掉一条 9 位变量减法链。ROM 低 8 位保留但不再读。
//   若以后要恢复"每段不同偏置"，把这里改回 `- {1'b0, rq[7:0]}` 即可。
localparam [8:0] B_OFF = 9'd48;

wire [8:0] h_dif   = {1'b0, bmax} - B_OFF;
wire [6:0] h7      = (h_dif[8] | starve) ? 7'd0   :
                      h_dif[7]           ? 7'd127 : h_dif[6:0];
wire [6:0] d_old   = rd[6:0];               // ph6：rd = 旧条高（ph5 读 128+bk）
wire [6:0] d_dec   = (d_old > DECAY) ? (d_old - DECAY) : 7'd0;
wire [6:0] d_new   = (h7 > d_dec) ? h7 : d_dec;

//-----------------------------------------------------------------------------
//  RAM 端口
//-----------------------------------------------------------------------------
//  读口归属：S_FFT / S_BAND（只在消隐里）归引擎，其余时间归扫描侧
wire [7:0]  raddr  =is_fft  ? {1'b0, (ph <= 3'd3) ? i1 : i0} :
                     is_band ? ((ph == 3'd5) ? {4'b1000, bk} : {2'b00, b6}) :
                               {4'b1000, scan_idx};

wire        we     = (cap_go & is_cap) |
                     (is_fft  & ((ph == 3'd5) | (ph == 3'd6))) |
                     (is_band &  (ph == 3'd6));
wire [7:0]  waddr  = is_cap ? {1'b0, n_rev} :
                     is_fft ? {1'b0, (ph == 3'd5) ? i1 : i0} :
                              {4'b1000, bk};
wire [15:0] wd_hi  = is_cap ? mpy[32:17] : s_re[16:1];   // 加窗结果 |x| < 2^14
wire [15:0] wd_lo  = is_cap  ? 16'd0 :
                     is_band ? {9'd0, d_new} : s_im[16:1];

wire [7:0]  rom_a  = is_cap  ? {1'b1, c7} :
                     is_band ? {2'b01, b6} : {2'b00, tw};

always @(posedge clk) begin
    if (we) wmem[waddr] <= {wd_hi, wd_lo};
    rd <= wmem[raddr];
end

always @(posedge clk) begin
    rq <= rom[rom_a];
end

assign scan_h = rd[6:0];

//-----------------------------------------------------------------------------
//  数据通路寄存器（不带复位：不进控制集，见计划 §6.3 规则 3）
//-----------------------------------------------------------------------------
always @(posedge clk) begin
    // ÷4 抽取：4 点盒式和，取 [17:2] 即平均
    if (smp_valid)
        d4 <= ((dc == 2'd0) ? 18'd0 : d4) + {{2{smp[23]}}, smp[23:8]};

    if (acc_en)      acc <= acc_sum;
    else if (nrm_sh) acc <= {acc[29:0], 1'b0};

    if (is_fft & (ph == 3'd3)) t_re <= acc[30:15];

    if (is_band & (ph == 3'd1))  ncnt <= 5'd28;
    else if (nrm_sh)             ncnt <= ncnt - 5'd1;

    if (is_band & (ph == 3'd4) & (bfirst | (lg > bmax)))
        bmax <= lg;
end

//-----------------------------------------------------------------------------
//  控制
//-----------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) begin
        st     <= S_CAP;
        ph     <= 3'd0;
        c7     <= 7'd0;
        bk     <= 4'd0;
        h1     <= 7'd1;
        msk    <= 6'd0;
        tw     <= 6'd0;
        dc     <= 2'd0;
        cap_go <= 1'b0;
        wd     <= 1'b0;
        starve <= 1'b0;
        bfirst <= 1'b1;
    end else begin
        if (smp_valid) dc <= dc + 2'd1;
        cap_go <= smp_valid & (dc == 2'd3) & is_cap;

        case (st)
        //---------------------------------------------------------------
        S_CAP: begin
            if (cap_go) begin
                c7 <= c7 + 7'd1;
                if (c7 == 7'd127) st <= S_WAIT;
            end else if (vbl) begin
                if (wd) begin                       // 2 帧没采满 ⇒ 当作静音
                    starve <= 1'b1;
                    st     <= S_BAND;
                    ph     <= 3'd0;
                    c7     <= 7'd1;
                    bk     <= 4'd0;
                    bfirst <= 1'b1;
                end else
                    wd <= 1'b1;
            end
        end
        //---------------------------------------------------------------
        S_WAIT: begin
            if (vbl) begin
                st  <= S_FFT;
                ph  <= 3'd0;
                c7  <= 7'd0;
                h1  <= 7'd1;
                msk <= 6'd0;
                tw  <= 6'd0;
            end
        end
        //---------------------------------------------------------------
        S_FFT: begin
            if (ph == 3'd6) begin
                ph <= 3'd0;
                c7 <= {1'b0, b6 + 6'd1};
                if (b6 == 6'd63) begin              // 本级结束
                    tw  <= 6'd0;
                    h1  <= {h1[5:0], 1'b0};
                    msk <= {msk[4:0], 1'b1};
                    if (h1[6]) begin                // 7 级全部结束
                        st     <= S_BAND;
                        c7     <= 7'd1;             // bin 0（直流）跳过
                        bk     <= 4'd0;
                        bfirst <= 1'b1;
                    end
                end else
                    tw <= tw + tw_step;
            end else
                ph <= ph + 3'd1;
        end
        //---------------------------------------------------------------
        S_BAND: begin
            case (ph)
            3'd3: if (nrm_done) ph <= 3'd4;         // 归一化，最多 28 拍
            3'd4: begin
                bfirst <= b_last;
                if (b_last) ph <= 3'd5;
                else begin
                    c7 <= c7 + 7'd1;
                    ph <= 3'd0;
                end
            end
            3'd6: begin                             // 写回条高
                bk <= bk + 4'd1;
                c7 <= c7 + 7'd1;
                ph <= 3'd0;
                if (bk == 4'd15) begin
                    st     <= S_CAP;
                    c7     <= 7'd0;
                    wd     <= 1'b0;
                    starve <= 1'b0;
                end
            end
            default: ph <= ph + 3'd1;               // 0,1,2,5
            endcase
        end
        endcase
    end
end

