localparam integer RD_TX_GAP = 1;         // 1 = 实验 A/A2 开（换位空拍）／0 = 关

// ★ RD 4 槽 ⇒ 最后一槽是 **槽 3**
wire rd_gap_hold = (RD_TX_GAP != 0) && (slot == 4'd4) && (ph >= 4'd12);

//==============================================================================
//  ★★ 实验 A-1（2026-10-22）：显示读的"起突发"也看一眼 Sdr_busy ★★
//==============================================================================
//  【为什么 RD 一直盲飞没出事】因为它的命令流是**一整串连续 +1** 的 128 条。
//      控制器对组内第 2~4 条按 `组首+相位` 重算地址 —— 只要地址连续，
//      无论它怎么重新分组，重算结果**永远等于真实地址** ⇒ 对分组错位免疫。
//      只有**跳址**才需要"跳点正好落在相位 0"。
//  【那 RD 还剩什么风险】每 128 条只有一次跳（突发起点），暴露率 0.8%。
//      而起点只要求 `ph_eff==0`（4 拍网格），没看忙 ⇒ 偶尔正好落进忙窗
//      ⇒ 那 128 字全部取错 ⇒ 屏幕上表现为**框外的零星白点**（未写区 FFFFFFFF）。
//      ⇒ 这就是 dbg_sel=12（l_white）一直非 0 的来源。
//  【修法尝试】只挡"起头"那一拍，`rd_run` 正在跑的串不受影响。
//      ★ 我当时估"供给损失 <1%"，**这个估计是错的** —— 见下面实测。
//  ★★★ 上板结果（2026-10-22）：**满屏黄（显示读 FIFO 被抽干）⇒ 已证否，固化 = 0** ★★★
//  【为什么我算错了】我把暴露率当成了"每 128 条一次"。实际上：
//      `rd_run` 在**每个回合**的槽 3 末就被清 0（窗口一结束就清）
//      ⇒ 128 条的突发要跨 **2 个回合**，而**每个回合都必须重新起一次头**
//      ⇒ 暴露率是 **"每回合一次"**，不是"每 128 条一次"。
//  于是代价 = P(busy) × 一个槽 / 该回合 RD 容量 = 0.46 × 16/64 = **11.5%**，
//      而 RD 的余量只有 14%（0.234 vs 0.201）⇒ 只剩 2.5%，任何抖动就慢慢漏干
//      ⇒ 几十秒后整屏变黄（不是一下坏，是"慢性失血"）。
//  【结论】RD 的"起头"是**每回合一次**的高频事件，不能拿 `Sdr_busy` 去挡。
//      真要挡，必须先把 `rd_run` 改成"跨回合保持"，但那等于关掉这个门本身。
//  ⚠ 顺带一条对"从 RD 借时间"的警告：RD 的真实抖动余量只有 ~2.5%（不是 14%），
//      任何从 RD 抢容量的改动都要按 2.5% 来算安全边界。
//  【回退】RD_START_GATE = 0（一行，也是当前固化值）。
//==============================================================================
localparam integer RD_START_GATE = 1;     // 2026-10-24 fix: 按注释恢复为 0（1 = 起头看忙，已证否，会降吞吐）
wire rd_start_ok = (RD_START_GATE == 0) || !Sdr_busy;

// ★ build F4（甲）：起突发那一拍要等 ctrl_ok；`rd_run` 已经在跑的串不受影响 ★
// ⚠ 注意上面那条：`rd_run` **每回合都会清 0** ⇒ 这里的"起头"是**每回合一次**，
//   不是"每 128 条一次"。任何加在这个判断里的条件都会被放大 8 倍代价。
wire rd_go   = rd_slot && !stall && !rd_gap_hold
             && (rd_run || ((ph_eff == 2'd0) && ctrl_ok && tag_room && rd_start_ok));

//==============================================================================
//  ★★★ build S：诊断开关 —— 停掉显示读（判决"纹理是不是和显示读交叉"）★★★
//==============================================================================
//  串口已经证明：坏字是**实时的帧缓存内容**（同一偏移在不同帧读到红圆/橙圆/绿三角…），
//  而命令地址确实在纹理槽、计数又全是 1:1 ⇒ **"第 N 拍 ↔ 第 N 条命令"被破坏了**。
//  剩下的唯一问题是"跟谁对不上"：
//      DRD_MUTE=1 ⇒ 显示读一条命令都不发
//        · `tex_bad`（key1=1 rsel 5）掉到 0  ⇒ 是**和显示读交叉** ⇒ 修时隙表（给两路各自回程窗口）
//        · `tex_bad` 基本不变               ⇒ 是**纹理自己 4 条命令之间**对不上 ⇒ 修拍/命令配对
//  代价：画面冻结（显示读停了），但读数照常刷新。★ 诊断完必须改回 0 ★
//==============================================================================
localparam integer DRD_MUTE = 0;         // 1 = 停掉显示读（只做诊断）

assign disp_rd_ready = DRD_MUTE ? 1'b0 : rd_go;

// ★ 2026-10-21 build 100M-20：冻结期间必须【保持】突发状态 ★
//   【踩过的坑（仿真已复现）】BUSY_HOLD 冻结时 ph 不动，但原来这里会把 rd_run
//   清 0 ⇒ 解冻后 RD 从"下一个 4 拍边界"重新起突发；而控制器的 4 命令分组
//   相位并没有复位 ⇒ 新突发的前几条被当成上一组的余项，地址按 grp_head+ph
//   重算 ⇒ 读回别处内容（= 板上"框外随机白点"）。
//   ⇒ 冻结时 rd_run 保持，解冻后从原位置继续，组的条数与相位都不变。
always @(posedge clk or posedge rst) begin
    if (rst)
        rd_run <= 1'b0;
    else if (stall)
        rd_run <= rd_run;             // 冻结：组状态原地保持
    else if (rd_go && disp_rd_en)
        rd_run <= 1'b1;               // 本拍真的发出去了一条命令
    else
        rd_run <= 1'b0;               // 断一拍 → 下一条命令必须等 4 拍边界
end

//==============================================================================
//  4. 显示写：与读完全对称
//==============================================================================
reg  wr_run;

wire wr_slot = (own == OWN_WR);
// ★★ 2026-10-21 build 100M-20：写段头部静音 8 拍 —— 吸收纹理组尾的回程 ★★
//   【板上的"白色竖条"】TX_TAIL=4 允许一个被忙冻结拉长的组把第 4 条命令放到
//   槽 10 的 ph0..3；它的 CAS 回程要到槽 10 ph14 才结束。而 WR 从槽 11 ph0
//   立刻起跑 ⇒ 写命令压进读回程 ⇒ 写错列 ⇒ 光栅顺序下就是一条竖线。
//   【修法】槽 11 前 8 拍不发写命令：最后一条 TX（≤槽10 ph3）到第一条 WR
//   （槽11 ph8）= 21 拍 ≥ CAS(11)+2，回程整段落在静音里。
//   【代价】WR 供给 64→56 字/256 拍 = 0.219 字/拍，需求 640/3180=0.201 ⇒ 1.09×
//   （原来的 1.24× 是拿换向安全换来的，这一刀必须让）。
//  ★★ 实验 C（2026-10-22）：写窗口起点挪用槽 10，所以这里的槽号也跟着挪 ★★
//   新表下 TX 尾巴溢到 **槽 9** ph0~3，而写从 **槽 10** 起跑 ⇒ 只有 13 拍 < 16 红线
//   ⇒ 必须静音槽 10 的前 4 拍：9ph3 → 10ph4 = **17 拍 ≥ 16** ✓
//   代价：写供给 80 → 76 字/轮（−5%，已含在 1384 拍/行的预算里）。
// ★ build N3：WR 首槽 = **槽 10**，缺口 4 拍（TX 尾巴溢到槽 9 ph0~3）
localparam integer WR_HEAD_GAP = 4;
wire wr_gap_hold = (WR_HEAD_GAP != 0) && (slot == 4'd9) && (ph < WR_HEAD_GAP[3:0]);

//==============================================================================
//  ★★ 实验 W1（2026-10-22）：写口的"起头看忙" —— 照抄纹理的 TX_BUSY_GUARD ★★
//==============================================================================
//  【动机】纹理读有四层保护，所以它撞忙只损失**时间**：
//      ① 开组看忙（tx_busy_blk = TX_BUSY_GUARD && Sdr_busy，见 :434/:988）
//      ② 组内 4 拍连发（100M-22）
//      ③ tx_abort → tx_retry 从第 k 个偏移续发，总命令数恒为 4（:1053-1063）
//      ④ 回程有 256 深标签环，可对账（可观测，不静默）
//  显示写这四条**一条都没有**：写没有 ack、没有回程、地址只增不退
//  （frame_fifo_write.v:259/:335）⇒ 撞进控制器忙窗的那几条命令被静默吞掉
//  ⇒ 帧缓存留洞 ⇒ 读回 32'hFFFFFFFF = 纯白。
//  板上已验证：dbg_sel=12（l_white）非 0 且逐帧变化 ⇒ 确实存在"从未写过的字"。
//
//  【粒度：挡就挡**整组 4 拍**，绝不能在组中间放行】
//  写流是"连续 1 字/拍"，控制器按"连续 4 条命令"分组，组内第 2~4 条的地址由它
//  自己按"组首+相位"重算。若某一组只发 3 条（比如只挡了 ph[1:0]==0 那一拍），
//  之后整串命令相对地址就错一位 ⇒ 整个突发 128 字全部读到/写到别处 —— 那比白条
//  严重得多。所以：**在上一组的第 4 拍采样 Sdr_busy，覆盖下一整组**（要么全发、
//  要么全不发）。采样点为什么不能放在组首，见下面 :837 的"血泪"段。
//
//  【配套 ①】`wr_run` 在挡忙期间必须**保持**（见下面 always 块），否则一次 4 拍的
//  挡会因"要等 ph_eff==0 才能重新起突发"膨胀成 16 拍不写，白丢 12 个字/次。
//  【配套 ②】top 的 `wr_stall` 阈值必须降到 **192/160**（带回滞）：挡忙会削写供给，
//  原来贴 448（512 的 87.5%）只剩 64 字余量，一顶到 512 就是 wfifo 静默丢字
//  ⇒ 整行横移，比白条难看的多。192 留出 320 字余量，且 192 > BURST_SIZE(128)。
//
//  【回退】WR_BUSY_GUARD 改 0 = 完全恢复原行为（wr_blk_g 恒 0，一行回退）。
//  【板上判据】真机 Sdr_busy 占空比很高（:1493"读回程/刷新/换向都拉高"），所以这一版
//  很可能"白条变少 + 帧率下降"，也可能写供给不够。读三处：
//      0x2C  l_white              —— 白条的字数，主判据（0 = 治好）
//      0x30  bit0 wr_full_seen    —— 必须仍为 0；变 1 = 写 FIFO 溢出 ⇒ 本实验作废
//      0x2F  {txabort,txhold}     —— 纹理侧有没有被连带影响
//==============================================================================
//  ★★ 实验 B′（写口只在窗口首看忙）—— **已试、已证否**，结论在下面那段 ★★
//==============================================================================
//  （原提案已删除，避免和下面的结论自相矛盾。一句话：只护 1/16 的组
//    ⇒ 上板立刻全屏白条 ⇒ 写口的每组都必须确认。）
//==============================================================================
localparam integer WR_BUSY_GUARD = 1;         // 1 = 写口按 4 拍组挡 Sdr_busy ／ 0 = 关
//==============================================================================
//  ★★★ 实验 B′ 已证否（2026-10-22 上板）：写口不能"只在窗口首看忙" ★★★
//==============================================================================
//  【当时怎么想的】以为写口和读口一样：一个 WR 窗口（槽 11~14）里 64 条命令地址
//      严格连续 ⇒ 对控制器分组免疫 ⇒ 只有窗口首需要看忙 ⇒ 税 46% → 3%。
//  【板上结果】只护 1/16 的组 ⇒ **全屏白条立刻回来**。
//  【为什么错了 —— 读和写的失败模式不同】
//      读：命令被拒收/延迟 ⇒ 组相位相对我们的意图漂移 ⇒ 控制器按"组首+相位"
//          重算 ⇒ **数据还在，位置错**。地址连续时重算结果恒等于真实地址
//          ⇒ **连续流确实免疫**（这就是 B 成立、RD 盲飞也干净的原因）。
//      写：命令被吞 ⇒ **数据直接消失**，地址照走 ⇒ 空洞。
//          ⇒ 命令都没了，连续不连续都没有意义 ⇒ **每条写出都必须确认**。
//  ⇒ 所以：**读的税可以靠"拉长连续段"压掉，写的税不可压缩。**
//      B 对 TX（读）成立；B′ 对 WR（写）不成立。这不是实现问题，是方向问题。
//  【写口要提速只能靠"给更多供给"，不能靠"少检查"】
//      见 :1050 附近的 TX5/WR5 重分配方案（要靠 B 先把纹理的税打掉才有富余）。
//  【回退】本来就是这个状态；留此段是为了别第三次踩。
//==============================================================================
wire wr_blk_now = (WR_BUSY_GUARD != 0) && Sdr_busy;    // 每一组都确认（不可省）
reg  wr_blk_g;                                         // ★ 必须是寄存器（见下）
always @(posedge clk or posedge rst) begin
    if (rst)
        wr_blk_g <= 1'b0;
    else if (stall)
        wr_blk_g <= wr_blk_g;                 // 冻结期间 ph 不动，决定也不变
    else if (ph[1:0] == 2'd3)
        wr_blk_g <= wr_blk_now;               // ★ 上一组最后一拍采样 ⇒ 下一组整组生效
end
//==============================================================================
//  ★★★ 血泪：采样点必须放在 ph[1:0]==3，不能放在 ph[1:0]==0 ★★★
//==============================================================================
//  【W1 第一版（采样点 = ph[1:0]==0）上板结果：白条没了，但**整屏花**】
//  原因不是"挡忙"这件事错了，而是**一组被拆成了 0/4 或 1/3**：
//      非阻塞赋值在 ph0 **结束时**才更新 ⇒ 同一组的 4 拍用了两个不同的值：
//          ph[1:0]==0  → 用【上一组】的旧采样
//          ph[1:0]==1/2/3 → 用【本组】的新采样
//      ⇒ 前一组=0、本组=1 时该组只发 1 条；反过来只发 3 条。
//  【为什么这一条就能把整屏搞花】
//      frame_fifo_write 每行正好 640 字（**4 的整数倍**），行尾有一次
//      `VFLIP_LINE_JUMP` 地址回跳。命令数一旦不再是 4 的倍数，这个回跳就落到
//      phase 1/2/3 上；而控制器对组内第 2~4 条命令是**按"组首+相位"自己重算地址**的
//      ⇒ 回跳之后那几条命令写到别处 ⇒ 每行错位、逐行递进 ⇒ 整屏花。
//  【正确做法】在**上一组的第 4 拍**（ph[1:0]==3）采样，值覆盖下一整组 ph0~3：
//      4 拍同值 ⇒ 挡的长度恒为 0 或 4 ⇒ 命令数永远 4 的整数倍 ⇒ 相位不可能漂。
//      而且决策只提前 1 拍，比"提前 4 拍"更跟得上忙窗。
//  【为什么不改成"组首实时采样本组即时生效"】
//      `wr_busy_blk = (ph[1:0]==0) ? wr_blk_now : wr_blk_g` 会把 **Sdr_busy 组合进
//      disp_wr_ready → App_wr_en** —— 而 App_wr_en 正是 frame_fifo_write.v:163-169
//      记录的那条 −0.090ns 最差路径（当年靠"拆掉锥里的加法器"才修好）。
//      再塞一个输入进去等于把违例请回来。所以 wr_blk_g 必须是**纯寄存器**输出。
//==============================================================================
wire wr_busy_blk = wr_blk_g;                  // 纯寄存器 ⇒ 不碰 App_wr_en 的锥

//==============================================================================
//  ★★ 实验 L（2026-10-22）：写口命令必须"有数据才发" —— 修 39% 的空命令 ★★
//==============================================================================
//  【板上证据】0x24 显示每帧约 506,000 条写命令，而一帧只写 640×480 = 307,200 字
//  ⇒ 1.65 倍。多出来的 199K 条是"没有数据也照样发命令"：
//      wr_go 不含 disp_wr_en ⇒ 写引擎还没送来数据时，命令照发
//      而地址只在 App_wr_en 时 +1（frame_fifo_write.v:259）
//      ⇒ 同一个地址被反复写。SDRAM 写是幂等的，所以画面不坏 —— 纯烧带宽。
//  【为什么不能直接写 `&& disp_wr_en`】那会成组合环：
//      App_wr_en = App_wr_en_d0 & wr_ready
//      wr_ready  = disp_wr_ready = wr_go          （顶层 .wr_ready(fw_wr_ready)）
//      disp_wr_en = App_wr_en                      （顶层 .disp_wr_en(fw_wr_en)）
//      ⇒ wr_go 直接依赖自己。
//  【第一版错在哪】改用"打一拍的 disp_wr_en" —— **同样锁死，上板全黑**：
//      disp_wr_en_d=0 → wr_go=0 → wr_ready=0 → App_wr_en=0 → disp_wr_en=0
//      下一拍 disp_wr_en_d 还是 0 ⇒ 永远起不来。
//      根本原因：`disp_wr_en` 是**本模块门控之后**的结果，不是上游的愿望。
//      （和 A-2 用 disp_rd_en 判"显示读闲不闲"是同一个错误，见 :829 那段教训。）
//  【正确做法】取 `frame_fifo_write` 的 `O_wr_busy`：
//      assign O_wr_busy = (state == S_WRITE_BURST ||
//                          (state == S_CHECK_FIFO && into_burst_r));
//      只依赖 state / into_burst_r 两个寄存器，**与 wr_ready 无关** ⇒ 无环。
//      语义也正好："正在突发、或马上要突发" = 有数据要写。
//      突发间隙（S_CHECK_FIFO 且 FIFO 不够）它自然为 0 ⇒ 空命令被挡掉。
//  【代价】每个突发的首、尾各差一拍（打拍造成）：突发 128 字 ⇒ 多 1 条重复命令，
//      0.8%；换来 39% 的命令减少，净赚。
//  【为什么不会切碎 4 命令分组】突发期间 state 恒为 S_WRITE_BURST ⇒
//      O_wr_busy 恒 1 ⇒ 门控不产生断点；突发之间 wr_run 自然清 0，
//      下一次从 ph_eff==0 重新对齐 ⇒ 组相位不漂。
//  【回退】把 `&& disp_wr_en_d` 删掉（一行），disp_wr_en_d 留着无害。
//==============================================================================
reg disp_wr_en_d;
