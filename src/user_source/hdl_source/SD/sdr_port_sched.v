// ★ 槽长改成 16 拍后，一个 4 字组仍然只占前 4 拍 ★
// ★ 100M-16：组内相位改用锁存的 gph（review 问题 6）——
//   原来用 ph_eff（= ph[1:0] - ph_off，组合依赖输入 ph_off）：ph_off 在一组的
//   4 拍之间被扫位器改掉，同组内后几条命令的地址/掩码索引会立即换口径。
//   gph 在 tx_start 时置 1、之后每发一条自己 +1，与 ph_off 完全解耦。
//   ph=0（起始拍）用请求地址的组首（零扩展，无加法器）；ph=1..3 用锁存组首拼相位
// ★★ 2026-10-21 重试只补发余项（修"组命令数 mod 4 漂移"）★★★
//  【原来的错】tx_abort 后重试把 4 条命令**全部重发**（只想留 4-k 条的 want），
