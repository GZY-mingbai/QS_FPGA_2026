//==============================================================================
//  ★★ 2026-10-18（第三版）：回程分发 + 读数据"错一拍"补偿（RD_LAG）★★
//==============================================================================
//  【为什么要有 RD_LAG】厂商手册 APUG011 §7「移植与注意事项」第 6 条原文：
//      "读数据时，SDRAM 与不同硬件，使用不同的频率和相位，
//        可能出现时钟和数据错一拍的情形，请根据实际情况，在应用中做调整。"
//
//  也就是说 `Sdr_rd_en` 与 `Sdr_rd_dout` 在真板上**可能相差一拍**。
//  这件事在两种用途上的表现完全不同：
//    · 帧缓存（顺序流）：整条流只是整体移 1 个字 ⇒ 画面整体移 1 像素 ⇒ **看不出来**
//    · 纹理（4 字组、每组只挑 1 个字）：每组挑到的字都会差一位
//        ⇒ 轮廓/颜色/位置都对，但整幅叠一层**稀疏错点**，偶尔挑到很远的字
//          ⇒ 一块残缺的重复图 —— 与板上照片完全一致
//  这也解释了为什么"基础画面正常、只有图片层花"，以及为什么仿真永远复现不了
//  （仿真里 en 和 dout 是严格同拍的）。
//
//  【RD_LAG 的语义】
//    0 = 对齐（`Sdr_rd_en` 与 `Sdr_rd_dout` 同一拍有效）—— 原来就是这个假设
//    1 = 数据晚一拍（en 在 t 拍、数据在 t+1 拍才有效）—— 本版默认
//  实现上：数据固定取 `dout_s1`（打一拍），使能按 RD_LAG 多打一拍。
//    RD_LAG=0：用 beat_s1 + dout_s1（同拍采样）
//    RD_LAG=1：用 beat_s2 + dout_s1（数据晚一拍，所以使能也要晚一拍去配它）
//==============================================================================
reg        beat_tx_s1, beat_tx_s2;
reg        beat_dp_s1, beat_dp_s2;
reg [1:0]  txid_s1, txid_s2;          // ★ {层号, 要不要} 跟着数据一起打拍 ★
reg [31:0] dout_s1;

//==============================================================================
//  ★★★ 2026-10-19 build D：标签环改成【寄存器读】★★★
//==============================================================================
//  【问题】原来身份是这么用的：
//      wire [2:0] tag_cur = tag_mem[tag_r];     ← 256 选 1 的【组合读】
//      beat_tx_s1 <= beat &&  tag_cur[2];       ← 身份和回拍【同一拍】配对
//      txid_s1    <= {tag_cur[1], tag_cur[0]};
//  `tag_r` 每拍 +1，所以必须在同一个 8ns 周期里完成
//      tag_r → 256:1 LUTRAM 读 → tag_cur → beat_tx_s1
//  一旦这一拍没稳定，用上的就是**上一条命令的身份**：
//      · 一条显示读的回拍被当成"纹理" ⇒ 帧缓存的内容被写进纹理 FIFO
//        ⇒ 那个像素拿到一个/不是纹理的值（纯色纹理下也是白的/脏的）
//      · 同时一条纹理回拍被当成"显示" ⇒ 显示流里多一个错字
//  ⇒ **命令数、回拍数、指针全都照常** ⇒ 现有所有计数器都看不见。
//  这也解释了"纯色时帧首第一个像素就可能脏"：这是逐拍的身份错，不依赖累积状态。
//
//  【改法】把「回拍使能 / 身份 / 数据」三样**一起**推后一拍，
//  使 RAM 读变成寄存器读（标准做法）：
//      t   : tag_cur = mem[tag_r] , beat = Sdr_rd_en&nempty , dout = Sdr_rd_dout
//      t+1 : tag_cur_q / beat_q / dout_q  ← 三者同拍寄存，配对关系不变
//      t+2 : beat_tx_s1 / txid_s1 / dout_s1 ← 再一起进原来的 s1 级
//  语义完全不变（整条回程统一晚 1 拍；下游是靠"使能数"推进的 FIFO 语义），
//  但那条 256:1 组合读从关键路径上消失了。
//==============================================================================
reg [2:0]  tag_cur_q;
reg        beat_q;
reg [31:0] dout_q;
reg [31:0] dout_q_d1;          // ★ build R：上一拍的回拍数据（检测"总线重复"）★

// ★ 2026-10-31：BRAM 同步读口 —— 与原 `tag_cur_q <= tag_cur` 同拍同址，只是去掉了异步复位。
//   复位值无关紧要：tag_cur_q 只在 beat_q=1 时被使用，而 beat_q=1 的前一拍必有一次真读。
always @(posedge clk) begin
    tag_cur_q <= tag_mem[tag_r];
end

always @(posedge clk or posedge rst) begin
    if (rst) begin
        beat_q    <= 1'b0;
        dout_q    <= 32'd0;
    end else begin
        beat_q    <= beat;
        dout_q    <= Sdr_rd_dout;
        dout_q_d1 <= dout_q;                              // 上一拍的数据
    end
end

always @(posedge clk or posedge rst) begin
    if (rst) begin
        beat_tx_s1 <= 1'b0; beat_tx_s2 <= 1'b0;
        beat_dp_s1 <= 1'b0; beat_dp_s2 <= 1'b0;
        txid_s1    <= 2'd0; txid_s2    <= 2'd0;
        dout_s1    <= 32'd0;
    end else begin
        beat_tx_s1 <= beat_q &&  tag_cur_q[2];   // ★ 用寄存器后的身份/使能 ★
        beat_tx_s2 <= beat_tx_s1;
        beat_dp_s1 <= beat_q && !tag_cur_q[2];
        beat_dp_s2 <= beat_dp_s1;
        // 身份和数据走同一条延迟线，rd_lag 切换时一起切换
        txid_s1    <= {tag_cur_q[1], tag_cur_q[0]};
        txid_s2    <= txid_s1;
        dout_s1    <= dout_q;                    // ★ 数据也取寄存后的 ★
    end
end

wire        beat_tx_d1  = rd_lag_q ? beat_tx_s2 : beat_tx_s1;   // ★ 100M-16：锁存的 rd_lag
wire        disp_vld_d1 = rd_lag_q ? beat_dp_s2 : beat_dp_s1;
wire [1:0]  txid_d1     = rd_lag_q ? txid_s2    : txid_s1;
wire [31:0] dout_d1     = dout_s1;

assign disp_rd_vld  = disp_vld_d1;
assign disp_rd_data = dout_d1;

//==============================================================================
//  10. 纹理回程：完全由标签决定（每一拍自带身份）
//==============================================================================
//  ★ 契约（和 ps_gen_image 严格对齐）★
//      图片层每发一个请求 = "读这个 4 字组"，并附 4 位掩码说这组里要哪几个字；
//      这里发 4 条读命令（组首 + 0..3），每条命令把自己的身份
//      {是不是纹理, 层号, 掩码[ph]} 存进标签环；
//      回程时**按标签投递**：标签说"要"就投给它指定的那一层，说"不要"就丢。
//
//  【为什么这版是对的（不变式 A）】
//  身份跟着**命令**走、再跟着**数据拍**回来，中间只经过一个环（FIFO 语义）。
//  设备保证"第 N 条命令的数据是第 N 拍回来"，所以"拍 ↔ 身份"永远同步。
//  旧版额外引入了一个自由计数 `tx_bcnt` 去推"这是组里第几个字"，
//  那需要"拍号/组号/层号"三者永远相等 —— 错一次就永久错，而且会把
//  **显示数据和纹理数据整帧串起来**（= 板上那次整屏色条）。
//  现在没有这个中间量了：少一拍只影响它自己。
//==============================================================================

// ★ 只有"标签说这个字要"才投递；层号也来自标签 ★
//  模式 9：不看 want，只要是个纹理回拍就写（验证 want 位是不是被误清）
wire tx_beat = beat_tx_d1;
wire tx_hit  = (exp_mode_q == 4'd9) ? tx_beat : (tx_beat && txid_d1[0]);  // ★ 100M-16：锁存的模式

reg  [1:0]  tex_pix_wr_r;
reg  [63:0] tex_pix_data_r;

// ★ 100M-16：模式 8 的数据跟着写使能一起改道（review 问题 19）
//   原来只把写使能拨给层0、数据仍按原标签放上半部 ⇒ 层0 的 FIFO 收到 0，
//   "把纹理统一投给层0"这个对照实验根本验不了。
wire [1:0] tx_pix_sel = (exp_mode_q == 4'd8) ? 2'b01 : (txid_d1[1] ? 2'b10 : 2'b01);

always @(posedge clk or posedge rst) begin
    if (rst) begin
        tex_pix_wr_r   <= 2'b00;
        tex_pix_data_r <= 64'd0;
    end else begin
        tex_pix_wr_r   <= tx_hit ? tx_pix_sel : 2'b00;
        tex_pix_data_r <= { (tx_pix_sel == 2'b10) ? dout_d1 : 32'd0,
                            (tx_pix_sel == 2'b01) ? dout_d1 : 32'd0 };
    end
end

assign tex_pix_wr   = tex_pix_wr_r;
assign tex_pix_data = tex_pix_data_r;

//==============================================================================
//  ★★ build 7：命令数 / 回拍数 / 环空丢拍数 —— 三个计数（纯观测）★★
//==============================================================================
//  【要回答的问题】"请求的像素数量、返回的像素数量、有效信号的数量，三者是不是一样"
//  本设计里真正需要 1:1 的是这两个：
//      cmd  = App_rd_en  的条数（真正发给控制器的读命令）
//      beat = Sdr_rd_en  的拍数（控制器说"数据有效"）
//  因为标签环是按 beat **事件数**推进的：
//      if (App_rd_en) tag_w++      // 一条命令一份身份
//      if (beat)      tag_r++      // 一拍数据消费一份身份
//  只要 cmd 与 beat 不是严格 1:1，tag_r 就**永久**落后/超前一条，
//  从此每拍数据都贴着隔壁命令的身份 ⇒ 该投的字被吞、不该投的字被投
//  ⇒ "多/少一个字" ⇒ 该层从那个像素起**整体错一格并逐帧累积**。
//
//  【三个事件的差别】
//      cmd  - beat   > 0 且持续增长  ⇒ 有命令被吞（数据没回来）
//      beat - cmd   > 0             ⇒ 有"幽灵回拍"（没发命令却回了数据）
//      beat - beat_acc > 0          ⇒ 标签环空，回拍被 `tag_nempty` 挡掉（数据丢了）
//  任意一条成立，就证明"身份必须按时间对齐、不能按事件对齐"——
//  也就是必须换成"固定延迟移位线"（延迟 10 拍是厂商手册给定的常数）。
//==============================================================================
reg [23:0] cnt_cmd;          // App_rd_en 条数
reg [23:0] cnt_beat;         // Sdr_rd_en 拍数
reg [23:0] cnt_acc;          // 真正被接受的回拍数（beat）

reg        f_orphan;         // 幽灵回拍（beat > cmd）
reg        f_starve;         // 命令被吞（cmd - beat 超过正常在飞量）
reg        f_ringdrop;       // 环空丢回拍

// 正常在飞量 = 固定读延迟 ≈ 10 条。超过 24（2 倍余量）就不是延迟，是丢命令。
localparam [23:0] STARVE_LIM = 24'd24;

wire [23:0] inflight = cnt_cmd - cnt_beat;      // 无符号差值（也用于判 beat>cmd）
wire        beat_gt  = (cnt_beat > cnt_cmd);

// ★ 上电暖机：初始化/刷新阶段控制器可能自己吐几拍 "有效"，那不代表错位 ★
//   只有在"已经正常发过一批命令"之后再开始记账，避免开机就误报。
wire armed = (cnt_cmd > 24'd64);

always @(posedge clk or posedge rst) begin
    if (rst) begin
        cnt_cmd      <= 24'd0;
        cnt_beat     <= 24'd0;
        cnt_acc      <= 24'd0;
        f_orphan     <= 1'b0;
        f_starve     <= 1'b0;
        f_ringdrop   <= 1'b0;
    end else begin
        if (App_rd_en)  cnt_cmd  <= cnt_cmd  + 24'd1;
        if (Sdr_rd_en)  cnt_beat <= cnt_beat + 24'd1;
        if (beat)       cnt_acc  <= cnt_acc  + 24'd1;
        if (armed && beat_gt)              f_orphan   <= 1'b1;
        if (armed && (inflight > STARVE_LIM)) f_starve <= 1'b1;
        // beat - beat_acc > 0 ⇒ 有回拍被 tag_nempty 挡掉（数据丢了）
        if (armed && (cnt_beat > cnt_acc))   f_ringdrop <= 1'b1;
    end
end

//==============================================================================
//  ★★ build 5："命令 ↔ 回拍"的**时间锁**一致性（这才是之前测不到的量）★★
//==============================================================================
//  【为什么总量 1:1 还会错】上板照片显示：图片区底色 = 常量 FF123456（大多正确），
//  但散着**短横条的红/绿/白/黄/青斑点**，颜色恰好是场景图层的调色板。
//  ⇒ 帧缓存的显示数据**漏进了纹理流**，而且是一漏就漏连续几个字。
//
//  只能是：控制器在某条命令上回了 2 拍、在另一条上回了 0 拍。
//  总数仍然相等（所以 build 7 的 cmd/beat 计数完全干净），
//  但标签环在这一段**多推/少推了一格** ⇒ 身份从"纹理"变成"显示"。
//
//  【怎么测】读延迟是固定的 ≈ 10 拍，所以 `Sdr_rd_en` 应该就是
//  `App_rd_en` **整体平移 10 拍**。把命令打 10/11 拍拿回来逐拍比：
//      恒 0        ⇒ 时间锁成立，假说死掉
//      偶尔为 1    ⇒ 滑移坐实，它就是所有症状的源头
//      几乎恒 1    ⇒ 延迟不是 10（看 11 拍那个计数器）
//
//  统计方式：每 65536 拍一个窗口（@125MHz ≈ 0.5ms），窗口内计数饱和到 15，
//  取**跨窗口最大值** ⇒ 数码管上是一个稳定的最坏值。
//==============================================================================

endmodule
