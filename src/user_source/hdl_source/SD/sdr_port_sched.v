//  ★★★ build 100M-15：装载写“已沉降”信号 —— 喂给 sd_bmp_loader 的 L_DRAIN ★★★
//------------------------------------------------------------------------------
//  【为什么需要它】装载器的 done 原来在“最后一个像素入 FIFO”那一拍就拉高，
//  但那一刻 FIFO 里可能还有几百个字、本模块的 4 字暂存里可能还有一组没发、
//  SDRAM 控制器里可能还有在途的写 ⇒ done 不代表“纹理已经写进 SDRAM”。
//  上游若拿 done 当“纹理可用”，就会读到还没更新的数据。
//
//  【判据】以下五个条件同时成立，并连续保持 LD_SETTLE_N 拍：
//      · ld_wr_vld  = 0  装载 FIFO 已空（没有待写数据）
//      · ld_fill    = 0  没有正在进行的 4 拍取数
//      · ld_buf_v   = 0  4 字暂存已空（没有攒着没发的组）
//      · ld_iss_act = 0  没有正在发的组（起始拍 + 3 个寄存拍）
//      · ld_dum_need= 0  没有欠着的空写组
//  连续保持是为了覆盖“最后一组已被控制器收下 → 数据真正落进 SDRAM”的内部
//  周转（本控制器 App_wr 收下即承诺写入，320ns 足够）。
//  任何一个条件掉 0，计数清零重数 —— 只会更晚不会更早，方向安全。
//------------------------------------------------------------------------------
wire ld_settle_cond = ~ld_wr_vld && ~ld_fill && ~ld_buf_v && ~ld_iss_act && ~ld_dum_need;
localparam [15:0] LD_SETTLE_N = 16'd32;    // @100MHz = 320ns，覆盖控制器写周转

// ★ 2026-11-03 [AREA]：唯一读者是 `>= 32` ⇒ 计数饱和在 32 即可（原来饱和在 0xFFFF），
//   6 位足够，输出逐拍相同。
reg [5:0] ld_settle_cnt;
always @(posedge clk or posedge rst) begin
    if (rst)
        ld_settle_cnt <= 6'd0;
    else if (!ld_settle_cond)
        ld_settle_cnt <= 6'd0;
    else if (ld_settle_cnt != LD_SETTLE_N[5:0])
        ld_settle_cnt <= ld_settle_cnt + 6'd1;
end

assign ld_wr_settled = (ld_settle_cnt == LD_SETTLE_N[5:0]);

