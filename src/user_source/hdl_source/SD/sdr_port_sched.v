// ★ 忙停止（BUSY_HOLD）★
//  【build 1 的教训】当时用 `Sdr_busy | Sdr_init_ref_vld` 一起按住 ⇒ 全屏乱码。
//  原因：真控制器的 `Sdr_busy` 是"正在干活"的状态位（经常为高），**不是**
//  "这一拍不收命令"的门 —— 按住它等于把整个用户口饿死。
//
//  ★★ 2026-10-18（build 6）：只按 `Sdr_init_ref_vld`，**不碰 Sdr_busy** ★★
//  依据是厂商手册 APUG011 §7「移植与注意事项」第 3 条原文：
//      "每次读写操作前，请判断 Sdr_busy 是否忙"
//  以及 §2.3 原文：
//      "在用户对虚拟 ERAM 做操作前……请先判断当前虚拟 ERAM 是否忙，
//       如果确认忙，**请等待 Sdr_init_ref_vld 信号变为低电平后**，再做读写操作。"
//  而表 3-1 对 Sdr_busy 的说明是 **"暂不使用"** ⇒ 真正要等的只有刷新标志。
//
//  【为什么这条很可能就是花屏的根因】
//  刷新窗口是**周期性**的（SELF_REFRESH_INTERVAL = 64e6/8/2048 = 3906 拍，
//  一帧 492 次），窗口内控制器不收命令。上层不看这个标志硬发：
//      · 命令被丢 ⇒ 标签环多记一位 ⇒ 此后显示/纹理数据**互相串**
//        （= 图片里混进场景像素：蓝色/橙色网点；场景里混进西瓜像素）
//      · 或者命令被推迟一拍 ⇒ 回程整体错一拍（手册 §7 第 6 条明确警告过）
//  两种情况都只在"切换/刷新"那一刻发生一次，所以表现为**稀疏的、有规律的错点**，
//  而不是整屏乱码 —— 与照片完全一致。
//
//  【冻结的代价】每次刷新 20 拍 / 3125 拍 = 0.64% 的时间，且冻结期间
//  时隙表不消耗时间（ph/slot 停住），客户端不丢自己那一份配额。
//
//  ★★★ 2026-10-21 build 100M-18：TX 组内撞忙 ⇒ 冻结时隙表（不 abort、不重试）★★★
//  【为什么改成冻结】abort→retry 看起来只是"晚点补发余项"，但控制器的 4 命令分组是
//    **全局**的：它数的是读口上连续的 4 条命令，而纹理组一旦被 abort，余项要等到
//    下一段纹理流才能补发 —— 中间会插进 60 条显示读 + 64 条显示写。这些命令是 4 的
//    整数倍，看着"相位能回来"，但只要任意一个口少发一条（RD 没数据、WR 没像素），
//    相位就永久偏 1~3，之后整条流都按 grp_head+ph 取错地址。
//    仿真证据（tb_txfix MODE=0，上限 8 拍）：abort 10 次 / 错字 5 / 分组错 15；
//    上限 24 拍：abort 2 次 / 错字 5 / 分组错 15（错字不随 abort 数下降 ⇒ 只要
//    发生一次就越界）。而 100M-17 的"无上限 hold"是 0 abort / 0 错 —— 它靠的是运气：
//    一旦忙窗压在窗口末尾，照样会走到 abort。
//  【所以正确的原语是冻结】组在飞且控制器忙 ⇒ ph/slot 一起停（stall），忙退去后
//    ph4 再把相位拉回 4 拍边界，组还是那一组、地址还是那 4 条，条数一条不差、
//    分组相位一拍不漂。代价：冻结期间显示读/写也停（它们有余量，且时隙表不消耗
//    时间 ⇒ 配额不丢）。
//  【看门狗】冻结超过 64 拍才强制 abort（只防控制器卡死，正常永不触发）。
reg  tx_act;
//  ★★★ 2026-10-21 build 100M-20：TX_BUSY_GUARD 重新打开（两图层重叠的必需要求）★★★
//  【为什么又打开 —— 新的事实】单层时它不必开，双层重叠时必须开：
//    · 两个图片框竖直不重叠时，两层共用同一套 (x,y) 扫描，**永远不会同时有请求在飞**
//      ⇒ TX 段只用掉一半（~160 组/行 vs 88 拍容量），组与组之间有空档，
//        显示读的回程阴影被 TX_LEAD_GAP=8 挡住就够，忙窗落在空档里，无代价。
//    · 一旦有行重叠（哪怕 1 行），两层同时要货 ⇒ TX 段被填满、组与组首尾相接
//      ⇒ 任何忙窗（读回程尾巴 / 写换向 / 控制器内部刷新）都必然落在**某一组中间**。
//      此时 `tx_busy_blk=0` 会让这一组照发，控制器把它按"显示组首+相位"重排
//      ⇒ 纹理命令读回的是**帧缓存内容** ⇒ 图片框里混进屏幕别处的像素
//      （板上现象：任意一行重叠就"干扰"，而且错的是框外内容）。
//  【代价】组在飞时撞忙 → 冻结整表（tx_stall，见 §2）⇒ 这段时间各口都停，
//    但时隙表不消耗时间 ⇒ 配额不丢。按 12.4 次/行的读回程阴影、每次 5~11 拍估，
//    损失约 3%；双层重叠行本来就是"需求 320 组 > 供给 286 组"，会再多停一点。
//  【回退】改回 0 即恢复"完全不看 Sdr_busy"（只允许单层时用）。
localparam integer TX_BUSY_GUARD = 1;      // 1 = 只在"开新组"看忙（组内绝不看）／0 = 完全不看

// ★ build N6 已回退 build N5 的 busy 实验（花屏）：Sdr_busy 仍按原判据，
//   纹理开组继续用通用闸门 ctrl_ok。
wire tx_busy_blk = (TX_BUSY_GUARD != 0) && Sdr_busy;
// ★★ 2026-10-21 build 100M-22：组内撞忙 **不再冻结整表** ★★
//   【板上事实】100M-20 把"组内撞忙"做成冻结整表（hold 含 tx_stall）后：
//       · 双图层重叠的框内干扰没了（说明"组首避开忙窗"这条策略有效）
//       · 但出现纯白竖带（整列内容缺失）+ 掉帧到 30fps
//   【为什么白带】真控制器的 4 命令分组是"读口上连续的 4 条命令"：
//       冻结把一组的 4 条拆到两段时间里去发 ⇒ 后几条被当成"新组的组首"，
//       控制器用它们自己的地址当 head，再按 head+ph 重算后 3 条 ⇒
//       读回的是 base+1..base+4（错位 1 组），落到帧缓存区 —— 而背景是白的，
//       于是"整列纯白"。而且冻结相位每轮固定 ⇒ 同一列每行都错 ⇒ 竖带。
//   【为什么掉帧】Sdr_busy 在真机上是"控制器正在干活"（读回程/刷新/换向都拉高），
//       占空比远高于仿真的 0.4%。组内一撞就冻结整表 ⇒ RD/WR 一起停 ⇒ 帧时超期。
//   ⇒ 定稿规则：**一个组的 4 条命令必须 4 拍连续发完，中间不许任何停顿**。
//      忙只用来决定"这一组能不能开始"（tx_start 的 !tx_busy_blk），
//      一旦开始就一路发完；显示读的阴影由 TX_LEAD_GAP=8 的确定性静音挡掉。
//   tx_stall/freeze_cnt 保留，只做诊断读数（dbg_sel=15），不再进 hold。
wire tx_stall    = tx_act && tx_busy_blk;  // 仅诊断：本拍"组在飞且忙"
wire tx_hold     = tx_stall;               // 诊断别名（TB 的 n_hold 数的是它）
wire hold = ((BUSY_HOLD != 0) && Sdr_init_ref_vld);   // 只让刷新冻结（手册硬性要求）

// 冻结看门狗（>64 拍才放弃等待）
reg [6:0] freeze_cnt;
always @(posedge clk or posedge rst) begin
    if (rst)            freeze_cnt <= 7'd0;
    else if (!tx_stall) freeze_cnt <= 7'd0;
    else if (freeze_cnt != 7'd127) freeze_cnt <= freeze_cnt + 7'd1;
end
wire tx_freeze_long = (freeze_cnt >= 7'd64);

//==============================================================================
//  ★★ build F4（甲）：控制器"此刻能不能收下一条命令" ★★
//==============================================================================
//  `Sdr_init_ref_vld`：手册 §2.3 明确要求"等它变低再操作"，无条件生效。
//  `Sdr_busy`       ：手册 §7 第 3 条要求"每次读写操作前先判断忙不忙"，
//                     但它字面上是"控制器正在干活"，用它**无条件冻结整表**会把表按死
//                     （build 1 的教训）。
//  ★ 100M-18 的折中 ★
//    · 起组：Sdr_busy 高就不开新组（只会少开，不会把表按死）
//    · 组内：Sdr_busy 高就冻结整表（tx_stall，见上）—— 范围限定在"一个 4 字组
//      从发出第 1 条到最后一条"的窗口内，最多几十拍，且是唯一能保住分组相位的做法
//    · 关闭：TX_BUSY_GUARD = 0 时上面两条同时失效（回到 100M-16 之前的裸发）
//==============================================================================
//==============================================================================
//  ★★ build F：起组前要求"刷新结束后已经安静 4 拍" ★★
//==============================================================================
//  【为什么】4 字组的 4 条命令**必须连续 4 拍发完**：组内第 2~4 条命令的地址会被
//  控制器用"组首 + 它自己的 4 拍相位"重算。只要组被 `stall`（刷新冻结）从中间
//  切开，第 4 条命令就会落在控制器的另一个相位上 ⇒ 取回同组里**错位的那个字**。
//  这是"组级"的错，无法从上层发现（计数仍然 1:1）。
//
//  【为什么不能直接把冻结推迟到组边界】那样组能连续，但会把 4 条命令一起塞进
//  刷新窗口；控制器若拒收一条，`Sdr_rd_en` 就少一拍 ⇒ **标签环永久错位** ⇒
//  比"一个字错"严重得多。所以不能动 `stall` 的时机。
//
//  【所以只能从"起组的时机"下功夫】刷新是周期性的（约 3906 拍一次，窗口约 20 拍），
//  起组又只发生在 `ph[1:0]==0`。最坏的情况是"组正好起在窗口刚打开那一拍"，
//  4 条命令全挤在窗口里。改成：**必须连续 4 拍没见过刷新，才允许起组**。
//  这样至少排除掉"贴着窗口边缘起组"这一种最坏对齐，代价是每次刷新后
//  ～4 拍不能起新组（492 次/帧 × 4 拍 ≈ 0.1% 的时间，可忽略）。
//==============================================================================
reg [2:0] ref_quiet;                 // 连续几拍没见过刷新（饱和到 4）

always @(posedge clk or posedge rst) begin
    if (rst)
        ref_quiet <= 3'd0;
    else if (Sdr_init_ref_vld)
        ref_quiet <= 3'd0;
    else if (ref_quiet != 3'd4)
        ref_quiet <= ref_quiet + 3'd1;
end

wire ref_settled = (ref_quiet == 3'd4);

//==============================================================================
//  ★★★ build O：起组前要求 `Sdr_busy` 也"安静 4 拍"（修"忙窗口撞突发"）★★★
//==============================================================================
//  【板上证据（build N 调度器 bank 读数）】
//      g_start = 76,800/帧      （4 条命令/组 ⇒ 307,200 条命令/帧）
//      g_cut   = 0              ⇒ 组从来没被切开（"槽 8 开组"假设证否）
//      addr_out= 0              ⇒ 地址永远在纹理槽内（地址假设证否）
//      ref_cmd = 0              ⇒ 没在刷新窗口发过命令
//      beat_nt = 0              ⇒ 没有无标签回拍
//      busy_cmd≈ 4,000          ⇒ **1.3% 的纹理命令是在 `Sdr_busy` 高的时候发出去的**
//  ⇒ 命令流/地址流/标签流全干净，只有"忙窗口"这一条通道还开着。
//  ⇒ 与垃圾组数（≈1,450 组/帧 ≈2%）同量级。
//
//  【为什么会有这一条】`ctrl_ok`（含 `!Sdr_busy`）只门控"开组那一拍"，
//  组内第 2~4 条命令走的是 `tx_cmd = tx_go && tx_slot && !stall`，**不看 ctrl_ok**。
//  于是只要 `Sdr_busy` 在组内拉高，后面几条就落进了控制器不收/不解的窗口
//  ⇒ 控制器按自己的相位/序列化处理 ⇒ **整个突发 4 个字一起错**（正是 run_last=4）。
//
//  【为什么不去给 tx_cmd 加 ctrl_ok】那会把组切断（`g_cut` 会从 0 变成非 0），
//  变成"只有 3 条命令的组"，反而更糟。所以只能从**起组时机**下手。
//
//  【代价】`Sdr_busy` 只占 1~2% 的时间 ⇒ 每次忙窗口后多等最多 4 拍，可忽略。
//==============================================================================
reg [2:0] busy_quiet;

always @(posedge clk or posedge rst) begin
    if (rst)
        busy_quiet <= 3'd0;
    else if (Sdr_busy || Sdr_init_ref_vld)
        busy_quiet <= 3'd0;
    else if (busy_quiet != 3'd4)
        busy_quiet <= busy_quiet + 3'd1;
end

wire busy_settled = (busy_quiet == 3'd4);

// ★ build P：撤掉 busy_settled ★
//   板上实测（build O）：`hd3p` 仍是 FFF（没治好），而 `busy_cmd` 从稳定的 F8x 变成乱跳
//   ⇒ 这一刀无效，还可能把开组饿着。先撤回，避免干扰后面的判断。
//   （`busy_quiet` 逻辑保留但不再参与 ctrl_ok，`busy_cmd`/`busy_mid` 读数保留备查。）
//==============================================================================
//  ★★★ build U：起组要避开"下一次刷新"（修"刷新窗口落在一组 4 条命令中间"）★★★
//==============================================================================
//  【板上证据链】
//    · 停掉显示读后仍有 `tex_bad ≈ 1930` 字/帧（0.63%）
//    · 组相位 `ph_off` 扫 0/1/2/3，`hd3p` 全是 FFF ⇒ **与相位无关**
//    · 算一下刷新：周期 3906 拍、窗口约 20 拍、一组 4 拍
//          P(一组撞刷新窗口) = (4+20)/3906 = 0.61%
//          每帧 76,800 组 × 0.61% ≈ 468 组 ≈ 1,874 字
//      实测 1930 字 —— 差 3%，不是巧合
//  ⇒ **一个刷新窗口落在一组的 4 条命令中间，那一组的 4 个字全废。**
//    这也解释了"与相位无关、与写无关、一次坏一整组 4 个字"。
//
//  【原来只有"刷新后安静 4 拍"（ref_settled），缺的是"刷新**开始前**也要避开】
//    刷新是周期性的 ⇒ 用"距上次刷新多少拍"就能预测下一次什么时候来：
//      离上次刷新 > 8 拍（已过） 且 离下次刷新 > 8 拍（还远）⇒ 才允许起组/起突发
//    代价：每个刷新周期里被挡掉约 16 拍（16/3906 = 0.4%），可忽略。
//
//  【为什么是 8 拍】一组 4 条命令 + 换向余量，8 拍足够覆盖；取大了会白等，取小了挡不住。
//  ★ 如果 REF_INTERVAL 和实际刷新周期不一致，这个窗口只会"少挡"或"多挡一点"，不会卡死 ★
//==============================================================================
//  ★ 100MHz 版：SELF_REFRESH_INTERVAL = 64e6/10/2048 = **3125** 拍（31.25us）
//    2026-10-21 build 100M-18 从 125MHz（3906）回退。ref_far 已撤销，这个数只用于
//    读数对照（ref_max），但必须跟真实周期一致，否则以后重新启用预测时会差 25%。
localparam integer REF_INTERVAL = 3125;   // 与 global_def 的 SELF_REFRESH_INTERVAL 一致（100MHz）
localparam integer REF_GUARD    = 8;

reg [12:0] ref_cnt;

always @(posedge clk or posedge rst) begin
    if (rst)
        ref_cnt <= 13'd0;
    else if (Sdr_init_ref_vld)
        ref_cnt <= 13'd0;                       // 刷新时刻 → 清零
    else if (ref_cnt != 13'd8191)
        ref_cnt <= ref_cnt + 13'd1;
end

// ★ 实测刷新周期：ref_cnt 的最大值 = 相邻两次刷新的间隔（用来核对 REF_INTERVAL）
reg [12:0] ref_max;
always @(posedge clk or posedge rst) begin
    if (rst) ref_max <= 13'd0;
    else if (ref_cnt > ref_max) ref_max <= ref_cnt;
end

wire ref_far = (ref_cnt > REF_GUARD[12:0]) &&
               (ref_cnt < (REF_INTERVAL[12:0] - REF_GUARD[12:0]));

// ★★ build U 的 ref_far 已撤销 ★★
//   板上实测：`ref_max` 顶到 0xFFF（12 位截断，真值 ≥4095）⇒ `Sdr_init_ref_vld`
//   几乎从不拉高（刷新是控制器**内部自动**做的，这个信号只在初始化时有效）。
//   于是 ref_cnt 一路涨过 3898 之后 ref_far 永久为假 ⇒ ctrl_ok 恒 0
//   ⇒ 一条命令都不发 ⇒ **全黑、数码管状态码 b**。
//   ⇒ "用刷新做前视"这条路不成立，撤销，恢复原状。
wire ctrl_ok = !Sdr_init_ref_vld && !((BUSY_GATE != 0) && Sdr_busy) && ref_settled;


// ★★ 4 字组相位必须跟"自由跑的时钟相位"重新对齐（2026-10-18 新增）★★
//  【为什么必须有这一条】冻结时隙表会把本表的相位（ph[1:0]）和**外部时钟相位**
//  拉开一个固定差（冻结了几拍就差几拍）。厂商规则是按"每 4 个时钟"分组的：
//  组内第 2~4 条命令的地址会被控制器用"组首 + 相位"自己算 —— 相位一旦对不上，
//  我们发的地址就被忽略，取回别处的数据。
//      model/sdr_as_ram_sim.v 的 PHASE_MODE=1 就在模拟这件事：
//      只加 Sdr_busy 忙停止、不做相位复位时，实测 grp_bad=5733（全错）、err_tx 7288。
//
//  【怎么修】ph4 = 自由跑的 2 位计数器（永远 +1，不受忙停止影响）。
//  正常情况下 ph4 与 ph[1:0] 逐拍相同（都是每拍 +1）；一旦被冻结，两者差 Δ。
//  只要"不等就不发命令、时隙表也停"，差的这几拍就会自己走回来：
//  ph4 继续跑、ph 停住 ⇒ 差每拍减 1 ⇒ ≤3 拍后重新相等，恢复发命令。
//      · BUSY_HOLD=0 时 ph4 永远等于 ph[1:0] ⇒ stall 恒 0 ⇒ 与以前逐拍完全一致
//      · 代价：每次忙窗口结束后最多补 3 拍（0.08% 的时间）
//      · 顺带还修掉一个隐患：任何原因造成的不连续都不会再破坏分组相位
reg  [1:0] ph4;
always @(posedge clk or posedge rst) begin
    if (rst) ph4 <= 2'd0;
    else     ph4 <= ph4 + 2'd1;
end
// ★ 100M-23 试过"组在飞时冻结 ph4"：**会死锁**，已回退，别再试 ★
//   tx_act=1 时 ph4 停 ⇒ 若此时 ph4 != ph[1:0]，stall 永远等不到相等 ⇒ ph 也停
//   ⇒ 组发不出去 ⇒ tx_act 永不清 ⇒ 整表停死（实测：组数掉到 1、写 0 字/行）。
//   ⇒ 正确结论：ph4 必须自由跑；它保证"每次停顿都是 4 拍的整数倍"，
//     而 4 的整数倍停顿对控制器是无害的（严格口径 PHASE_MODE=1 实测 0 组错）。

// ★ 100M-22：**不要在组内改 stall 的定义**（试过 `stall & ~tx_act`：模型里读流
//   会和期望队列错开 2 个字，数据错 2.8 万字 —— 说明 stall 同时承担"显示读突发
//   与 4 拍网格对齐"的职责，不能局部停）。所以 stall 保持原样，只把"忙"从
//   `tx_cmd` 里删掉：忙不再能切开一个组，而 4 拍网格的再对齐仍按时发生。
wire stall = hold | (ph4 != ph[1:0]);

always @(posedge clk or posedge rst) begin
    if (rst) begin
        slot <= 4'd0;
        ph   <= 4'd0;
    end else if (!stall) begin
        ph <= ph + 4'd1;
        if (ph == 4'd15)
            slot <= slot + 4'd1;      // 4 位自然回绕 = 0..15
    end
end

// ★ build F：组内相位（带偏移）。下面所有"组内偏移"与"组首判据"都用它。
//   `ph[1:0] - ph_off` 在 2 位里自然模 4 回绕。ph_off=0 时与以前逐拍等价。
// ★ 100M-16：ph_off 用【静默时锁存】的 ph_off_q（review 问题 20）——
//   在途命令必须按发出时的相位处理；只在标签环空、各突发都不在飞时采样
//   （帧间自然满足），帧内漂移不影响已经在飞的组。
reg  [1:0] ph_off_q;
reg  [1:0] tx_ph_off_q;                 // ★ 实验 2：纹理组专属相位 ★
reg        rd_lag_q;
reg  [3:0] exp_mode_q;
wire [1:0] ph_eff = ph[1:0] - ph_off_q;
wire [1:0] tx_ph_eff = ph[1:0] - tx_ph_off_q;   // 纹理组相位（与显示解耦）

// ★ 100M-16：标签环占用（review 问题 7）—— 声明提前到这里，因为 rd_go 和
//   tx_start 的 tag_room 要用；驱动 always 块还在原位置（tag_we_q 之后）。
//   读写指针相等既是空也是满 ⇒ 原来只当空用，环满时会静默覆盖身份。
//   结构上在飞量 ≈ 读延迟（~24 条）<< 256，本来就满不了；这里加一道硬闸：
//   没空位就不许发新的读命令（rd/tx 的"启动"点都查），从根上消除覆盖可能。
//   在飞突发中途不查（rd_run 已启动的 128 条突发不能被拦断）—— 占用受读
//   延迟约束，起头时有空位 ⇒ 整段突发期间也不会满。
reg  [9:0] tag_occ, tag_occ_max;
wire        tag_room = (tag_occ <= ((10'd1 << TAG_AW) - 10'd8));

//  ★ own 是寄存器 ★：命令输出（App_rd_en/addr、App_wr_*）只由寄存器驱动，
//    避免出现"槽号 → 查表 → mux → 端口"的长组合路径（旧版就是死在类似路径上）。
reg  [2:0] own;
wire [3:0] slot_nxt = slot + 4'd1;           // 4 位自然回绕
//  ★ 槽 15：装载期间 = LD（写装载数据），装完之后 = ID（写段→读段的换向缓冲）★
//  装载器 FIFO 一空（ld_wr_vld=0）就自动变回 ID，所以运行期等于白捡了一个 ID 槽。
//  ★ build 100M-5：暂存缓冲里还有 4 个字（ld_buf_v=1）时，槽 15 也必须保持 LD ——
//    否则最后 4 个字会卡在暂存里发不出去（FIFO 已经空了，槽 15 变 ID）。
