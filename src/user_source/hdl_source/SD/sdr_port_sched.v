//    从此永久错位 ⇒ 后续每个组的组首字被按"上一组+相位"重算 ⇒
//    签名实验的指纹（top_bin=12：每 4 组的组首字坏）正是这条漂移。
//  【修法】重试从第 k 个偏移接着发（k = 中断时的 gph），只发剩下的 4-k 条：
//    每个逻辑组的命令总数恒 = 4，4 命令分组永不漂移；且余项偏移是连续后缀
//    k..3（中断只可能发生在前缀发完之后），地址 base+k..base+3 顺序递增，
//    控制器"组首+相位"重算的结果与我们发的完全一致。
reg  [1:0]  tx_retry_k;              // 重试起始偏移（中断时的 gph = 已发条数）
wire [1:0]  tx_skip  = tx_retry_v ? tx_retry_k : 2'd0;
wire [1:0]  gph_eff  = tx_start ? tx_skip : gph;
wire [20:0] tx_addr  = tx_start ? {tx_req_a[20:2], tx_skip}
                                : {tx_base[20:2],  gph};

// ★ build F：这一条命令"属于哪一层、这组里这个字要不要" —— 逐命令决定，随标签走 ★
//    ★ 100M-16：掩码索引也用 gph_eff（与地址同源，见上）★
//    ★ 必须在标签环之前声明（第 9 节的 always 要用）★
wire [3:0] cur_mask = tx_start ? tx_req_m : tx_mask;
wire       cur_lay  = tx_start ? tx_req_l : tx_layer;
wire       cur_want = cur_mask[gph_eff];

//==============================================================================
//  ★★ 2026-10-21 build 100M-17：忙保护改成"能等就等"（hold），不再动不动 abort ★★
//==============================================================================
//  【为什么必须改】abort→retry 的账不是"一条命令"，而是：
//        已发的余项作废 + 等下一个 4 拍对齐起点（最坏跨到下一轮 176 拍）
//        + 重试优先于新组（抢走一个新组起点）
//    忙窗多数只有 1~3 拍（换向尾巴、刷新前后），等一等完全装得下 ⇒ 白赔 1~2 组。
//  【hold 为什么不破坏契约】控制器按"每 4 条命令一组、组首地址采纳、后 3 条按
//    组首+组内序号重算"分组 —— 它只数**条数**和 **base+j**，不管这 4 条之间隔
//    几拍。abort/retry 本来就会在组内留空隙，hold 只是把空隙留在原地、且不消耗
//    重试项，重发条数恒为 0 ⇒ mod-4 不变式更稳。
//  【abort 只在两种情况下发生】
//    ① 忙到"本 TX 窗口剩余拍数装不下余项"（连槽 10 借的 4 拍也不够）
//    ② 组被带出了 TX 窗口（兜底，正常不会发生）
//    ★ stall（刷新冻结）不再 abort：冻结期间 ph 不动，解冻后原地接着发即可 ★
//==============================================================================
reg  [3:0] tx_issued_mask;
always @(*) begin
    case (gph)
        2'd0:    tx_issued_mask = 4'b0000;
        2'd1:    tx_issued_mask = 4'b0001;
        2'd2:    tx_issued_mask = 4'b0011;
        default: tx_issued_mask = 4'b0111;
    endcase
end
// ★ 还差哪几个偏移没发 —— 只看"发没发"，与"这层要不要"无关 ★
//   （原写法用 tx_mask & ~issued 当重试条件：一组 mask=0001 在 gph=1 被中断时，
//     余项掩码=0 ⇒ 不重试 ⇒ 这个逻辑组只发 1 条命令 ⇒ mod-4 直接漂移。
//     守卫越忙这个洞越常踩，必须用 issued 掩码。）
wire [3:0] tx_issue_left = 4'b1111 & ~tx_issued_mask;

// ★ 100M-18：abort 只剩两路 —— ① 组被带出 TX 窗口（冻结机制下不可能发生，
//   纯兜底）② 冻结看门狗超时（>64 拍，只防控制器卡死）。正常运行时恒为 0，
//   所以"重试"这条会改变全局分组相位的路径在真机上不会被走到。
wire tx_abort = tx_act && (!tx_win || tx_freeze_long);
wire       tx_complete = tx_cmd && (gph_eff == 2'd3);

always @(posedge clk or posedge rst) begin
    if (rst) begin
        tx_act   <= 1'b0;
        tx_base  <= 21'd0;
        tx_mask  <= 4'd0;
        tx_layer <= 1'b0;
        tex_lr   <= 1'b0;
        gph      <= 2'd0;
        tx_retry_v <= 1'b0;
        tx_retry_a <= 21'd0;
        tx_retry_m <= 4'd0;
        tx_retry_l <= 1'b0;
        tx_retry_k <= 2'd0;
    end else if (tx_start) begin
        // ★ 重试时从 tx_skip 接着发（只发余项 4-k 条）；skip=3 ⇒ 本拍即整组完 ★
        tx_act   <= (tx_skip != 2'd3);
        tx_base  <= {tx_req_a[20:2], 2'b00};
        tx_mask  <= tx_req_m;
        tx_layer <= tx_req_l;
        tex_lr   <= tx_req_l;
        gph      <= tx_skip + 2'd1;             // 起始拍已用掉 tx_skip（skip=3 回 0，但 tx_act=0）
        if (tx_retry_v)
            tx_retry_v <= 1'b0;                 // 重试项已取出
    end else if (tx_complete) begin
        // 只在第 4 条命令实际发出后结束本组；若中途停顿，由 tx_abort 保存余项重试。
        tx_act   <= 1'b0;
    end else if (tx_abort) begin
        // 已发拍仍按标签正常回送；重试只补发未发的偏移（k..3），保持命令数 mod 4 = 0。
        tx_act   <= 1'b0;
        // ★ 100M-17：判据用 issued 掩码（4'b1111 & ~issued），不能用 want 掩码 ★
        if (tx_issue_left != 4'd0) begin
            tx_retry_v <= 1'b1;
            tx_retry_a <= tx_base;
            tx_retry_m <= tx_mask;              // 投递掩码照抄，只重发偏移 k..3
            tx_retry_l <= tx_layer;
            tx_retry_k <= gph;                  // 中断时已发 gph 条 ⇒ 从偏移 gph 继续
        end else begin
            tx_retry_v <= 1'b0;
        end
    end else if (tx_cmd) begin
        gph      <= gph + 2'd1;              // 组内相位自己走
    end
end

// 组首即把请求所有权交给调度器；中断后的剩余偏移由本地重试项负责。
// ★ build FIFO-Q 段 4：ack 的语义变了 —— 从"tx_start 收下这组"改成"成功入队"。
//   这是反压的命脉：请求侧靠 ack 推进，如果队列满了还照回不误，它会一直推、
//   队列爆掉。所以只有入队成功（未满）才回 ack，满了就自然停住。
assign tex_req_ack = {tq1_en, tq0_en};

//==============================================================================
//  A-4 续：有界连发的 run 计数器（放在这里是因为要用 tx_start / tx_retry_v）
//  ★ 实验 B：同时维护 run_addr_q = "下一组应有的地址"，供 tx_run_cont 判连续 ★
//==============================================================================
always @(posedge clk or posedge rst) begin
    if (rst) begin
        run_left   <= 4'd0;
        run_layer  <= 1'b0;
        run_addr_q <= 19'd0;
    end else if (tx_start && !tx_retry_v) begin
        // 无论继续还是新开 run，都把"下一组"的地址索引记账本上：
        // 下一组若真是 本组+4，[20:2] 就正好 +1 ⇒ tx_run_cont 成立。
        run_addr_q <= tx_req_a[20:2] + 19'd1;
        if ((run_left != 4'd0) && (tx_req_l == run_layer))
            run_left <= run_left - 4'd1;              // 继续本 run
        else begin
            run_layer <= tx_req_l;                    // 开一个新 run
            run_left  <= TX_RUN_N - 4'd1;
        end
    end else if (!tx_slot) begin
        // ★ 保险：run 不跨 TX 窗口。窗口起点是"跳址风险 + 长空档后重建分组"的位置，
        //   必须重新看一次忙。清掉 run_left 后，窗口第一组会走完整的守卫检查。
        //   代价：每窗口多一次检查 ⇒ 税 ≈ 46%/22 ≈ 2%，可忽略。
        run_left <= 4'd0;
    end
    // 重试（tx_start && tx_retry_v）不算新组、也不消耗 run 额度 ⇒ 不改动
end

//==============================================================================
//  5b. 借槽决策（实验 K：粒度从"整回合"降到"单槽"）
//==============================================================================
//  【判据】"下一个槽 TX 用不用得上"，用 3 个来源的或（都是最上游的"要货"）：
//      tx_act       组在飞（4 条必须连续发完）
//      t_pre_v      已寄存、还没开组的请求
//      tex_req_vld  图层请求 FIFO 队首有效（最上游的"要货"信号）
//  ⇒ 任一为 1：下一槽归 TX；全为 0：下一槽借给 WR。
//
//  【为什么把粒度从"整回合"改成"单槽"】
//      整回合粒度下，只要这一回合里出现过**一次**纹理需求，整个回合的 4 个 TX 槽
//      就全部不借 —— 而实际上常常只有 1~2 个槽在被用，其余是空着的。
//      板上数据正是这样：写口 6 槽后 0x2A 掉到 432（−66%），但 TX 少一槽让
//      0x2B 从 306 涨到 1111，总等待几乎没动（1562→1543）⇒ 纯零和搬家。
//      逐槽后，闲的 TX 槽能真正借出去，忙的那一刻立刻收回，不再是整回合互斥。
//
//  【毛刺怎么办】原设计靠"累计一整轮"滤掉 `t_pre_v` 换项那一拍毛刺。
//      逐槽后同样的毛刺只白丢 **1 个槽（16 拍）**，而不是原来的 5 个槽（80 拍）
//      ⇒ 抖动代价反而降到 1/5，所以不需要再额外滤。
//
//  【为什么不会死锁】借槽期间 `tx_slot=0` ⇒ `tx_start=0` ⇒ 纹理组发不出去
//      ⇒ `tex_req_vld` 保持为 1 ⇒ 下一个槽边界判据就是 1 ⇒ 立刻收回。
//      最坏只丢 1 个槽，比原来的 1 整轮快 5 倍。
//
//  【生效范围】`borrow_slot` 只对槽 5..7 生效，所以 `wr_borrow` 在别的槽边界
//      更新也无害；槽 4 边界那次正好决定槽 5，是有效的那一次。
//  【回退】把最后的 else-if 改回"回合边界 (slot==15&&ph==15) + !tx_seen"。
//==============================================================================
// ★ build FIFO-Q 段 5：请求进队列后 tex_req_vld 就归 0 了，必须把"队列非空"
//   也算成纹理忙，否则借槽判闲会误判成"纹理空闲"、把 TX 槽借给写口 ⇒ 纹理饿死。
wire tx_busy_now = tx_act || t_pre_v || (|tex_req_vld) || !tq0_empty || !tq1_empty;

//**************************************************************************
//  ★★★ 安全阀：本槽内发过 TX 命令 ⇒ 下一槽**绝不**借给 WR ★★★
//**************************************************************************
//  【不加它会怎样】只看 `tx_busy_now` 有一个致命窗口：
//      槽 4 ph15 发出最后一条纹理读命令，而请求 FIFO 正好在那拍被取空
//      ⇒ 下一个槽边界上 `tex_req_vld` 已经是 0 ⇒ tx_busy_now=0 ⇒ 槽 5 借给 WR
//      ⇒ 读（槽4 ph15）→ 写（槽5 ph0）**只隔 1 拍** ⇒ 读→写红线（≥16）当场破
//      ⇒ 白条立刻回来。
//  【为什么"本槽发过命令就不借"就够了】槽 4 不发读命令时，最近的读命令必然
//      在槽 3 或更早 ⇒ 槽3 ph1x → 槽5 ph0 至少隔了槽4 整槽 16 拍 ⇒ ≥16 ✓
//      槽 5/6/7 同理：只要"上一个 TX 槽"没发命令，间隔就一定够。
//  【置位优先】ph==15 那一拍既可能 tx_cmd=1 又命中断言清零 —— 必须让置位赢，
//      否则本槽最后一条命令会被漏记。所以 `tx_cmd` 分支写在 `ph==15` 之前。
//**************************************************************************
reg tx_in_slot;
always @(posedge clk or posedge rst) begin
    if (rst)             tx_in_slot <= 1'b0;
    else if (stall)      tx_in_slot <= tx_in_slot;      // 冻结：保持
    else if (tx_cmd)     tx_in_slot <= 1'b1;            // 置位优先
    else if (ph == 4'd15) tx_in_slot <= 1'b0;           // 槽边界清
end

always @(posedge clk or posedge rst) begin
    if (rst) begin
        wr_borrow <= 1'b0;
    end else if (stall) begin
        // 冻结：时隙表不前进，决策原地保持（与 own/slot 同口径）
        wr_borrow <= wr_borrow;
    end else if (ph == 4'd15) begin
        // ★ 槽边界：为"下一个槽"做一次决定（slot_nxt = slot+1，时序正好对上）
        //   两个条件都要满足才借：下一槽确实没纹理活 + 本槽没发过纹理命令
        wr_borrow <= (WR_BORROW_EN != 0) && !tx_busy_now && !tx_in_slot;
    end
end

//==============================================================================
//  6. 装载写：LD 槽 —— "4 字暂存 + 撞忙重发"
//==============================================================================
wire ld_slot  = (own == OWN_LD);
//
//  【为什么不再"边发边弹 FIFO"】
//   build 100M-4 板上三个数把范围锁死了：
//       tex_bad   ≈ 50,000（16.3%）
//       ld_busy   ≈ 55,000（装载期"写命令撞 Sdr_busy"的拍数）
//       ld_occ_max = 9 / 16 ⇒ 装载 FIFO 从没满过，装载器一个 push 都没丢
//   两个独立统计落在同一量级 ⇒ **控制器在忙窗口里把写命令吞了**。
//   旧实现是"发一拍、弹一个字"：被吞的那一拍，字已经从 FIFO 弹走 ⇒ 永久留洞。
//
//  【新结构】
//   ① 取数（与 SDRAM 时序无关）：FIFO 里 ≥4 个字时，连续 4 拍搬进 hbuf[0..3]，
//      同时 `ld_wr_ack` 弹 4 个字，搬完置 `ld_buf_v`。
//   ② 发组：LD 槽 ph_eff==0 且 !Sdr_busy 时，用 hbuf 的 4 个字发一组 4 拍。
//   ③ 这 4 拍里**任何一拍** Sdr_busy 拉高 ⇒ 本组作废，hbuf 保持有效，
//      下一轮用**同样的 4 个字**重发；只有整组干净才 `ld_buf_v <= 0`。
//   ⇒ 被忙窗口吞掉的那一组，数据还在 hbuf 里，一个都不会丢。
//   代价：装载时间最坏翻倍（约 0.2s → 0.4s），上电无感。
//
//  【为什么重发是安全的】同一组 4 个字写两遍，写的是同样的数据到同样的地址，
//   幂等。所以"疑似被吞"就重发，不需要知道控制器到底收没收到。
//
//  【槽尾仍然留 4 拍】ph[3:2]!=3 保持 100M-2 的结论（写→读换向空档），
//   两组保护叠加，互不冲突。
//==============================================================================
reg [52:0] hbuf [0:3];         // {addr[20:0], data[31:0]} × 4
reg [1:0]  fcnt;               // 取数拍号
reg        ld_fill;            // 正在取数
reg        ld_iss;             // 正在发组
reg [1:0]  icnt;               // 发组拍号
reg        ld_try_busy;        // 本组期间见过 Sdr_busy
reg [3:0]  ld_retry;           // 连续重发次数（兜底防卡死）

//------------------------------------------------------------------------------
//  ★ build 100M-8：空位补写 + 写降速
//------------------------------------------------------------------------------
//  【空位补写要解决什么】如果坏字的成因是"写拍流里每 16 拍丢 1 拍"（与地址无关），
//  那么把纹理排成 12/16 稀疏还不够 —— 丢的那一拍会落到某个真字上。
//  补 4 个空拍以后，每个 16 拍窗口正好是 12 真 + 4 空，丢的那一拍落在空拍上，
//  真数据一个字都不少。
//  空拍写到哪里无所谓（没人读），固定写 0x1F0000..3，写得对不对都不看。
//
//  【为什么由本模块补，而不是让装载器多推 4 个字】
//  装载器的数据来自 SD 卡，`bmp_data_wr_en` 来了就得收，中间插不进 4 拍停顿；
//  而本模块本来就"攒 4 个字再发"，补一组空拍只是多走一遍同样的流程。
//------------------------------------------------------------------------------
reg [1:0]  ld_real3;           // 本块已发的真组数（0/1/2）
reg        ld_dum_need;        // 该补一组空写了
reg        buf_is_dum;         // hbuf 里当前这组是空组

wire ld_fifo_ok = (ld_wr_used >= 5'd4);      // 保守值（同步过来的计数），够 4 个字才取

// 取数组的选择与条件：
//   · 已经欠着一组空写（ld_dum_need=1）⇒ 取空组，不需要等 FIFO
//   · 否则取真组，必须 FIFO 里够 4 个字
wire ld_dum_pick = ld_dum_need;
wire ld_can_fill = !ld_fill && !ld_buf_v && (ld_dum_pick || ld_fifo_ok);

// ★ 写降速（fm_slow）已删除：它压不住坏字，只是把装载拖慢一倍。
wire ld_iss_start = ld_buf_v && !ld_iss && ld_slot && !stall && ctrl_ok
                    && (ph_eff == 2'd0) && (ph[3:2] != 2'd3) && !Sdr_busy;

assign ld_iss_act = ld_iss || ld_iss_start;  // 共 4 拍：起始拍 + 3 个寄存拍
wire [1:0] ld_idx = ld_iss ? icnt : 2'd0;

wire       ld_wr_ack_i = ld_fill && !buf_is_dum;   // 空组不弹 FIFO
assign     ld_wr_ack   = ld_wr_ack_i;

always @(posedge clk or posedge rst) begin
    if (rst) begin
        ld_fill <= 1'b0; fcnt <= 2'd0;
        ld_buf_v <= 1'b0;
        ld_iss  <= 1'b0; icnt <= 2'd0; ld_try_busy <= 1'b0;
        ld_retry <= 4'd0;
        ld_real3 <= 2'd0; ld_dum_need <= 1'b0; buf_is_dum <= 1'b0;
    end else begin
        // ---- ① 取数：4 拍搬进 hbuf，同时弹 FIFO（空组则不弹）----
        if (ld_can_fill) begin
            ld_fill    <= 1'b1;
            fcnt       <= 2'd0;
            buf_is_dum <= ld_dum_pick;           // 这一组是空的还是真的，取数时就定下
        end else if (ld_fill) begin
            hbuf[fcnt] <= buf_is_dum ? {DUMMY_ADDR + {19'd0, fcnt}, 32'h0000_0000}
                                     : {ld_wr_addr, ld_wr_data};
            if (fcnt == 2'd3) begin
                ld_fill  <= 1'b0;
                ld_buf_v <= 1'b1;                // 4 个字齐了
            end else
                fcnt <= fcnt + 2'd1;
        end

        // ---- ② 发组 / ③ 判定 ----
        if (ld_iss_start) begin
            ld_iss      <= 1'b1;
            icnt        <= 2'd1;                 // 起始拍已经用掉 idx=0
            ld_try_busy <= Sdr_busy;             // 起始拍已要求 !busy，这里恒 0
        end else if (ld_iss) begin
            if (Sdr_busy) ld_try_busy <= 1'b1;
            if (icnt == 2'd3) begin
                ld_iss <= 1'b0;
                // 整组 4 拍都没撞忙 ⇒ 这 4 个字算写成功；否则保留，下一槽重发
                if (!(ld_try_busy || Sdr_busy) || (ld_retry == 4'd15)) begin
                    // （连续 16 次都不干净就"认了"—— 宁可留几个洞，也不能让装载卡死）
                    ld_buf_v <= 1'b0;
                    ld_retry <= 4'd0;
                    if (buf_is_dum) begin
                        ld_dum_need <= 1'b0;     // 空组发完，欠账清掉
                    end else begin
                        // 真组发完：数满 3 个就欠一组空写（12 真 + 4 空 = 16 拍）
                        if (ld_real3 == 2'd2) begin
                            ld_real3    <= 2'd0;
                            ld_dum_need <= 1'b1;
                        end else
                            ld_real3 <= ld_real3 + 2'd1;
                    end
                end else
                    ld_retry <= ld_retry + 4'd1;
            end else
                icnt <= icnt + 2'd1;
        end
    end
end

