//  ★ build Q：标签环占用观测（验证"溢出"这个根因）
//    tag_occ     : 当前在飞条数（+1 于写标签，-1 于回拍）
//    tag_occ_max : 本帧最大占用（改前应顶到 64 并被覆盖；改后应 < 176）
//    tag_ovf     : 占用已经 == 深度却还在写标签的次数（**溢出直接证据**）
//------------------------------------------------------------------------------
// （tag_occ / tag_occ_max 的声明已移至 ph_eff 附近 —— 100M-16，见上）

always @(posedge clk or posedge rst) begin
