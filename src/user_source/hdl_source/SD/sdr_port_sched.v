//  ★★ 实验 B（2026-10-22）：run 内部免检忙 —— 前提是"地址连续" ★★
//==============================================================================
//  【原理】控制器对每组 4 条命令只采纳第 1 条的地址，后 3 条按"组首+相位"重算。
//      ⇒ 命令流**严格连续**时，重算结果永远等于真实地址（对怎么分组无关）；
//      ⇒ 只有**跳址**才需要"跳点落在相位 0"。
//      ⇒ run 内部没有跳址 ⇒ 不需要看忙；只有 run 首需要。
//      ⇒ 检查次数 46% → 46%/N，N=8 时约 6%。
//
//  【为什么必须有 `tx_run_cont`】行尾回跳（VFLIP_LINE_JUMP）和跨层切换都是跳址。
//      它们必须**不算 run 内部**、必须仍然看忙，否则会重演"整组 4 字坏"。
//      判据：下一组地址正好 = 上一组 + 4（即 [20:2] 上加 1）才算连续。
//
//  【和仲裁段 `run_hold` 的分工】
//      `run_hold` 只管"同一个层连发 N 组"（跳不跳都连发，跨跳无妨）；
//      `tx_run_cont` 只管"这一组能不能免检忙"（必须地址连续）。
//      两者分开 ⇒ 仲裁段不需要看见 `tx_req_*`，避免了"先用后声明"（见 100M-34）。
//
//  【回退】TX_RUN_N = 1 ⇒ run_left 恒 0 ⇒ 本判据恒 0 ⇒ 退回逐组看忙。
//==============================================================================
