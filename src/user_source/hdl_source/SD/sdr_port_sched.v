reg  ld_buf_v;                 // 4 字暂存缓冲有效
wire ld_iss_act;               // 正在向 SDRAM 发一组（4 拍）

//==============================================================================
//  ★★★ 实验 W2（2026-10-22）：TX 空闲时把槽 5..9 借给显示写 ★★★
//==============================================================================
//  【为什么】整机带宽占用只有 ~60%，但时隙表是**静态**的：
//    · TX 只在 180/480 行（37.5%）有活 ⇒ **62% 的回合整个槽 4~9 是空的**；
//    · 而写口在那 62% 的回合里仍被卡在 4 槽（64 字/轮）⇒ 非图像行
//      「需求 0.5 字/场景拍 = 供给 0.5」正好打平，**一点余量都没有**
//      ⇒ 任何一个 hiccup（挡忙/换向/刷新）都直接换算成帧时间 ⇒ 撞 16.7ms 就掉档。
//    ⇒ 问题不是"带宽不够"，是"峰值消费者借不到邻居的空闲"。
//
//  【做法】每个**回合**开始时看"上一整轮有没有纹理需求"：
//      没有 ⇒ 本回合槽 5..9 的所有权从 TX 改成 WR（4+5 = 9 槽 ≈ 144 字/轮，
//      写口供给 0.5 → 1.125 px/场景拍 ⇒ 非图像行 384,000 拍 → 170,667 拍）
//
//  【为什么从槽 5 起、槽 4 不借】读→写必须 ≥16 拍（红线）：
//      末条显示读 ≤ 槽3 ph11（RD_TX_GAP 静音后 4 拍）→ 槽4 整槽空转 → 槽5 ph0
//      = **21 拍** ✓。若从槽 4 起就只有 5~12 拍 ✗ —— 那正是白条/花屏的机制。
//      槽 4 仍是 OWN_TX，但借槽回合里 `tx_start` 被关掉 ⇒ 整槽真空、不发命令。
//
//  【为什么 4 命令分组不会破】借槽以 **16 拍整槽**为单位 ⇒ 每个方向每段连续的
//      命令数都是 4 的整数倍（16 拍 = 4 组、80 拍 = 20 组、64 拍 = 16 组），
//      每段起点都在 ph[1:0]==0 ⇒ 组首相位不漂，mod-4 不变式保住。
//
//  【为什么按"回合"锁存而不是按槽】若在一轮中间翻转，会出现"WR 用槽5、TX 用槽6"，
//      读命令紧跟写命令 1 拍 ⇒ 直接踩换向红线。按回合锁存最安全。
//
//  【代价】纹理"刚醒来"的那一轮白等 256 拍（2.56µs）。但框内是连续 180 行，
//      所以每帧只发生 1~2 次 ⇒ 可忽略。
//
//  【配套】top 的 `wr_stall` 水位抬到 **384/320**：借槽后一轮能吃 144 字，
//      原来 192 的门槛会让 FIFO 在突发中途掉到 128 以下 ⇒ 写口反而吃不满。
//
//  【回退】WR_BORROW_EN 改 0 = 时隙表完全恢复原样（一行）。
//==============================================================================
localparam integer WR_BORROW_EN = 1;      // 借槽恢复（TX 4 槽 ⇒ 槽 9 是 ID，结构安全）
reg  wr_borrow;                           // 下一槽是否把 TX 的槽借给 WR（逐槽锁存）
// ★ 实验 K：`tx_seen`（整回合"出现过纹理需求"）已删除 —— 逐槽判据直接用
//   `tx_busy_now` 看下一槽，不再需要回合级的累积标记。
// 槽 5..7 的借用覆盖：只改"谁拥有这个槽"，绝不碰换向缓冲
// ★ 实验 M 期间曾把上界放到 8 并关掉借槽（因为 TX 占到槽 9）。现在 TX 回到 4..7、
//   槽 8 是 ID 换向缓冲 ⇒ 上界必须回到 **7**，否则 WR 会占用换向缓冲槽。
// ★ build N3：TX 占 4..8 ⇒ 借槽上界跟着放到 **8**（槽 9 是 ID 换向缓冲，不能借）
//   借槽只在"纹理确实没需求"（tx_busy_now=0）时发生 ⇒ 那时 TX 不发命令，
//   所以不存在"TX 末条 → 借来的 WR 首条"的换向问题，红线不受影响。
wire borrow_slot = (WR_BORROW_EN != 0) && wr_borrow
                && (slot_nxt >= 4'd7) && (slot_nxt <= 4'd8);   // ★ TX 现为 5..8，借尾部 2 槽

//==============================================================================
//  ★★ 实验 A-2（2026-10-22）：显示读空闲的槽按"槽"借给纹理读 ★★
//==============================================================================
//  【为什么只借给 TX、绝不借给 WR】
//      RD 与 TX 都是读 ⇒ 同方向，随便接，**完全不碰换向红线**。
//      若借给 WR：槽 3 → 槽 4 只有 1 拍，写→读红线（17 拍）当场破 ⇒ 白条/花屏。
//
//  【判据必须用 `!disp_rd_en`（引擎的"我想发"），不能用"这轮没发命令"】
//      用后者会和实验 A-1 形成正反馈：A-1 让 RD 忙时推迟起突发 ⇒ RD 看起来更"闲"
//      ⇒ 借得更勤 ⇒ RD 更饿 ⇒ 读 FIFO 抽干 ⇒ 黄色欠载条。
//      用 `disp_rd_en` 则天然自限：槽被借走后引擎会一直"想发"，判据立刻变假 ⇒ 停止借。
//
//  【粒度 = 一个槽（16 拍 = 4 个 4 字组）】长度是 4 的整数倍 ⇒ mod-4 不漂。
//  【为什么 rd_idle_q 必须是寄存器】`disp_rd_en` 可能组合依赖 `disp_rd_ready`，
//      而 ready = rd_go ← own ← own_nxt ← 本判据 ⇒ 直接用会成组合环。
//      在槽边界采一拍存起来，环就断开了。
//  【回退】RD_LEND_EN = 0（一行）。
//==============================================================================
//  ★★ 2026-10-23：**关掉**（RD_LEND_EN = 0）★★
//    上板证据：HD 静止页出现青色像素 —— 那是 `frame_read_write` 里的欠载染色标记，
//    说明**显示读 FIFO 被抽干**。而"RD 闲时把槽借给 TX"正是元凶：
//      读的规则是"过阈值就发一个 128 字突发"，发完就闲 ⇒ `rd_idle_q=1` ⇒ 槽被借走
//      ⇒ 借走期间（TX 此时可能根本没需求）这些槽**白白空转** ⇒ RD 想起新突发时
//      已经浪费了若干个槽 ⇒ 突发被推迟 ⇒ 显示端在这一段时间里净消耗 > 预取余量 ⇒ 欠载。
//    现在 RD 固定 6 槽（0..5），谁也不借 ⇒ 上限 37.5M 字/s vs 888 需求 18.4M（49%）。
//    【回退】RD_LEND_EN = 1。
//==============================================================================
localparam integer RD_LEND_EN = 0;        // 1 = 借 ／ 0 = 关
reg rd_idle_q;                            // 上一个槽边界时"读引擎真的没有待读需求"
//==============================================================================
//  ★★★ 血泪（2026-10-22）：判据必须是 `disp_rd_want`，绝不能是 `disp_rd_en` ★★★
//==============================================================================
//  【第一版上板结果：**满屏黄**】
//  第一版写的是 `rd_idle_q <= !disp_rd_en`。而 frame_fifo_read.v:160-161：
//      assign App_rd_want = App_rd_en_d0;              // 未门控
//      assign App_rd_en   = App_rd_en_d0 & rd_ready;   // ← 已被本模块门控
//  顶层接的 disp_rd_en 正是**门控后**那个 ⇒ 形成顺序锁死：
//      借掉一个槽 → rd_ready 变低 → disp_rd_en 变低 → 判据认为 RD "更闲"
//      → 继续借 → rd_ready 永远起不来 ⇒ RD 一条命令都发不出去
//      ⇒ 读 FIFO 恒空 ⇒ read_data 恒为 UNDERRUN_COLOR(32'hFFFF00FF)
//      ⇒ 经 top 的 [31:8] = FF,FF,00 = **黄** ⇒ 满屏黄。
//  【教训】"忙/闲"判据必须取**引擎的愿望**（want），不能取**门控后的结果**（en）——
//      后者是"我们的许可"造成的，用它判因果会自我强化。
//  【为什么加一级寄存器还是没用】寄存器只断了**组合环**，断不了**顺序锁死**：
//      锁死靠的是"每拍都重新得出同一个错误结论"，加拍数只会让它更稳。
//==============================================================================
always @(posedge clk or posedge rst) begin
    if (rst)
        rd_idle_q <= 1'b0;
    else if (ph == 4'd15)
        rd_idle_q <= !disp_rd_want;       // 槽边界采样"引擎没需求"，供下一个槽使用
end
wire rd_lend_slot = (RD_LEND_EN != 0) && (slot_nxt <= 4'd4) && rd_idle_q;

//==============================================================================
//  ★ 2026-10-23：静止页把 TX 槽 4..7 借给显示读（修"斜缝"）★
//==============================================================================
//  【现象】HD 静止页出现斜向接缝；打开欠载染色后缝是**青色**
//    （`UNDERRUN_RGB=24'hFF_FF_00` 经零扩展 + 顶层取 [31:8] = 00FFFF = 青）
//    ⇒ 显示读 FIFO 真的在饿 ⇒ 每行少几个字 ⇒ 误差逐行累积成斜切。
//
//  【为什么正好在这时候饿】显示读本来就没有余量：
//      RD 4 槽 = 64 拍/256 拍 = 0.25 字/拍；
//      一行 640 像素占 2560 拍 @100MHz ⇒ 需求也是 0.25 字/拍 —— **刚好打平**。
//    再扣 `rd_gap_hold`（槽 3 末 4 拍静音，-6.25%）和刷新停顿（~1.3%），
//    有效显示期就入不敷出，全靠消隐期把 FIFO 补回来；补不及就欠载。
//
//  【做法】"写引擎没有一帧在写"时，把槽 4..7 的所有权临时改成 RD。
//    ★ 判据只用 `!dbg_wbusy && !rd_idle_q`，**绝不能加 `wr_borrow`** ★
//      wr_borrow 是"纹理这一槽有没有活"，每个槽边界都会抖（B 层一启动就翻），
//      拿它当判据 ⇒ 时隙表在**同一回合中间**翻转 ⇒ 显示读的一段突发被切断，
//      而那个切断点没有 rd_gap_hold 保护 ⇒ 按键那一瞬间撕裂。
//      dbg_wbusy 反映的是"写引擎有没有一帧在写"，只在一帧开始/结束时变化；
//      再加上"只在回合边界锁存"，整张表在一轮 256 拍内绝对稳定。
//    RD 从 4 槽变 8 槽（0.25 → 0.5 字/拍），欠载从结构上消失。
//
//  【为什么安全】
//    ① 同方向借槽（RD 与 TX 都是读），完全不碰读→写换向红线；
//    ② 槽 8 仍是 ID，RD→WR 的 16 拍红线不变；
//    ③ 以整槽（16 拍）为单位 ⇒ 每段连续命令数仍是 4 的倍数，mod-4 组相位不漂；
//    ④ 判据是"别人没活"，**不是**"别人被门控后没发出去"——
//       后者会形成"借走 → 它更闲 → 继续借"的正反馈（本模块历史上最大的坑）；
//    ⑤ 用 `dbg_wbusy`（frame_fifo_write 的 O_wr_busy，只依赖 state），
//       它在静止页恒 0，绝不会把写口饿死；
//    ⑥ 再加 `!rd_idle_q`：显示读**自己确实有需求**才借。否则 RD 空闲时反而占住
//       TX 的槽（同时 rd_lend_slot 又把 0..3 借给 TX）⇒ 两边互相让，谁都跑不快；
//    ⑦ **按回合锁存**（slot==15 且 ph==15 才更新一次）：一轮 256 拍内表绝不翻转。
//       这是本模块写明的纪律（见 §4"为什么按回合锁存而不是按槽"）。
//       ★ 反面教材（2026-10-23 上板踩过）：第一版用 `wr_borrow` 做判据，
//         它每个槽边界都抖 ⇒ 表在同一回合里翻转 ⇒ **按键那一瞬撕裂**。
//    ⑧ **必须再加"当前没有纹理请求"**（2026-10-23 第二次上板踩到）：
//       只判 `!dbg_wbusy` 是不够的 —— 合成一帧结束后 `dbg_wbusy` 会短暂回 0，
//       而过渡期间两层仍在不停地要纹理。这时把槽 4..7 借给 RD ⇒ **TX 一个槽都拿不到**
//       ⇒ 纹理断供 ⇒ 该帧要几秒钟才完成 ⇒ `tick` 不来 ⇒ 1.34s 看门狗超时
//       ⇒ 直接跳到目标高清图。上板现象就是"完全静止 → 稍微左移一点 → 闪到图2"。
//       加上 `tex_req_vld == 0` 之后，借槽只在**真正静止**（两层都没有新请求）时发生，
//       过渡/合成期间时隙表与原始设计逐拍一致。
//==============================================================================
//  ★★ 2026-10-23：**关掉**（RD_BORROW_TX = 0）★★
//==============================================================================
//  【为什么关】它是我为了消"静止页斜缝"加的，但它把 RD 从"4 槽 + 槽3末 4 拍静音"
//    变成"8 槽连发 8 个突发"。而读 FIFO 的安全边界（`frame_fifo_read.v:37-49`：
//    `INFLIGHT_MAX=16`、阈值 368、峰值必须 ≤504 < 512）**是按 4 槽节奏算的**。
//    8 槽连发改变了突发节奏 ⇒ 水位可能踩到 512 ⇒ 9 位差值回绕成 0 ⇒ 继续灌 ⇒
//    丢字 ⇒ 画面错位/撕裂。
//  【证据】它的行为恰好**在按键那一刻翻转**：按下后 `compose_en<=0` ⇒ 不产帧 ⇒
//    连续 4096 拍没有纹理请求 ⇒ `tx_quiet_ok=1`、`dbg_wbusy=0` ⇒ `rd_borrow_r` 翻 1。
//    而"按键瞬间撕裂"的时间线，正好从我加它的那一版开始，一直到现在。
//  【代价】静止页那条斜缝可能回来。那条另行解决（正确做法是把 `compose_en` 作为
//    `static_page` 送进调度器、并按 vsync 锁存，而不是靠"多久没请求"去猜）。
//  【回退】改回 1 即恢复。
//==============================================================================
localparam integer RD_BORROW_TX = 0;

reg rd_borrow_r;

// ★ 2026-10-23："静止页"用"长时间没有纹理请求"来判定，而不是"当拍没请求"。
//   当拍没请求在过渡期也会偶尔成立（层与层之间的空档），借走一个回合的槽
//   就会让纹理断供 256 拍 —— 帧时间被拉长，过渡看起来"卡"。
//   这里要求连续 4096 拍（82µs）完全没有纹理请求，才认为真的在静止页。
reg  [11:0] tx_quiet;
always @(posedge clk or posedge rst) begin
    if (rst)                        tx_quiet <= 12'd0;
    else if (tex_req_vld != 2'b00)  tx_quiet <= 12'd0;
    else if (tx_quiet != 12'hFFF)   tx_quiet <= tx_quiet + 12'd1;
end
wire tx_quiet_ok = (tx_quiet == 12'hFFF);

always @(posedge clk or posedge rst) begin
    if (rst)
        rd_borrow_r <= 1'b0;
    else if (stall)
        rd_borrow_r <= rd_borrow_r;                    // 冻结：决策原地保持
    else if ((ph == 4'd15) && (slot == 4'd15))         // ★ 回合边界，一轮只决定一次
        rd_borrow_r <= !dbg_wbusy && !rd_idle_q && tx_quiet_ok;
end

wire rd_borrow_tx = (RD_BORROW_TX != 0) && rd_borrow_r
                 && (slot_nxt >= 4'd5) && (slot_nxt <= 4'd8);

wire [2:0] own_nxt = (slot_nxt == 4'd15) ? ((ld_wr_vld || ld_buf_v) ? OWN_LD : OWN_ID)
                                         : (rd_borrow_tx  ? OWN_RD
                                          : (borrow_slot   ? OWN_WR
                                           : (rd_lend_slot ? OWN_TX : own_of(slot_nxt))));
always @(posedge clk or posedge rst) begin
    if (rst)
        own <= OWN_RD;                       // slot 复位成 0，槽 0 = RD
    // ★ 100M-16：own 必须和 slot/ph 同一个推进条件（review 问题 4）
    //   原来只看 ph==15：stall 冻结时 slot 停住而 own 照换 ⇒ 恢复后一两拍内
    //   own 与 slot 不匹配，错误的所有者拿到旧槽最后一个拍的命令机会。
    else if (!stall && ph == 4'd15)
        own <= own_nxt;                      // 每 16 拍换下一槽（与 slot 同步）
end


//==============================================================================
//  3. 显示读：只在 RD 槽放行，且任何"起步/恢复"必须落在 4 拍边界
//==============================================================================
//  【rd_run 的语义】= "上一拍真的发出去了一条命令"。
//    · 连续发就一直连续（一个槽 16 拍全都能用）
//    · 一断（引擎自己停一拍，或槽结束）就清 ⇒ 再起步必须等 ph[1:0]==0
//  【为什么必须是 4 拍边界】厂商规则"每 4 个时钟才允许换一次地址"。
//  如果恢复点落在组中间（ph[1:0]!=0），这一拍就是一个"非 4 拍边界的跳址"：
//  控制器不会报错，只会用"组首+相位"自动累加的地址取数 ⇒ 取回别处的数据。
//  仿真实测：不卡这个边界，tb_video 会冒出 6 条"分组错" + 2 个坏像素。
//  ★ 与旧表的关系 ★ 旧表槽长就是 4 拍，恢复点天然在 4 拍边界；
//    槽加长到 16 拍后，必须靠 rd_run 的清除时机把这条纪律补回来。
//==============================================================================
reg  rd_run;

wire rd_slot = (own == OWN_RD);

//==============================================================================
//  ★★★ 实验 A（2026-10-20）：RD→TX 换位空拍 ★★★
//==============================================================================
//  【假设】黄色虚线 = 显示读（帧缓冲）命令与纹理读命令在同一个 4 拍组里混发：
//    时隙表是 RD×4 → TX×6 直接硬切（槽 3→4 零间隔），显示读突发又恰好跑满
//    槽 3 的最后一拍（128 字突发跨 2 轮、每轮 RD 段 64 条背靠背），于是
//    "槽 3 ph15 的显示命令"与"槽 4 ph0..3 的纹理组"落在控制器同一个
//    4 拍窗口里 ⇒ 纹理命令的地址被控制器按"显示组首+相位"重算 ⇒
//    纹理通道读回**帧缓冲数据**（串口已证实坏字是实时帧缓存内容）。
//    计数仍 1:1、11 拍时间锁仍为 0、rd_lag 也对 —— 全部绿灯，只有数据是错的。
//
//  【A2 板上结果】A2（8 拍空隔）反而**更严重** ⇒ 隔离带假设被否决：
//    空隔只改相位不改混发，症状随相位漂移 ⇒ 病根是【组相位】不是混发。
//    ⇒ 回退到 A（4 拍空隔，已知最好），另起 tx_ph_off 相位扫描（实验 2）。
//  【做法（保留 A）】RD 段最后一个槽（槽 3）的 ph>=12（最后 4 拍）禁止发显示读命令：
//      最后一条显示读命令 ≤ 槽3 ph11，第一条纹理命令 = 槽4 ph8（被忙挡住后自然对齐）
//      ⇒ 读回程 11 拍整段落在静音区/忙窗里，不会和纹理组首交错。
//    显示读供给 64→60 条/256 拍 = 0.234 命令/拍，需求 0.201（1.16 倍余量）；
//    纹理供给不动（纹理是稀缺资源，不许动）。
//
//  【判读】烧录后（保持 ANIM_FREEZE_ALL=1 便于对比）：
//      虚线消失   ⇒ 坐实"批宽 > 4" ⇒ 本开关固化；若还有极少量 ⇒ 查 ph_off
//                   漂移（刷新冻结后相位没跟上控制器，见 §2 stall/ph4 注释）
