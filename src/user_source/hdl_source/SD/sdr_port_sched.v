//  9. 标签环 + 回程分发（1 位/命令，Sdr_rd_en 每拍弹 1 位）
//==============================================================================
//  ★ 深度必须跟 TAG_AW 一致 ★
//    原来这里写死 [0:63]，但指针是 TAG_AW=8（0~255）；
//    指针一过 63 就越界读出 X ⇒ 回程数据被判成"既不是显示也不是纹理"
//    ⇒ 读 FIFO 永远收不到数据 ⇒ 显示永久欠载 ⇒ 纯黑。
//    （仿真实测：25600 个读命令只投出 6400 个像素，正确。）
//  ★★ build F：标签从 1 位扩成 3 位 = {是不是纹理, 层号, 这个字要不要} ★★
//  【为什么必须扩】原来标签只说"这条命令是纹理还是显示"，而"哪一层、这组里
//  哪个字"要靠回程拍数去推（pend + tx_bcnt）。那条链一旦错一次就永久错，
//  表现就是**显示数据和纹理数据互串 → 整屏色条**。
//  现在把身份**跟着命令一起存进环里**，回程每一拍自己带着身份回来：
//  少一拍只影响它自己，绝不会把后面所有配对一起带偏。这就是不变式 A。
//  ★ 2026-10-21 修 EMB 超限（真正源头）★★
//  【为什么超限】TEX_IS_SIG=0 时签名比较链是死逻辑 ⇒ tag_a_mem/tag_addr_tex_mem
//    被综合器整体裁掉，u_sched 只占 1 个 EMB（tag_mem）；签名实验置 1 后三个
//    数组全部复活 ⇒ u_sched 1→4 ⇒ 全局 64→67 超限。
//  【修法】三个数组都标 ram_style="dram"（分布式 RAM/LUT，不占 EMB）——
//    与 osd_font_cache 的 owner_a/b/c 同一写法。容量 256×25bit≈6.4Kbit，
//    代价约百来个 LUT，u_sched 的 EMB 归零、全局回到 63/64。
//  （★签名实验结束、TEX_IS_SIG 改回 0 后这些数组又会被裁掉，属性可留可撤。★）
// ★★ 2026-10-31 [MSLICE]：tag_mem 改落块 RAM（原 force dram）★★
//  EG4 的分布式 RAM 只能放在 MSlice 里，而工程卡在 mslice 4909 > 4900。
//  这张表的读本来就是**寄存器读**（tag_cur_q <= tag_mem[tag_r]，见 build D），
//  正好是 BRAM 的同步读口 ⇒ 时序/语义逐拍不变，只占 1 个 BRAM9K（全局还剩 9 个）。
//  读写同址只发生在环空时（tag_w == tag_r），此时 beat=0、读出值不被使用。
//  读寄存器必须**不带异步复位**（BRAM 输出寄存器不支持），见下面 tag_cur_q。
reg  [2:0]       tag_mem [0:(1<<TAG_AW)-1];           /* fehdl force_ram=1, ram_style="bram" */
reg  [TAG_AW-1:0] tag_w, tag_r;
integer          tag_i;
initial for (tag_i = 0; tag_i < (1<<TAG_AW); tag_i = tag_i + 1) tag_mem[tag_i] = 3'b000;

//  ★★ 2026-10-18：这里原来是 `tag_cnt != 0`（= tag_w - tag_r 的减法 + 比较）★★
//  它是全设计最差那条建立路径的第一段（见 §9.16）：
//      tag_w → 8 位减法 → 与 0 比较 → tag_mem 读 → tx_bhit → FIFO 写使能
//  而我们只关心"环里有没有东西"，直接比指针是否相等就够了 —— 减法整段删掉。
//  环空时 tag_w==tag_r；环满（256）时也相等，但那本来就该按"没有标签"处理
//  （在飞上限 176 < 256，永远不会真满）。
wire        tag_nempty = (tag_w != tag_r);

wire        beat     = Sdr_rd_en && tag_nempty;
//  tag_cur 只在这里（和下面的打拍块）用；beat_tx/beat_dsp 这两个中间量
//  已由 beat_tx_d1 / disp_vld_d1 取代，避免留下未使用的线网。

//------------------------------------------------------------------------------
//  ★★ 2026-10-18 时序根修：标签写入整体延后一整拍 ★★
//------------------------------------------------------------------------------
//  【问题】原来 tag_mem 的写使能 / 写地址 / 写数据全是"当拍组合"：
//      Sdr_init_ref_vld → ctrl_ok → tx_start → tx_cmd → App_rd_en → RAM.we
//  布局布线报告里这条路是 `u_sched/ramread0_syn_351.e[0]`：
//      Slack = −0.020ns（起点 sdr_init_ref 的 ref_vld 触发器，6 级逻辑）
//  它偶尔采错 ⇒ **回来的纹理字被投给显示口，或显示字被投给纹理口**；
//  而命令数与回拍数仍然 1:1（指针照常 +1）⇒ 所有计数器都读不到这种错
//  ⇒ 表现就是"图片区里稀疏、会动的场景色错点"。
//
//  【改法】把 {有效, 是不是纹理, 层号, 要不要} 整体打一拍寄存，写 RAM 和推指针
//  都用寄存后的版本。写侧统一晚 1 拍只改变环形队列的相位，而队列的读侧
//  （Sdr_rd_en，实测晚 11 拍）与它本来就没有固定相位关系 ⇒ 语义完全不变。
//  收益：RAM 的写使能/地址/数据只由寄存器驱动，那条 6 级链断成两截。
//------------------------------------------------------------------------------
// ★ build R：把"这条命令的地址属于哪个区间"随标签一起存 ★
//   纹理槽 = 1,703,936..2,010,496；帧缓存 = 0..614,399 ⇒ 用 1 位就能分开。
//   回拍时就能判："纹理标签 + 显示地址" ⇒ 地址通路串了；
//   "纹理标签 + 纹理地址 + 数据不是纹理字" ⇒ 数据通路串了。
// ★ 2026-10-31：build R/X 的诊断表 tag_addr_tex_mem / tag_a_mem（以及 tag_ta_q、tag_aa_q、
//   tag_addr_tex_q、tag_a_q）已删除 —— 读出值从未被使用（综合本来就裁掉），留着只会在
//   哪天被接上时复活 256×22 bit 的 LUTRAM（10-21 那次 EMB 超限就是这么来的）。
// ★ build X：完整 21 位命令地址（跟标签一起存，回拍时取出）
//   这是唯一能一刀切开"地址错"和"数据错"的东西：
//     打出来 addr < 614400      ⇒ 地址就是帧缓存 ⇒ 地址通路有病
//     打出来 addr ≥ 1703936     ⇒ 地址对 ⇒ 控制器返回了错数据
reg        tag_we_q;
reg        tag_tx_q;
reg  [1:0] tag_id_q;

//==============================================================================
//  ★★★ build 100M-8：写通道的三个修复开关（声明已提前到文件前部）★★★
//==============================================================================

always @(posedge clk or posedge rst) begin
    if (rst) begin
        tag_we_q <= 1'b0;
        tag_tx_q <= 1'b0;
        tag_id_q <= 2'd0;
    end else begin
        tag_we_q <= App_rd_en;
        tag_tx_q <= tx_cmd;
