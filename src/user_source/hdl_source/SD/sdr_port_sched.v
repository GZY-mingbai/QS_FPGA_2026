//==============================================================================
//  ★★★ 2026-10-23 S1：照抄纹理写的"起头直接看忙" ★★★
//==============================================================================
//  【抄的是哪一条】`ld_iss_start`（:1835）的忙检查只有一条核心：
//        && !Sdr_busy          // 起头那一拍直接看忙，不预测
//  帧缓存写原来**只有** `wr_blk_g`：在上一组第 4 拍采 `Sdr_busy`，覆盖下一整组。
//  那是"前视预测"——忙在这个采样点之后才拉高，整组 4 条写命令就盲发进去。
//  而写被吞 = 数据直接消失（读不是），地址照走 ⇒ 帧缓存永久留一个洞。
//
//  【为什么必须寄存器化】`disp_wr_ready → frame_fifo_write.App_wr_en` 是全设计
//  最差路径（曾经 slack −0.090ns，靠拆掉锥里的加法器才修好，见 :1098 那段）。
//  把 `Sdr_busy` 组合进这条锥等于把违例请回来。延迟一拍对忙窗口（4~16 拍）
//  没有任何影响，所以用 `Sdr_busy_q`。
//
//  【`wr_busy_blk` 保留不动】新判据是**在它之上再加一层**，只可能更严格 ——
//  这一版的原则是"只收紧、不放松"，绝不重演花屏。
//  占空也基本不变：`wr_go` 的输出条件没动，只是起头多等一拍。
