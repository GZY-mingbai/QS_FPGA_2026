wire        tx_go   = tx_act || tx_start;
// ★★ 100M-22：组内命令 **不看 Sdr_busy、也不看 stall**，4 拍连续发完 ★★
//   【为什么连 stall 都要去掉】stall = hold | (ph4 != ph[1:0])，其中
//   `ph4 != ph[1:0]` 是"把时隙表拉回 4 拍网格"的再对齐，它**每行会来好几次**
//   （tb_txfix 实测 196 次/30 行 ≈ 6.5 次/行）。它落在组内就正好把一组的 4 条
//   切成 2+2 或 3+1 ⇒ 真控制器把后半段当新组（组首换成 base+1）⇒
//       读回 base+1..base+4（错位一组）⇒ 落到帧缓存区 ⇒ 背景是白的 ⇒ 整列纯白。
//   而且再对齐发生在固定相位 ⇒ 同一列每行都错 ⇒ 板上就是"贯穿全高的白竖带"。
//   【为什么去掉是安全的】控制器只按"读口上连续 4 条命令"分组，不看时隙表的网格；
//   纹理组自己 4 条连续 ⇒ 分组永远从 base 开始、地址恒 base+j。
//   时隙表的 4 拍网格只对显示读/写的"起突发"节拍有意义，纹理不需要。
//   刷新冻结（hold）保留，但它是"初始化刷新完成标志"，运行期基本不来。
