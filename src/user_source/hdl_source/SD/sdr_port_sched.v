wire wr_go   = wr_slot && !stall && !wr_gap_hold && !wr_busy_blk
             && (wr_run || ((ph_eff == 2'd0) && ctrl_ok && !Sdr_busy_q));

//==============================================================================
//  ★★★ 2026-10-23 回退记录：写口重发（wbuf）已撤销 ★★★
//==============================================================================
//  【做过什么】照抄装载写那套，把写口改成"4 字暂存 + 撞忙整组重发"：
//      缓冲没满就 disp_wr_ready=1，攒 4 字后只在 ph_eff==0 整组发出，撞忙则重发。
//  单测（SD/tb_wrgrp.v）是过的：吞掉 289 条命令、105 组不干净、帧缓存 0 空洞。
//
//  【为什么又撤销 —— 上板直接花屏】问题不在重发本身，而在它**改变了握手时机**：
//      `disp_wr_ready` 从"只在 WR 槽放行(25% 占空)"变成"缓冲没满就放行(≈100%)"，
//  连带三件事同时变了：
//      ① 写引擎的 `O_wr_busy`（= dbg_wbusy）从"经常为 1"变成"几乎一直为 1"，
//         而它**参与借槽判据** `wr_borrow`（WR_BORROW_EN=1）⇒ 写口开始大量借
//         槽 5~7 ⇒ 纹理读的槽被抢 ⇒ 纹理断供 ⇒ **图片层花屏**。
//      ② 写引擎内部 `write_cnt` 的推进节奏变了，`into_burst`/`tail_ready_r`
//         这些按"WR 槽速率"设计的判据跟着偏移。
//      ③ `disp_wr_ready` 变成了"几乎总为 1"，等于把整条写路的反压拿掉了。
//  ⇒ 结论：**写口的手势（何时放行）是全局耦合的，不能当局部改。**
//     要用重发，必须做成"正常路径一个字节都不动，只在脏组后补发 4 条"的形态。
//
//  【下一步的正确做法（尚未实现）】影子重放：
//      · 正常路径完全保持 `disp_wr_ready = wr_go`（逐拍与现在一致）
//      · 每发一个字，同时抄进 `sbuf[ph[1:0]]`（4 深，仅记录）
//      · 该组任一拍见到 Sdr_busy ⇒ 置 replay_pend
//      · 下一个 WR 槽的 4 拍边界，把 sbuf 的 4 个字**补发一遍**（幂等），
//        补发期间把 `wr_go` 压住 4 拍（上游自动等）
//      ⇒ 干净时命令流与现在**逐拍相同**，不可能引入花屏。
//==============================================================================
assign disp_wr_ready = wr_go;

// 同 rd_run：冻结期间保持突发状态，避免解冻后相位漂移
// ★ 实验 W1：挡忙（wr_busy_blk）期间也必须保持 —— 否则 4 拍的挡会膨胀成 16 拍
always @(posedge clk or posedge rst) begin
    if (rst)
        wr_run <= 1'b0;
    else if (stall || wr_busy_blk)
        wr_run <= wr_run;
    else if (wr_go && disp_wr_en)
        wr_run <= 1'b1;
    else
        wr_run <= 1'b0;
end

//==============================================================================
//  5. 纹理读：一个 TX 槽按 4 拍一组取，最多若干组在飞
//==============================================================================
//  请求来自图片层（已按需排好队）。这里只做三件事：
//    · 选一层（轮流，避免某层被饿死）
//    · 请求地址提前一拍寄存（保证 App_rd_addr 只由寄存器驱动，无组合长路径）
//    · 把"这条命令属于哪一层、它是不是本组里被需要的那一个字"逐条登记
//  不做：地址比较、去重、重发、组号匹配 —— 请求按 FIFO 顺序服务，
//  回程也按顺序，一一对应。
//
//  ★★ 2026-10-18 build E：回程改成【一条命令一份说明】★★
//  【为什么要改】原来用"全局组内相位" `tx_bcnt` 去挑字：
//      tx_bcnt 是所有纹理回程拍的**自由计数器**（0,1,2,3,0,1,2,3…）
//      回程按 pend 队首判层，按 tx_bcnt==pend_head[1:0] 判"这个字要不要"
//  这条链把三件互不相关的事绑在了一个计数器上：
//      (a) 当前是第几拍回程  (b) 当前组是第几个字  (c) 当前组属于哪一层
//  只要有一次回程拍没进来（控制器拒收 / 半组 / 换向 / 上电相位不明），
//  tx_bcnt 就永久错位 ⇒ 挑错字 + 判错层 ⇒ 花点 / 双影 / 竖直白缝，
//  而且**从错位那一刻起整帧都坏**（下一帧重新错另一个量 ⇒ 逐帧闪）。
//  仿真里之所以永远 PASS，是因为模型从不丢命令（BUSY_HOLD 一开就不丢了）。
//
//  【现在的模型】把说明跟着命令走：
//      · 每发一条纹理读命令，就把 {层号, 本命令的组内偏移 == 需要的偏移?} 压进
//        一个深度 64 的队列（在飞命令上限 = 60，TAG 环 256 够用）
//      · 每回来一拍纹理数据，就弹队首：队首说"要"，就把数据投给它指定的那一层；
//        说"不要"，就只弹掉、丢弃
//  ⇒ 不再有"拍号/组号/层号"三者对齐的问题。发几条命令就压几条说明，
//     回来几拍就弹几条；哪怕某一条命令真被控制器拒收，也只是那一个像素缺一次，
//     不会把**后面所有**的命令/数据配对全部带偏。
//  ⇒ 这也是"ps_gen_image 一次请求换一个字"这个契约唯一正确的实现：
//     **请求粒度 = 命令粒度 = 数据粒度 = 说明粒度**，四者严格 1:1。
//==============================================================================
reg        tex_lr;                 // 上次服务了哪一层（轮流用）
//  ★★ 2026-10-18：这里原来是"优先再服务同一层"（粘住），不是轮流 ★★
//  旧写法：tex_lr ? (vld[1] ? 1 : 0) : (vld[0] ? 0 : 1)
//      tex_lr 记的是"刚服务过的那层"，于是它**又优先给自己** ⇒ 只要该层队列不空，
//      另一层就一直轮不到。两层都满时表现为"一层连续吃掉 64 个（LEAD 上限）、
//      另一层饿到 FIFO 见底"⇒ 场景被迫停住 ⇒ 帧率掉、拖累预算被吃光
//      ⇒ 预算用尽后另一层带空 FIFO 继续推进 ⇒ 永久错位（花屏 + 残缺重复图）。
//  现在：优先给**另一层**，才是注释里说的轮流。
//
//==============================================================================
//  ★★ 实验 A-4（2026-10-22）：把"逐组轮流"改成"有界连发" ★★
//==============================================================================
//  【为什么要改】逐组轮流时命令流是 A0-3 │ B0-3 │ A4-7 │ B4-7 …
//      ⇒ **每 4 条就有一次跳址**。而跳址正是唯一会被"组首+相位重算"打歪的地方。
//      改成"同一层连发 N 组再换层"后：
//          N=1 （原状）跳址间隔 8 条
//          N=8        跳址间隔 36 条   ← 本版
//          N=22       跳址间隔 92 条（= 整个 TX 窗，留给实验 B）
//  【为什么不能"粘到空"】那是 2026-10-18 之前的旧写法，会让一层连吃 64 组
//      （LEAD 上限），另一层饿到像素 FIFO 见底 ⇒ 永久错位（见上一段注释）。
//      **有界**（每层最多 N 组 = 32 拍）就不会：另一层最多只多等 32 字，
//      而像素 FIFO 是 512 深。
//  【本版（A）不改变忙守卫的行为】守卫仍然每组都查 ⇒ A 版的帧率应当**不倒退**，
//      它只是把"跳址率"降下来，为实验 B 做铺垫。A 的通过判据是"中性"。
//  【实验 B 已落地】B 在 run 内部免检忙，其前提"地址连续"由 `tx_run_cont` 负责
//      （见 :1108 那一块）。注意分工：**仲裁段只用 `run_hold`（不判地址），
//      守卫只用 `tx_run_cont`（判地址）** —— 这样仲裁段不必看见 `tx_req_*`，
//      避免了"先用后声明"（100M-34 的教训）。
//  【回退】TX_RUN_N = 1（等价于原来的逐组轮流，同时 tx_run_cont 恒 0 = B 也关）。
//==============================================================================
// ★★ build P16 修正：15 → **8** ★★
//   TX 窗口只有 16 组。设 15 时一层拿 15 组、另一层只剩 1 组 ⇒ 层1 每窗口
//   只有 4 字，而它一行需要 160 字 ⇒ 40 个窗口才够 ⇒ FIFO 必空 ⇒
//   ① img_rdy1=0 按停整条流水线 ⇒ 30fps
//   ② 显示侧拿 cur_pix 旧值 ⇒ 脏点
//   设 8 ⇒ 两层均分（各 32 字/窗口），5 个窗口凑满一行 160 字。
//   单层场景下 15 才有意义（没有第二层来抢），双层必须均衡。
//==============================================================================
//  ★★ build FIFO-Q：纹理请求分层队列 ★★
//==============================================================================
//  【解决什么】两层请求是同步交错的（层0,层1,层0,层1,...），而 `tx_run_cont`
//  要求"同层 + 地址连续"才算连续 ⇒ 每 8 组必断一次 ⇒ 又要重新走 tx_start 看忙。
//  而 `Sdr_busy` 在真机上占空比很高（读回程/刷新/换向都拉高）⇒ 开组大量被挡。
//  实测对照：单层（地址连续、全程免检忙）60fps，双层（每 8 组断一次）30fps，
//  而两者命令数完全相同（115,200 条/帧）⇒ 差的就是"断"的代价。
//
//  【做法】两层各一个 16 深同步 FIFO，请求先入队；调度侧把一层取空再切另一层
//  ⇒ 一个 TX 窗口（16 组）只服务一层，只在窗口边界切一次。
//
//  【为什么深度是 16】上游 LEAD=256 像素 = 64 字 = 16 组，再深也填不满。
//
//  【反压】只有"入队成功"才回 tex_req_ack ⇒ FIFO 满时请求侧自然停住（这是
//  唯一正确的反压方式：原来 ack 是 tx_start 时给的，改成入队时给）。
//
//  【不碰什么】4 命令分组的相位（ph_eff/gph/tx_skip）完全不动 —— 只换"请求从
//  哪里来"。所以历史上那个"分组相位偏 1~3 就整条流错地址"的雷区不受影响。
//
//  【pop 为什么要寄存一拍】pop 条件依赖 t_sel_l，而 t_sel_l 依赖 empty（本块的
//  组合输出）⇒ 同拍闭环。把 pop 打一拍再用，断开这个环；因为 t_pre_v=1 时不会
//  再次锁存，晚一拍推进读指针是安全的。
//==============================================================================
localparam integer TQF_AW = 4;                        // 16 深
reg  [22:0]     tq0 [0:(1<<TQF_AW)-1];                // {组地址[20:2] 19b, mask 4b}
reg  [22:0]     tq1 [0:(1<<TQF_AW)-1];
reg  [TQF_AW:0] tq0_w, tq0_r, tq1_w, tq1_r;
wire [TQF_AW:0] tq0_cnt  = tq0_w - tq0_r;
wire [TQF_AW:0] tq1_cnt  = tq1_w - tq1_r;
wire            tq0_empty = (tq0_cnt == 0);
wire            tq1_empty = (tq1_cnt == 0);
wire            tq0_full  = (tq0_cnt == (1<<TQF_AW));
wire            tq1_full  = (tq1_cnt == (1<<TQF_AW));

wire tq0_en = tex_req_vld[0] && !tq0_full;
wire tq1_en = tex_req_vld[1] && !tq1_full;

reg  tq0_pop_q, tq1_pop_q;                            // 打一拍的 pop 请求

always @(posedge clk) begin
    if (tq0_en) tq0[tq0_w[TQF_AW-1:0]] <= {tex_req_addr[20:2], tex_req_mask[3:0]};
    if (tq1_en) tq1[tq1_w[TQF_AW-1:0]] <= {tex_req_addr[41:23], tex_req_mask[7:4]};
end
always @(posedge clk or posedge rst) begin
    if (rst) begin
        tq0_w <= 0; tq0_r <= 0; tq1_w <= 0; tq1_r <= 0;
    end else begin
        if (tq0_en)     tq0_w <= tq0_w + 1'b1;
        if (tq1_en)     tq1_w <= tq1_w + 1'b1;
        if (tq0_pop_q)  tq0_r <= tq0_r + 1'b1;    // pop_q 由段 3 单独驱动
        if (tq1_pop_q)  tq1_r <= tq1_r + 1'b1;
    end
end

// ★ build R15 已回退：15 试过，板上**零收益**（0x28 仍 16.73ms、0x2C 仍 5）。
//   结论：切层频率不是这段等待的来源，别再从这一格找时间。
//   回到 8（= 16 组窗口两层均分），这是"脏像素消失"时验证过的那一档。
// ★★ build FB16b（2026-10-22）：8 → **1**，即【退回逐组看忙】★★
//  【为什么】板上 565 模式（60fps）下，图片层出现少量脏点。假说是：
//    `tx_run_cont` 让纹理在【连发的 8 组 = 32 条命令】里**完全不看 Sdr_busy**
//    （见 :1567 `(!tx_busy_blk || tx_run_cont)`），一旦控制器拒收其中一条，
//    这条命令没有任何回程拍 ⇒ 标签环整体错一位 ⇒ 那片像素拿到错数据 ⇒ 少量脏点。
//    三条通路里只有纹理有 run_cont：显示读 RD_START_GATE=1、显示写每组确认，
//    所以症状**只在图片层**，与观察完全一致。
//  【为什么现在敢关】当初开 run 是因为带宽零余量，逐组看忙会让供给塌陷；
//    现在 60fps 还有 ~6.7ms 余量，付得起。代价：一帧 640 组各多等几拍 ≈ 0.05ms。
//  【判读】脏点消失/明显变少 ⇒ 假说成立，再往 2~3 找吞吐甜点；
//          一点没变 ⇒ 排除忙，回去扫 CLKC2_CPHASE（DQ 采样相位）。
localparam [3:0] TX_RUN_N = 4'd1;         // 1 = 逐组看忙（关闭 run 连发）
reg  [3:0] run_left;                      // 本 run 还能连发几组
reg        run_layer;                     // 本 run 服务的是哪一层
wire       run_hold = (TX_RUN_N > 4'd1) && (run_left != 4'd0)
                   && (run_layer ? !tq1_empty : !tq0_empty);   // FIFO-Q: 看该层队列有没有货
// ⚠ run_left / run_layer 的更新在文件后段（TX 段之后）—— 因为要用 tx_start，
//   而它在这里还没声明（本文件 :1199 才声明；先用后声明会让 iverilog 报
//   "Unable to bind"，见文件头 100M-34 的教训）。

// ★ build FIFO-Q：选层依据从"请求线上有没有 valid"改成"该层队列有没有货"。
//   轮转规则保留（tex_lr 记录上次服务的层），避免某一层长期独占：
//     上次是层0 ⇒ 优先层1（若层1 非空），否则层0
//     上次是层1 ⇒ 优先层0（若层0 非空），否则层1
wire       t_sel_l  = run_hold ? run_layer
                               : (tex_lr ? (tq0_empty ? 1'b1 : 1'b0)
                                         : (tq1_empty ? 1'b0 : 1'b1));
wire       t_sel_v  = t_sel_l ? !tq1_empty : !tq0_empty;   // 选中的层确实有货
wire [22:0] t_sel_q = t_sel_l ? tq1[tq1_r[TQF_AW-1:0]]
                              : tq0[tq0_r[TQF_AW-1:0]];
wire [20:0] t_sel_a = {t_sel_q[22:4], 2'b00};             // 恢复成 21 位组基地址
wire [3:0]  t_sel_m = t_sel_q[3:0];

// 请求地址寄存一拍。FIFO 输出在未弹出前是稳定的，寄存后仍然有效。
reg  [20:0] t_pre_a;
reg  [3:0]  t_pre_m;               // ★ build F：这组的掩码 ★
reg         t_pre_l;
