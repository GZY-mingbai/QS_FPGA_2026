// ★ build 100M-11：预清阶段往 FIFO 里灌常量，正常装载灌 BMP 像素。
//   地址一律走 dst_addr（同一套地址生成器）⇒ 预清的范围**正好等于**装载要写的范围，
//   稀疏布局下也不会错位。
wire [52:0] fifo_din = in_clr ? {{11'd0, tex_base + clr_cnt}, PREFILL_COLOR}
                              : {{11'd0, tex_base + scale_woff}, scale_wdata};

