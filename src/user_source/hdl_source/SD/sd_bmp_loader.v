//==============================================================================
//  ★★★ build 100M-12：换成【扇区间流控】（100M-10b 的 ack 限速已作废）★★★
//==============================================================================
//  【100M-10b 错在哪】我把 `write_req / write_req_ack` 当成了逐像素流控，
//  实际去读 bmp_read.v 才发现它是**一次性握手**：
//      ST_LOAD_HDR 校验完 → write_req <= 1  （bmp_read.v:477）
//      ST_LOAD_WAIT 收到 ack → write_req <= 0，进 ST_LOAD_DATA （:499-502）
//      ST_LOAD_DATA 里 `sd_sec_read` 一直拉高，逐扇区往下读，**再没有任何握手**
//  ⇒ 把 ack 压到 1/32 拍只是把"开始"推迟几十拍，一进 LOAD_DATA 就全速灌。
//  板上实测也印证了：100M-11 的洋红横线约占一半，`ld_drop` 仍是 38 万。
//
//  【这一版怎么改】把流控挪到**扇区边界**：
//    bmp_read 加一个 `wr_credit` 输入，只有它=1 才重新拉高 `sd_sec_read`
//    去读下一个扇区。扇区 = 512 字节 ≈ 170 像素，是天然的节流单位。
//    ⇒ 产速被精确钉在排水速率以下，FIFO 不会涨满，一个字都不丢。
//
//  【水位从哪来】用 `img_afifo` 新增的 `wlevel`（**写域**自己算的），
//    不是读域的 `rcount` —— 后者是二进制值，跨域采样会翻出不相干的中间值，
//    而且它保守欠报（让人以为更空），方向是危险的。详见 img_afifo.v。
//==============================================================================
localparam integer LD_CREDIT_LEVEL = 192;   // FIFO 低于这个数才放行下一个扇区
//  512 深、门槛 192：放行后一个扇区涨 ~170 ⇒ 最高约 362，留 150 个空位兜底。

//==============================================================================
//  打包与地址
//==============================================================================
// 下采样目标尺寸（0 = 不下采样，等于源尺寸）
localparam integer OW = (OUT_W == 0) ? IMG_W : OUT_W;   // 565 打包模式的行宽（像素）
localparam integer OH = (OUT_H == 0) ? IMG_H : OUT_H;
localparam        DOWNSAMPLE = (OW != IMG_W) || (OH != IMG_H);

// ---- 运行时有效尺寸（load_fmt 决定）----
//  565：ow=320 / oh=240，每个 32 位字装 2 个像素
//  888：ow=640 / oh=480，每个 32 位字装 1 个像素
// 打包：{8'hFF, R, G, B} —— 和场景图的 {A,R,G,B} 完全一致，实时侧零转换。
// 【注意字节序】bmp_read 输出的 bmp_data 已经是 {R,G,B}（它内部做过字节重排），
// 这里直接补 alpha 即可。如果上板发现红蓝颠倒，先查 bmp_read 里的那个 case。

//==============================================================================
//  ★★ 2026-10-22 build P16：纹理统一存 16 位（RGB565），两个字并成一个 32 位字 ★★
//==============================================================================
//  【为什么】板上实测：32 位纹理 + 两层 => 纹理命令 230400 条/帧 => 30fps；
//    单层（115200 条）=> 60fps。所以纹理负载砍半就能过。
//    16 位打包后两层只需 86400 条/帧，比那个已验证的 60fps 配置还低 25%。
//
//  【兼容 640x480】本改造与源分辨率无关：无论 OW x OH 是 240x180、320x240 还是
//    640x480，都是「输出像素每 2 个拼成 1 个字」，行宽一律 = OW/2。
//    => 将来接高清路（640x480 -> 320x480 字）不需要再改这里，只要改 OUT_W/OUT_H。
//
//  【布局】一个 32 位字 = {奇像素, 偶像素}：
//        低 16 位 = 该行第 2k   个像素（先到的）
//        高 16 位 = 该行第 2k+1 个像素（后到的）
//    => 地址 = 行号 * (OW/2) + (col_o >> 1)，写使能只在 col_o 为奇数时拉高。
//
//  【为什么打包在装载时做】显示侧每拍只处理一个像素，打包解包会引入额外流水；
//    而装载是一次性的，慢一点无所谓。
//
//  【回退】三处改回去：dst_off 的 col_o>>1 -> col_o；fifo_we 去掉 && col_o[0]；
//    load_pix 用回 pack_pix，同时 SRC_W 恢复成 OW。
//==============================================================================
//==============================================================================
//  ★★ 2026-10-27：旧的"采样 + 打包 + dst_off"整块已删除 ★★
//  现在像素流是：bmp_read → bf FIFO(256x24) → bmp_scale → 写 FIFO。
//  分辨率换算、565 打包、行翻转全部由 bmp_scale 负责（SD/bmp_scale.v），
//  这里不再需要 col_o/row_o/sample_*/pix565_lo/dst_off。
//==============================================================================


//==============================================================================
//  写地址：线性布局，纹理就是一块连续的 640×480
//==============================================================================
//  ★ 上一版这里有一条"稀疏 12/16 布局"（TEX_PAT/sparse_lay，基址 1228800，
//    物理组号 p = g + g/3，把每个 16 字块的最后一组跳掉）。它基于"坏字严格
//    1/16、绝对地址 ≡15 (mod 16"这个观察，但板上结果证伪了：
//    稀疏布局把 tex_bad 从 49,051 压到约 700，而不动布局的"补空位"也压到 707
//    —— 同样的残差，说明根因不是"物理字 12..15 写不进"，稀疏白扔 25% 容量。
//  ⇒ 整块删除（连同 ps_gen_image 里配套的映射）。
//------------------------------------------------------------------------------

//==============================================================================
//  ★ build 100M-15：接单参数校验
//==============================================================================
//  dst_addr 只有 21 位：tex_base + OW*OH 一旦越过 2^21 就回绕，写到错误的
//  SDRAM 区域（静默，没有任何征兆）。load_offset 走 [31:9] 右移，非 512B
//  对齐的偏移会被静默向下取整而不是报错。
//  这两条都在 L_IDLE 接单时一次性判掉：不合法就不启动，直接报 err。
//  当前参数实测：TEX0 1703940+307200=2011140 < 2^21 ✓，偏移由
//  tools/sd_fat_offset.py 从 FAT 目录表算出，簇天然 512B 对齐 ✓。
//==============================================================================
wire [31:0] tex_span  = {11'd0, tex_base}
                      + (load_fmt ? (IMG_W * IMG_H) : (OW * OH));  // 纹理区末尾（不含）
wire        param_ovf = (tex_span > 32'd2097152);       // 越过 2^21
wire        param_unal= (load_offset[8:0] != 9'd0);     // 未 512B 对齐
wire        param_bad = param_ovf | param_unal;

//==============================================================================
//  ★ 2026-10-27：col_o/row_o 坐标推进块已删除（地址由 bmp_scale 直接给出）
//==============================================================================

//==============================================================================
//  写 FIFO：{addr[20:0], data[31:0]} 53bit，50MHz → 125MHz
//==============================================================================
wire        fifo_full;

//------------------------------------------------------------------------------
//  ★ build 100M-11：预清的实体（放这里才能引用 OW/OH 和 fifo_full）
//------------------------------------------------------------------------------
//  CLR_LEN = OW*OH：跑完整一圈 col_o/row_o 正好回到 0，不影响后面的装载
//  clr_push：满就等 —— 预清自己一个字都不许丢，否则"洞用洋红标出来"就不成立了
// ★ 注意：CLR_LEN 是"坐标栅格大小"，不是"实际字数"。
//   565 模式下每个字会被写两遍（col_o 偶/奇映射到同一地址，幂等），
//   所以必须跑满 ow*oh 个**坐标**，col_o/row_o 才能回到 (0,0)；
//   把它改成 38,400 会让预清只跑 120 行就跳走，后续整幅图错位。
// ★ 565：纹理是 160 字/行 × 240 行 = OW*OH/2 个字（1 字 = 2 个 RGB565 像素），
//   与 ps_gen_image 的 SRC_W「字数」口径一致。旧值是 OW*OH（每字写两遍的幂等
//   写法），现在渲染器每字只写一次 ⇒ 必须用真实字数，否则预清会越界到下一槽。
wire [20:0] CLR_LEN = load_fmt ? (IMG_W * IMG_H) : (OW * OH / 2);

assign in_clr   = (st == L_CLR);
assign clr_push = in_clr && !fifo_full && (clr_cnt != CLR_LEN);

//------------------------------------------------------------------------------
//  ★ build 100M-12：ack 复原成"一次性握手"，流控改走 wr_credit
//------------------------------------------------------------------------------
//  `write_req / write_req_ack` 是装载**开始时的一次性握手**（见上面的说明），
//  所以这里不需要任何限速，复原成原来的"打一拍应答"即可。
//  真正节流的是下面 `wr_credit` —— bmp_read 在两个扇区之间等它。
//------------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) bmp_ack <= 1'b0;
    else     bmp_ack <= bmp_write_req;
end

//------------------------------------------------------------------------------
//  ★ build 100M-12：扇区间流控信用
//------------------------------------------------------------------------------
//  `fifo_level` 是写域水位（img_afifo 新增的 wlevel，已经同步好的读指针算出来的）。
//  低于 LD_CREDIT_LEVEL 才允许 bmp_read 去读下一个扇区。
//  一个扇区 ≈ 170 像素，所以"放行后最高水位 ≈ 192+170 = 362 < 512"，永不满。
//------------------------------------------------------------------------------
wire [AFIFO_AW:0] fifo_level;

// 2026-10-27：信用改看**源像素 FIFO**（一扇区 ≈170 像素，门槛 80）
// ★ 2026-10-27：只有**渲染器真的在吃像素**（L_FEED）时才按水位限流。
//   否则（L_DRAIN/L_DONE：渲染器已提前收工，例如 contain 模式少用的源行）
//   必须无条件放行：源 FIFO 满了就不再写入（bf_we 自带 !bf_full），
//   bmp_read 把剩余字节读完回 IDLE，下一单的 can_load 才回得来。
//   旧写法在水位 ≥80 时永久拉低 ⇒ bmp_read 卡死 ⇒ 上层再也发不出 load_start。
assign wr_credit = (st != L_FEED) ? 1'b1 : (bf_cnt < 9'd80);
wire        fifo_empty;
wire [52:0] fifo_dout;

// 写 FIFO 的写使能：搬运状态收像素
// ★ 必须把 L_HDR 也算进来 ★
//   L_HDR 里 bmp_data_wr_en 拉高的那一拍就是**第 1 个像素**（见上面 L_HDR 的注释），
//   漏掉它会导致整幅图错位 + 状态机永远卡死。
// （单独拎出来是为了让端口连接保持"纯标识符"，tools/check_port_bind.py
