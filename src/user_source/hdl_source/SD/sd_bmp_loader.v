//==============================================================================
//  sd_bmp_loader.v —— SD 卡 BMP → SDRAM 纹理装载器
//==============================================================================
//
//  【它干什么】
//  给定"文件在 SD 卡里的字节偏移 + 字节长度 + 目标纹理基址"，把这张 BMP 的
//  像素搬进 SDRAM 的纹理区。搬运过程中顺手做两件事：
//      1. BGR → {8'hFF, R, G, B} 打包成 32bit（实时侧就零转换了）
//      2. 行翻转（BMP 自底向上存，翻成正序，读的时候直接顺序映射）
//
//  【为什么行翻转放在这里做】
//  翻转要在写地址上做手脚（第 r 行写到 (H-1-r) 行）。装载器本来就一行一行地
//  处理，一行之内地址连续，所以只要**每行开头算一次行基址**再行内自增即可 ——
//  零额外开销。放到读侧做的话每行都要反算，得不偿失。
//
//  【接口分成两边】
//      50MHz 侧（clk）：SD 卡 + BMP 解析 + 打包 + 地址计算
//      125MHz 侧（mclk）：写 FIFO 出口，交给写仲裁器塞进 SDRAM 写口
//  中间用一个 53bit × 16 深的异步 FIFO 跨时钟域（{addr[20:0], data[31:0]}）。
//
//  【为什么 FIFO 要带地址】
//  因为行翻转让写地址不是线性的，仲裁器没法自己推算。
//
//  【背压】
//  FIFO 满时装载器停下等 —— SD 读本来就慢，等一下无所谓。
//  这样"显示正在写帧、写口被占满"的时候装载器会自动让路，不会丢数据。
//
//  【绝不卡死】
//  文件头校验失败 / 长度不对 / SD 卡没初始化好 / 像素流中途断流 —— 一律回
//  IDLE 并置错误码，不会停在中间状态。
//
//  ★★★ build 100M-15：本轮修订（一次性修复评审意见）★★★
//  【done 的语义】原来是“最后一个像素入 FIFO”的同拍拉高，但那一刻 FIFO
//    里可能还有几百个字、仲裁器暂存里可能还有一组没发、控制器里可能还有
//    在途写 ⇒ done 不代表“纹理已经写进 SDRAM”。现在增加 L_DRAIN 状态：
//    等本 FIFO 排空（fifo_empty）+ 仲裁器报“已沉降”（wr_settled）之后
//    done 才拉高。带 1s 超时兜底（err_code=2），不会变成新的卡死点。
//  【像素流断流】L_FEED 原来只在 pix_cnt==0 时判错，而 L_HDR 进 L_FEED 时
//    pix_cnt 已置 1 ⇒ 那个分支是死代码；真正会卡死的是“搬了一半 bmp_read
//    因文件比预期短而提前回 IDLE”。现在判 pix_cnt < len_pix。
//  【像素数上限】len_pix 原来只用 load_length/3 粗估（文件头 54 字节也计成
//    了像素）。现在 bmp_read 把头部解析出的 pix_avail 交出来，装载器在收到
//    第 1 个像素时把 len_pix 收紧到 min(len_pix, pix_avail)。
//  【参数校验】接单时检查 tex_base + OW*OH 是否越过 2^21（会回绕）、
//    load_offset 是否 512B 对齐；不合法直接报错（err_code=3/4），不再静默
//    取整或写错位置。
//  【输出坐标】col_o/row_o 原来只随全局复位清零，靠“预清恰好跑满一圈”
//    回原点。现在 L_IDLE 里每拍都把它们摁在 0，中止路径也不会留半趟坐标。
//
//==============================================================================

module sd_bmp_loader #(
    parameter integer CLK_FREQ_HZ = 50_000_000,
    //  ★★★ build 100M-10（2026-10-19）：写 FIFO 16 → 512 深 ★★★
    //  【为什么必须加深】上板实测 `ld_occ_max = 0x10 = 16` —— 也就是说这个 16 深
    //  的 FIFO **真的到过满值**。满的那一刻 `img_afifo` 内部是
    //      we_q <= we && !wfull      ← push 被静默丢掉
    //  而本模块的 `col_o / row_o / pix_cnt` 照样前进（见下面 dbg_drop 的注释）
    //  ⇒ 那个纹理地址**永远留洞**，露出来的是上电前残留在 SDRAM 里的旧内容。
    //  这也解释了"反复切模式（=反复重装）脏像素会逐渐消失"：每遍随机丢一批，
    //  多遍下来每个字都被覆盖到了。
    //  【为什么是 512】一个 SD 扇区 = 512 字节 ≈ 170 像素，是天然的突发单位。
    //  512 深 = 能整扇区吞下再慢慢排空，余量 3 倍。
    //  【资源】53bit × 512 ≈ 27 kbit，正好 3 块 18Kb BRAM（本来就是 block RAM）。
    //  ★ 不要再调回 16。要省资源就先把 `c_drop` 读到 0 再说。
    parameter integer AFIFO_AW    = 9,          // 写 FIFO 深度 = 512（原 4 = 16）
    parameter integer IMG_W       = 640,        // 源图宽（BMP 里写的宽）
    parameter integer IMG_H       = 480,        // 源图高
    //--------------------------------------------------------------------------
    //  ★★ 2026-10-18 build D：装载时就把图**缩小**存进 SDRAM ★★
    //  【为什么】640×480 的源图 + 图层 2.667 倍缩放 ⇒ 每个输出像素都要去
    //  "跨 2~3 个字的随机地址"取一个字，再靠 4 字组挑字。这条随机取址路径
    //  在板上反复出问题（源 x 走过头、两个苹果、稀疏错点），而**顺序读**
    //  （帧缓存）一直是 100% 正确的。
    //  ⇒ 装载时直接下采样成 OUT_W×OUT_H（240×180）存好，图层改成 1:1 顺序读：
    //      · 地址流与帧缓存完全同构（连续递增）⇒ 4 字组天然对齐、永不挑错字
    //      · 纹理需求从 86400 组/帧降到 21600 组/帧 ⇒ 带宽余量 9 倍
    //  0 = 不下采样（默认，保持老 TB 行为不变）
    parameter integer OUT_W       = 0,
    parameter integer OUT_H       = 0
)(
    input  wire        clk,             // 50MHz（SD 侧）
    input  wire        rst,
    input  wire        mclk,            // 125MHz（写口侧）

    //------------------------------------------------------------------
    //  控制
    //------------------------------------------------------------------
    input  wire        load_start,      // 启动脉冲
    input  wire [31:0] load_offset,     // BMP 在 SD 卡里的字节偏移（必须 512 对齐）
    input  wire [31:0] load_length,     // 文件字节长度（兜底，防止坏文件头跑飞）
    input  wire [20:0] tex_base,        // 目标纹理在 SDRAM 里的基址
    //------------------------------------------------------------------
    //  ★ 2026-10-22 查看器：输出格式二选一（运行时可切，同一张 BMP 两种存法）
    //      0 = 320×240 RGB565 打包（1 字 2 像素，1/2 抽样）—— 过渡动画用
    //      1 = 640×480 RGB888（1 字 1 像素，不抽样）        —— 高清静止帧用
    //  约束：两种模式都从同一张 640×480 24bit BMP 读，load_length 是**文件字节数**。
    //------------------------------------------------------------------
    input  wire        load_fmt,

    output wire        sd_ready,        // SD 卡初始化完成（给顶层排启动时序用）
    output wire        ready,           // 空闲（只看本模块状态机）
    output wire        can_load,        // ★ 真正可以接 load_start：本模块空闲 **且** bmp_read 也空闲
    output wire        busy,            // 正在装载
    output wire        done,            // 装载完成（单拍脉冲）
    output wire        err,             // 装载失败（单拍脉冲：文件头非法 / 偏移填错 / 卡里不是 BMP）
    output wire [3:0]  state_code,      // 调试状态码
    // ★ 2026-10-27 诊断：**粘滞**错误码（0=无错 1=头部/断流 2=排空超时
    //   3=纹理越界 4=偏移未对齐）。原来 `err_code` 每个 IDLE 拍都被清零，
    //   而 `err` 又是单拍脉冲 ⇒ 上板完全看不到失败原因。
    output wire [3:0]  err_code_o,
    // ★ 2026-10-27 诊断：bmp_read 的状态码（0=IDLE 1=SCAN 2=LOAD_HDR
    //   3=LOAD_WAIT 4=LOAD_DATA）。`ready = (state==ST_IDLE)` 就是它的 0。
    //   板上 err_code=0 且装载器 IDLE ⇒ 装载没启动 ⇒ bmp_ready=0 ⇒ 看这一位。
    output wire [3:0]  bmp_state_o,
    //------------------------------------------------------------------
    // ★ 2026-10-26：装载进度 0..F（接数码管，一张图装载中的百分比）
    //   【怎么算】源图恒为 640×480 ⇒ `row`（源行号）0..479，
    //     row>>5 正好 0..15 十六档，**零成本**（一根移位线）。
    //   【什么时候到 F】done/err 时锁 F 并粘滞，直到下一次 load_start
    //     —— 否则装完瞬间掉回 0，看不出"刚装完"。
    //   【为什么用 row 不用 pix_cnt】pix_cnt/len_pix 需要除法，row 不需要。
    //   【时钟域】本模块跑在 sd_card_clk（50MHz，与系统 clk 同源），
    //     顶层仍按多比特慢变信号打两拍同步（见 top 的 ld_prog_sync）。
    //------------------------------------------------------------------
    output wire [3:0]  ld_prog,
    input  wire        load_fit,        // ★ 2026-10-27：适应屏幕（1=拉伸 0=contain）
    output wire [15:0] src_w_o,         // ★ 解析出的源分辨率（信息条显示）
    output wire [15:0] src_h_o,
    //------------------------------------------------------------------
    // ★ 2026-10-19 build 100M-4：写 FIFO "满时丢字" 计数（只观测）
    //   背景：`img_afifo` 内部是 `we_q <= we && !wfull` —— 满的那一刻这个 push
    //   被**静默丢掉**，而本模块的 `col_o/row_o/pix_cnt` 照样前进 ⇒ 地址永久留洞。
    //   把这个数读出来就能判定"6% 的洞"到底是不是这里丢的。
    //   饱和到 FFF，真实丢字数 ≥ 0xFFF 时恒显示 FFF。
    //------------------------------------------------------------------
    //  ★ build 100M-10：12 位 → 20 位。原来 12 位饱和到 FFF(4095)，一张图
    //  真丢 1.8 万字的话永远只显示 FFF，看不出量级。20 位能到 104 万。

    //------------------------------------------------------------------
    //  ★ build 100M-12：给 bmp_read 的"扇区间流控信用"
    //    1 = FIFO 还有空间，可以去读下一个扇区；0 = 先等着。
    //    bmp_read 的 ST_LOAD_DATA 里用它决定要不要重新拉高 sd_sec_read。
    //------------------------------------------------------------------
    output wire        wr_credit,

    //------------------------------------------------------------------
    //  写通道（125MHz 侧，接写仲裁器）
    //------------------------------------------------------------------
    output wire        wr_vld,          // FIFO 非空（有字要写）
    // ★ 2026-10-18：FIFO 里"真实还有几个字"（写口组包判据用）★
    //   原来写仲裁器用"vld 持续了几个周期"来估字数，可 vld 是电平信号：
    //   FIFO 里只剩 1~3 个字时它照样是高 ⇒ 仲裁器以为"够 4 个"就开组，
    //   于是连取 4 个（把空气取出来）⇒ 装载器地址推进 4 但只有 1~3 个真数据
    //   ⇒ 纹理区被写脏 + 写口命令流断裂（板上第 1 位 = 4 写口违规）。
    output wire [AFIFO_AW:0] wr_used,
    output wire [20:0] wr_addr,
    output wire [31:0] wr_data,
    input  wire        wr_ack,          // 仲裁器取走一个字（单拍）
    input  wire        wr_settled,      // ★ build 100M-15：仲裁器“写已沉降”（mclk 域电平）

    //------------------------------------------------------------------
    //  SD 卡扇区读（客户口）
    //------------------------------------------------------------------
    //  ★ 2026-10-27 step 3.1：SD 控制器已上移到顶层（sd_card_top + 仲裁器），
    //    本模块不再出四个 SD 引脚，改成"一个扇区级客户"：
    //      拉高 sd_sec_read（地址同时有效）→ 仲裁器授权后控制器吐 512 字节
    //      → sd_sec_read_end 单拍 → 拉低，等下一次。
    //    语义与原来直连 sd_card_top 完全一致，bmp_read 一行都没改。
    //------------------------------------------------------------------
    output wire        sd_sec_read,
    output wire [31:0] sd_sec_read_addr,
    input  wire [7:0]  sd_sec_read_data,
    input  wire        sd_sec_read_data_valid,
    input  wire        sd_sec_read_end,
    input  wire        sd_init_done      // SD 卡初始化完成（sdcard_top 输出）
);

//==============================================================================
//  状态编码
//==============================================================================
localparam L_IDLE = 4'd0;   // 空闲
localparam L_HDR  = 4'd1;   // 让 bmp_read 读文件头校验
localparam L_FEED = 4'd2;   // 搬运像素
localparam L_DONE = 4'd3;   // 完成（发一拍 done）
localparam L_ERR  = 4'd4;   // 出错（文件头非法 / 长度不对）
localparam L_CLR  = 4'd5;   // ★ build 100M-11：装载前先把整片纹理刷成常量
localparam L_DRAIN = 4'd6;  // ★ build 100M-15：等 FIFO 排空 + 写沉降，done 才拉高

//==============================================================================
//  ★★★ build 100M-11：装载前预清（把"残留旧数据"这条路断掉）★★★
//==============================================================================
//  【为什么】上板现象："直接烧录" 和 "断电 30 秒再烧录" 画面差很多。
//  这说明 **未写到的那些字露出来的是 SDRAM 里的残留旧内容** ——
//  内容取决于上一次跑的是什么，所以每次上电都不一样。
//  只要装载还有漏写（`B2 0 9 ≠ 0`），这个差异就永远存在。
//
//  【做法】每次装载前，先用一个**已知常量**把这张图要占的整片纹理区
//  （tex_base + 0 .. tex_base + OW*OH - 1）写一遍，然后再开始搬 BMP。
//  于是：
//      · 写到的字    = 真图
//      · 没写到的字  = 这个常量（**每次上电都一样**）
//  上电行为从此确定，不再受"上一次跑过什么"影响。
//
//  【为什么用洋红】它就是"洞"的显色剂：屏幕上任何一个洋红点 = 一个没写到的字。
//  想把洞藏起来就换成 32'hFFFF_FFFF（和苹果图的底色一致，洞在背景上看不出来）。
//  ★ 注意：换成白色只是"看不见"，不代表洞没了 —— 判据仍然是 `B2 0 9 = 0`。
//
//  【代价】每张图多 OW*OH 次写（307,200 字），按排水 2.34M 字/s 约 0.13s/张。
//  走的是同一条 FIFO 通路，并且带 `!fifo_full` 门控 ⇒ 预清自己一个字都不会丢。
//==============================================================================
localparam [31:0] PREFILL_COLOR = 32'hFFFF_00FF;   // 洋红（洞的显色剂）
//  ★ CLR_LEN / clr_cnt / clr_push 的实体放到下面 "写 FIFO" 那一节
//    （要引用 OW/OH 和 fifo_full，iverilog 不允许先用后声明）
//    ★ 这里先声明，因为 col_o/row_o 的推进块（在上面）要读 clr_push ★
reg  [20:0] clr_cnt;               // 预清进度 0 .. CLR_LEN-1
wire        in_clr;                // 正在预清
wire        clr_push;              // 这一拍往 FIFO 推一个常量

reg [3:0]  st;
reg [15:0] row, col;        // 当前**源**图里的行列（只用于 ld_prog 进度）

//==============================================================================
//  ★ 提前声明：下面 bf FIFO / 渲染器要用，而 iverilog 与 TD 都不接受
//  "先用后声明"（TD 会把它们当隐式 1 位线，等于静默截断）。
//==============================================================================
wire [15:0] src_w, src_h;                   // bmp_read 解析出的源分辨率
wire        scale_pix_rd, scale_we, scale_done, scale_busy;
// 写 FIFO 快满 → 冻结 bmp_scale 的冲刷（留 12 字余量，抵消 we/woff 打一拍的滞后）
localparam integer WR_FIFO_DEPTH = (1 << AFIFO_AW);
wire        scale_stall = (wr_used >= (WR_FIFO_DEPTH - 12));

wire [20:0] scale_woff;
wire [31:0] scale_wdata;
wire        bmp_data_wr_en;                 // 源像素有效（3 字节拼满一拍）
wire [23:0] bmp_data;
wire        bmp_ready;
wire        bmp_write_req;
wire [3:0]  bmp_state_code;

//==============================================================================
//  ★★ 2026-10-27：源像素 FIFO + 画布渲染器（bmp_scale）★★
//==============================================================================
//  旧路径是"像素 → 采样 → 打包 → 直接推 SDRAM 写 FIFO"，只能处理 640×480
//  （和它的 1:2 缩小版）。现在中间插一级：
//      任意 W×H 像素 → bf_fifo(256×24) → bmp_scale → 固定画布字流
//  bf_fifo 是为了**解耦两个速率**：渲染器一个源像素可能要写很多列（放大），
//  或者要反复冲刷同一行（纵向放大），此时必须能反压 SD 侧的扇区读取。
//  一扇区 ≈170 像素 ⇒ 门槛 80、深度 256 保证"放行一扇区永远不溢出"。
//  【★ 2026-10-27：改块 RAM ★】256×24 = 6144 bit，原来用组合读（
//   `pix (bf_mem[bf_rp[7:0]])`）⇒ 综合成分布式 RAM，约 380 个 LUT。
//   改成"读地址寄存 + 输出寄存"就能落进 1 个 9Kb 块（9Kb 池还剩 12 块）。
//  【怎么保持语义不变】读地址用 **rp + 本拍消费**（rp_nxt），这样：
//      · 稳态（FIFO 不空）：消费后的下一拍 bf_q 正好是下一个元素 ⇒ 仍是 1 拍/像素
//      · 空→有：写口正好写到要读的地址，块 RAM 读旧值 ⇒ 用写数据旁路
//      · 消费后变空：下一拍 bf_dv=0，渲染器多等一拍（只有这种情况有气泡）
(* ram_style = "block" *) (* ramstyle = "block" *) (* syn_ramstyle = "block" *)
reg  [23:0] bf_mem [0:255];
reg  [23:0] bf_ram;         // ★ RAM 的**纯**同步读输出（不带任何旁路）
reg         bf_hit_r;       // ★ 旁路选择位，与 bf_ram 同拍
reg  [23:0] bf_dat_r;       // ★ 旁路数据，与 bf_ram 同拍
reg         bf_dv;          // bf_q 本拍有效
reg  [8:0]  bf_wp, bf_rp;
wire [8:0]  bf_cnt   = bf_wp - bf_rp;
wire        bf_full  = (bf_cnt >= 9'd256);
wire        bf_we    = bmp_data_wr_en && ((st == L_FEED) || (st == L_HDR)) && !bf_full;
wire        bf_pop   = scale_pix_rd && bf_dv;            // 本拍真的吃掉一个
wire [8:0]  bf_rp_n  = bf_rp + (bf_pop ? 9'd1 : 9'd0);   // 消费后的读地址
wire        bf_hit   = bf_we && (bf_wp == bf_rp_n);      // 写的就是要读的那格

//------------------------------------------------------------------------------
//  ★★★ 2026-10-27：把"写旁路"移出 RAM 读表达式 —— 这才是落不进 BRAM 的真凶 ★★★
//------------------------------------------------------------------------------
//  【现象】syn 日志：`SYN-1027 : Infer Logic DRAM(u_loader/ramread0_syn_4)
//    read 256x24, write 256x24` ⇒ 6144 bit 全落分布式 RAM ≈ **384 个 LUT**。
//    明明上面写着 `ram_style = "block"`，属性被无视了。
//
//  【真凶】原来是这一行：
//        bf_q <= bf_hit ? bmp_data : bf_mem[bf_rp_n[7:0]];
//    RAM 的输出被 `? :` 组合选择掉了 ⇒ 输出不是"寄存后的 RAM 数据" ⇒
//    综合器认为这东西没法用块 RAM 的同步读实现，退回分布式 RAM。
//    （宽度 24 / 深度 256 都不是原因；`img_afifo` 用同样的 256 深度
//      + 同样的提前取址写法就能推成 BRAM。）
//
//  【改法】RAM 读只留 `bf_ram <= bf_mem[addr]` 这一句，纯净；
//    旁路的**选择位和数据各打一拍**（bf_hit_r / bf_dat_r），
//    再把 `bf_q` 做成寄存器之后的一级组合选择。
//
//  【为什么时序完全等价】三个量在同一拍寄存，所以下一拍同时可用：
//      原：bf_q(T+1) = bf_hit(T) ? bmp_data(T) : mem[bf_rp_n(T)]
//      新：bf_q(T+1) = bf_hit_r(T+1) ? bf_dat_r(T+1) : bf_ram(T+1)
//                    = bf_hit(T)   ? bmp_data(T)   : mem[bf_rp_n(T)]
//    逐位相同。RAM 读的延迟也不是问题：`img_afifo` 证明了 TD 的
//    `dout <= mem[addr]`（地址已提前一拍给出）就是 1 拍、
//    等价于组合读的 first-word-fall-through。本模块本来就在用
//    同样的"提前一拍取址"（bf_rp_n = 消费后的读地址）。
//
//  【代价】+25 FF（bf_hit_r + bf_dat_r[23:0]），换 −384 LUT。
//  【写读同址】写口本拍写、读口本拍读同一格时，块 RAM 读回旧值 ⇒
//    仍然由 bf_hit/bf_dat_r 这条旁路兜住，行为与改前一致。
//------------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) begin
        bf_wp <= 9'd0; bf_rp <= 9'd0;
        bf_ram   <= 24'd0;
        bf_hit_r <= 1'b0;
        bf_dat_r <= 24'd0;
        bf_dv <= 1'b0;
    end else begin
        if (bf_we) begin
            bf_mem[bf_wp[7:0]] <= bmp_data;
            bf_wp <= bf_wp + 9'd1;
        end
        // 读口：**只做 RAM 同步读**，不带任何组合旁路（否则推不成 BRAM）
        bf_ram   <= bf_mem[bf_rp_n[7:0]];
        // 旁路的选择位与数据同拍寄存
        bf_hit_r <= bf_hit;
        bf_dat_r <= bmp_data;
        bf_dv    <= (bf_wp != bf_rp_n);       // 下一拍 bf_q 是否对应一个真实元素
        bf_rp    <= bf_rp_n;
    end
end

// ★ 旁路选择放在 RAM 输出寄存器**之后**（一级组合 LUT），
//   三个源（bf_ram / bf_hit_r / bf_dat_r）同拍有效 ⇒ bf_q 与原设计同拍。
wire [23:0] bf_q = bf_hit_r ? bf_dat_r : bf_ram;

// 给渲染器的接口（与原来完全一致：pix_vld / pix / pix_rd）
wire        bf_pix_vld = bf_dv;
wire [23:0] bf_pix     = bf_q;

// 断流判据：FIFO 里既没有像素、渲染器也不在吃 ⇒ 连续 1.3s 就判截断
reg [22:0] feed_idle;
// 84ms @50MHz：必须大于"一次 SD 扇区读 + 一整行冲刷(641 拍)"的量级，
// 远小于用户能察觉的卡顿；旧值 1.3s 只是让坏文件多冻一秒多。
wire       feed_stall = (feed_idle == 23'h3F_FFFF);
always @(posedge clk or posedge rst) begin
    if (rst)                                    feed_idle <= 23'd0;
    else if (st != L_FEED)                      feed_idle <= 23'd0;
    else if (bf_we || scale_pix_rd)             feed_idle <= 23'd0;
    else if (!feed_stall)                       feed_idle <= feed_idle + 23'd1;
end

// 源图行列（只给 ld_prog 看）
always @(posedge clk or posedge rst) begin
    if (rst) begin
        col <= 16'd0; row <= 16'd0;
    end else if (st == L_IDLE) begin
        col <= 16'd0; row <= 16'd0;
    end else if (bf_we) begin
        if (col + 16'd1 >= src_w) begin col <= 16'd0; row <= row + 16'd1; end
        else                            col <= col + 16'd1;
    end
end

reg         scale_start;      // 单拍启动
reg         scale_done_seen; // 本次加载已经启动过渲染器（防重复 start）

