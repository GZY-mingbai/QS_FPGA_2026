    .fmt      (load_fmt),
    .pix_vld  (bf_pix_vld),
    .pix      (bf_pix),
    .pix_rd   (scale_pix_rd),
    .we       (scale_we),
    .woff     (scale_woff),
    .wdata    (scale_wdata),
    .busy     (scale_busy),
    .done     (scale_done),
    // ★ 2026-10-27：FIFO 快满就冻结 bmp_scale 的冲刷（留 12 字余量，
    //   抵消 we/woff 打一拍造成的滞后）。AFIFO_AW=9 ⇒ 深 512。
    .stall    (scale_stall)
);
reg        load_go;         // 给 bmp_read 的启动脉冲
reg [31:0] lat_sector;
reg        bmp_ack;         // 给 bmp_read 的写握手自应答
reg [3:0]  err_code;
reg        err_p;           // 出错脉冲（给顶层报"这一槽没装上"）
// ★ 2026-10-27：粘滞错误码 —— 只在"新一单真正开始"时清零，其它时候保持。
//   这样上板失败后数码管能一直看到原因，不会被 IDLE 冲掉。
reg [3:0]  err_lat;
always @(posedge clk or posedge rst) begin
    if (rst)
        err_lat <= 4'd0;
    else if (load_start && bmp_ready)
        err_lat <= 4'd0;                 // 新一单开始：清掉上次的
    else if (err_p)
        err_lat <= err_code;             // 出错那拍记下来（此后一直保持）
end
assign err_code_o = err_lat;
assign bmp_state_o = bmp_state_code;
reg        hdr_busy_seen;   // L_HDR 期间是否见过 bmp_read 忙起来（用来判"文件头非法"）

