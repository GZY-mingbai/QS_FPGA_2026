//==============================================================================
//  ★ build 100M-15：mclk 域 → clk 域电平同步 + 排空超时计数（L_DRAIN 用）
//==============================================================================
//  fifo_empty（img_afifo 的 rempty）和 wr_settled（仲裁器的沉降标志）都是
//  mclk 域产生的电平信号，直接采会亚稳态。两拍同步链，方向保守：同步滞后
//  只会让 L_DRAIN 多等几拍，不会早退。
//  排空超时：正常排空 ≤512 字 ≈ 1.3ms；1s（@50MHz）还排不完 ⇒ 写通路坏了
//  （或剩下 1~3 个字的尾巴凑不够 4 字一组），报 err_code=2 收工。
//==============================================================================
reg  fifo_empty_s1, fifo_empty_s2;
reg  wr_settled_s1, wr_settled_s2;
always @(posedge clk or posedge rst) begin
    if (rst) begin
        fifo_empty_s1 <= 1'b0; fifo_empty_s2 <= 1'b0;
        wr_settled_s1 <= 1'b0; wr_settled_s2 <= 1'b0;
    end else begin
        fifo_empty_s1 <= fifo_empty; fifo_empty_s2 <= fifo_empty_s1;
        wr_settled_s1 <= wr_settled; wr_settled_s2 <= wr_settled_s1;
    end
end

localparam [25:0] DRAIN_TO = 26'd49_999_999;   // 1s @50MHz（正常排空 ~1.3ms，余量 760×）
reg  [25:0] drain_cnt;
always @(posedge clk or posedge rst) begin
    if (rst)
        drain_cnt <= 26'd0;
    else if (st != L_DRAIN)
        drain_cnt <= 26'd0;
    else if (!(fifo_empty_s2 && wr_settled_s2))
        drain_cnt <= drain_cnt + 26'd1;
end
wire drain_to = (st == L_DRAIN) && (drain_cnt >= DRAIN_TO);

//==============================================================================
//  主状态机
//==============================================================================
always @(posedge clk or posedge rst) begin
    if (rst) begin
        st        <= L_IDLE;
        load_go   <= 1'b0;
        lat_sector<= 32'd0;
        err_code  <= 4'd0;
        err_p     <= 1'b0;
        hdr_busy_seen <= 1'b0;
    end else begin
        load_go <= 1'b0;
        err_p   <= 1'b0;                        // 默认单拍脉冲

        if (!sd_init_done) begin
            // SD 卡没就绪 → 回空闲（等初始化完再重试）
            st       <= L_IDLE;
            // ★ row/col 由下面那个独立 always 独占驱动（进 L_IDLE 自动归零），
            //   这里再写一次就是多驱动，TD 直接报 row[15] driven from multiple places。
            err_code <= 4'd0;
        end else begin
            scale_start <= 1'b0;
            case (st)
            //--------------------------------------------------------------
            //  L_IDLE：等启动
            //--------------------------------------------------------------
            L_IDLE: begin
                err_code<= 4'd0;
                hdr_busy_seen <= 1'b0;
                scale_done_seen <= 1'b0;    // 每一单只允许启动一次渲染器
                // ★ build 100M-15：输出坐标的归零不在这里做 —— col_o/row_o 由
                //   “行列推进”块独占驱动（状态机里再赋值 = 多驱动，综合报错）。
                //   归零条件合并在那个块的 L_IDLE 分支里，见文件上部的说明。
                if (load_start && bmp_ready) begin
                    // ★ build 100M-15：参数校验不过就不启动，直接报错
                    //   纹理越界会静默回绕写到别的区；偏移非 512B 对齐会被
                    //   右移静默取整、读到错误位置。都不启动，错误码 3/4。
                    if (param_bad) begin
                        err_code <= param_ovf ? 4'h3 : 4'h4;
                        st       <= L_ERR;
                    end else begin
                    // 字节偏移 → 扇区号（FAT32 里文件数据一定从簇边界开始，
                    // 而簇 = 整数个 512B 扇区，所以偏移天然是 512 对齐的；
                    // 上面 param_unal 已把违反这一假设的情况挡掉）
                    // ★ 一定是"右移 9 位"（÷512），不是"把低 9 位清零" ★
                    //   踩过的坑：写成 {load_offset[31:9], 9'd0} 时算的是
                    //   "偏移按 512 向下取整"，偏移非 0 时扇区号会大 512 倍，
                    //   于是去读一个根本不存在的位置（偏移 0 时两者相同，看不出来）。
                    lat_sector <= {9'd0, load_offset[31:9]};
                    // 像素数上限 = min(一帧像素数, 字节长度/3)
                    //   ★ build 100M-15：这里只是初值。load_length 是整文件
                    //     字节数（含 54 字节头），除 3 会多算约 18 个像素；
                    //     收到第 1 个像素时用 bmp_read 交出的 pix_avail
                    //     （头部 file_len/pixel_offset 算出的权威值）收紧，
                    //     见下面 L_HDR。
                    // ★ 2026-10-27：删掉 len_pix = load_length/3。
                    //   ① 它的唯一读者（"文件比预期短"判据）已由 feed_stall 取代；
                    //   ② DSP 已 100%，这个 32 位 ÷3 会落成大乘法器（数百 LUT）。
                    clr_cnt    <= 21'd0;
                    // ★ build 100M-11：先去预清整片纹理，清完再让 bmp_read 开工。
                    //   （这里**不能**先发 load_go —— 否则 bmp_read 提前吐像素，
                    //     预清期间那些像素会被丢掉，第一行就错位了。）
                    st         <= L_CLR;
                    end
                end
            end

            //--------------------------------------------------------------
            //  L_CLR：装载前把整片纹理区刷成 PREFILL_COLOR（洞的显色剂）
            //--------------------------------------------------------------
            //  走到这里的唯一前提是 L_IDLE 收到 load_start。
            //  clr_push 自带 `!fifo_full` 门控 ⇒ 预清自己一个字都不会丢。
            //  col_o/row_o 从 0 跑到 OW*OH-1 正好落回 0，紧接着的 L_HDR
            //  从 (0,0) 开始写，不用再复位。
            //--------------------------------------------------------------
            L_CLR: begin
                if (clr_push) begin
                    if (clr_cnt + 21'd1 >= CLR_LEN) begin
                        clr_cnt <= 21'd0;
                        load_go <= 1'b1;          // 清完才启动 bmp_read
                        st      <= L_HDR;
                    end else begin
                        clr_cnt <= clr_cnt + 21'd1;
                    end
                end
            end

            //--------------------------------------------------------------
            //  L_HDR：bmp_read 读文件头 + 校验（它会自己走完 HDR→WAIT→DATA）
            //--------------------------------------------------------------
            L_HDR: begin
                // bmp_read 收到 load_start 后会离开 IDLE 去读文件头
                if (!bmp_ready)
                    hdr_busy_seen <= 1'b1;

                // ★★★ 这一拍就是【第 1 个像素】，不能只切状态 ★★★
                //  【踩过的坑 · 2026-10-16 全链路仿真】
                //  原来这里只写 `st <= L_FEED`，于是第一个像素既没被 pix_cnt 数到、
                //  也没被写进 FIFO（fifo_we 当时要求 st==L_FEED）。结果：
                //      · 纹理少第 1 个像素（整幅图错位 1 个像素）
                //      · pix_cnt 永远差 1 → **永远到不了 len_pix → 状态机卡死在 L_FEED**
                //        （上板表现就是"装载永远不结束、图片永远不出来"）
                // ★★ 2026-10-27：不再等"第一个像素"，改等 bmp_read 的写握手 ★★
                //   握手那一拍头部已经解析完 ⇒ src_w/src_h 有效，可以启动渲染器。
                //   像素要几百拍后才到（bmp_read 还要重读扇区 0），正好留给
                //   bmp_scale 算几何（3 次串行除法 ≈ 100 拍）。
                if (bmp_write_req) begin
                    // 写握手只应出现一次；万一它连续几拍为高，也绝不能再 start
                    //（渲染器一旦收工回 IDLE，重复 start 会把画布重画一遍 ⇒ 花屏）
                    if (!scale_done_seen) begin
                        scale_start    <= 1'b1;
                        scale_done_seen <= 1'b1;
                    end
                    st <= L_FEED;
                end
                // ★ 绝不卡死 ★
                //   它忙过一阵又回到空闲、却一个像素都没吐 → 文件头非法
                //   （偏移填错、卡里那个位置不是 BMP、分辨率/位深不对……）
                //   没有这一条的话状态机会永远停在 L_HDR。
                else if (hdr_busy_seen && bmp_ready) begin
                    err_code <= 4'h1;
                    st       <= L_ERR;
                end
            end

            //--------------------------------------------------------------
            //  L_FEED：收像素、算地址、压 FIFO
            //--------------------------------------------------------------
            L_FEED: begin
                // 渲染器跑完（它自己数完 src_h 行）⇒ 去排空
                if (scale_done) st <= L_DRAIN;
                // 断流兜底：bmp_read 已经结束、FIFO 也空了，而渲染器还没跑完
                //   ⇒ 文件比头部声明的短（截断）。用"连续 1.3s 没有像素进出"判，
                //   避免把正常的"冲刷整行"误判成断流。
                else if (feed_stall) begin
                    err_code <= 4'h1;
                    st       <= L_ERR;
                end
                // 【绝不卡死】bmp_read 已经结束本次事务（回 IDLE）但像素还没搬够
                //   ⇒ 文件比预期短（头部 file_len 与 load_length 不一致）→ 报错。
                //   ★ build 100M-15：原来只判 pix_cnt==0，而 L_HDR 进 L_FEED 时
                //     pix_cnt 已置 1 ⇒ 那个分支永远是死代码；真正会卡死的是
                //     “搬了一半断流”。bmp_read 回 IDLE 的唯一可能就是文件读完了
                //     （bmp_len_cnt >= file_len → ST_IDLE），此时确实没有像素了。
                //     优先级：同一拍既有像素又 bmp_ready 时先收像素（else-if
                //     天然保证）—— 收完正好够数就走 L_DRAIN，不会误报。
                // ★ 2026-10-27：删掉"bmp_ready && pix_cnt < len_pix"这条。
                //   渲染器才是收工权威（scale_done），而 len_pix 来自
                //   load_length/3 —— 把 54 字节文件头也算成了像素，正常文件
                //   末尾必然差 18 个 ⇒ 100% 误报（联仿里 100x400 就是这么挂的）。
                //   真正的"文件比声明短"由上面的 feed_stall 兜底。
            end

            //--------------------------------------------------------------
            //  L_DRAIN：等本 FIFO 排空 + 仲裁器“写已沉降”，done 才拉高
            //--------------------------------------------------------------
            //  ★ build 100M-15：done 的语义从“像素已交给 FIFO”升级为
            //    “纹理已经写进 SDRAM”：
            //      ① fifo_empty_s2 —— 写 FIFO 已排空（rempty 两拍同步过来）
            //      ② wr_settled_s2 —— 仲裁器：FIFO 空 + 暂存空 + 无在发组 +
            //         无欠空写组，且连续保持 32 拍（覆盖控制器写周转）
            //    两者都是电平、方向保守（只会更晚不会更早）。
            //  【为什么不会永远等】预清 + 图像的总字数是 4 的倍数（OW*OH 和
            //    采样像素数都是），仲裁器 4 字一组取数 ⇒ 正常路径 FIFO 可精确
            //    排空；LD 槽在 ld_wr_vld||ld_buf_v 时无条件归装载 ⇒ 不会饿死。
            //    超时（err_code=2）只是防“写通路坏了/尾巴凑不够一组”的兜底。
            //--------------------------------------------------------------
            L_DRAIN: begin
                if (drain_to) begin
                    err_code <= 4'h2;
                    st       <= L_ERR;
                end else if (fifo_empty_s2 && wr_settled_s2) begin
                    st <= L_DONE;
                end
            end

            //--------------------------------------------------------------
            //  L_DONE / L_ERR
            //--------------------------------------------------------------
            L_DONE: st <= L_IDLE;
            default: begin   // L_ERR
                // ★ build 100M-15：不再在这里覆盖 err_code —— 各检测点写入的
                //   具体错误码（1=文件头非法/断流 2=排空超时 3=纹理越界
                //   4=偏移未对齐）要保留到上层读得见。
                err_p    <= 1'b1;           // 报给顶层：这一槽没装上
                st       <= L_IDLE;
            end
            endcase
        end
    end
end

assign src_w_o = src_w;
assign src_h_o = src_h;
assign sd_ready = sd_init_done;
assign ready  = (st == L_IDLE);
assign busy   = (st != L_IDLE);
assign done   = (st == L_DONE);
assign err    = err_p;

// ★ can_load：给"上一层"用的接单条件 ★
//  【为什么要单独开一根】
//   st == L_IDLE 只说明**自己**空着，但下一单还要靠 bmp_read 去读文件头，
//   L_IDLE 那行的收单条件是 `load_start && bmp_ready` —— 如果上一张图搬够
//   len_pix 就收工走人，而 bmp_read 还在把本扇区剩下的字节读完（或者文件头里的
//   file_len 字段被写坏成超大值，它压根读不完），bmp_ready 就会一直是 0：
//      ready=1 但收不了单 → 上层发的 load_start 被整个丢掉 → 上层永远等下去。
//   把这根引出去，上层改成"can_load 才发单"，就再也不会出现这种假就绪。
assign can_load = (st == L_IDLE) && bmp_ready;

// 状态码：给数码管看
assign state_code = (st == L_IDLE) ? 4'h0 :
                    (st == L_CLR)  ? 4'h8 :      // ★ build 100M-11：预清中
                    (st == L_HDR)  ? 4'h1 :
                    (st == L_FEED) ? (4'h2 + {2'b0, bmp_state_code[1:0]}) :
                    (st == L_DRAIN)? 4'hD :      // ★ build 100M-15：排空中
                    (st == L_DONE) ? 4'hE : 4'hF;

