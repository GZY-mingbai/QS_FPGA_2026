//==============================================================================
//  sd_bus_arbiter.v —— SD 卡扇区级总线仲裁（图像 / 音频）
//==============================================================================
//
//  【为什么需要它】
//  以前 `sd_card_top` 被埋在 `SD/sd_bmp_loader.v` 里面，SD 的四个引脚也从
//  装载器出。现在音频也要读卡（放 WAV），而 SPI 总线只有一组，所以把
//  `sd_card_top` 提到顶层，两个客户通过本模块分时复用。
//
//  【为什么粒度是"一个扇区"】
//  `sd_card_top` 的读请求是**电平**语义：
//      拉高 sd_sec_read（地址同时有效）→ 它自己发 CMD17 → 吐 512 字节
//      → 在 S_READ_END 那一拍给出 sd_sec_read_end（单周期）
//      → 回 S_WAIT_READ_WRITE 重新等请求（此时才重新锁存地址）
//  换句话说：**在 end 之后换人，控制器里没有任何半截状态**。
//  这正是最小、最安全的复用粒度，也不需要改 sd_card_top 一行。
//
//  【仲裁策略：图像优先 + 音频按需抢占】
//    · 音频 FIFO 低于低水位（I_aud_urgent=1）→ 音频赢；
//    · 否则图像有请求 → 图像赢（保护装载看门狗的 1.34s 预算）；
//    · 都不满足 → 音频（它一次只拿 1 个扇区就够 2.67ms，不会饿死）。
//  【为什么不能做严格轮转】图像一张图 1800 扇区、0.65s，轮转会让它翻倍到
//  1.3s，正好撞上 1.34s 的装载看门狗 ⇒ 直接降级。音频平均只占 13%，
//  按需抢占就够了。
//
//  【授权一旦给出就锁存到 end】
//  客户中途撤请求也不会把授权收回来（否则控制器会把 end 发给别人）。
//  真的等不到 end（SD 卡异常）有超时兜底：21ms 后强制给客户一个 end 脉冲，
//  然后进 A_TO 把可能迟到的 end 吃掉，再回空闲。
//
//  【时钟域】全部在 sd_card_clk（50MHz）—— sd_card_top、两个客户都在这个域，
//  数据通路是纯组合 mux，不需要任何同步器。
//==============================================================================

module sd_bus_arbiter #(
    //--------------------------------------------------------------------------
    //  超时：一个扇区正常 ~360us（SCLK 12.5MHz），这里给 20ms，约 55 倍余量
    //--------------------------------------------------------------------------
    parameter integer TIMEOUT_CYC = 1_000_000,
    // ★ 2026-10-30：音频限速（每 AUD_GAP_CYC 最多 1 个扇区），0 = 关闭
    parameter integer AUD_GAP_CYC = 66_000
)(
    input  wire        I_clk,               // sd_card_clk 50MHz
    input  wire        I_rst,               // 高有效
    input  wire        I_sd_init_done,      // 卡初始化完成前不授权

    //------------------------------------------------------------------
    //  客户 0：图像装载器（sd_bmp_loader）
    //------------------------------------------------------------------
    input  wire        I_img_req,
    input  wire [31:0] I_img_addr,
    output wire [7:0]  O_img_data,
    output wire        O_img_dv,
    output wire        O_img_end,

    //------------------------------------------------------------------
    //  客户 1：音频（sd_audio_reader）
    //------------------------------------------------------------------
    input  wire        I_aud_req,
    input  wire [31:0] I_aud_addr,
    input  wire        I_aud_urgent,        // FIFO 低于低水位 → 抢占
    output wire [7:0]  O_aud_data,
    output wire        O_aud_dv,
    output wire        O_aud_end,

    //------------------------------------------------------------------
    //  到 sd_card_top
    //------------------------------------------------------------------
    output reg         O_sd_sec_read,
    output reg  [31:0] O_sd_sec_addr,
    input  wire [7:0]  I_sd_sec_data,
    input  wire        I_sd_sec_dv,
    input  wire        I_sd_sec_end,

    //------------------------------------------------------------------
    //  调试
    //------------------------------------------------------------------
    output reg         O_timeout,           // 粘滞：发生过一次等不到 end
    output wire [1:0]  O_owner             // 0=空闲 1=图像 2=音频 3=间隙/超时
);

//==============================================================================
//  状态编码
//==============================================================================
localparam A_IDLE = 2'd0;   // 空闲，等请求
localparam A_IMG  = 2'd1;   // 已授权给图像，等 end
localparam A_AUD  = 2'd2;   // 已授权给音频，等 end
localparam A_GAP  = 2'd3;   // 强制一拍 req=0（让控制器回 WAIT 后再重新锁地址）

reg  [1:0]  st;
reg  [31:0] S_addr;         // 已锁存的扇区号（授权瞬间锁，之后保持不变）
reg  [19:0] to_cnt;         // 等 end 的计时

//==============================================================================
//  优先级
//==============================================================================
//  aud_urgent 时必须让音频赢，否则 FIFO 会在 10ms 内见底（爆音/断音）；
//  其余情况图像优先，保证装载时间不被音频拖长。
wire img_want = I_img_req;
wire aud_want = I_aud_req;

//------------------------------------------------------------------------------
//  ★ 2026-10-30：音频**限速**（每 AUD_GAP_CYC 最多 1 个扇区）
//------------------------------------------------------------------------------
//  【上板现象】一边放音乐，HD 装载明显变慢（有时候干脆卡住）。
//  【原因】音频的 urgent 是"低水位"语义，水位在门槛附近抖动时它就会**连续**
//    来抢；每个扇区在总线上要 ~364us，抢得越勤，图像那条链每行都要多等一个
//    扇区。图像一张 640x480 = 1800 扇区，行边界 480 次 × 364us ≈ 175ms。
//  【为什么可以限速】音乐只需要 48000 字/秒 = 每 2.67ms 一个扇区（128 字）。
//    这里给 1.33ms（2 倍余量）就绝对够听，而图像能拿到 >=70% 的带宽。
//  【为什么放在仲裁器】这是"公平性/有界性"的职责，且与音频内部状态无关 ——
//    音频那边再出什么毛病，图像也不会被拖垮。
reg [16:0] aud_gap_cnt;
reg        aud_ok;                              // 1 = 允许音频再拿一个扇区
always @(posedge I_clk or posedge I_rst) begin
    if (I_rst) begin
        aud_gap_cnt <= 17'd0;
        aud_ok      <= 1'b1;
    end else if (!aud_ok) begin
        if (aud_gap_cnt >= AUD_GAP_CYC[16:0]) begin
            aud_ok      <= 1'b1;
            aud_gap_cnt <= 17'd0;
        end else
            aud_gap_cnt <= aud_gap_cnt + 17'd1;
    end else if (st == A_AUD) begin
        aud_ok      <= 1'b0;                    // 刚给过一个，开始计时
        aud_gap_cnt <= 17'd0;
    end
end

wire aud_win  = aud_want && aud_ok && (I_aud_urgent || !img_want);
wire img_win  = img_want && !aud_win;

//==============================================================================
//  超时判定（计数器饱和，不会回绕）
//==============================================================================
wire to_hit = (to_cnt >= TIMEOUT_CYC);

//==============================================================================
//  主状态机
//==============================================================================
always @(posedge I_clk or posedge I_rst) begin
    if (I_rst) begin
        st             <= A_IDLE;
        S_addr         <= 32'd0;
        O_sd_sec_read  <= 1'b0;
        O_sd_sec_addr  <= 32'd0;
        to_cnt         <= 20'd0;
        O_timeout      <= 1'b0;
    end else begin

        case (st)
        //----------------------------------------------------------------------
        //  A_IDLE：等一个请求
        //----------------------------------------------------------------------
        A_IDLE: begin
            to_cnt <= 20'd0;
            if (I_sd_init_done && (img_win || aud_win)) begin
                S_addr        <= img_win ? I_img_addr : I_aud_addr;
                O_sd_sec_addr <= img_win ? I_img_addr : I_aud_addr;
                O_sd_sec_read <= 1'b1;
                st            <= img_win ? A_IMG : A_AUD;
            end
        end

        //----------------------------------------------------------------------
        //  A_IMG / A_AUD：已授权，收字节，等 end
        //----------------------------------------------------------------------
        A_IMG, A_AUD: begin
            if (I_sd_sec_end) begin
                // 正常收工：撤请求，进间隙
                O_sd_sec_read <= 1'b0;
                to_cnt        <= 20'd0;
                st            <= A_GAP;
            end else if (to_hit) begin
                // 异常兜底：这一拍直接给客户一个"假 end"（见下面的组合 assign），
                // 把它从等待里放出来；下一拍进间隙，把可能迟到的真 end 当空气吃掉。
                O_sd_sec_read <= 1'b0;
                O_timeout     <= 1'b1;
                to_cnt        <= 20'd0;
                st            <= A_GAP;
            end else begin
                to_cnt <= to_cnt + 20'd1;
            end
        end

        //----------------------------------------------------------------------
        //  A_GAP：req 已经拉低一拍。
        //   为什么必须有这一拍：sd_card_top 在 S_WRITE_END/S_READ_END 之后
        //   回到 S_WAIT_READ_WRITE，下一拍会重新锁存 sd_sec_read_addr。
        //   如果这一拍 req 还是高、地址又已经换成下一个客户，控制器就会
        //   拿错地址再读一个扇区（静默，数据全错）。
        //----------------------------------------------------------------------
        A_GAP: begin
            st <= A_IDLE;
        end

        default: st <= A_IDLE;
        endcase
    end
end

//==============================================================================
//  数据/结束信号的分发（纯组合，同域）
//==============================================================================
//  超时那一拍也要给客户一个 end（S_to），否则客户会一直等在 S_REQ 里。
assign O_img_data = I_sd_sec_data;
assign O_aud_data = I_sd_sec_data;

assign O_img_dv   = I_sd_sec_dv && (st == A_IMG);
assign O_aud_dv   = I_sd_sec_dv && (st == A_AUD);

//  超时那一拍也要给客户一个 end（to_hit），否则客户会一直等在等 end 的状态里。
assign O_img_end  = (st == A_IMG) && (I_sd_sec_end || to_hit);
assign O_aud_end  = (st == A_AUD) && (I_sd_sec_end || to_hit);

assign O_owner    = st;

endmodule
