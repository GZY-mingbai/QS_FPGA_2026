//=============================================================================
// 文件名   : seg_decoder.v
// 模块名   : seg_decoder
// 功能     : 【七段数码管译码器】
//            把 4bit 二进制数 (0~15) 翻译成七段数码管的段码 (a~g 共 7 段)。
//            纯组合逻辑，没有时钟、没有寄存器。
//
// 什么是七段数码管 ?
//   一个"8"字形的显示器件，由 7 根发光条（a~g）加 1 个小数点(dp)组成。
//   点亮相应的段就能拼出数字。比如想显示"0"，就要点亮 a b c d e f 六段，
//   只有中间的 g 段不亮。所谓"段码"，就是用 7 个 bit 表示这 7 段亮不亮。
//
// 本模块的段码排列（共阳极，低电平点亮）：
//   位序 =>   [6]   [5]   [4]   [3]   [2]   [1]   [0]
//             g     f     e     d     c     b     a
//   因为 7'b100_0000 效果是"只亮 a 段"却对应数字 0，说明实际电路是共阳极：
//   输出 0 才点亮，1 熄灭。所以这里给的段码表是"反着的"（0 表示亮）。
//
// 如何使用 ?
//   输入端接一个 4bit 数（比如计数器输出），输出端 seg_data 接数码管的段选线。
//   本例程中真正使用的是 seg_scan.v（8bit 版本、带小数点），
//   这个 7bit 版本是配套的通用小模块。
//=============================================================================

module seg_decoder
(
	input[3:0]      bin_data,     // bin data input - 待显示的数字，0~15
	output reg[6:0] seg_data      // seven segments LED output - 七段段码输出
);

// 组合逻辑 case 表：输入数字 -> 输出段码
// always@(*) 表示"输入一变就立刻重算"，等价于纯组合电路
always@(*)
begin
	case(bin_data)
		4'd0:seg_data <= 7'b100_0000;   // 显示 0
		4'd1:seg_data <= 7'b111_1001;   // 1
		4'd2:seg_data <= 7'b010_0100;   // 2
		4'd3:seg_data <= 7'b011_0000;   // 3
		4'd4:seg_data <= 7'b001_1001;   // 4
		4'd5:seg_data <= 7'b001_0010;   // 5
		4'd6:seg_data <= 7'b000_0010;   // 6
		4'd7:seg_data <= 7'b111_1000;   // 7
		4'd8:seg_data <= 7'b000_0000;   // 8（全亮）
		4'd9:seg_data <= 7'b001_0000;   // 9
		4'ha:seg_data <= 7'b000_1000;   // A
		4'hb:seg_data <= 7'b000_0011;   // b
		4'hc:seg_data <= 7'b100_0110;   // C
		4'hd:seg_data <= 7'b010_0001;   // d
		4'he:seg_data <= 7'b000_0110;   // E
		4'hf:seg_data <= 7'b000_1110;   // F
		default:seg_data <= 7'b111_1111; // 全灭（防呆，二进制不会有除0~15外的值）
	endcase
end
endmodule
