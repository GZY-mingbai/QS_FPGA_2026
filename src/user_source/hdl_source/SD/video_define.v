
//==============================================================================
//  video_define.v  —— 分辨率宏定义（整个文件就一行）
//==============================================================================
//
//  【这个文件干什么的】
//  它定义了一个宏 VIDEO_640_480，用来告诉 color_bar.v 该用哪套时序参数。
//
//  【`define 是什么】
//  这是 Verilog 的"文本替换"预处理指令，和 C 语言的 #define 一样。
//  写了这一行之后，凡是代码里出现 `VIDEO_640_480 的地方，
//  都会被替换/识别成"已定义"。
//
//  【color_bar.v 里怎么用它】
//  那里用了一堆 `ifdef ... `endif 把各种分辨率的参数表包起来，
//  只有被定义的那个才会生效。本工程只定义了 640_480，
//  所以其他分辨率的参数会被编译器完全忽略（不占任何资源）。
//
//  ★ 想换分辨率怎么办 ★
//  把这一行改成比如 `define VIDEO_800_600，
//  前提是 color_bar.v 里必须有对应的参数表（它里面有 7 种分辨率的表）。
//  但这只是"时序"换了，你还必须同步改：
//    ① video_pll 的输出频率（像素时钟要变）
//    ② top 里 HDMI IP 的 HTOTAL/VTOTAL 等参数
//    ③ FRAME_PIXELS、bmp_width/height
//    ④ TF 卡里图片的实际分辨率
//  只改这一行是不够的，切记。
//
`define	VIDEO_640_480
