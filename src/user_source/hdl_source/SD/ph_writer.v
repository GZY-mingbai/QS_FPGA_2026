//==============================================================================
//  ph_writer.v —— wav / txt 的“占位图”生成器（直接写 SDRAM 槽）
//==============================================================================
//
//  【为什么需要】文件页四宫格里，.wav / .txt 没有可显示的图像。空着会露出
//  SDRAM 里的陈货（相册帧缓存）⇒ 上板看起来像“花屏”。所以给它们画一张
//  程序生成的占位图：音频 = 均衡器柱，文本 = 文本行。
//
//  【为什么不用 Flash 里的 BMP】
//  计划里写的是“烧两张图到 flash，再给 bmp_loader 做输入 mux”。实际做的
//  时候有两个硬约束：
//    ① flash 里 0x03D000 之后是图标/提示音分区，**没有留占位图的位置**，
//       而烧 flash 需要接板子 + 专用下载器，本轮无法验证；
//    ② bmp_loader 的输入 mux 要同时切 addr/data/dv/end 四组线并保证
//       512 字节分帧，比“直接生成像素”更容易出错。
//  程序生成的好处：不依赖任何外部数据、可仿真验证、占用小（≈120 LUT），
//  而且**改了配色立刻生效**。接口（start/kind/base → busy/done）与
//  bmp_loader 同构，将来要换成 flash 图源只改这个模块。
//
//  【分辨率】（2026-11-04 起）槽 = 160×120 RGB565 直存：每行 80 字（每字 2 个显示像素）、
//  行距 160 字（槽间距 40960 不变），显示侧 1:1（见 ps_gen_image 的 quad_map）。
//  写 9600 个字，比读卡快两个数量级。原来是 320×240、显示时 2:1 抽样，
//  装载要读两倍的源行。
//  【写法】行内地址 +1，行末 +81（跳过行距里没用的 80 字）。
//  握手沿用装载写口：vld 保持到 ack（sdr_port_sched 的 LD 槽按配额服务）。
//==============================================================================

module ph_writer (
    input  wire        clk,
    input  wire        rst,

    //------------------------------------------------------------------
    //  启动
    //------------------------------------------------------------------
    input  wire        I_start,             // 单拍
    input  wire [1:0]  I_kind,              // 2 = WAV   3 = TXT   0 = 纯黑（BMP 还没装好时的底）
    input  wire [20:0] I_base,              // 槽基址（字地址）
    output reg         O_busy,
    // ★ 2026-11-04：1 = 本次是"纯黑"。像素数据不在这里清零 —— 顶层写口本来就有一台
    //   ph/bmp 32 位 2 选 1 mux，每位只用了 3 个输入，把 `& ~O_black` 并进去不多占 LUT。
    output wire        O_black,
    output reg         O_done,              // 单拍：整幅写完

    //------------------------------------------------------------------
    //  装载写口（与 bmp_loader 的 wr_* 同构，顶层做二选一）
    //------------------------------------------------------------------
    output reg         O_wr_vld,
    output reg  [20:0] O_wr_addr,
    // ★ 数据必须是**组合**输出：`wx` 在 ack 那一拍就前进，若把数据也打一拍，
    //   地址会比数据超前一个像素（实测整幅图右移 1 列）。
    output wire [31:0] O_wr_data,
    input  wire        I_wr_ack
);

// 显示坐标（0..159 × 0..119）
reg  [7:0] wx;                  // 字列（= 显示 x）
reg  [7:0] wy;                  // 显示 y（0..119），实际写两行
reg  [1:0] kind_r;
reg        run;

//------------------------------------------------------------------------------
//  配色（RGB565）
//------------------------------------------------------------------------------
localparam [15:0] C_BG     = 16'h10A4;   // 深底 #101423
localparam [15:0] C_GREEN  = 16'h3E71;   // #3ECF8E（音频）
localparam [15:0] C_BLUE   = 16'hADBA;   // #A9B6D6（文本）
localparam [15:0] C_DIM    = 16'h18C6;   // 内层稍亮一点的底

//------------------------------------------------------------------------------
//  像素函数（纯组合，只有一个"2px 边框 + 纯色卡"）
//------------------------------------------------------------------------------
//  ★ 2026-11-01：**这一版是"删"出来的**。
//    上一版有"4 根均衡器柱（柱高 4 档）/ 3 条文本条（行长 3 档）"，看着好一点，
//    但那是 2 个 case（8 位 4:1 / 3:1 mux）+ 一串 8 位比较，实测 75 LUT。
//    现在只剩：
//      · 外圈 2px = 主色（绿 = 音频 / 蓝 = 文本）  → 4 个比较
//      · 内圈 2px = 深底                            → 4 个比较（可与上面共用边界）
//      · 正中 32×32 一个实心块 = 主色              → 4 个比较
//    总计 ~25 LUT。wav / txt 靠**颜色**区分，不再靠图形。
//  ★ 为什么全对齐到 2 的幂/常量：减法/乘法在这个器件上一律 1 位 1 LUT，
//    上一版把 (wx-40)>>4 换成 wx[6:5] 就省了 200 LUT（见 PLAN §7J）。
//------------------------------------------------------------------------------
reg [15:0] ac;                  // 本图主色
reg [15:0] pc;                  // 当前像素

// 2px 外框 / 2px 内圈 / 正中色块（全部是常量比较，无加减法）
// ★ 2026-11-04：槽改成 160×120 直存（每字 = 横向相邻 2 个显示像素），wx 是**字**列 0..79
//   ⇒ 横向常量减半（2px 外框 = 1 字，4px = 2 字，色块 64..95 = 32..47 字）
wire outer = (wx < 8'd1) || (wx >= 8'd79) || (wy < 8'd2) || (wy >= 8'd118);
wire ring  = (wx < 8'd2) || (wx >= 8'd78) || (wy < 8'd4) || (wy >= 8'd116);
wire block = (wx >= 8'd32) && (wx < 8'd48) && (wy >= 8'd44) && (wy < 8'd76);

always @(*) begin
    ac = kind_r[0] ? C_BLUE : C_GREEN;     // 2 = WAV（绿） 3 = TXT（蓝）
    if (outer)      pc = ac;
    else if (ring)  pc = C_BG;
    else if (block) pc = ac;
    else            pc = C_DIM;
end

// 数据 = 当前 (wx,wy) 的两个像素（左右同色）
assign O_wr_data = {pc, pc};
assign O_black   = ~kind_r[1];

//------------------------------------------------------------------------------
//  主状态机
//------------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) begin
        O_busy    <= 1'b0;
        O_done    <= 1'b0;
        O_wr_vld  <= 1'b0;
        O_wr_addr <= 21'd0;
        wx        <= 8'd0;
        wy        <= 8'd0;
        kind_r    <= 2'd2;
        run       <= 1'b0;
    end else begin
        O_done <= 1'b0;

        if (!run) begin
            O_busy   <= 1'b0;
            O_wr_vld <= 1'b0;
            if (I_start) begin
                wx       <= 8'd0;
                wy       <= 8'd0;
                kind_r   <= I_kind;          // 原样锁存（0 = 黑，见 O_black）
                // ★ 地址就是写口本身：只在 ack 那一拍 +1，和 data 同源同拍
                O_wr_addr <= I_base;
                run      <= 1'b1;
                O_busy   <= 1'b1;
                // ★ 这一拍不发 vld：`pc` 用的是**上一张图**的 kind_r，
                //   第一个像素会画成另一种颜色的边框。下一拍 kind_r 已稳定。
                O_wr_vld <= 1'b0;
            end
        end else begin
            O_wr_vld <= 1'b1;
            if (O_wr_vld && I_wr_ack) begin
                if (wx == 8'd79) begin
                    // 行末：跳到下一行行首（行距 160 字，本行只写了 80 字）
                    O_wr_addr <= O_wr_addr + 21'd81;
                    wx <= 8'd0;
                    if (wy == 8'd119) begin
                        // 全部写完（80 × 120 = 9600 字 = 2400 组，组内 4 个 ack 正好整除）
                        run      <= 1'b0;
                        O_busy   <= 1'b0;
                        O_done   <= 1'b1;
                        O_wr_vld <= 1'b0;
                    end else begin
                        wy <= wy + 8'd1;
                    end
                end else begin
                    O_wr_addr <= O_wr_addr + 21'd1;
                    wx <= wx + 8'd1;
                end
            end
        end
    end
end

endmodule
