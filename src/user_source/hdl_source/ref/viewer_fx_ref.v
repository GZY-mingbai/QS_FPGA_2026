//==============================================================================
//  viewer_fx.v —— 过渡动画的逐帧几何发生器（按"进度"参数化）
//==============================================================================
//
//  【它算什么】给 A/B 两块图片层输出"这一帧"的
//      pos  = {X0[15:0], Y0[15:0]}      （负坐标 = 图移出屏幕，图层支持）
//      size = {RW[15:0], RH[15:0]}
//      k    = {KX[19:0], KY[19:0]}      （Q16：源宽/RW）
//      alpha_b                          （B 盖在 A 上的不透明度）
//
//  【★ 2026-10-23 重写：一切由"进度"导出，时长只由 T_END 决定 ★】
//  旧版把"每帧走多少像素"写死在公式里（X0A = -20t），所以 T_END 一改，
//  位移就把图甩到屏幕外面去了。现在统一先算一个进度量
//
//      q = t * 256 / T_END        （0 .. 256，就是 e 的 Q8 定点）
//
//  所有几何量都写成 (q * 总量) >> 8，于是：
//      · 改 T_END 只改时长，几何形状/端点完全不变
//      · q=0   一定等于"起始静止帧"
//      · q=256 一定等于"目标静止帧"
//  这条不变式由 tb_fx.v 逐帧断言（见 app.md 第 8 节）。
//
//  【★ 2026-10-26：所有插值改走 ease-in-out（smoothstep）★】
//      e = 3u² − 2u³ （u = q/256，Q8 定点）⇒ 两端斜率 0、中点最快。
//      线性插值"起步就全速、到终点急停"，观感生硬；smoothstep 是标准缓动。
//      端点精确不变：e(0)=0、e(256)=256 ⇒ 下面的端点不变式照旧成立。
//
//  【★ 2026-10-26：方向感知 dir（前后关系匹配）★】
//      dir=1（key_next，"下一张"）⇒ 画面**向左/向上**滚出，新图从右/下进入
//      dir=0（key_prev，"上一张"）⇒ 全部水平/竖直镜像，画面向右/向下滚回
//      镜像公式：x0' = IMG_W − x0 − w（y 同理用 IMG_H）⇒ 起点/终点/中点
//      三个不变式都与 dir 无关（终点仍是 B=640×480@(0,0)），只是"从哪侧出屏"不同。
//      fx2（淡入淡出）无方向；fx3/fx4 的"放大段"绕屏幕中心对称，也与 dir 无关。
//
//  【五种效果；e = ease(q_f) 或 ease 后的分段进度】
//    fx0 左右平移：  next  A X0=-640e, B X0=640-640e   prev 全部取反      （1s）
//    fx1 上下平移：  next  A Y0=-480e, B Y0=480-480e   prev 全部取反      （1s）
//                    （next=向上滚：内容上移、新图从下方进入；prev=向下滚）
//    fx2 淡入淡出：  两层都在 (0,0) 全屏         alpha = 255e（无方向）   （1s）
//    fx3 缩小交换：                                                       （3s）
//        前半段 s1：A 缩到 50% 且与 B 一起横移（缩小和移动**同时**进行）
//            A  尺寸 640×480 → 320×240，next 时中心 (320,240) → (-160,240)
//               ⇒ next pos = (-320s1, 120s1)  prev pos = (640s1, 120s1)
//            B  尺寸恒 320×240，next 从右侧屏外滑到屏幕中心
//               ⇒ next pos = (640-480s1, 120)  prev pos = (480s1-320, 120)
//            两层中心以同一速度横移 480px（刚性平移对），A 同时缩放。
//            段末（q=128）：B 精确停在屏幕中心 320×240@(160,120)，A 已完全出屏
//                          （next 出左侧、prev 出右侧）。
//        后半段 s2：B 以屏幕中心为锚放大 50% → 满屏（绕中心对称，与 dir 无关）
//            pos = (160-160s2, 120-120s2)  size = (320+320s2, 240+240s2)
//            段末（q=256）：B = 640×480@(0,0)，与目标静止帧逐像素相同。
//        ★ 2026-10-26：fx3/fx4 的 ease-in-out 是**整条动画一条曲线**
//          （用户要求"不要按缩放分"）：s1/s2 只是把同一条 smoothstep
//          切成两半用，段边界处全速通过，不再有"停稳"感。
//    fx4 缩小交换 + 移门式交接，**缩放档 80%**（2026-10-26 v5）：           （3s）
//        前半段 s1：A 从满屏缩到 80%（640×480 → 512×384）并左移；
//            B 以 80% 从屏右外滑入 —— **接缝恒等**（A 右沿 ≡ B 左沿 ≡ 640−384s1），
//            零缝隙零重叠，两层像一扇移门精确对接。
//              next: A=(-256s, 48s) size=(640-128s, 480-96s)
//                    B=(640-384s, 48) 512×384
//              prev: 水平镜像（A 向右、B 从左侧进入；A 左沿 ≡ B 右沿 ≡ 384s）
//            中点（q=128）：A@(-256,48) 管屏幕左 256px、B@(256,48) 管右 384px。
//        后半段 s2：A **保持 80%**、以与前半段相同的 256px 位移继续移出屏；
//            B 边放大边左移铺满（左沿 256→0、宽 512→640、高 384→480）。
//              next pos=(256-256s, 48-48s)  prev pos=(-128+128s, 48-48s)
//            接缝恒等延续（A 右沿 ≡ B 左沿 ≡ 256−256s2），s2=1 时精确交汇于 0：
//            A 刚好完全出屏的同一刻 B 刚好铺满。
//        ★ 对称性设计（2026-10-26 修"观感不对称"）：
//            · A 前半段/后半段位移相等（各 256px）⇒ 速度曲线关于中点严格对称；
//            · B 位移 384+256（加放大），不再"前狂奔 512 后停滞 128"；
//            · 去掉 v4 的"两层重叠 128s1"——B alpha=255 会盖住 A，重叠区画面混杂；
//            · 左图最终缩放（80%）== 右图初始缩放（80%）（用户要求）。
//
//  【fx3/fx4 的硬约束（上板踩出来的）】
//  约束一：**画框面积绝不能超过 640×480**。
//      ps_gen_image.v:752 里 `rq_can_adv` 带着 `(rq_idx < NPX)`，
//      而 rq_idx 数的是本帧框内源像素个数，上限被写死成 NPX=307200。
//      旧版 fx3 让 A 长到 800×600 = 480000 ⇒ rq_idx 撞上限 ⇒ 请求侧停走
//      ⇒ 显示侧等一个永远不来的像素 ⇒ 帧收不满 ⇒ 没有 tick ⇒ 卡在状态 3。
//      触发点还特别早：q=2 时 RW=641，641×480=307680 就已经超了。
//      现在 fx3 全程 ∈ [320×240, 640×480]、fx4 全程 ∈ [512×384, 640×480]，
//      面积只减不增 ✓
//  【不变式】（tb_fx 逐帧断言，均与 dir 无关）
//      q=0   ⇒ A == 640×480 @ (0,0)     与起始静止帧逐像素相同
//      q=256 ⇒ B == 640×480 @ (0,0)     与目标静止帧逐像素相同
//      q=128 ⇒ fx3：B == 320×240 @ (160,120) 图2 恰好在屏幕中心
//      q=128 ⇒ fx4：A@(-256,48)、B@(256,48)，都是 512×384，接缝恒等相接
//               （next：A 右沿 ≡ B 左沿 ≡ 256；prev：A 左沿 ≡ B 右沿 ≡ 384）
//               ⇒ 零缝隙零重叠，并集盖满屏幕
//      ∀q    ⇒ 两层的宽×高都不超过 640×480（约束一）
//  【代价】fx3/fx4 中间帧是故意露黑底的（图片缩小必然露出背景），
//    这是"缩小交换"效果的固有观感，不再是旧版那种"拉进来"的挤压感。
//
//  【K 怎么来（不再查表）】
//      KX = 65536*160/RW，KY = 65536*240/RH
//  旧版用 33 项常量表，只覆盖 t=0..32（default 直接夹到 RW=448）——
//  一旦 T_END 变长，缩放会在前 1/9 的时间缩到底然后静止。
//  现在改成**每帧串行算 4 次除法**（KX_A/KY_A/KX_B/KY_B）：
//      24 拍/次 × 4 = 96 拍，占一帧 835000 拍的 0.011%。
//  不用运行时组合除法（TD 会把它做成一坨长组合逻辑，时序危险），
//  也不用 `/` 运算符，纯移位相减，结果精确。
//  注意：k 比 size 晚 ~100 拍到位，而 ps_gen_image 只在帧起点采样配置，
//  帧间有几十万拍，所以完全来得及。
//
//==============================================================================

module viewer_fx_ref #(
    parameter integer IMG_W  = 640,
    parameter integer IMG_H  = 480,
    parameter integer SRC_W  = 160,     // 缩略图行宽（字）= 320/2
    parameter integer SRC_H  = 240,     // 缩略图行数（像素）
    // ★ 过渡总帧数按时长分档（2026-10-26，用户指定）：
    //   T_END_F = 60 帧 ≈ 1.0s  → fx0/fx1/fx2（平移/淡入，动作简单，要快）
    //   T_END_S = 180 帧 ≈ 3.0s → fx3/fx4（缩小交换，编排长，保持 3s）
    // 改这两个数只改时长，几何形状/端点完全不变（q 由 t/T_END 归一化）。
    parameter integer T_END_F = 60,
    parameter integer T_END_S = 180,
    // ★ 2026-10-27：fx3 宽高走偶数步（见 §1 的 g320 注释）。
    //   0 = 旧行为（逐 1px），只给 tb_fx_equiv 的旧版逐值对照用。
    parameter integer FX3_EVEN = 1
)(
    input  wire        clk,
    input  wire        rst,

    input  wire [2:0]  fx_id,           // 0..4（★ 2026-10-26：2→3 位，新增 fx4）
    input  wire [11:0] t,               // 0..T_END（★ 2026-10-24：9→12 位，支持 T_END=3000）
    input  wire        upd,             // 一拍脉冲：锁存当前 t 的几何
    input  wire        dir,             // ★ 2026-10-26：1=next(下一张,向左/上滚)
                                        //              0=prev(上一张,向右/下滚)

    output reg  [31:0] pos_a,
    output reg  [31:0] size_a,
    output reg  [39:0] k_a,
    output reg  [31:0] pos_b,
    output reg  [31:0] size_b,
    output reg  [39:0] k_b,
    output reg  [7:0]  alpha_b
);

//==============================================================================
//  0. 进度量 q = t*256/T_END（0..256）—— 快/慢两档，按效果选用
//==============================================================================
//  不用运行时除法：预先把 256/T_END 做成 Q16 常数，运行时只做一次乘法 + 移位。
//  QMUL = round(256 * 65536 / T_END)，t = T_END ⇒ q = 256（含舍入后正好 256）。
//  ★ 2026-10-26：按时长分档 —— fx0/1/2 用 q_f（T_END_F=60/1s），
//    fx3/fx4 用 q_s（T_END_S=180/3s）。两档各自算，互不干扰。
localparam integer QSH   = 16;
localparam integer QMUL_F = ((256 << QSH) + (T_END_F / 2)) / T_END_F;
localparam integer QMUL_S = ((256 << QSH) + (T_END_S / 2)) / T_END_S;

// ★★★ 2026-10-25 修：QMUL 原来被截成 **16 位** ★★★
//  【现象】把 T_END 从 3600 改成 180 后，"动画速度没变，只是时长变短，
//    缓慢移动一会儿就闪到第二张图"。
//  【原因】QMUL = 256×65536/T_END：
//      T_END = 3600 ⇒ QMUL = 4659   （< 65535，16 位够，所以以前没暴露）
//      T_END = 180  ⇒ QMUL = 93207  （**> 65535 ⇒ 被截成 27670**）
//    ⇒ q 只走到 76/256 ⇒ 画面只移动约 30% 就到达 T_END（跳到终点）。
//  【修法】乘积两操作数都显式扩到 32 位，QMUL 取 24 位。
//  【额外保险】t ≥ T_END 时直接把 q 钳到 256（防 9 位回绕成 0）。
wire [31:0] qmul_f = {20'd0, t} * {{8{1'b0}}, QMUL_F[23:0]};
wire [31:0] qrnd_f = qmul_f + 32'h0000_8000;      // +0.5LSB，四舍五入
wire [8:0]  q_f    = (t >= T_END_F[11:0]) ? 9'd256 : qrnd_f[24:QSH];   // fx0/1/2

wire [31:0] qmul_s = {20'd0, t} * {{8{1'b0}}, QMUL_S[23:0]};
wire [31:0] qrnd_s = qmul_s + 32'h0000_8000;
wire [8:0]  q_s    = (t >= T_END_S[11:0]) ? 9'd256 : qrnd_s[24:QSH];   // fx3/4

//==============================================================================
//  0b. ease-in-out（smoothstep）：e = 3u² − 2u³（u = q/256，Q8）
//==============================================================================
//  【为什么】线性插值起步即全速、到终点急刹；smoothstep 两端斜率为 0、
//    中点最快，是标准的 ease-in-out。对 fx0/1/2 直接用 e 驱动几何。
//  【算式】e = (3q² − 2q³/256) / 256 = (768q² − 2q³) >> 16
//  【端点】q=0 ⇒ e=0；q=256 ⇒ e=256（768·2^16 − 2·2^24 = 2^24，>>16 = 256）✓
//  【位宽】统一 32 位中间量（链式乘法按 32 位上下文求值）：q²≤2^16、
//    768q²≤2^25.5，全部装得下 —— 不会像旧 QMUL 那样被静默截断。
// ★ 2026-10-27：q²/ez/q³ 这一段挪到下面的"两级流水"里（见 §0d）

//==============================================================================
//  0c. fx3/fx4 的两段进度 —— ★ 2026-10-26：整条动画共用一条 ease 曲线 ★
//==============================================================================
//  【用户要求】"ease in out 改成整个动画的，不要按缩放分"。
//  【旧做法（已废）】前半/后半各自算一次 smoothstep ⇒ 段边界速度归零，
//    观感是"滑到位停一下再放大"。
//  【现在】整条动画只有**一条** smoothstep（e_s），两段只是把它切成两半用：
//      q_s ≤ 128（前半段）：eu = e_s × 2           （本段局部进度 0..256）
//      q_s ≥ 128（后半段）：eu = (e_s − 128) × 2   （本段局部进度 0..256）
//    段边界（q_s=128）处 e_s 斜率**最大** ⇒ 接缝处全速通过，
//    观感是"一气呵成"而不是"停稳再动"；整条曲线仍是头慢尾慢 ✓
//  【为什么边界取 q_s=128】smoothstep(0.5)=0.5 ⇒ e_s(128)=128 精确，
//    q_s=128 与 e_s=128 是同一点 ⇒ 两段几何严格相接（中点不变式仍成立）。
//==============================================================================
//  0d. ★★★ 2026-10-27：两级流水 —— 把 ease 曲线从"一周期串 4 个 DSP"里解放出来 ★★★
//==============================================================================
//  【问题】原来一整个组合链是
//      q² (DSP) → q²·(768−2q) (DSP+ADD) → e·640 (DSP) → 加法 → p_pos_a_reg
//  实测（布局布线后）：`mult5_syn_4.clk → p_pos_a_reg` 数据路径 **26.0ns**
//  （cell 16.9 + net 9.1），逻辑级数 8（MULT18=3 ADDER=4），50MHz/20ns 下
//  WNS −6.15ns。这一条路径就吃掉了整个 `sd_card_clk` 域的余量。
//
//  【做法】插两级寄存器，把链切成三段，每段最多 1 个 DSP：
//      第 1 段：t·QMUL → q          （已有）
//      第 2 段：q → q²              → q2_r
//      第 3 段：q2·(768−2q) → e     → e_r / eu_r
//      之后再 e·常数（1 个 DSP）+ 加法 → p_pos_a
//
//  【为什么可以延拍】`upd` 是"本帧几何锁存"脉冲，原来只比 `t` 晚 1 拍。
//  模块内部已经把 `upd` 再延 2 拍（`upd_d2`）来对齐流水线 —— 即几何比原来
//  晚 2 个时钟（40ns）落定。下游 `cfg_wait` 本来就要等 **120 拍** 才认为
//  配置稳定（除法器要 24 拍），40ns 完全淹没在里面 ⇒ 对外行为不变。
//==============================================================================
reg  [8:0]  q_f_r, q_s_r;
// ★★★ 2026-10-27：q² 只需 17 位，不是 32 位 ★★★
//   q ≤ 256（t=T_END 时 q=t*256/T_END 正好 256）⇒ q² ≤ 65536 ⇒ **17 位**。
//   原来声明成 32 位会连带把下面两个乘法撑成 32×32：
//   一个 32×32 无符号乘法要 4 个 18×18 DSP 才装得下，而 u_fx 只分到 3 个 DSP
//   ⇒ 装不下的部分全部落 LUT（每个 32×32 约 800 LUT 等价面积）。
//   而 (768 − 2q) ≤ 768 只需 10 位 ⇒ 实际是 **17×10**，一个 DSP 就够。
reg  [16:0] q2_r,  qs2_r;
reg  [8:0]  e_r,   eu_r;
reg         upd_d1, upd_d2;

wire [9:0]  ezm_c  = 10'd768 - {1'b0, q_f_r, 1'b0};    // ≤768，10 位
wire [9:0]  ezms_c = 10'd768 - {1'b0, q_s_r, 1'b0};
wire [26:0] ez_c   = q2_r  * ezm_c;                    // 17×10 → 27 位
wire [26:0] ezs_c  = qs2_r * ezms_c;
wire [8:0]  es_c   = ezs_c[24:16];   // 位号与原来的 32 位版本完全一致
wire        seg2_c = (q_s_r >= 9'd128);
wire [8:0]  eu_c   = seg2_c ? ((es_c - 9'd128) << 1) : (es_c << 1);

always @(posedge clk or posedge rst) begin
    if (rst) begin
        q_f_r <= 9'd0;  q_s_r  <= 9'd0;
        q2_r  <= 32'd0; qs2_r  <= 32'd0;
        e_r   <= 9'd0;  eu_r   <= 9'd0;
        upd_d1<= 1'b0;  upd_d2 <= 1'b0;
    end else begin
        // 第 2 段：q 打拍 + q² 寄存
        q_f_r <= q_f;
        q_s_r <= q_s;
        q2_r  <= q_f * q_f;      // 9×9，结果 ≤ 65536，17 位装得下
        qs2_r <= q_s * q_s;
        // 第 3 段：用寄存后的 q²、q 算 ease，再寄存
        e_r   <= ez_c[24:16];
        eu_r  <= eu_c;
        // upd 对齐（延时 2 拍）
        upd_d1 <= upd;
        upd_d2 <= upd_d1;
    end
end


//==============================================================================
//  1. 每帧的线性量（fx0/1/2 = e*总量 >> 8；fx3 = eu*总量 >> 8）
//==============================================================================
//  乘积最大 256*640 = 163840（18 位），统一用 19 位装。
//==============================================================================
//  ★★★ 2026-10-27：14 条「e×常数」乘法合并成 4 条 ★★★
//==============================================================================
//  【原来】下面这一片是 14 条**独立的常数乘法**：
//      e_r  × {640, 480, 255}            ← dq_x / dq_y / dq_a
//      eu_r × {320,240,120,480,160,640,
//              48,96,128,256,384}       ← 11 条 d3_*
//    每条都被综合成一组移位加法器（常数 480 = 256+128+64+32 要 3 个加法器，
//    640 = 512+128 要 1 个），合计约 **16 个 19 位加法器**。
//    而 `#dsp 29/29` 已经打满 ⇒ 这些乘法里装不进 DSP 的部分全落 LUT。
//
//  【关键观察】所有常数都跟 640 / 128 成简单的有理数关系：
//      640 = 640×1     320 = 640/2     160 = 640/4
//      480 = 640×3/4   240 = 640×3/8   120 = 640×3/16
//      128 = 128×1     256 = 128×2     384 = 128×3
//      96  = 128×3/4   48  = 128×3/8
//    ⇒ 只要先算出 **e×640、eu×640、3e、3eu** 四个基量，
//      其余全部退化成**常数移位**（移位不花 LUT）。
//
//  【为什么移位是精确等价的】（记 X>>k = floor(X/2^k)，移位可结合）
//      (eu*640)>>9  = floor(2·eu·320 / 512) = floor(eu·320/256) = (eu*320)>>8  ✓
//      (eu*640)>>10 = floor(eu·640/1024)    = (eu*160)>>8                       ✓
//      (3·eu*640)>>10 = floor(eu·1920/1024) = floor(eu·480/256) = (eu*480)>>8   ✓
//      (3·eu*640)>>11 = (eu*240)>>8、>>12 = (eu*120)>>8                          ✓（同式）
//      (3eu)>>1 = floor(3eu/2)   = (eu*384)>>8                                   ✓
//      (3eu)>>3 = floor(3eu/8)   = (eu*96)>>8                                    ✓
//      (3eu)>>4 = floor(3eu/16)  = (eu*48)>>8                                    ✓
//      eu>>1    = (eu*128)>>8、eu = (eu*256)>>8                                  ✓
//    注意：**必须先乘后移、只截断一次**。若写成「移位后相加」，
//    每一项各自的 floor 累加会偏小（eu=7 时 7*480/256=13，而
//    (7>>1)+(7>>2)+(7>>3)=3+1+0=4 再加 7 也不等于 13）⇒ 几何全错。
//
//  【附带】alpha 也不需要乘法：e*255 = e*256 − e ⇒ (e*255)>>8 = e−1（e>0）
//      ⇒ pal = (e_r==0) ? 0 : (e_r−1)，连那条减法器都省了。
//
//  【省下的】14 条乘法 → 4 条（其中 2 条是「×640 = 2 项移位」，1 条 ×3），
//    约 −160 LUT，并腾出若干 DSP 给别处的乘法。
//  【等价性验证】tb_fx_equiv（旧版改名 viewer_fx_ref.v）逐值比对 7 个输出。
//==============================================================================
//  ---- 4 个基量 ----
//  e_r / eu_r ≤ 256（见上）⇒ e*640 ≤ 163840（18 位）、3e ≤ 768（10 位）
// ★ 2026-10-30：×640 从「推断乘法」改成「2 项移位相加」，腾 2 个 DSP 给音频 FFT。
//   【为什么原来会吃 DSP】本段注释早就写了「×640 = 2 项移位」，但源码里留着
//     `* 11'd640`，TD 会老实拉一个 18×18 DSP 进来（u_fx 的 6 个 DSP 里有 2 个是它）。
//   【为什么要改】FFT 的复数乘必须落 DSP；换成 LUT 乘法器要 ~200 LUT，
//     而这里换成移位只多 18 LUT/个 ⇒ 净赚 160+ LUT。
//   【为什么是逐位等价】640 = 512 + 128 = 2^9 + 2^7；两个乘积都在 **18 位上下文**
//     里被截断，而 (e·512 mod 2^18) + (e·128 mod 2^18) 与 (e·640 mod 2^18)
//     恒等 —— 即使 e_r 超过 256 回绕也成立。所以 tb_fx_equiv 的逐值比对不受影响。
//   【范围核对】e_r/eu_r ≤ 256 ⇒ 最大 256×640 = 163840 ≤ 2^18−1，正常情况不溢出。
wire [17:0] ep    = {e_r,  9'd0} + {2'd0, e_r,  7'd0};   // e  × 640
wire [17:0] eup   = {eu_r, 9'd0} + {2'd0, eu_r, 7'd0};   // eu × 640
wire [9:0]  e3    = {1'd0, e_r}  + {2'd0, e_r,  1'b0};   // 3e
wire [9:0]  eu3   = {1'd0, eu_r} + {2'd0, eu_r, 1'b0};   // 3eu
wire [18:0] ep3   = {1'd0, ep}   + {2'd0, ep,  1'b0};    // 3·e·640  ≤ 491520（19 位）
wire [18:0] eup3  = {1'd0, eup}  + {2'd0, eup, 1'b0};    // 3·eu·640

//  ---- 由基量移位得到全部 14 个量（移位免费）----
wire [15:0] px    = {6'd0, ep [17: 8]};    // (e*640)>>8   ≤ 640
wire [15:0] py    = {6'd0, ep3[18:10]};    // (e*480)>>8   ≤ 480
wire [7:0]  pal   = (e_r == 9'd0) ? 8'd0 : (e_r[7:0] - 8'd1);   // (e*255)>>8

// ---- fx3/fx4 专用量（eu：本段局部进度 0..256）----
wire [15:0] g640   = {6'd0, eup [17: 8]};   // fx3：prev 时 A 的右移量（镜像 640s）
// ★★★ 2026-10-27：fx3 的宽/高增量**强制偶数化** ★★★
//   【上板现象】320×240 放大到 640×480 的过程中，画面有"微量左右位移"。
//   【量化分析】原来的 g320 = floor(eu*640/512)、g240 = floor(3eu*640/2048)
//     都是逐 1px 变化的：框宽在 320/321/322… 之间交替。奇宽时框中心落在
//     x.5 上（pos = 160 - floor(g320/2) 只能整数），而 `ps_gen_image` 的
//     源坐标取整是 floor ⇒ 内容中心会跟着在 320 / 320.5 / 321 之间跳。
//     实测（tb_scale_center 对称双标记）：整段最大漂移 1.5px。
//   【改法】宽高只走偶数步，且回中量严格取一半：
//        g160 = g320/2、g120 = g240/2
//     ⇒ 框中心恒为 320 / 240，奇数宽带来的 ±0.5px 抖动从源头消失。
//     代价：缩放粒度从 1px 变 2px（90 帧走 320px，肉眼不可见）。
//   【端点不变】eu=0/128/256 时 0/160/320 与 0/120/240 都是偶数，
//     t=0 与 t=T_END 的几何逐位不变（tb_fx 的端点断言仍然成立）。
wire [15:0] g320_r = {7'd0, eup [17: 9]};                // fx3：A 宽收缩量（原始）
wire [15:0] g240_r = {8'd0, eup3[18:11]};                // fx3：A 高收缩量（原始）
wire [15:0] g320   = (FX3_EVEN != 0) ? {g320_r[15:1], 1'b0} : g320_r;
wire [15:0] g240   = (FX3_EVEN != 0) ? {g240_r[15:1], 1'b0} : g240_r;
wire [15:0] g160   = (FX3_EVEN != 0) ? {1'b0, g320[15:1]} : {8'd0, eup [17:10]};
wire [15:0] g120   = (FX3_EVEN != 0) ? {1'b0, g240[15:1]} : {9'd0, eup3[18:12]};
wire [15:0] g480   = {7'd0, eup3[18:10]};   // fx3：前半段两层中心横移量
wire [15:0] g128   = {8'd0, eu_r[8: 1]};    // fx4：A 宽收缩量 / B 横向偏移
wire [15:0] g256   = {7'd0, eu_r};          // fx4：A 前半段左移量 / A、B 后半段左移量
wire [15:0] g384   = {7'd0, eu3 [9: 1]};    // fx4：B 前半段左移量 / A 前半段 prev 镜像量
wire [15:0] g96    = {9'd0, eu3 [9: 3]};    // fx4：A 高收缩量
wire [15:0] g48    = {10'd0, eu3[9: 4]};    // fx4：纵向偏移（80% 档居中）

//==============================================================================
//  2. 组合计算（按 fx_id 选一族几何）
//==============================================================================
reg [31:0] c_pos_a, c_size_a, c_pos_b, c_size_b;
reg [7:0]  c_alpha;

always @(*) begin
    // 默认 = fx0 的 t=0 起点：A 满屏、B 贴在右边外面
    c_pos_a  = {16'd0, 16'd0};
    c_size_a = {16'd640, 16'd480};
    c_pos_b  = {16'd640, 16'd0};
    c_size_b = {16'd640, 16'd480};
    c_alpha  = 8'd255;

    case (fx_id)
    //---- fx0：左右平移（dir 镜像：next 左滚 / prev 右滚）----
    3'd0: begin
        c_pos_a = dir ? {16'd0 - px, 16'd0} : {px, 16'd0};
        c_pos_b = dir ? {16'd640 - px, 16'd0} : {px - 16'd640, 16'd0};
    end
    //---- fx1：上下平移（dir 镜像：next 上滚 / prev 下滚）----
    3'd1: begin
        c_pos_a = dir ? {16'd0, 16'd0 - py} : {16'd0, py};
        c_pos_b = dir ? {16'd0, 16'd480 - py} : {16'd0, py - 16'd480};
    end
    //---- fx2：淡入淡出（无方向）----
    3'd2: begin
        c_pos_a = {16'd0, 16'd0};
        c_pos_b = {16'd0, 16'd0};
        c_alpha = pal;
    end
    //---- fx3：缩小交换 ----
    3'd3: begin
        if (!seg2_c) begin
            // ★ 前半段：A 缩到 50% 且与 B 一起横移（缩小和移动同一进度、同时进行）
            //   next：A 中心 (320,240)→(-160,240)、B 从屏右外滑到屏幕中心 (160,120)
            //   prev：水平镜像 —— A 中心 (320,240)→(800,240)、B 从屏左外滑到 (160,120)
            c_pos_a  = dir ? {16'd0 - g320, g120} : {g640, g120};
            c_size_a = {16'd640 - g320, 16'd480 - g240};
            c_pos_b  = dir ? {16'd640 - g480, 16'd120}
                           : {g480 - 16'd320, 16'd120};
            c_size_b = {16'd320, 16'd240};
        end else begin
            // ★ 后半段：B 以屏幕中心为锚放大 50% → 满屏（绕中心对称，与 dir 无关）
            //   A 已完全出屏（next 出左、prev 出右），冻结即可
            c_pos_a  = dir ? {16'd0 - 16'd320, 16'd120} : {16'd640, 16'd120};
            c_size_a = {16'd320, 16'd240};
            c_pos_b  = {16'd160 - g160, 16'd120 - g120};
            c_size_b = {16'd320 + g320, 16'd240 + g240};
        end
    end
    //---- fx4：缩小交换 + 移门式交接，缩放档 80%（2026-10-26 v5）----
    3'd4: begin
        if (!seg2_c) begin
            // ★ 前半段：A 缩到 80% 并左移，B 以 80% 从屏右外滑入
            //   **接缝恒等**：A 右沿 ≡ B 左沿 ≡ 640−384s1
            //     ⇒ 零缝隙、零重叠，两层像一扇移门精确对接。
            //     （v4 的"重叠 128s1"会让 alpha=255 的 B 盖在 A 上，
            //       重叠区画面混杂 —— 那是"观感不对称"的隐藏来源之一）
            //   A 左沿位移 256px、B 左沿位移 384px；
            //   A 前半段与后半段位移**相等**（各 256px）⇒ A 的速度曲线
            //   关于中点严格对称，不会"前慢后快"。
            //   中点：A@(-256,48) 512×384（管屏幕左 256px）、
            //        B@(256,48) 512×384（管屏幕右 384px，左半身在屏外）
            c_pos_a  = dir ? {16'd0 - g256, g48} : {g384, g48};
            c_size_a = {16'd640 - g128, 16'd480 - g96};
            c_pos_b  = dir ? {16'd640 - g384, 16'd48}
                           : {g384 - 16'd512, 16'd48};
            c_size_b = {16'd512, 16'd384};
        end else begin
            // ★ 后半段：A 保持 80%，以**与前半段相同的 256px 位移**继续移出屏；
            //   B 边放大边左移铺满（左沿 256→0、宽 512→640、高 384→480）。
            //   接缝恒等延续：A 右沿 ≡ B 左沿 ≡ 256−256s2，
            //   s2=1 时两者精确交汇于 x=0 —— A 刚好完全出屏的同一刻
            //   B 刚好铺满，零缝隙零重叠交接。
            //   prev 为水平镜像（A 出右屏、B 左沿钉 −128→0 向右铺开）。
            c_pos_a  = dir ? {16'd0 - 16'd256 - g256, 16'd48}
                           : {16'd384 + g256, 16'd48};
            c_size_a = {16'd512, 16'd384};
            c_pos_b  = dir ? {16'd256 - g256, 16'd48 - g48}
                           : {16'd0 - 16'd128 + g128, 16'd48 - g48};
            c_size_b = {16'd512 + g128, 16'd384 + g96};
        end
    end
    //---- 兜底：未定义 id 按 fx3 处理（安全默认值）----
    default: begin
        if (!seg2_c) begin
            c_pos_a  = dir ? {16'd0 - g320, g120} : {g640, g120};
            c_size_a = {16'd640 - g320, 16'd480 - g240};
            c_pos_b  = dir ? {16'd640 - g480, 16'd120}
                           : {g480 - 16'd320, 16'd120};
            c_size_b = {16'd320, 16'd240};
        end else begin
            c_pos_a  = dir ? {16'd0 - 16'd320, 16'd120} : {16'd640, 16'd120};
            c_size_a = {16'd320, 16'd240};
            c_pos_b  = {16'd160 - g160, 16'd120 - g120};
            c_size_b = {16'd320 + g320, 16'd240 + g240};
        end
    end
    endcase
end

//==============================================================================
//  3. 帧边界锁存几何
//==============================================================================
//==============================================================================
//  ★★★ 2026-10-24 根因修复：pos/size 必须与 k 同拍生效 ★★★
//==============================================================================
//  【病根】原来 `upd` 那一拍就更新 pos_a/size_a，而 k_a/k_b 要经过 4 次串行除法
//    （约 100 拍）才逐个通道写完。若帧起始锁存（ps_gen_image 的 f_x0/f_rw/f_kx）
//    正好落在"新尺寸 + 旧 k"之间，就会用**上一个效果的缩放系数**去算源列：
//        sx = (x - f_x0) * f_kx >>> 16
//    于是框内位置也能算出 sx >= 160 ⇒ 地址跨到下一行的第 0 个字
//    ⇒ 屏幕上"图像左边那一小段跑到右边缘"。
//  【证据】数码管 SEL4 的 bit3（rq_in_box && !rq_in_range）在过渡期读到 8 —— 框内
//    确实出现过 sx>=160。而对 A 层 RW=640、源 160 字、KX=16384 来说这是数学上
//    不可能的值，只能是 k 陈旧。
//  【修法】upd 时只把新几何存进"影子寄存器"，等除法跑完（固定 120 拍，约 2.4us）
//    再和 k_a/k_b 一起生效 —— 三者永远同属一次 upd，不会再混搭。
//==============================================================================
reg [31:0] p_pos_a, p_size_a, p_pos_b, p_size_b;
reg [7:0]  p_alpha;

always @(posedge clk or posedge rst) begin
    if (rst) begin
        p_pos_a <= {16'd0,   16'd0};
        p_size_a<= {16'd640, 16'd480};
        p_pos_b <= {16'd640, 16'd0};
        p_size_b<= {16'd640, 16'd480};
        p_alpha <= 8'd255;
    end else if (upd_d2) begin
        p_pos_a <= c_pos_a;
        p_size_a<= c_size_a;
        p_pos_b <= c_pos_b;
        p_size_b<= c_size_b;
        p_alpha <= c_alpha;
    end
end

// 除法耗时：4 通道 × 24 拍 = 96 拍，留余量取 120
reg [7:0] cfg_wait;
always @(posedge clk or posedge rst) begin
    if (rst)            cfg_wait <= 8'd0;
    else if (upd_d2)       cfg_wait <= 8'd120;
    else if (cfg_wait != 8'd0) cfg_wait <= cfg_wait - 8'd1;
end
wire cfg_apply = (cfg_wait == 8'd1);     // 除法已完成，几何与 k 同时生效

always @(posedge clk or posedge rst) begin
    if (rst) begin
        pos_a   <= {16'd0, 16'd0};
        size_a  <= {16'd640, 16'd480};
        pos_b   <= {16'd640, 16'd0};
        size_b  <= {16'd640, 16'd480};
        alpha_b <= 8'd255;
    end else if (cfg_apply) begin
        pos_a   <= p_pos_a;
        size_a  <= p_size_a;
        pos_b   <= p_pos_b;
        size_b  <= p_size_b;
        alpha_b <= p_alpha;
    end
end

//==============================================================================
//  4. KX/KY：每帧串行算 4 个除法（KX_A, KY_A, KX_B, KY_B）
//==============================================================================
//  KX = (65536*SRC_W)/RW     KY = (65536*SRC_H)/RH
//  被除数是常量；除数 ≤ 800 ⇒ 商 ≤ 65536*160/512 = 20480（15 位）。
//  恢复余数法：24 拍，每拍把 {rem, 下一位} 与除数比较、相减、置商位。
//------------------------------------------------------------------------------
localparam [23:0] NUM_X = 24'd10485760;   // 65536*160
localparam [23:0] NUM_Y = 24'd15728640;   // 65536*240

reg  [23:0] dv_num;          // 当前被除数
reg  [11:0] dv_rem;
reg  [23:0] dv_quo;
reg  [5:0]  dv_step;         // 24 .. 0
reg  [2:0]  dv_ch;           // 0=KX_A 1=KY_A 2=KX_B 3=KY_B
reg         dv_busy;

reg  [15:0] den_rw_a, den_rh_a, den_rw_b, den_rh_b;

wire [15:0] den_cur = (dv_ch[1:0] == 2'd0) ? den_rw_a :
                      (dv_ch[1:0] == 2'd1) ? den_rh_a :
                      (dv_ch[1:0] == 2'd2) ? den_rw_b : den_rh_b;
wire [15:0] den_safe = (den_cur == 16'd0) ? 16'd1 : den_cur;

wire [11:0] rem_sh = {dv_rem[10:0], dv_num[dv_step[4:0] - 5'd1]};
wire        rem_ge = (rem_sh >= {2'b00, den_safe});

always @(posedge clk or posedge rst) begin
    if (rst) begin
        dv_num   <= NUM_X;
        dv_rem   <= 12'd0;
        dv_quo   <= 24'd0;
        dv_step  <= 6'd0;
        dv_ch    <= 3'd0;
        dv_busy  <= 1'b0;
        den_rw_a <= 16'd640;
        den_rh_a <= 16'd480;
        den_rw_b <= 16'd640;
        den_rh_b <= 16'd480;
        k_a      <= {20'd16384, 20'd32768};      // 复位即"2 倍放大"，安全值
        k_b      <= {20'd16384, 20'd32768};
    end else if (upd_d2) begin
        // ---- 帧起点：锁存本帧的 4 个除数，启动除法 ----
        den_rw_a <= c_size_a[31:16];
        den_rh_a <= c_size_a[15:0];
        den_rw_b <= c_size_b[31:16];
        den_rh_b <= c_size_b[15:0];
        dv_num   <= NUM_X;
        dv_rem   <= 12'd0;
        dv_quo   <= 24'd0;
        dv_step  <= 6'd24;
        dv_ch    <= 3'd0;
        dv_busy  <= 1'b1;
    end else if (dv_busy) begin
        if (dv_step != 6'd0) begin
            dv_quo  <= {dv_quo[22:0], rem_ge};
            dv_rem  <= rem_ge ? (rem_sh - {2'b00, den_safe}) : rem_sh;
            dv_step <= dv_step - 6'd1;
        end else begin
            // ---- 本通道出结果，接着算下一个 ----
            case (dv_ch)
            3'd0: k_a[39:20] <= dv_quo[19:0];    // KX_A
            3'd1: k_a[19:0]  <= dv_quo[19:0];    // KY_A
            3'd2: k_b[39:20] <= dv_quo[19:0];    // KX_B
            default: k_b[19:0] <= dv_quo[19:0];  // KY_B
            endcase
            dv_ch   <= dv_ch + 3'd1;
            dv_num  <= ((dv_ch + 3'd1) & 3'd1) ? NUM_Y : NUM_X;
            dv_rem  <= 12'd0;
            dv_quo  <= 24'd0;
            dv_step <= 6'd24;
            if (dv_ch == 3'd3) dv_busy <= 1'b0;
        end
    end
end

endmodule
