//==============================================================================
//  ps_gen_text.v —— 像素源生成器：点阵文字（多行）
//==============================================================================
//
//      扫描坐标 (x,y) ──► [ ps_gen_text ] ──► pix {A,R,G,B}
//                              ▲   ▲
//              slot_tbl(异步读) │   │ glyph_row(同步读 1 拍)
//                              │   └──── osd_font_cache 的字形 BRAM 读口
//                              └──────── osd_font_cache 的槽位表读口
//
//  【一个实例渲染 NL 行，而不是"一行一个实例"（★ 重要设计决策 ★）】
//  文字层要给每个像素出一个颜色，所以每拍要读一次字形 BRAM。而 BRAM 只有一个
//  读口 —— 如果"一行一个实例"，NL 个实例就要同时读，读口必然冲突，只能把 BRAM
//  复制 NL 份（NL=4 就是 64KB）或用多口 RAM，代价大。
//
//  但**屏幕上的文本行在垂直方向是分带的**：每行只有 16 像素高，彼此不重叠。
//  所以对任意一个像素 (x,y)，**最多只有一行"命中"**。于是：
//      · 组合逻辑先选出"这个 y 落在哪一行"（sel）
//      · 只用这一行的槽位表去查槽位号
//      · 只读一次字形 BRAM
//  一个实例、一个读口、一条流水线就够，而且**整层只占 1 个合并级**。
//
//  【★ 延迟 = 2 拍 ★】（第一级在缓存里，第二级在本模块）
//
//      第 t   拍：组合算出 lx/ly/char_col/row/col/slot → glyph_addr 送到缓存 BRAM
//      第 t+1 拍：缓存 BRAM 吐出 glyph_row；本模块同时把元数据（col/颜色/hit/ready）
//                对齐寄存（s1_*），因为它们要和 glyph_row 同拍用
//      第 t+2 拍：pix <= (s1_hit & s1_ready & glyph_row[15-s1_col]) ? 颜色 : 透明
//
//  ★ 三个"必须"，少一个就会变成 3 拍：
//      ① slot_tbl 必须是**纯组合异步读**（不能是同步 RAM）；
//      ② 缓存的字形 BRAM 读口只能有**地址寄存器一级**；
//      ③ 本模块**不要**再对 glyph_addr 打拍（它必须是组合输出）。
//
//  【★ 位序（最容易搞反的地方）★】
//  字库每个字形 32 字节 = 16 行 × 2 字节，**先左半 8 列、再右半 8 列**，
//  每字节 bit7 = 该 8 列里最左边的像素。所以缓存把一行装成 16 位字时必须是
//      glyph_row = { 左字节, 右字节 }        // [15:8]=左 8 列, [7:0]=右 8 列
//  于是第 col 列（0 = 最左）对应 **bit 15-col**：
//      glyph_row[15 - col]
//  用文档里的 '中' 验证过（见 tb_ps_gen_text.v 的期望值）。
//
//  【★ 越界保护 ★】
//  x < X0 时 16 位无符号减法会回绕成大数。这里不靠"回绕后比较"兜底，而是：
//      · hit 要求 ly < 16 且 lx < 行长(像素)  → 回绕的大数必然判不过；
//      · 送给缓存的 char_col 另外再夹一次（lx < MAXLEN*16 才给真值，否则给 0），
//        避免异步查表越界产生 X 或别名。
//
//  【cfg 总线格式】
//      txt_xy  [22*NL-1:0]  第 i 行占 [22*i +: 22] = { Y0[10:0], X0[10:0] }
//      txt_col [24*NL-1:0]  第 i 行占 [24*i +: 24] = { R[7:0], G[7:0], B[7:0] }
//
//==============================================================================

module ps_gen_text #(
    parameter integer IMG_W  = 640,     // 屏幕宽
    parameter integer IMG_H  = 480,     // 屏幕高
    parameter integer NL     = 4,       // 文本行数
    parameter integer MAXLEN = 32       // 每行最多字符数（= 槽位表深度）
)(
    input  wire        clk,
    input  wire        rst,             // 高有效、异步（与其它 ps_* 一致）

    input  wire [15:0] x,               // 扫描坐标（接坐标延迟链 c6）
    input  wire [15:0] y,
    input  wire        valid,
    input  wire        ce,              // ★ 流水推进（接像素级 pipe_ce = pixel_ready）
                                        //   不加这一路时，背压停顿会让本层继续前移
                                        //   ⇒ 文字相对底图每停一次滑一格（上板"动态毛刺"）

    // ---- 每行配置（来自 app_scene_cfg）----
    // ★ 2026-10-27：位宽收窄，见 osd_menu.v 端口处的说明
    input  wire [22*NL-1:0] txt_xy,     // 每行 {Y0[10:0], X0[10:0]}
    // ★ 2026-11-01：原来是每行 24 位颜色（8 行 = 192 个 FF + 一台 24 位 8:1 mux）。
    //   实际只有 3 种颜色：暗(C0C0C0) / 高亮(FFFFFF) / 标题(F0F0F0)。
    //   改成每行 2 位"颜色号"（16 个 FF），颜色在**像素侧**选 —— 省 ~130 LUT。
    input  wire [ 2*NL-1:0] txt_ci,     // 每行 2 位：0=暗 1=高亮 2=标题

    // ---- 来自 osd_font_cache ----
    input  wire [10*NL-1:0] slot_tbl,   // 每行：输入 char_col → 槽位号（组合异步读）
    input  wire [ 8*NL-1:0] line_len,   // 每行的字符数
    input  wire [    NL-1:0] line_ready,// 该行绑定是否已就绪
    input  wire [15:0]      glyph_row,  // 字形 BRAM 同步读回（地址后 1 拍）

    // ---- 给 osd_font_cache ----
    output wire [ 8*NL-1:0] slot_col,   // 每行的 char_col（缓存的槽位表读地址）
    output wire [13:0]      glyph_addr, // = slot*16 + row（★ 组合输出，不要打拍）

    output reg  [31:0] pix,             // 文字像素；字外 = 32'h00000000（透明）
    output reg         out_valid
);

localparam [7:0]  MAXLEN_B = MAXLEN[7:0];
localparam [15:0] MAXLEN_PX = MAXLEN[15:0] << 4;    // MAXLEN × 16

//==============================================================================
//  1. 逐行组合：算 lx / ly / 命中 / char_col
//==============================================================================
// ★★ 2026-10-31 [LUT-4]：逐行减法/比较从 16 位降到 12 位（结果逐位不变）★★
//  这 8 行的命中判定每个像素都要算一遍（8 × 两台减法 + 一台比较）。
//  值域：扫描坐标 x,y < 1024（640×480），行原点 x0/y0 是 11 位有符号（−1024..1023）
//  ⇒ x−x0、y−y0 ∈ [−1023, 2047]，12 位补码装得下、符号位正确；
//  所有门限（len×16 ≤ MAXLEN×16 = 512、16）也都 < 2048 ⇒ 无符号比较与 16 位版逐值相同
//  （负差在 12 位里 ≥ 2048，同样必然判不过）。只用到 LX[8:0]/LY[3:0]，高位不外露。
//  ⚠ 若将来 MAXLEN > 127 或坐标 ≥ 1024，这里要加宽。
wire [11:0] LX   [0:NL-1];
wire [11:0] LY   [0:NL-1];
wire        LHIT [0:NL-1];

genvar gi;
generate
for (gi = 0; gi < NL; gi = gi + 1) begin : g_line
    // ★★★ 必须做**符号扩展**，不能零扩展 ★★★
    //   y0 在滚动动画里会是负值（最小 −184），如果零扩展成 0x0348=840，
    //   `LY = y - y0` 就变成大数回绕，整行文字一个字都不显示。
    //   x0 恒为正（112..624），符号扩展对它无害。
    wire [11:0] x0 = {txt_xy[22*gi + 10],      txt_xy[22*gi      +: 11]};
    wire [11:0] y0 = {txt_xy[22*gi + 21],      txt_xy[22*gi + 11 +: 11]};

    // ★ 2026-11-03 [AREA]：行长不再夹到 MAXLEN —— 唯一的写者 osd_menu 的 ctl_len
    //   只会给 0 / nm_use(≤31) / 19 / 32（= MAXLEN），复位为 0 ⇒ 夹子恒不起作用。
    //   并且 LX < len×16 ⟺ LX[11:4] < len（len×16 是 16 的倍数、len ≤ 255 时 16·len < 4096）
    //   ⇒ 12 位比较缩成 8 位，省掉每行一台 8 位比较 + 8 位 2:1 选择。
    assign LX[gi] = x[11:0] - x0;       // x < x0 时 12 位里回绕成 ≥2048 → 下面必然判不过
    assign LY[gi] = y[11:0] - y0;

    assign LHIT[gi] = (LX[gi][11:4] < line_len[8*gi +: 8]) && (LY[gi] < 12'd16);
end
endgenerate

//------------------------------------------------------------------------------
//  槽位表读地址：只有"列号在合法范围内"时才给真值，否则给 0（防异步查表越界）
//------------------------------------------------------------------------------
generate
for (gi = 0; gi < NL; gi = gi + 1) begin : g_sc
    // ★ 2026-11-03 [AREA]：越界钳 0 删除。槽位表是 {行,列} 纯拼接（不会越界），
    //   而 LX ≥ MAXLEN×16 时该行 LHIT 必然为假 ⇒ 这一行的槽号不会被选中，
    //   只影响"无命中时"的字形读地址，pix 逐位不变（s1_hit=0 ⇒ pix=0）。
    assign slot_col[8*gi +: 8] = {3'd0, LX[gi][8:4]};
end
endgenerate

//==============================================================================
//  2. 选出命中的那一行（低序号优先；正常情况下至多一行命中）
//==============================================================================
// 注：LHIT 是 unpacked 数组，不能用 |LHIT 归约，所以在这里一趟循环同时算出
//     "有没有命中" 和 "命中的是哪一行"（从高到低扫 → 低序号优先）。
//==============================================================================
// ★ 2026-10-25：sel 原来只有 2 位（原设计 NL≤4）。NL=6 时必须 3 位，
//   否则第 4/5 行会被截成 0/1，文字串行。这里按 NL 自动定位宽。
localparam integer SELW = (NL <= 2) ? 1 : (NL <= 4) ? 2 : (NL <= 8) ? 3 : 4;
wire [SELW-1:0] sel;
reg  [SELW-1:0] sel_r;
reg        hit_any_r;
integer    k;

always @(*) begin
    sel_r     = {SELW{1'b0}};
    hit_any_r = 1'b0;
    for (k = NL - 1; k >= 0; k = k - 1)
        if (LHIT[k]) begin
            sel_r     = k[SELW-1:0];
            hit_any_r = 1'b1;
        end
end

assign sel     = sel_r;
wire   hit_any = hit_any_r;

//---- 命中行的局部坐标 ----
wire [11:0] lx_sel = LX[sel];
wire [11:0] ly_sel = LY[sel];
wire [3:0]  row    = ly_sel[3:0];            // 字形内的行号 0~15
wire [3:0]  col    = lx_sel[3:0];            // 字形内的列号 0~15

//---- 命中行的槽位号与颜色 ----
// 槽位号 10 位：0 = 保留的"空白槽"（BRAM 内容恒 0），1~512 = 512 个可用字形槽
wire [9:0]  slot     = slot_tbl[10*sel +: 10];
// 3 种固定颜色（菜单的配色就是这三档，见 osd_menu 的 txt_ci 赋值）
localparam [23:0] C_DIM   = 24'hC0C0C0;
localparam [23:0] C_HI    = 24'hFFFFFF;
localparam [23:0] C_TITLE = 24'hF0F0F0;
// ★ 2026-11-03：第 4 档 = 置灰（只读控件，例如自动亮度打开时的亮度行）
localparam [23:0] C_GRAY  = 24'h707070;
wire [1:0]  ci_sel   = txt_ci[2*sel +: 2];
wire [23:0] col_sel  = (ci_sel == 2'd1) ? C_HI :
                       (ci_sel == 2'd2) ? C_TITLE :
                       (ci_sel == 2'd3) ? C_GRAY  : C_DIM;
wire        rdy_sel  = line_ready[sel];

//==============================================================================
//  3. 字形 BRAM 读地址（组合送出去，缓存的 BRAM 地址寄存器在下一拍采样）
//==============================================================================
//  slot(10 位, 0~512) × 16 + row(0~15) → 最大 512×16+15 = 8207 → 14 位够
//
//  ★ 用**拼接**而不是加法：{slot,4'd0} 的低 4 位恒为 0，row 也只占低 4 位，
//    所以 {slot,4'd0} + {10'd0,row} ≡ {slot,row}，完全等价。
//    这不是微优化 —— 这条链在像素路径上：
//        slot_tbl 的 128:1 选一(≈5 级) → 这里的加法器(≈3 级) → 缓存 BRAM 的读地址寄存器
//    gate.qor 里 sd_card_clk 10ns 下"11 级"那批路径（约 30 条）就是它，
//    换掉加法器后少 3 级，整条链压到 8 级左右。
assign glyph_addr = {slot, row};

//==============================================================================
//  4. 第 1 级寄存：把"要和 glyph_row 同拍使用"的元数据对齐
//==============================================================================
reg        s1_hit, s1_ready, s1_valid;
reg [3:0]  s1_col;
reg [31:0] s1_color;

always @(posedge clk or posedge rst) begin
    if (rst) begin
        s1_hit   <= 1'b0;
        s1_ready <= 1'b0;
        s1_valid <= 1'b0;
        s1_col   <= 4'd0;
        s1_color <= 32'd0;
    end else if (ce) begin
        s1_hit   <= hit_any;
        s1_ready <= rdy_sel;
        s1_valid <= valid;
        s1_col   <= col;
        s1_color <= {8'hFF, col_sel};   // A 恒 255：文字不透明
    end
end

//==============================================================================
//  5. 第 2 级寄存：位选择 + 上色
//==============================================================================
//  字外 / 该行未就绪 / 该位没点亮 → 输出全 0（透明），让底下图层透出来。
//==============================================================================
wire lit = glyph_row[15 - s1_col];

always @(posedge clk or posedge rst) begin
    if (rst) begin
        pix       <= 32'h0000_0000;
        out_valid <= 1'b0;
    end else if (ce) begin
        // ★★ 2026-10-28：这里原来只判 `s1_hit & s1_ready & lit`，**漏了 s1_valid** ★★
        //   `hit_any` 只是"x/y 落在某个字符串框内"的组合判断，**不含 valid**；
        //   行场消隐期间 valid=0 但 x/y 照常在计数，一旦扫到某个字符串框，
        //   s1_hit 就会是 1 ⇒ pix 输出 A=0xFF 的实色。
        //   而下游 osd_top 的合并级是
        //       m_pix <= (txt_pix[31:24] != 8'd0) ? txt_pix : gfx_pix;
        //   **只看 alpha、不看 txt_v**，于是消隐区画出来的文字被当成有效像素
        //   盖到图形层上 —— 表现就是屏幕上多出一条 1px 宽的虚线竖条，
        //   而且"虚"的位置会随扫描行上下漂。
        //   加 s1_valid 只多一个与项（LUT4 → LUT5，面积可忽略）。
        pix       <= (s1_valid & s1_hit & s1_ready & lit) ? s1_color : 32'h0000_0000;
        out_valid <= s1_valid;
    end
end

endmodule
