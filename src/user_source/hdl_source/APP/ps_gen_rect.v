//==============================================================================
//  ps_gen_rect.v —— 像素源生成器：矩形（实心，轴对齐）
//==============================================================================
//
//      扫描坐标 (x,y) ──► [ ps_gen_rect ] ──► pix {A,R,G,B}
//                              ▲
//                     cfg {X0,Y0,RW,RH} + color
//
//  【★ 位置/尺寸/颜色都是"运行时输入"，不再是 parameter ★】
//  这样将来做动画（让方块平移、变大、变色）只要改 app_scene_cfg.v 里的寄存器，
//  本模块一行都不用动。
//
//  代价：**几乎为零**。因为判定本来就是"减法 + 比较"，用常数还是用变量，
//  综合出来的电路一样大。（真正会变贵的是"常数乘法"，那是三角/多边形的事，
//  它们的顶点仍然保持 parameter 静态。）
//
//  【怎么判定"这个坐标在不在矩形里"】
//
//      dx = x - X0          // 16 位无符号减法
//      dy = y - Y0
//      inside = (dx < RW) && (dy < RH)
//
//  为什么等价？如果 x < X0，x - X0 在无符号下会回绕成接近 65535 的大数，
//  必然 >= RW → 判为"不在矩形里"。正好是我们要的。
//
//  【cfg 总线格式】见 app_scene_cfg.v 顶部：
//      cfg   [63:0] = { X0[15:0], Y0[15:0], RW[15:0], RH[15:0] }
//      color [31:0] = { A[7:0],   R[7:0],  G[7:0],  B[7:0]  }
//
//  【延迟 = 1 拍】，非矩形区域输出透明（32'h00000000）。
//
//==============================================================================

module ps_gen_rect #(
    parameter integer IMG_W = 640,      // 屏幕宽
    parameter integer IMG_H = 480       // 屏幕高
)(
    input  wire        clk,
    input  wire        rst,
    input  wire [15:0] x,
    input  wire [15:0] y,
    input  wire        valid,
    input  wire [63:0] cfg,             // {X0, Y0, RW, RH}
    input  wire [31:0] color,           // {A, R, G, B}
    output reg  [31:0] pix,
    output reg         out_valid
);

//------------------------------------------------------------------------------
//  拆总线
//------------------------------------------------------------------------------
wire [15:0] X0 = cfg[63:48];
wire [15:0] Y0 = cfg[47:32];
wire [15:0] RW = cfg[31:16];
wire [15:0] RH = cfg[15:0];

//------------------------------------------------------------------------------
//  判定（纯组合）
//------------------------------------------------------------------------------
wire in_bounds = (x < IMG_W) && (y < IMG_H);

wire [15:0] dx = x - X0;            // x < X0 时回绕成大数 → 自动判为"在外"
wire [15:0] dy = y - Y0;

wire inside = in_bounds && (dx < RW) && (dy < RH);

//------------------------------------------------------------------------------
//  输出打一拍
//------------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) begin
        pix       <= 32'h0000_0000;
        out_valid <= 1'b0;
    end else begin
        pix       <= inside ? color : 32'h0000_0000;
        out_valid <= valid;
    end
end

endmodule
