//==============================================================================
//  ps_merge_overlay.v —— 像素源合并器：直接叠加
//==============================================================================
//
//  【合并器在体系里的位置】
//
//      s1 (前景) ─┐
//                 ├─► [ ps_merge_overlay ] ─► pix
//      s2 (背景) ─┘
//
//  两个输入**必须同拍对齐**（同一时刻是同一个扫描坐标的像素）。
//  对齐由 app_demo_scene.v 的"坐标延迟链"保证，本模块不管这件事。
//
//  【叠加规则（二选一）】
//
//      s1 的 alpha ≠ 0  →  取 s1（前景不透明，盖住背景）
//      s1 的 alpha = 0  →  取 s2（前景透明，露出背景）
//
//  这就是"非图形区域为透明（#00000000）"这条约定带来的好处：
//  图形生成器只要把图形外的像素输出成 32'h00000000，叠加逻辑就自然成立了。
//
//  【延迟 = 1 拍】
//  合并器是链式串联的（一层套一层），必须打拍把关键路径剪短，否则 7 层叠起来
//  的组合逻辑在 100MHz（10ns）下不可能收敛。打拍不损失吞吐——还是每拍一个像素。
//
//  【资源】一个 32 位 mux，零乘法器。
//
//==============================================================================

module ps_merge_overlay (
    input  wire        clk,
    input  wire        rst,
    input  wire        ce,

    input  wire [31:0] s1_pix,          // 前景像素 {A,R,G,B}
    input  wire        s1_valid,
    input  wire [31:0] s2_pix,          // 背景像素
    input  wire        s2_valid,

    output reg  [31:0] pix,             // 合并结果
    output reg         out_valid
);

//------------------------------------------------------------------------------
//  叠加判定（纯组合）
//------------------------------------------------------------------------------
wire s1_opaque = (s1_pix[31:24] != 8'd0);

always @(posedge clk or posedge rst) begin
    if (rst) begin
        pix       <= 32'h0000_0000;
        out_valid <= 1'b0;
    end else if (ce) begin
        pix       <= s1_opaque ? s1_pix : s2_pix;
        out_valid <= s1_valid & s2_valid;
    end
end

endmodule
