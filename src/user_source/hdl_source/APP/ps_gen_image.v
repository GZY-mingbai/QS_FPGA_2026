//  【修法】两段式兜底，让本层对丢包**免疫**：
//      ① pix_wait 超过 RETRY_AT → **重发一次请求**，地址取"显示侧当前
//         需要的那个源像素"（丢的就是它，因为两条扫描同序）。这能真正自愈。
//      ② pix_wait 超过 GIVEUP_AT → 认为真拿不到了，**允许显示侧继续推进**
//         （用 cur_pix 顶替）。最坏只是图片上多一条重复像素，绝不整屏黑。
