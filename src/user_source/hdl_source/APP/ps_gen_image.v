//  上一版想的是"pix_count + 在飞 ≤ 深度"，但漏了一件事：
//  **积压主要不在像素 FIFO，而在请求 FIFO（深度 128 个请求）**。
//      节流只问 `pix_count < 48`；只要它低于 48，请求就能一路 push 进去，
//      堆在请求 FIFO 里排队，然后成批回来一次性涌进像素 FIFO。
//  ⇒ 调 `PIX_HIWAT` 治不了，因为瓶颈量是"已承诺 − 已落地"的差额。
//
//  【本版的做法】直接记这个差额：
//      push_w = 已经交给仲裁器的字数（req_push 时 += popcount(mask)）
//      pop_w  = 显示侧已经消费的字数（pix_pop 时 += 1）
//      committed = push_w − pop_w
//                 = 请求 FIFO 里的 + 在飞命令的 + 像素 FIFO 里的（全算进去）
//  节流：committed < 96。
//
//  【为什么这是数学保证，而不是调参】
//      像素 FIFO 内容 = committed − 在飞 ≤ committed ≤ 96 < 128
//  与 LEAD 多大、突发多猛、在飞几条全部无关 ⇒ 写满丢字在结构上不可能再发生。
//  （这也是 img_layer_ctrl.v:19 那条"深度 ≥ 2×LEAD"不变式的正确落实方式：
//    它约束的其实是**这个差额**，不是 FIFO 里已经躺着几个字。）

// popcount(req_mask)：4 位最多 4
wire [2:0]  pc_mask = {2'd0, req_mask[0]} + {2'd0, req_mask[1]}
                    + {2'd0, req_mask[2]} + {2'd0, req_mask[3]};

// 20 位版本，给数码管读数用（16 位装不下 307200，会回绕）
