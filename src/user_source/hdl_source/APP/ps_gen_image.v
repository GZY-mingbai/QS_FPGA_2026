//==============================================================================
//  ps_gen_image.v —— 像素源生成器：SDRAM 纹理图层（可缩放 / 可移动）
//==============================================================================
//
//  【它是干什么的】
//  把 SDRAM 里的一张纹理（比如从 SD 卡装进来的 BMP），按 cfg 指定的目标矩形
//  缩放后画到屏幕上，并支持运行时改位置/尺寸（做动画）。
//
//      扫描坐标 (x,y) ──► [ ps_gen_image ] ──► pix {A,R,G,B}
//                              ▲     │
//                       cfg 寄存器  ├─ req_push/req_addr ──► 请求 FIFO ──► SDRAM 读仲裁
//                                  └─ ◄── pix_head/pix_count ── 像素 FIFO ◄──
//
//  【★ 核心难点：为什么要"预取领先（lookahead）"★】
//
//  天真做法是"输出第 k 个像素时去请求第 k 个像素"。但 SDRAM 读是**有往返延迟**的
//  （本工程实测约 10 拍 @125MHz = 80ns），而场景图是 50MHz（20ns 一拍）。
//  每输出一个像素就要等一个往返 → 最多 1 像素 / 80ns = 12.5M 像素/s，
//  而 60fps 需要 307200 / 16.7ms = 18.4M 像素/s —— **不够**。
//
//  所以本模块内部跑**两条扫描**：
//
//      ┌─ 请求扫描 (rq_x, rq_y)：尽量往前跑，最多领先显示扫描 LEAD 个像素
//      │      → 提前把"以后要用的像素"请求出去
//      │
//      └─ 显示扫描 (x, y)：来自坐标链，受 adv 门控
//             → 真正输出像素，从像素 FIFO 里取
//
//  两条扫描走的是**同一条源坐标序列**（同样的映射、同样的顺序），所以
//  第 k 个"需要新像素"事件在两边一一对应 —— 显示侧只需要在"自己也是新像素"
//  的时候弹一次 FIFO，**不需要在 FIFO 里存任何标记，也不需要时间戳**。
//
//  【横向复用】
//  放大时相邻多个目标像素映射到同一个源像素（sx 不变）→ 显示侧直接复用
//  当前像素寄存器，**不弹 FIFO、不产生新的 SDRAM 读**。
//
//  【包围盒预判】
//  目标坐标不在矩形内时不发请求、输出透明。动画里图片通常只占屏幕一部分，
//  这一条免费把读命令降到"Σ 各层目标面积 / 屏面积"。
//  ★ 支持负的 X0/Y0（图片部分移出屏幕左上角）—— in_rect 用有符号比较。
//
//  【流水线深度 D_img = 3】
//      拍 0：输入 (x,y)
//      拍 1：s1_*（映射 + in_box）
//      拍 2：s2_*（is_new 判定）
//      拍 3：pix / out_valid 寄存器出结果
//  → 插到场景图里时，这一层要喂"比最底层生成器早 2 拍"的坐标（见 app_demo_scene.v）。
//
//  【★ 帧边界处理（踩过的坑）★】
//  一开始想用"检测到 (0,479) 就复位整条流水线"来做帧同步，结果**复位那一拍
//  把推进也吃掉了**，导致图层内部扫描比外部扫描慢 1 拍 —— 整幅图横向偏移
//  一个像素。正确做法是：
//
//      只在"没有推进 且 停在帧起点"时复位（那就是帧间空闲期）。
//      · 帧间空闲：adv=0 且 (x,y)=(0,479) → 连续复位（反正没推进，免费）
//      · 帧内停顿：adv=0 但坐标不在起点 → 什么都不做 = 冻结流水线 ✓
//      · 正常推进：adv=1 → 推进 ✓
//  这样复位不占推进拍，两条扫描严格同步。
//
//  【流控】
//  layer_ready 参与全局 pixel_ready；它只管"要弹像素时 FIFO 里必须有货"。
//  请求侧自己节流（请求 FIFO 满就停），不需要参与全局流控。
//
//==============================================================================

module ps_gen_image #(
    parameter integer IMG_W = 640,      // 屏幕宽
    parameter integer IMG_H = 480,      // 屏幕高
    parameter integer SRC_W = 640,      // 纹理行宽（每行多少个字）
    // ★★ 2026-10-18 build 9：诊断开关 —— 强制请求地址按 4 字对齐 ★★
    //  1 = 请求地址低 2 位清零（组内偏移恒为 0，调度器永远挑组首那个字）
    //      ⇒ 画面会变成"横向只有 1/4 列"的块状图，但每个像素必须是对的
    //  用来把"组内挑错字"和"地址本身就错"分开：
    //     块状但干净 ⇒ 组内偏移/4 字组逻辑有问题
    //     仍然花点   ⇒ 地址/请求通路有问题
    parameter integer ALIGN_ONLY = 0,
    //--------------------------------------------------------------------------
    //  ★★ 2026-11-01：文件页四宫格（quad_en=1 时启用）★★
    //  几何全部是常量 ⇒ 综合成常数比较，不占寄存器。
    //  单元参考：viewer_scene 的 QUAD_BASE / quad_sel 的默认布局。
    //--------------------------------------------------------------------------
    // ★ 2026-11-04：列间距 16 → 32（用户要求拉开），左列 208 → 192，右列仍从 384 起
    parameter integer Q_X0 = 192,       // 左列起点
    parameter integer Q_Y0 = 100,       // 上排起点
    parameter integer Q_CP = 192,       // 列距（160 格宽 + 32 间距）
    parameter integer Q_RP = 160,       // 行距（120 格高 + 40 名字区）
    parameter integer Q_CW = 160,       // 格宽
    parameter integer Q_CH = 120,       // 格高
    parameter integer LEAD  = 64,       // 预取领先量（像素）
                                        // ★ 必须 ≤ 像素 FIFO 深度的一半 ★
                                        // 深度 = 128（AFIFO_AW=7）→ 取 64，留一倍余量。
                                        // 【踩过的坑】曾经设成 128 = 深度：预取刚好把
                                        // FIFO 填满，之后每来一个像素都被 wfull 挡掉
                                        // （像素 FIFO 的 wfull 悬空 = 静默丢弃）
                                        // → 像素消失 → 图片层卡住。
                                        // 历史：最初是 12（按仿真往返 10 拍定的），太小。
    //  ★ 本版（冻结地址实验）固定 0：关掉"自校验 + 染色"，看**原始**纹理字。
    //    因为地址被冻结后 期望偏移 与 实际偏移 必然不符，染色会把整屏涂掉，
    //    反而看不出数据有没有被改。
    parameter integer PAT_CHK = 0,      // 1 = 校验纹理内容是否与期望地址一致（诊断用）
    // ★★★ 2026-10-27：源坐标采样点是否取"目标像素中心" ★★★
    //   1（默认）= mx = lx*kx + kx/2，消除左沿偏置带来的 1~1.5px 横向漂移；
    //   0 = 旧行为（mx = lx*kx），只给 tb_pgi_equiv 的"逐拍等价"对照用。
    //   中心采样在 1:1（kx=32768）时仍然选到同一批像素（low/high 交替），
    //   所以静止页逐像素不变；只改变非整数缩放时的取整相位。
    parameter integer SAMPLE_CENTER = 1
)(
    input  wire        clk,
    input  wire        rst,
    input  wire        pipe_ce,         // shared scene/output pipeline advance
    input  wire        adv,             // = streaming：1 时才推进显示侧
    input  wire        frame_active,    // = ps_start：本帧是否正在进行
                                        //   0 → 帧间空闲，可以安全复位
                                        //   1 且 adv=0 → 预热或帧内停顿，必须保持

    // ---- 显示扫描坐标（来自坐标延迟链）----
    input  wire [15:0] x,
    input  wire [15:0] y,

    // ---- 配置（全部运行时寄存器，改它就是做动画）----
    input  wire [31:0] cfg_pos,         // {X0[15:0], Y0[15:0]}   目标矩形左上角（有符号）
    input  wire [31:0] cfg_size,        // {RW[15:0], RH[15:0]}   目标矩形宽高
    input  wire [39:0] cfg_k,           // {KX[19:0], KY[19:0]}   Q16 定点倒数 = 65536×源/目标
    // ★★ 2026-10-30 [ZOOM-ANCHOR]：源相位（Q16 源字单位）★★
    //  【要解决什么】缩放预览的锚点。旧做法只能靠 `pos = −(z−1)a` 把框推到屏幕外，
    //    而 `cfg_ok` 卡 RW/RH ≤ 1024、`map_src` 的 `lx` 截到 11 位 ⇒ 4×/8× 直接全黑。
    //  【做法】框保持 (0,0,640×480) 不动，把锚点换算成**源坐标的相位**：
    //      sx = (x·kx + PHX) >> 16      PHX = ax·(k_fit_x − kx)
    //    因为 `z·kx ≡ k_fit_x`（k_fit_x = 16384、k_fit_y = 32768 恒成立），
    //    (z−1)·kx = k_fit_x − kx ⇒ 一次乘法就能得到相位。
    //  【收益】框不变 ⇒ 渲染量 ×1、cfg_ok 永远满足、请求预算的 480 行永远正确。
    //  【z=1】PHX = PHY = 0 ⇒ 与本改动之前**逐位相同**。
    input  wire [19:0] cfg_ori,         // ★ [ZOOM-EXACT] {ORIX[9:0], ORIY[9:0]} 锚点（源坐标原点）
    input  wire [20:0] tex_base,        // 该层纹理在 SDRAM 里的基址
    input  wire        layer_en,        // 该层是否启用（0 → 全透明）
    input  wire        quad_en,         // ★ 1 = 四宫格：屏幕坐标直接映射到 4 个槽
    // ★ 2026-11-03：哪几个槽本页有内容（bit = {row,col}）。空槽当"框外"：
    //   不取址、不显示 ⇒ 末页不满 4 格时不再露出上一页留在 SDRAM 里的图。
    //   必须帧内恒定（顶层和 quad_mode 一起在 ps_new_frame 采样），请求侧/显示侧才一致。
    input  wire [3:0]  quad_vm,

    // ---- 请求 FIFO（→ SDRAM 读仲裁）----
    output wire        req_push,
    output wire [20:0] req_addr,
    output wire [3:0]  req_mask,        // ★ build F：这个 4 字组里要哪几个字 ★
    input  wire        req_ready,       // 请求队列未满

    // ---- 像素 FIFO（← SDRAM 读仲裁），show-ahead ----
    input  wire [31:0] pix_head,        // 队首像素
    input  wire [9:0]  pix_count,       // 可读个数（★ 100M-41：AFIFO_AW=9 → 10 位★）
    output wire        pix_pop,         // 弹出队首

    // ---- 输出 ----
    output wire [31:0] pix,             // {A,R,G,B}（build 9：改为 wire，由末尾 assign 染色）
    output reg         out_valid,
    output wire        layer_ready,
    // ★★ 2026-10-23：本层"这一列是否归我负责"（与 pix 同拍）★★
    //   viewer_scene 用它做两层解耦：只有"负责这一列的那一层"没数据时才停整幅。
    //   判据就是 pix_raw 的框内门（`s2_in_box && out_in_box_w`）再与上 f_en/dead，
    //   和"这拍会不会真的产出像素"完全等价。
    output wire        in_box_o,
    // ★ 2026-11-05 [INBOX-P]：与 `pix` **严格同拍**的框内标志（in_box_o 是第 2 拍，
    //   pix 是第 3 拍 ⇒ 相差一个像素）。viewer_scene 选层用它，否则四宫格整幅右偏 1px。
    //   in_box_o 保留给 layer_ready（那是"下一个要弹出的像素"，必须看第 2 拍）。
    output wire        in_box_p,

    // ★ build F2：本帧是否已经被 give_up 放弃 ★
    //   必须走正规端口 —— 综合器不支持 `u_gen.layer_dead` 这种跨模块层次引用
    //   （TD 直接报 "external reference ... remains unresolved"）。
    output wire        layer_dead_o,
    //  ★ build 3：三个输出全部改含义（端口名不变，减少改动面）★
    //   layer_div_o  = ★"三个颜色字节不相等"是否发生过（粘滞）★
    //                  为 1 ⇒ 收到的 32 位字 R≠G≠B，即"字节被打乱"（真彩色的直接证据）
    output wire        layer_div_o,
    //   layer_diff_o = ★第一个错配字的低字节：{[7:4]=高半字节, [3:0]=低半字节}★
    //                  把它拼回来就能直接看到"我们到底收到了什么"
    output wire [7:0]  layer_diff_o,
    output wire [19:0] push_w_o,        // 本帧 请求侧提交的字数（掩码位数之和）
    // ★ 2026-10-23：帧末的 (push − pop) 快照。bit3 = 符号（1=少交付），
    //   bit[2:0] = 差的绝对值。用来判断"竖条是数量错位还是取字内容错"。
    //   [4]=符号(1=少交付)  [3:0]=对数码（0=真配平，B≈256~511=每行差1）
    output reg  [4:0]  dbg_delta,
    // ★ 2026-10-23：4 个"粘滞事件"标志（本帧内发生过就置 1，帧界清零）
    //   [0] 空弹：要弹但 FIFO 空（s2_is_new && !pix_avail）
    //   [1] pop_stall：因缺料冻结扫描
    //   [2] give_up：单像素等太久被放弃
    //   [3] 框内但源坐标越界（rq_in_box && !rq_in_range）
    output reg  [3:0]  dbg_evt,
    // ★ 2026-10-24：像素轨迹探针（给 dbg_uart）
    //   {sx[15:0], py[15:0], px[15:0], flags[5:0], head[31:0], raw[23:0]} = 110 位
    output wire [127:0] smp_bus,
    // ★ 采样窗口：**锁在框右边界内的 32 列**（边界随动画移动，
    //   固定 x 窗口只会碰巧对上）。Y_SEL 由参数指定。
    output wire        smp_win,
    //   layer_neq_o  = 跨帧粘滞：本层是否被 give_up 放弃过
    output wire        layer_neq_o,

    // ★★ 2026-10-17 虚线根修：弹空抑制（A/B 对照开关）★★
    //  【机制】像素 FIFO 空（need_pix）时，场景冻结经 pixel_ready 传播有
    //  1~2 拍延迟；而 pix_pop = adv && pop_want 不看 FIFO 占用 —— 每个
    //  "等批"边界的这 1~2 拍会弹出 FIFO 存储体的【陈旧垃圾】，并且事件
    //  照常消费 ⇒ 该像素永久错位。上板症状：固定 x 的亮块（虚线）+
    //  图片花屏；数据无关（mode1 纯橙依旧）✓、随纹理流量涨落 ✓、
    //  仿真不复现（仿真纹理源太快，need_pix 从不拉长）✓。
    //  【修法】FIFO 空（且未放弃）时：不弹、整条显示流水线冻结一拍，
    //  数据到位后继续 —— pop↔事件配对保持，绝不错位。
    //  no_underrun_fix = 1 时关闭本修复（A/B 对照，验证用）。
    input  wire        no_underrun_fix,
    // ★ 2026-10-24：像素 FIFO 的**真实空标志**（来自 img_afifo 的 rempty，
    //   与 img_layer_hd 用的是同一个信号）。HD 页用它没有竖条；
    //   本层原来用的 pix_count 是跨时钟同步的滞后值，拿它当空判据会误判。
    input  wire        pix_empty,
    //==========================================================================
    //  ⓘ build "8 模式切换"：key1 轮换，一版固件验 8 个假设
    //    全部是【运行时】开关（纹理开机装载，所以不能靠换纹理来切换）
    //      0 正常   1 冻结组号(=0)  2 mask 恒 1111   3 关 LEAD 节流
    //      4 关弹空抑制  5 ds_idx 用 adv  6 绕过 map_src  7 请求侧冻结
    //==========================================================================
    input  wire [3:0]  exp_mode
);

localparam integer NPX = IMG_W * IMG_H;
localparam [15:0]  SW16 = SRC_W[15:0];
// ★ [PGI-SLIM] 四宫格格宽超过纹理行宽时才需要显式钳位（否则 map_src 已保证 sx ≤ SW16-1）
localparam         SX_CLAMP = (Q_CW > SRC_W);

//==============================================================================
//  0. 拆配置总线
//==============================================================================
wire [15:0] X0 = cfg_pos[31:16];
wire [15:0] Y0 = cfg_pos[15:0];
wire [15:0] RW = cfg_size[31:16];
wire [15:0] RH = cfg_size[15:0];

wire signed [19:0] KX = cfg_k[39:20];
wire signed [19:0] KY = cfg_k[19:0];

// ★ [ZOOM-EXACT] 锚点：源坐标原点（10 位 × 2）。见 viewer_ctrl 的 [ZOOM-EXACT] 说明：
//     sx = ((x − a)·kx + a·k_fit) >> 16 ，a·k_fit 只是移位 ⇒ 不需要相位累加器。
wire [9:0] ORIX = cfg_ori[19:10];
wire [9:0] ORIY = cfg_ori[9:0];

// ★ 100M-16：本帧配置锁存（review 问题 9/20）—— 帧边界采样、帧内恒定，
//   请求侧与显示侧不可能混用新旧配置；上层也只许在帧边界改配置。
reg [15:0]        f_x0, f_y0, f_rw, f_rh;
// ★ 右下角预算值（见 in_rect 注释）：只在配置那一拍算一次
reg [15:0]        f_x1, f_y1;
reg signed [19:0] f_kx, f_ky;
// ★ [ZOOM-EXACT] 锚点 + "半像素偏置"预先合成一个常量（帧边界只算一次）
//   phc_x = a·k_fit_x + kx/2 = (ORIX<<14) + kx/2
//   phc_y = a·k_fit_y + ky/2 = (ORIY<<15) + ky/2
//   ⇒ map_src 里加法器个数不变，只是常数项不同；不需要任何累加器。
// ★ 锚点直接并进"框原点"：f_x0a = X0 + ORIX ⇒ map_src 只做一次减法（省两个减法器）
reg [15:0]        f_x0a, f_y0a;
reg [24:0]        f_phxc, f_phyc;
reg [20:0]        f_tbase;
reg               f_en;

// ★ 100M-16：配置安全范围（review 问题 14/15）
//   map_src 的差值截到 11 位有符号（±1023）。框内差值 = [0, RW-1]，所以只要
//   RW/RH ≤ 1024，截断永远安全；in_rect 的 17 位边界加法也不会溢出
//   （|X0|≤32768 + 1024 < 65536）。超纲配置一律按"出框"处理（透明、不请求），
//   绝不回绕出错误地址。
// ★ 四宫格模式恒为真：quad_map/quad_hit 只用常量几何，完全不读 f_rw/f_rh，
//   而相册那边的 a_size 在启动阶段可能是 0 —— 那种情况下不该把四宫格判成"无效"。
//   非四宫格时这一行与原来逐位相同。
wire cfg_ok = quad_en || ((f_rw != 16'd0) && (f_rh != 16'd0) &&
                          (f_rw <= 16'd1024) && (f_rh <= 16'd1024));

//==============================================================================
//  1. 坐标映射与包围盒判定
//==============================================================================
//  sx = (x - X0) * KX >>> 16      KX = 65536 × 源宽 / 目标宽
//  sy = (y - Y0) * KY >>> 16      KY = 65536 × 源高 / 目标高
//
//  【为什么把差值截到 11 位】目标坐标最多 639，差值也在 ±639 内，11 位有符号够。
//  截窄之后乘法器从 48 位降到 31 位，逻辑量省一大截（学自 ps_scale.v 的撕裂修复）。
//
//  【越界怎么办】先判 in_rect；不在框内时映射结果一律不用（输出透明、不发请求）。
//==============================================================================
//  ★★ 配置必须当【参数】传进来，不能在函数里直接读模块级 wire ★★
//  踩过的坑：iverilog 不会把"函数体内读到的模块级 wire"算进该函数的敏感依赖，
//  于是配置（cfg_pos/cfg_k）变了、函数结果却不刷新 —— 表现为整幅图用上一帧
//  的缩放/位置。把配置显式当参数传，依赖关系就明确了（TD 综合也更稳）。
// ★★★ 2026-10-27：乘法改**无符号**并收窄操作数 ★★★
//   【为什么原来是有符号】`kx` 声明成 `signed [19:0]`，但它的实际取值范围是
//     全正的：KX = 65536×160/RW，RW ∈ [320,640] ⇒ KX ∈ [16384, 32768]；
//     KY = 65536×240/RH，RH ∈ [240,480] ⇒ KY ∈ [32768, 65536]。
//     而 `lx` 那一侧本来就写了 `{1'b0, lx[10:0]}`（最高位补 0）⇒ 恒正。
//     **两边都正却做有符号乘法**，综合器要额外处理符号位（符号扩展 /
//     Baugh-Wooley 修正），面积比无符号贵 20~30%。
//   【又能省多少】12×20 signed ≈ 15×20 unsigned 的面积。
//     按实际范围收到 **11×18 unsigned**（kx≤32768 需 17 位，ky≤65536 需 17 位，
//     统一留 18 位），面积约降到 66% ⇒ 每个乘法省 ~68 LUT。
//     本模块例化 2 次（A/B 层）、每次 2 个乘法（x/y）⇒ **约 -270 LUT**。
//   【为什么安全】in_rect 已经保证 px≥x0、py≥y0，所以 lx/ly 恒非负；
//     除法器在 cfg_ok 里挡了 RW==0，k 不会出现负值或溢出。
//==============================================================================
//  ★★ 2026-11-01：四宫格几何（常量）
//==============================================================================
//  【为什么必须做在 ps_gen_image 内部】
//  本模块内部有**两套坐标**：
//      · 请求侧：自带计数器 rq_x/rq_y，从 (0,479) 扫到 (639,0)
//      · 显示侧：直接用输入端口 x/y
//  正常情况下两者是同一个值（都来自 app_scan_gen），所以框判定一致。
//  如果在外层把 x/y 换成"格子内局部坐标"而 rq_* 还是整屏坐标，
//  两边的 in_rect 立刻指向不同区域 ⇒ 请求侧发 19200 个字就扫完全帧，
//  显示侧还要 76800 个 ⇒ **死锁**（实测 exactly 卡在第 102610 个像素）。
//  ⇒ 唯一正确的做法：两边都吃**整屏坐标**，四宫格变换在这里统一做。
//
//  【变换】
//      col = px >= X1              （X1 = X0 + CP = 384）
//      row = py >= Y1              （Y1 = Y0 + RP = 260）
//      lx  = px - (col ? X1 : X0)
//      ly  = py - (row ? Y1 : Y0)
//      hit = (lx < CW) && (ly < CH) && 左右都没落到间隙里
//      源字列 sx = lx                （kx 按"整行 160 字铺满 160 列"取，见 viewer_scene）
//      源行   sy = 2·ly + 1          （240 行源 → 120 行显示，2:1 纵向抽样）
//      半字 frac = 0x8000            （恒取高半 ⇒ 源像素 2·lx+1）
//      槽偏移 = {row, col} << 16     （每槽 65536 字）
//==============================================================================
localparam integer Q_X1 = Q_X0 + Q_CP;      // 384
localparam integer Q_X2 = Q_X1 + Q_CW;      // 544
localparam integer Q_Y1 = Q_Y0 + Q_RP;      // 260
localparam integer Q_Y2 = Q_Y1 + Q_CH;      // 380

function quad_hit;                          // 1 = 这个屏幕坐标落在某个格子里
    input [15:0] px, py;
    reg colr, rowr;
    begin
        colr = (px >= Q_X1) && (px < Q_X2);
        rowr = (py >= Q_Y1) && (py < Q_Y2);
        quad_hit = (colr || ((px >= Q_X0) && (px < Q_X0 + Q_CW))) &&
                   (rowr || ((py >= Q_Y0) && (py < Q_Y0 + Q_CH))) &&
                   quad_vm[{(py >= Q_Y1), (px >= Q_X1)}];
    end
endfunction

function [1:0] quad_slot;                   // {row, col}
    input [15:0] px, py;
    begin
        quad_slot = {(py >= Q_Y1), (px >= Q_X1)};
    end
endfunction

//  ★ 槽号直接折进 sy（而不是在地址上再加一个加法器）：
//      sy = slot*Q_SROW + (2·ly+1)        Q_SROW = Q_SLOT/160 = 256
//    于是 rq_off = sy*SW16 + sx = slot*40960 + (2ly+1)*160 + lx
//    ⇒ 槽基址天然落在乘法结果里，**rq_off 上不需要任何额外加法器**
//      （那个加法器正好和已知的最差路径同锥，去掉它对时序/面积都有好处）
//    代价：槽间距从 2^16 变成 40960 字（非 2 的幂），由 quad_loader 直接算。
localparam integer Q_SROW = 256;            // = Q_SLOT / SRC_W 的整数值（见下）
function [47:0] quad_map;                   // {frac, sy, sx}
    input [15:0] px, py;
    reg [15:0] lx, ly;
    reg [15:0] syw;
    begin
        lx = px - ((px >= Q_X1) ? Q_X1[15:0] : Q_X0[15:0]);
        ly = py - ((py >= Q_Y1) ? Q_Y1[15:0] : Q_Y0[15:0]);
        // {row,col} 是 2 位 ⇒ {slot, 8'd0} = slot*256，纯拼接，零逻辑
        // ★ 2026-11-04：槽里直接是 160×120（每行 80 字、行距仍 160 字）⇒ 1:1 显示：
        //   源行 = ly，源字 = lx/2，半字 = lx[0]（偶像素在低半字）。
        //   原来槽里是 320×240、显示时 2:1 抽样 ⇒ 装载要读两倍的行（上板"缩略图装得很慢"）。
        syw = {quad_slot(px, py), 8'd0} + ly;
        quad_map = {lx[0], 15'd0, syw, 1'b0, lx[15:1]};
    end
endfunction

function [47:0] map_src;
    input [15:0] px;
    input [15:0] py;
    input [15:0] x0;
    input [15:0] y0;
    input [17:0] kx;            // 无符号（原 signed [19:0]）
    input [17:0] ky;
    input [24:0] phc_x;         // a·k_fit + 半像素偏置（帧内恒定）
    input [24:0] phc_y;
    // ★ [ZOOM-EXACT] 锚点左侧 (px−x0−ox) 会是**负数** ⇒ 必须有符号乘。
    //   12 位有符号足够：屏幕宽 640 ⇒ |px−x0−ox| ≤ 639 < 2048。
    reg signed [11:0] sxl, syl;
    reg signed [30:0] pxl, pyl; // 12×19 有符号积
    reg   [28:0] mx, my;        // 29 位（真值恒 ≥0 且 <2^29，见下）
    reg   [16:0] sxs, sys;      // 无符号（原 signed [16:0]）
    begin
        // ★ 2026-10-30 [ZOOM-EXACT]：先减锚点再乘，等价于"乘完再加 a·(k_fit−k)"：
        //     (x−a)·kx + a·k_fit  ≡  x·kx + a·(k_fit−k)
        //   a·k_fit 是移位常数 ⇒ 省掉整条相位累加器；且锚点**逐位精确**。
        //   【为什么取低 29 位就对】有符号积可能为负，但"乘积 + a·k_fit"的真值
        //     恒 ≥0（最左端 x=0：−ox·kx + ox·k_fit = ox(k_fit−kx) ≥ 0）且 <2^29
        //     （≤ 640×32768×2 = 42M < 536M）。模 2^29 加法对负中间值同样成立，
        //     所以直接取低 29 位累加即可，不需要任何符号扩展到 36 位。
        sxl = px - x0;          // x0 已经是"框原点 + 锚点"（见 f_x0a）
        syl = py - y0;
        // ★ 2026-10-27 试验：采样点取目标像素中心（+kx/2），已并入 phc_x/phc_y
        pxl = sxl * $signed({1'b0, kx});
        pyl = syl * $signed({1'b0, ky});
        mx  = pxl[28:0] + phc_x;
        my  = pyl[28:0] + phc_y;
        sxs = mx[28:16];        // 等价于原来的 mx >>> 16（正值两者相同）
        // 2026-10-24 保险: kx 若陈旧(除法未完成)会让框内位置算出 sxs>=SW16
        //   ⇒ 地址跨到下一行第 0 个字 = 图像左边那一小段。
        //   这里在 16 位上下文中直接钳到最后一列（对正常帧是空操作）。
        if (sxs > (SW16 - 1)) sxs = SW16 - 1;
        sys = my[28:16];
        // [47:32] = 亚像素位置 frac（mx 的低 16 位），[31:0] 保持原布局
        map_src = {mx[15:0], sys[15:0], sxs[15:0]};
    end
endfunction

//==============================================================================
//  ★★ 2026-10-22 build N：水平插值用的"亚像素位置" ★★
//==============================================================================
//  【要解决什么】非整数倍放大时，最近邻会让源像素覆盖的屏幕宽度在 2 和 3 之间交替
//  （240→640 是 2.67 倍），网格线因此粗细不匀、互相吞并 ⇒ 看起来像"脏像素"。
//      320→640 是精确 2 倍，本来就没这个问题；但缩放动画的中间态必然经过非整数倍，
//      所以插值必须做。
//
//  【只做水平方向】人眼对竖线的粗细跳变极敏感（一眼就能看出来），
//  而横线的不均匀在动态画面里几乎不可见。垂直插值要缓存整行（240×32 位/层），
//  资源和时序代价都大得多，所以本版只做水平。
//
//  【frac 是什么】`map_src` 里算出的 `mx = lx * kx`，高 16 位是整数坐标，
//  低 16 位 `mx[15:0]` 就是"当前屏幕像素落在两个源像素之间的哪个位置"：
//      frac = 0      ⇒ 正好落在源像素 A 上
//      frac 越大     ⇒ 越靠近源像素 B
//      跨过 65536    ⇒ 源坐标进位，A→B
//
//  【2026-10-26 改动：不再单独算一遍】原来为了不动 map_src 的 32 位返回值，
//  另写了一个 `map_frac_x()` 把同一个 `lx*kx` 重算一次，指望综合器 CSE 合并。
//  但 DSP 已经 29/29 占满，任何没被合并掉的乘法都要用几百 LUT 顶 ⇒ 改成
//  map_src 直接返回 48 位 {frac, sys, sxs}，从结构上保证全局只有一个乘法。
//  唯一使用者 ds_frac 取 [47:32]；rq 侧只取低 32 位，高 16 位被综合剪掉。
//==============================================================================

// 【有符号包围盒】支持 X0/Y0 为负（图片部分移出屏幕）
// ★★ 2026-11-01：右下角 x1/y1 改成**预算好的寄存器**，函数里只剩 4 个比较 ★★
//  原来 x1s = x0s + rw、y1s = y0s + rh 在函数里算，而这个函数有 **3 个调用点**
//  （请求侧 1 个 + 显示侧 2 个）⇒ 6 台 17 位加法器（≈100 LUT），
//  而且 `f_y0 → req_fifo.wgray.ce` 是整条 sd_card_clk 域的**最差路径**
//  （place 后 SWNS −6.4ns，线延迟占 53%）。
//  改成寄存器后：加法只剩 2 台（每帧配置时算一次），组合链短 2 级。
function in_rect;
    input [15:0] px;
    input [15:0] py;
    input [15:0] x0;
    input [15:0] y0;
    input [15:0] x1;        // = x0 + rw（调用方给 f_x1）
    input [15:0] y1;        // = y0 + rh（调用方给 f_y1）
    reg signed [16:0] pxs, pys, x0s, y0s, x1s, y1s;
    begin
        pxs = $signed({1'b0, px});
        pys = $signed({1'b0, py});
        x0s = $signed(x0);
        y0s = $signed(y0);
        x1s = $signed({1'b0, x1});
        y1s = $signed({1'b0, y1});
        in_rect = (pxs >= x0s) && (pxs < x1s) &&
                  (pys >= y0s) && (pys < y1s);
    end
endfunction

