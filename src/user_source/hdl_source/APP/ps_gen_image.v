    if (rst)             push_cnt <= 20'd0;
    else if (idle_reset) push_cnt <= 20'd0;
    else if (req_push)               push_cnt <= push_cnt + {17'd0, pc_mask};
end
assign push_w_o = push_cnt;

//  ★ 弹出计数（与 push_cnt 同期，帧末一起快照）—— 名字避开已有的 pop_cnt
