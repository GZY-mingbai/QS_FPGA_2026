wire pix_avail = !pix_empty;

//==============================================================================
//  ★★★ 2026-10-24：帧间排空 FIFO 残留（跨帧错位的真正来源）★★★
//==============================================================================
//  【现象】push−pop 每帧都是 +1（左3=1）；竖条贯穿全高、内容 = 图像最左边那一小段。
//  【推论】那个多出来的字**没有被任何像素消费**，帧末留在像素 FIFO 里。
//    下一帧显示侧第一个 pop 取到的是"上一帧留下的字" ⇒ 之后每个 pop 都晚一个字
//    ⇒ 整帧错位一个字 ⇒ 行末取到下一行的字 0 ⇒ 竖条从第一行贯穿到最后一行。
//    而竖向 fx1 的 push/pop 精确配平（框==整宽、从不 flush 出框）⇒ 没有竖条。
//  【为什么可以安全排空】帧间（idle_reset = ~frame_active）没有任何像素需要新字：
//    本帧已收满 307200，下一帧的字还没被请求。此时 FIFO 里的任何字都是**垃圾**。
//  【修法】帧间用真实空标志 pix_empty 做条件，把残留一个字一个字弹掉。
//    弹的是垃圾、不进 cur_pix（drain 期间 pop_want=0，cur_pix 更新无副作用）。
//==============================================================================
//==============================================================================
//  ★★★ 2026-10-24 最终修复：**帧首补偿弹**（跨帧错位的根治）★★★
//==============================================================================
//  【上板现象（用户逐帧观察）】竖条出现时，**整幅图往左移了 4px**，
//    并且"紧贴屏幕左边的 4 个像素"出现在图片框的最右侧。
//  ⇒ 这不是"某一列坏了"，而是**整帧的字流相对显示位置错开了一个字**：
//        正常：[字0][字1][字2] … [字159]
//        错位：[字1][字2][字3] … [下一行字0]
//    一个字 = 2 个 RGB565 像素 = 4 个屏幕列 ⇒ 整幅左移 4px，行末补上"下一个字"。
//  ⇒ 错位从帧的**第 0 个字**就开始 ⇒ 只能是**上一帧留下的字还躺在 FIFO 里**。
//  【为什么"帧间排空"没治好】出问题的那一帧耗时 > 20ms（缺料、give_up），
//    帧间**没有空闲期** ⇒ idle_reset 只有几拍 ⇒ drain_act 来不及执行
//    ⇒ 残留被带进下一帧 ⇒ 下一帧整帧错位 ⇒ 而且它又超时 ⇒ 残留继续传递。
//    这正是"只有竖条出现时才掉帧、且竖条会连续好几帧"的原因。
//  【修法】在**帧首上升沿**（frame_active 上升沿）判断：FIFO 非空且量很小
//    （≤4 个字）⇒ 那一定是上一帧的残留垃圾（帧间请求侧不推进，不会预取）
//    ⇒ 立刻弹掉它，只弹不显示。这样错位不会再跨帧传播。
//  【安全性】
//    · 帧间 rq_can_adv 因 rq_scan_end=1 而关闭、rq_x/rq_y 又每拍复位 ⇒ 不会预取，
//      所以帧首 FIFO 里的少量字必然是残留，不是本帧的；
//    · 只弹 1 次即清（fix_pending），不会连续吞掉本帧的字；
//    · 第一个像素若 pix_avail=1 会用 pix_head（不用 cur_pix）⇒ 不受影响。
//==============================================================================
//==============================================================================
//  ★ 2026-10-24：**停用**（保留代码便于回退）
//==============================================================================
//  【为什么停用】它假设"帧首 FIFO 里那 1 个字一定是上一帧的残留"。但：
//     帧首 warmed=0 ⇒ layer_ready 直接报 1 ⇒ 请求侧立刻全速发本帧第一批
//     ⇒ 本帧第一个字往返只要几十拍，可能在 fix_pending 生效前就到了
//     ⇒ 于是被弹掉的是【本帧第一个字】⇒ 本帧少 1 个字
//     ⇒ 整幅左移 4px，且这次 pop 计入本帧计数 ⇒ push−pop 显示 +1。
//  这与实测"整幅左移 + 左3=1"完全一致，而"帧间排空 drain_act"发生在
//  无任何需求的时候，是安全的，保留。
//  【正解】跨帧残留的正确处理是"让 push/pop 在帧边界严格对齐"，
//  而不是"盲弹一个"。等确认这一版现象后再决定。
//==============================================================================
reg fix_pending;
always @(posedge clk or posedge rst) begin
    if (rst)                           fix_pending <= 1'b0;
    // ★★★ 2026-10-24：**永久关闭** ★★★
    //  它会在帧首"弹掉一个字但不显示"。若那个字其实是**本帧的第一个字**
    //  （帧首请求侧立刻全速发本帧第一批，往返只要几十拍，完全可能已经到货），
    //  结果就是：FIFO 少一个字、push/pop 却仍然配平
    //  ⇒ **整幅左移 4px，而所有数码管读数都正常**。
    //  这正是"计数全对、画面还是错"的直接成因，必须彻底关掉。
    //  跨帧残留改由 `drain_act`（只在 idle_reset 期间、无任何需求时）处理。
    else                               fix_pending <= 1'b0;
end

reg drain_act;
always @(posedge clk or posedge rst) begin
    if (rst)              drain_act <= 1'b0;
    else if (!idle_reset) drain_act <= 1'b0;      // 帧内绝不排空
    else if (pix_empty)   drain_act <= 1'b0;      // 已排空
    else                  drain_act <= 1'b1;      // 帧间且非空 ⇒ 继续弹
end

//==============================================================================
//  ★★★ 2026-10-24 根因修复：give_up 之后把"迟到的那个字"空弹掉 ★★★
//==============================================================================
//  【三条实验事实】
//    · 100M-25 之后 give_up 只剩诊断用途，不再跳过弹出 ⇒ 它会一直冻结扫描等字
//    · 那个字**等 0.33ms 不回来、等 4ms 也不回来**（实测）⇒ 它真的丢了
//    · 若"缺料就重复像素、不弹"，则**每次缺料都永久错位一个字**
//      ⇒ 后半段所有行偏移 ⇒ 看起来像"撕裂"
//  【所以正确做法 = 三个动作配合】
//    ① 冻结扫描等字（保证不错位）—— pop_stall 保持不变
//    ② 只等 82us 就放弃（GIVEUP_AT=4096），**不拖长帧 ⇒ 不掉帧**
//    ③ 放弃时把这个位置**标记为已显示过**；迟到的字到货后**空弹掉不显示**
//       ⇒ pop 与 push 重新 1:1 ⇒ **不错位 ⇒ 没有竖条**
//  【为什么空弹能恢复对齐】
//    缺料那一列已经用 cur_pix 重复显示过了（位置已消费），
