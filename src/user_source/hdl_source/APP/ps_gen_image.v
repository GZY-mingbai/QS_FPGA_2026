// ★ 2026-10-27：dem_d 已删（同上：无读者的 20 位绝对差电路）。

//  ★★ 2026-10-23：帧末快照 (push − pop) ★★
//  一帧结束的那一拍（frame_active 下降沿）取值。判读：
//     bit3=0, |差|=n  ⇒ 多交付 n 个字（FIFO 多积、流右移）
//     bit3=1, |差|=n  ⇒ 少交付 n 个字（FIFO 缺料、流左移）
//     0,0             ⇒ 数量配平 ⇒ 是取字内容错（pix_head/半字）
//  帧末本应为 0；出现竖条的那一帧不为 0，就是这里。
//  ★ 对数刻度：一位十六进制覆盖 0 ~ ≥2048，解决"低3位把 480 显示成 0"的歧义
//      0 → 真配平     1..7 → 1..7      8..15 → 8     16..63 → 9
//      64..255 → A    **256..511 → B（= 每行差 1 个字的 480）**
//      512..1023 → C  1024..2047 → D  ≥2048 → E
wire [19:0] d_abs  = (push_cnt >= popw_cnt) ? (push_cnt - popw_cnt)
                                            : (popw_cnt - push_cnt);
wire [3:0]  d_code = (d_abs == 20'd0)   ? 4'h0 :
                     (d_abs < 20'd8)    ? d_abs[3:0] :
                     (d_abs < 20'd16)   ? 4'h8 :
                     (d_abs < 20'd64)   ? 4'h9 :
                     (d_abs < 20'd256)  ? 4'hA :
                     (d_abs < 20'd512)  ? 4'hB :
                     (d_abs < 20'd1024) ? 4'hC :
                     (d_abs < 20'd2048) ? 4'hD : 4'hE;


reg frame_d;
// ★ 帧内粘滞事件（本帧发生过就保持 1；帧界清 0 并**保留上一帧的值**给数码管）
// ★★ 2026-10-24 定位：每帧「框出口 flush」次数（fx0 理论值 = 480）
//   显示 count>>5：480>>5=15=F。479>>5=14=E ⇒ **差一次就能读出来**
reg [9:0] bxf_cnt, bxf_snap;
always @(posedge clk or posedge rst) begin
