wire [31:0] pix_sel   = (s2_is_new && pix_avail) ? pix_head : cur_pix;   // 当前**字**

//==============================================================================
//  ★★ 2026-10-23：565 半字选择改用与**地址同拍**的亚像素位置 ★★
//==============================================================================
//  【要解决的现象】横向切换时图层边缘有一条竖条，内容是**该层另一处的像素**，
//    只在 565（过渡）出现、888 高清页没有。
//  【为什么】565 是"1 个字 = 2 个源像素"，高低半字由亚像素位置 `frac` 决定：
//        frac < 32768 → 取低半字（偶数源像素）
//        frac >= 32768 → 取高半字（奇数源像素）
//    而 `ds_frac_d2` 走的是**另一条独立延迟链**（ds_frac_d1/d2），与地址用的
//    `ds_sx_d2`（来自 map_src(x)）只是"理论上"同拍。只要两链差一拍，那一列就取到
//    **相邻的另一个源像素** —— 画面上就是"另一段画面"，而且只在半字相位翻转处出错。
//  【改法】frac 改成用 `px_x_d2` **现场重算**。`px_x_d2` 与 `ds_sx_d2` 在同一个
//    `if (pipe_ce)` 里由同一个 x 延迟 2 拍 ⇒ 取哪个字、取这个字的哪一半**必然同拍**，
//    结构上不可能再错位。（`ds_frac_d1/d2` 保留不动，供其它观察用。）
//==============================================================================
// ★★ 2026-10-24：半字选择也必须用**钳位后**的列 ★★
//  【上板证据】竖条只有 **1 像素** 宽，颜色是该图像某一列的纵向剖面
//    （绿叶→红肉→黄籽）；565 是 1 字 = 2 像素，
//    **错一个字 = 4 像素，错半个字 = 1 像素** ⇒ 是高低半字选错。
//  【病根】地址已经钳到 SW16-1，但 `frac` 仍用**未钳位**的 px_x_d2。
//    框右边界那一列 dx=640 ⇒ frac=(640*kx)&0xFFFF=0 ⇒ 选【低半字】，
//    而该列本应取本行末字的【高半字】⇒ 显示同一字里的另一个像素 ⇒ 1 像素竖线。
//  【修法】与地址、事件、last_* 用**同一个钳位判据**；钳位列统一取该字后半。
//==============================================================================
//  ★★★ 2026-10-24 根因修复（2px 竖条）：半字选择必须用**流水线里的 frac** ★★★
//==============================================================================
//  【注释与实现矛盾】1208 行的设计意图写得清清楚楚：
//      「ds_frac_d2 = (px - x0) * kx 的低 16 位 = 当前屏幕像素落在字内的位置」
//    `ds_frac_d2` 是**随像素一起流水过来**的（与 ds_sx_d2 / pix_raw 同一套延迟链，
//    由同一条 valid 限定推进），天然与"这一拍正在输出的那个像素"严格对应。
//  【但实现用了 frac_now = map_frac_x(px_x_d2, ...)】—— 拿延迟后的屏幕坐标**现算**。
//    一旦流水线出现停顿（pop_stall 缺料冻结、s2_hold、帧边界气泡），
//    `px_x_d2` 与 `pix_raw` 之间就会差一拍/一列 ⇒ frac 取到**相邻列**的值
//    ⇒ `frac < 32768` 的判定翻转 ⇒ **半字选错** ⇒ 该字的一半（2 个屏幕列）
//      显示成同一个字的另一半 ⇒ **2px 竖条**。
//    只在动画时：静止时框==全屏、请求侧始终领先、流水线不停顿。
//  【2026-10-26】原来这里还留了一根 `frac_now = map_frac_x(px_x_d2, ...)`，
//  注释写着"仅作对照/未来缩放用"——它没进任何逻辑，纯死代码，而且带着一次
//  11×20 乘法。已删除（frac_sel 只用流水线里的 ds_frac_d2）。
//==============================================================================
// ★ [PGI-SLIM] ds_sx_d2 > SW16-1 只可能出现在四宫格（map_src 已钳位），而四宫格 frac 恒 0x8000，
//   与强制 0xFFFF 一样取高半 ⇒ 钳位比较是空操作（SX_CLAMP=1 时保留原式）
wire [15:0] frac_sel   = SX_CLAMP ? ((ds_sx_d2 > (SW16 - 16'd1)) ? 16'hFFFF : ds_frac_d2) : ds_frac_d2;
wire [15:0] pix565_sel = (frac_sel < 16'd32768) ? pix_sel[15:0]
                                                 : pix_sel[31:16];

wire [31:0] pix_unpack = {8'hFF,
                          pix565_sel[15:11], pix565_sel[15:13],   // R5 -> R8
                          pix565_sel[10:5],  pix565_sel[10:9],    // G6 -> G8
                          pix565_sel[4:0],   pix565_sel[4:2]};    // B5 -> B8

wire [31:0] pix_out = pix_unpack;


//==============================================================================
//  5. 主时序：复位 / 帧间空闲复位 / 请求侧自由跑 / 显示侧受 adv 门控
//==============================================================================
//  三条支路互斥：
//    · rst         ：异步复位
//    · idle_reset  ：帧间空闲（adv=0 且停在帧起点）→ 全部回到帧起点，不占推进拍
//    · 否则        ：请求侧按自己的节奏跑；显示侧只在 adv=1 时推进
//                    （adv=0 且不在帧起点 = 帧内停顿 → 显示侧自然冻结 ✓）
//==============================================================================
always @(posedge clk or posedge rst) begin
    if (rst) begin
        rq_x        <= 16'd0;
        rq_y        <= IMG_H - 1;
        rq_idx      <= 19'd0;
        ds_lead     <= LEAD[18:0];
        last_rq_vld <= 1'b0;
        last_rq_sx  <= 16'd0;
        last_rq_sy  <= 16'd0;
        last_ds_vld <= 1'b0;
        last_ds_sx  <= 16'd0;
        last_ds_sy  <= 16'd0;
        ds_sx_d1    <= 16'd0;
        ds_sy_d1    <= 16'd0;
        ds_sx_d2    <= 16'd0;
        ds_sy_d2    <= 16'd0;
        pix_wait    <= 18'd0;
        retry_tick  <= 11'd0;
        retry_cnt   <= 3'd0;
        s1_valid    <= 1'b0;
        s1_in_box   <= 1'b0;
        s1_is_new   <= 1'b0;
        s2_valid    <= 1'b0;
        s2_in_box   <= 1'b0;
        s2_is_new   <= 1'b0;
        cur_pix     <= 32'd0;
        prev_pix    <= 32'd0;      // ★ build N：插值用的 A，必须清零否则 x 会污染输出
        ds_frac_d1  <= 16'd0;
        ds_frac_d2  <= 16'd0;
        pix_raw     <= 32'd0;
        in_box_s3   <= 1'b0;
        out_valid   <= 1'b0;
        warmed      <= 1'b0;
        rq_scan_end <= 1'b0;
        f_x0 <= 16'd0; f_y0 <= 16'd0; f_rw <= 16'd0; f_rh <= 16'd0;
        f_x1 <= 16'd0; f_y1 <= 16'd0;
        f_kx <= 20'sd0; f_ky <= 20'sd0; f_tbase <= 21'd0; f_en <= 1'b0;
        f_x0a  <= 16'd0; f_y0a <= 16'd0;
        f_phxc <= 25'd0; f_phyc <= 25'd0;
    end else if (idle_reset) begin
        // ---------- 帧间空闲：回到帧起点 ----------
        rq_x        <= 16'd0;
        rq_y        <= IMG_H - 1;
        rq_idx      <= 19'd0;
        ds_lead     <= LEAD[18:0];
        last_rq_vld <= 1'b0;
        last_rq_sx  <= 16'd0;
        last_rq_sy  <= 16'd0;
        last_ds_vld <= 1'b0;
        last_ds_sx  <= 16'd0;
        last_ds_sy  <= 16'd0;
        ds_sx_d1    <= 16'd0;
        ds_sy_d1    <= 16'd0;
        ds_sx_d2    <= 16'd0;
        ds_sy_d2    <= 16'd0;
        pix_wait    <= 18'd0;
        retry_tick  <= 11'd0;
        retry_cnt   <= 3'd0;
        s1_valid    <= 1'b0;
        s1_in_box   <= 1'b0;
        s1_is_new   <= 1'b0;
        s2_valid    <= 1'b0;
        s2_in_box   <= 1'b0;
        s2_is_new   <= 1'b0;
        cur_pix     <= 32'd0;
        prev_pix    <= 32'd0;      // ★ build N：插值用的 A
        ds_frac_d1  <= 16'd0;
        ds_frac_d2  <= 16'd0;
        pix_raw     <= 32'd0;
        in_box_s3   <= 1'b0;
        out_valid   <= 1'b0;
        warmed      <= 1'b0;
        rq_scan_end <= 1'b0;
        // ---------- 帧边界锁存本帧配置（帧内恒定）----------
        f_x0 <= X0; f_y0 <= Y0; f_rw <= RW; f_rh <= RH;
        f_x1 <= X0 + RW; f_y1 <= Y0 + RH;   // 右下角预算（in_rect 用）
        f_kx <= KX; f_ky <= KY; f_tbase <= tex_base; f_en <= layer_en;
        // ★ [ZOOM-ANCHOR] 相位：与半像素偏置在这里一次性合成（每帧只算一次）
        f_x0a  <= X0 + {6'd0, ORIX};
        f_y0a  <= Y0 + {6'd0, ORIY};
        // a·k_fit 就是移位：x 方向 k_fit=16384 ⇒ a<<14；y 方向 k_fit=32768 ⇒ a<<15
        f_phxc <= {{1'b0, ORIX}, 14'd0} + ((SAMPLE_CENTER != 0) ? {7'd0, KX[18:1]} : 25'd0);
        f_phyc <= {ORIY, 15'd0}         + ((SAMPLE_CENTER != 0) ? {7'd0, KY[18:1]} : 25'd0);
    end else begin
        // ---------- 显示扫描计数 ----------
        // ★ 2026-10-19：改成和"弹出/流水线"同一个使能 adv_eff ★
        //   原来用 `adv`：`adv_eff = adv && !pop_stall`，所以每次"FIFO 空"事件
        //   都会让 ds_idx 多走一步，而像素既没前进也没弹出 ⇒ 计数与实际位置分离
        //   ⇒ `ahead = rq_idx - ds_idx` 失真 ⇒ 预取被过早放开/收紧。
        //   一个像素的"坐标 / 计数 / 弹出"必须由同一个使能驱动。
        //★★★ 2026-10-19 关键修正：ds_idx 必须数"真正消费掉的像素" ★★★
        //  【实测】ds_idx = 307,200 而 pop_cnt = 302,400，差 4,800。
        //    原因：`ds_idx` 数 `adv_eff`，而真正消费还要看 `pop_want`
        //    （`s2_is_new` 为 1 才算换了一个源像素）。`adv_eff` 的拍数比
        //    真实弹出多 4,800 次/帧 ⇒ **ds_idx 虚高**
        //      ⇒ `ahead = rq_idx - ds_idx` 被低估
        //      ⇒ `rq_ok_ahead = ahead < LEAD` 过早判"跑太远" ⇒ 请求侧被节流
        //      ⇒ 请求扫描一帧只走到 302,600（走不完 307,200）
        //      ⇒ 少 4,600 个像素的请求 ⇒ 那段之后整体前移一格
        //      ⇒ 累积 7 行、断裂、逐帧会动
        //   旁证：commit_max 顶到 203、thr_cnt ≈ 180k 拍（被节流卡住 9% 的拍）。
        //
        //  【修法】ds_idx 与 pix_pop 用同一个事件
        //      （`adv_eff && pop_want && !dead`，就是 pix_pop 的定义）
        //   于是"弹出数 ≤ 提交数" ⇒ **ds_idx ≤ rq_idx 恒成立**，
        //   结构上不可能再出现"显示侧跑到请求侧前面"。
        //   模式 5 = 回退到"用 adv 计数"的最老行为，仅作对照。
        if (pix_pop && (ds_lead < NPX[18:0] + LEAD[18:0]))
            ds_lead <= ds_lead + 19'd1;

        // ---------- 请求扫描（不受 adv 门控）----------
        if (rq_go_eff) begin
            // ★ 100M-16：扫到最后一个屏幕像素就置 rq_scan_end（review 问题 2）
            if (rq_at_last) rq_scan_end <= 1'b1;
            // ★★★ 2026-10-19 修：rq_idx 只能数"源像素变化"，不能数"屏幕位置" ★★★
            //  【原来】rq_idx 每扫一个屏幕位置就 +1，一帧最多 +307200（=NPX）；
            //  而 ds_idx（上面 760 行）只在**框内真正消费一个源像素**时才 +1，
            //  一帧最多 240×180 = 43200。两个计数器数的不是同一件事。
            //  ⇒ `ahead = rq_idx - ds_idx` 立刻虚高，而且越走越离谱：
            //       框 240×180、K=2.667 时，扫完第一行框内像素：
            //           rq_idx = 640（整行位置）   ds_idx ≈ 240（框内源像素）
            //           ahead   = 400 > LEAD(64)  ⇒ rq_ok_ahead = 0
            //       ⇒ **请求侧永久卡死**，整帧只发出约 64 个请求
            //       ⇒ 像素 FIFO 空 ⇒ need_pix 拉满 4ms ⇒ give_up
            //       ⇒ layer_dead ⇒ 该层全透明（= "图片不显示"）
            //  数码管实测就是这个：wr_lat 读到 000（期望 4B0 = 1200）。
            //  而且 dead 之后 layer_ready 被强制拉 1 ⇒ **帧率不受影响**
            //  ⇒ 三层现象（不显示 / 不掉帧 / wr_lat=0）同出一个原因。
            //
            //  【为什么 `IMG_11_DIAG=1`（1:1 全屏）一直看不出来】
            //  框 == 全屏时"位置数"恰好等于"源像素数"，两个计数器天然相等，
            //  这个 bug 被完全掩盖。只要框比屏幕小，它就必然发作。
            //
            //  【修法】与 ds_idx 用同一个事件：只在 rq_new（框内源像素发生变化）
            //  时 +1。这样 ahead 的含义就是"已请求、未消费的**源像素**个数"，
            //  与像素 FIFO 里的实际占用一一对应，LEAD 才真正是"领先多少个像素"。
            if (rq_new) rq_idx <= rq_idx + 19'd1;
            if (rq_x == IMG_W - 1) begin
                rq_x <= 16'd0;
                rq_y <= rq_y - 16'd1;
            end else begin
                rq_x <= rq_x + 16'd1;
            end
            if (rq_new) begin
                last_rq_vld <= 1'b1;
                last_rq_sx  <= rq_sx_c;      // ★ 存钳位后的值
                last_rq_sy  <= rq_sy;
            end
        end

        // ---------- 预热：请求侧先跑 LEAD 个像素，再放显示侧开工 ----------
        // 不预热的话两侧同速推进、领先量永远为 0（踩过的坑，见第 3 节）。
        // ★ 100M-16：小图层总需求可能不足 LEAD 个源像素（小图标/窄裁剪），
        //   只判 rq_idx >= LEAD 会永远预热不完（review 问题 3）⇒ 加上
        //   "本帧屏幕扫描已结束"：该请求的都请求了，显示侧放行。
        //   （出框位置不计入 ahead，所以小图层的请求侧不会被 LEAD 卡死，
        //     一定能扫到屏幕终点。）
        if ((rq_idx >= LEAD[18:0]) || rq_scan_end)
            warmed <= 1'b1;

        // ---------- 显示流水线：与场景/合成/写使能共用 pipe_ce ----------
        // pipe_ce=0 时所有像素级都保持；帧尾 pipe_ce=1、adv=0 时继续送气泡，
        // 让已接受像素完整排空。s1_valid 只标记本拍真正接受的新扫描像素。
        //==============================================================================
        //  ★★★ 2026-10-24 最终修复：s2 要字没字时，整条像素流水线原地冻结一拍 ★★★
        //==============================================================================
        //  【为什么需要这一拍】FIFO 见底时，viewer_scene 的 layer_ready 会组合拉低
        //  并传回 pipe_ce；但那条路径要经 ps_gen_image → img_layer_ctrl → viewer_scene
        //  → App → 再回来，存在一拍延迟。
        //  ⇒ 那一拍 pipe_ce 仍为 1，而 s2 需要新字（s2_is_new=1）却 pix_avail=0
        //  ⇒ pix_pop=0 ⇒ 该字需求被流水线吃掉、字永远留在 FIFO
        //  ⇒ push−pop = +1 ⇒ 之后每次 pop 晚一个字 ⇒ 行末取到下一行字 0
        //  ⇒ 图像左边那一小段出现在 A 右边缘 = 那条竖线。
        //  【为什么只在横向（fx0）】竖向 fx1 的框 == 整宽，请求侧始终领先、FIFO 不见底；
        //  fx0 每行在 x=640−px 处出框 flush，那一瞬 FIFO 见底 ⇒ 每帧恰好漏 1 次。
        //  【为什么之前加 s2_hold 会死锁】那次同时改了 viewer_scene 的 pixel_ready
        //  （把 tex_ok 变成硬性要求）⇒ 帧收不满 ⇒ 状态机卡住。这次**只冻结本模块内部**，
        //  外部流控一个字都不动，并用 !give_up 兜底防死锁。
        if (pipe_ce && !s2_hold_w) begin
            s1_valid  <= adv_eff;
            s1_in_box <= adv_eff && f_en && ds_in_box && !dead;   // ★ dead → 全透明
            s1_is_new <= adv_eff && f_en && ds_new   && !dead;
            // ===== 2026-10-24 根因修复：坐标/frac 延迟链必须 valid 限定 =====
            //  原来这些寄存器只被 pipe_ce 门控、不看 adv_eff；而 s1_valid <= adv_eff
            //  —— 数据链在 pop_stall 那拍进的是气泡。
            //  ⇒ pop_stall 之后坐标链比数据链超前 1 列
            //  ⇒ frac_now = map_frac_x(px_x_d2,...) 用超前一列的亚像素
            //  ⇒ 半字选到相邻源像素 ⇒ 该列显示隔壁源像素 = 1 像素竖线。
            //  只在动画/边界：静止时框==全屏、请求侧始终领先，不会 pop_stall；
            //  动画时边界要 flush 当前组，FIFO 短暂见底 ⇒ 只在边界发生。
            //  修法：第 1 级跟 adv_eff，第 2 级跟 s1_valid（valid-qualified pipeline）。
            if (adv_eff) begin
                ds_sx_d1   <= ds_sx;
                ds_sy_d1   <= ds_sy;
                ds_frac_d1 <= ds_frac;
            end
            if (s1_valid) begin
                ds_sx_d2   <= ds_sx_d1;
                ds_sy_d2   <= ds_sy_d1;
                ds_frac_d2 <= ds_frac_d1;
            end
            if (adv_eff && ds_new) begin
                last_ds_vld <= 1'b1;
                last_ds_sx  <= ds_sx_k;      // ★ 存钳位后的值
                last_ds_sy  <= ds_sy;
            end

            s2_valid  <= s1_valid;
            s2_in_box <= s1_in_box;
            s2_is_new <= s1_is_new;

            // 拍 3：出像素 + 抓取新弹出来的像素
            // 这一拍 FIFO 的队首就是"要给这个像素用的那个源像素"
            // ★★ 千万别用 pix_count 去判断"这一拍的 pix_head 有没有效" ★★
            //   pix_count 来自读域指针，是**跨时钟同步后的保守值（滞后约 2 拍）**；
            //   拿它做门控会在正常通路里把有效像素换成 cur_pix（旧值）——
            //   实测：全分辨率真图的画面一致率从 ~99% 掉到 30%。
            //   真正丢包的情形由第 6 节的 give_up 兜底（只要不黑屏就够）。
            //★★★ 100M-39：输出那一拍**再判一次框** ★★★
            //  【为什么】白条的五个特征（固定屏幕 x / 全高 / 在框**外** / 内容是纹理 /
            //  关掉图层就消失）只指向一件事：**图层在框外输出了非零像素**。
            //  而 pix_raw 的框外分支本来是 0 ⇒ 只能是 `s2_in_box`（寄存了两拍）
            //  在某些拍上仍报"框内"。
            //  【做法】用与 s2_in_box **严格同拍**的目标坐标（px_x_d2/px_y_d2）
            //  组合再判一次，两者都为真才输出像素。
            //  【性质】流水线一致时 out_in_box ≡ s2_in_box ⇒ **逐位无变化**；
            //  只有两者不一致（也就是我们要找的那一拍）才会被强制成透明。
            //==============================================================================
            //  ★★ build P16：16 位打包纹理的拆包（取代插值）★★
            //==============================================================================
            //  【为什么去掉插值】纹理现在是「一个 32 位字 = 两个 RGB565 像素」，
            //  120 字/行铺满 640 像素 ⇒ 每字覆盖 5.33 个屏幕像素。这种倍数下
            //  插值收益很小，而拆包本身必须做。先保证正确，画质后续再说。
            //  【怎么选半字】`ds_frac_d2` 是「当前屏幕像素落在字内的位置」（0~65535）：
            //      0 ~ 32767   ⇒ 字的前半 = 偶数源像素 ⇒ 取低 16 位
            //      32768~65535 ⇒ 字的后半 = 奇数源像素 ⇒ 取高 16 位
            //  这和原来插值用的是同一个信号，位置天然对齐。
            //  【565 -> 888】低位补高位：5 位扩 8 位用 {v, v[4:2]}，6 位用 {v, v[5:4]}，
            //  这样纯白 FFFFF 仍然映射成 FFFFFF，纯色不失真。
            //==============================================================================
            //  【为什么需要】非整数倍放大时最近邻会让源像素覆盖宽度在 2/3 之间交替，
            //  网格线粗细不匀、互相吞并 ⇒ 视觉上就是"脏像素"。插值把硬跳变成渐变，
            //  线宽均匀，网格也就正了。
            //
            //  【A 和 B 怎么取】输出级只有两个源像素可用：`cur_pix`（已弹出的当前源像素）
            //  和 `pix_head`（FIFO 队首，下一个）。要分两种情况：
            //      s2_is_new = 1（刚跨到新源像素这一拍）：
            //            cur_pix 还是**旧的 A**（本拍才要 pop），pix_head 是 B
            //            ⇒ A = cur_pix，B = pix_head
            //      s2_is_new = 0（保持拍）：
            //            cur_pix 已经是 B（上拍 pop 存的），prev_pix 是 A
            //            ⇒ A = prev_pix，B = cur_pix
            //   下面两个三元式就是这两行，两种情形都得到正确的 (A,B) 对。
            //
            //  【为什么 prev_pix 只在 pix_pop 时更新】放大 2 倍时 pix_pop 每 2 拍一次，
            //  中间那拍不 pop ⇒ prev_pix 稳定保持 A，正好配上正在被重复使用的 B。
            //
            //  【为什么 kx >= 65536 时不插值】1:1 时 frac 恒 0，插值式会输出 A（上一个）
            //  ⇒ 整幅图左移一像素。缩小（kx>65536）时也不该插值（本来就不重复采样）。
            //  只有 kx < 65536（放大）才是插值的用武之地。
            //
            //  【权重】iw_a = 65536 - frac，iw_b = frac，两者和恒为 65536 ⇒ 归一化正确，
            //  纯色区域插值后颜色不变（A=B 时结果就是 A）。
            //==============================================================================
            //  （插值的 wire 声明已挪到模块级 :928 附近 —— Verilog-2001 不允许在
            //    always 块里声明 wire；这里只做赋值。）
            //==============================================================================
            pix_raw   <= !s2_valid ? 32'h0000_0000 :
                         s2_in_box ? pix_out : 32'h0000_0000;
            in_box_s3 <= f_en && !dead && s2_in_box;   // ★ [INBOX-P] 与 pix_raw 同拍
            out_valid <= s2_valid;
            if (pix_pop) begin
                prev_pix <= cur_pix;
                cur_pix  <= pix_head;     // ★ 弹了就一定用它，不再有"空弹丢弃"
            end
        end

        // ---------- 丢包自愈计时（只有在"要弹但没货"时才增长）----------
        //  pix_wait   ：总共等了多久  → 到 GIVEUP_AT 就彻底放弃这个像素
        //  retry_tick ：距上次重发多久 → 到 RETRY_TICK_MAX 就再重发一次
        //  retry_cnt  ：已重发几次    → 到 MAX_RETRY 就只等 give_up 了
        if (!need_pix) begin
            pix_wait   <= 18'd0;                // 不需要等 / 已经有货 → 全部清零
            retry_tick <= 11'd0;
            retry_cnt  <= 3'd0;
        end else begin
            pix_wait <= pix_wait + 18'd1;
            if (retry_tick >= RETRY_TICK_MAX) begin
                retry_tick <= 11'd0;
                if (retry_cnt < MAX_RETRY)
                    retry_cnt <= retry_cnt + 3'd1;
            end else begin
                retry_tick <= retry_tick + 11'd1;
            end
        end
    end
end

//==============================================================================
//  6. 弹 FIFO 与流控
//==============================================================================
// 【为什么 pop_want 里不能含 adv】否则会形成
//   adv → pop_want → layer_ready → pixel_ready → adv 的组合环。
//   pop_want 只用寄存器（s2_*），layer_ready 就是纯组合的稳定函数。
//
// 【为什么要带 warmed】预热期请求侧还没跑到 LEAD，此时必须挡住显示侧，
//   否则两侧同速推进、领先量建不起来（见第 3、5 节）。
//==============================================================================

// FIFO 只在共享流水线推进、且当前 s2 token 确实需要新源像素时弹出。
// layer_ready 在队首无货时拉低全局 pipe_ce，所有像素级一起保持。
//★★★ 2026-10-23：弹出必须同时有货（`pix_avail`）★★★
//  【病根】原来 `pix_pop = pipe_ce && pop_want && !dead` **不看 FIFO 有没有货**。
//    FIFO 空时仍然弹 ⇒ 异步 FIFO 读指针越过队尾、回绕到 0
//    ⇒ 之后每次弹出都**错开一个字** ⇒ 这一行后面的内容整体偏移
//    ⇒ 行尾那一列取到**下一行的第 0 个字 = 行首 = 左边那一小段**。
//  【为什么 SEL2 = 0（数量配平）】弹出确实发生了、计数照样 +1，所以 push−pop 恒 0
//    —— 这正是"计数配平但内容错"的唯一形状。
//  【为什么闪烁】只在"某个 s2_is_new 时刻 FIFO 恰好空"才触发；
//    FIFO 空 ⟺ layer_ready=0 ⟺ 伴随停顿/掉帧。
//  【为什么上一轮给 pix_sel 加门控没用】那只改了"显示什么"，没阻止读指针前进。
//  【改法】空的时候不弹（保持读指针），显示继续用 cur_pix（重复上一像素）。
//  ★ drain_act 期间也要真的弹（FIFO 的 re = pix_pop），否则残留永远排不掉
// ★ 2026-10-24：去掉 `!dead`。`dead`（该层本帧透明）期间照样弹字，
//   否则 pix_pop 被禁、流水线却照走 ⇒ 又漏一个 ⇒ 恢复显示后整幅错位。
//   透明的效果由 pix_raw<=0 实现，与"弹不弹"无关。
//==============================================================================
//  ★★★ 2026-10-24：帧切换那一拍会多弹一个字（"一帧到下一帧之间"）★★★
//==============================================================================
//  【病根】drain_act 是寄存器，帧首那一拍仍然是 1（idle_reset 已经变 0）：
//      帧间末拍：idle_reset=1、FIFO 还有字 ⇒ drain_act <= 1
//      帧首首拍：idle_reset=0、frame_active=1，但 drain_act 仍为 1
//                ⇒ pix_pop = drain_act && pix_avail = 1
//                ⇒ **弹掉本帧第一个字**
//    而同一拍 popw_cnt 被 idle_reset 清零覆盖 ⇒ 这次 pop 不计入本帧
//    ⇒ 物理：本帧少 1 个字（画面左移 4px）
//    ⇒ 计数：push − pop = +1、符号位 0
//    两条实测现象一次对齐。
//  【修法】组合门控：只有"真的在帧间"（idle_reset=1）才允许排空，
//    帧首那一拍 idle_reset 已为 0 ⇒ drain_now 必定为 0 ⇒ 绝不弹本帧的字。
//==============================================================================
wire drain_now = drain_act && idle_reset;

assign pix_pop     = (pipe_ce && pop_want && pix_avail)
                  || (drain_now && pix_avail)
                  || (fix_pending && pix_avail);   // ★ 帧首清残留

// ★★ 图层没启用时，必须直接报"就绪" ★★
//  【踩过的坑 · 2026-10-16 上板全屏黑屏】
//  纹理还没装好时 layer_en = 0（App 里被 tex_ready 与掉），于是：
//      rq_go = layer_en && ... = 0  →  请求侧一步不走  →  warmed 永远不置 1
//      →  layer_ready = warmed && ... = 0
//      →  app_demo_scene 的 pixel_ready = img_rdy0 & img_rdy1 = 0
//      →  app_scan_gen 的 streaming = ps_start & pixel_ready = 0
//      →  坐标永不推进、ps_valid 恒 0  →  frame_writer 一个像素都收不到
//      →  **整屏黑**（连白底、图形、文字都没有）
//  层关闭时本层输出本来就全透明，一个像素都不需要，所以"就绪"既是正确的，
//  也是流控必须的 —— 局部失败绝不允许把整条流水线锁死。
//
// ★ give_up：最后一个保险丝（丢包自愈的第二段）★
//  万一"重发请求"也拿不到像素（比如请求 FIFO 一直满、或卡根本没插），
//  等够 GIVEUP_AT 之后也必须报"就绪"，让显示侧带着 cur_pix 继续推进。
//  代价只是图片上多一条重复像素，**绝不会整屏黑**。
// ★★★ 2026-10-24★★★  之前只关了 pop_stall，没关 layer_ready：
//  缺料时 layer_ready 仍报 0 ⇒ pixel_ready=0 ⇒ **扫描照样冻结** ⇒ 帧变长 ⇒ 掉帧。
//  证据：打开开关后 dbg_evt 从 7 变成 **5**（bit1 pop_stall 消失），但掉帧依旧
//  ⇒ 冻结来自 layer_ready，不是 pop_stall。
//  修法：同一个开关也放开 layer_ready ⇒ 缺料时扫描不冻结（帧不变长），
//  代价是该位置重复一个像素（pix_pop 仍需 pix_avail）。
// ★★★ 2026-10-24：**正确的流控 = 缺料不冻结（重复像素）、快满才冻结（防溢出）** ★★★
//  【实验记录】
//    · 缺料冻结（原行为）⇒ 帧变长 ⇒ 掉帧（但不裂）
//    · 完全不冻结（刚才试的）⇒ 不掉帧（但扫描跑到纹理前面
//      ⇒ 像素 FIFO 被灌满 ⇒ pix_wfull 丢字 ⇒ 整行平移 ⇒ 看起来像撕裂）
//  【正确做法】两边都要管：
//    · FIFO 空 ⇒ **不冻结**，pix_pop 仍需 pix_avail 所以重复一个像素（不拖长帧）
//    · FIFO 快满（≥ 900/1024）⇒ **冻结**，防止写满丢字（避免像素流错位）
//  ★★ 2026-11-01【抖动根修】s2_hold 必须与全局流控**同一个信号** ★★
//  【病根】原来 s2_hold 只冻结本模块内部流水线（`if (pipe_ce && !s2_hold)`），
//    而 `pipe_ce` / 场景坐标 / frame_writer 的 take 仍然照走。
//    ⇒ 只要 s2_hold 命中一拍（缺字、帧首清残留 fix_pending），
//      **输出就比扫描落后一个像素**，而两者此后再也对不回去
//      ⇒ 该行内容整体平移 1 像素；每行命中的位置不同 ⇒ **逐行抖动/锯齿**。
//    这类"内部冻结、外部不冻"的窗口是整份代码里唯一能产生 1 像素错位的机制。
//  【修法】把 s2_hold_w 直接并进 layer_ready ⇒ 冻结是**全局**的：
//    扫描、frame_writer、合并级、本模块一起停，恢复后相位不变。
//  【代价】0 个 LUT（原来是 `~pop_want|pix_avail`，现在换成 `!s2_hold_w`，
//    宽度更小：s2_hold_w 已经含 pop_want && !pix_avail）。
//  【为什么不会死锁】`fix_pending` 的清除项 `fix_pending && pix_avail`
//    在 pix_pop 里**不受 pipe_ce 门控**（见上面的 pix_pop 定义），
//    所以 pipe_ce 被自己拉低时它照样能清掉，一拍后自动放行。
assign layer_ready = ~f_en | dead |
                     (warmed && !s2_hold_w &&
                      (no_underrun_fix ? (pix_count < 10'd900) : 1'b1));
//                    ★ 100M-33：`| pix_bypass` 已删除 —— 没数据就挡住整条扫描
// ★ build F：`dead` 直接把该层判为"就绪"（它已经不消费任何像素了），
//   这样整条场景图不会被一个放弃掉的层拖住 —— 局部失败不扩散。


//==============================================================================
//  ★★ build 9：跨帧粘滞的"dead 现场"（取代 F6 的 want/pop 计数）★★
//==============================================================================
//  F6 那对计数器已证明无用：请求侧按设计领先 LEAD 个扫描像素，
//  帧末那批预取字必然被 flush 丢掉 ⇒ want > pop 天然成立。已废弃。
//
//  现在记的是真正会"杀画面"的事：
//      dead_seen  = 跨帧粘滞（只在 rst 清）。一旦为 1，说明
//                   give_up 真的触发过 ⇒ 该层从那一刻起全透明
//                   ⇒ 底下场景透上来（就是"图片区里冒出不属于这张图的颜色"）
//      frz_cnt    = ★ build C：本帧"要弹但 FIFO 空"的次数（饱和 0..15）★
//                   它是"停等”的直接度量。板上现象"偏差随丢字变多”
//                   已被证实不成立（ovf_max=0），所以下一个候选就是停等次数。
//  为什么要跨帧：每帧清零就会在数码管上每帧翻转一次，肉眼抓不住（
//  build 8 的第 3 位就是这样"一直在变"）。
//==============================================================================
//==============================================================================
//  ★★★ 2026-10-27 P1-D1：纹理自校验 / 错字分类 / 帧级计数 —— 整块删除 ★★★
//==============================================================================
//  【为什么删】这一整套（build 2 / I / J / L / M）都建立在"纹理按源偏移编码成
//  地址签名"的假设上，靠 `exp_off`（显示侧本该读的偏移）与实际读回的字逐字比对。
//  `exp_off` 来自 `ds_off_d2 = ds_sy_d2 * SW16 + ds_sx_c`。
//
//  但 `chk_evt = pix_take && warmed && (PAT_CHK != 0)`，而 PAT_CHK 默认 0、
//  `App.v` / `img_layer_ctrl.v` 都没有覆盖它 ⇒ **整条通路恒为 0**。
//
//  【为什么必须显式删】它带了 `(* use_dsp="yes" *)`。TD 的流程是"先把乘法映射成
//  DSP，再做 DCE"，DSP 一旦例化就删不掉 ⇒ 两个 ps_gen_image 实例各白占 1 个 DSP
//  （实测 29/29 满占用里就有这 2 个）。删掉之后 DSP 才有余量。
//
//  【下游是否有人用】`layer_div_o` / `layer_diff_o` 在 img_layer_ctrl 里接到
//  `bneq_r` / `byte_r`，这两个线网**再无任何消费者**（纯调试读数）⇒ 恒 0 无影响。
//  `layer_neq_o`（dead_seen）是唯一还有意义的，保留。
//==============================================================================
reg dead_seen;    // 跨帧粘滞：被 give_up 放弃过（只 rst 清）
always @(posedge clk or posedge rst) begin
    if (rst)           dead_seen <= 1'b0;
    else if (give_up)  dead_seen <= 1'b1;
end

assign layer_diff_o = 8'h00;     // 诊断通路已删，恒 0
assign layer_div_o  = 1'b0;      // 诊断通路已删，恒 0
assign layer_neq_o  = dead_seen;

// 不再染色：像素原样输出
// ★ 100M-16：输出端加 dead/关层 透明门控（review 问题 11）
//   原来 pix_raw 不看当前 dead：give_up 置起后流水线里还压着 1~2 级旧状态，
//   会继续输出旧数据/空 FIFO 的陈旧值，与"该层全透明"的注释不符。
assign pix = (!f_en || dead) ? 32'h0000_0000 : pix_raw;

//==============================================================================
//  ★ 2026-11-01：像素轨迹探针（smp_bus / smp_win）**整体删除**
//==============================================================================
//  它是 2026-10-24 为了"串口回传边界上下文"临时加的：
//  · 3 组 49 位寄存器 × 2 级延迟（pix_sel_q/q2、frac_sel_q/q2、psel_low_q/q2）
//  · 一个 128 位打包 assign + 出框列计数器 + 采样窗口比较
//  顶层早在 2026-10-26 清理数码管时就把这两根线断开了（top:1221 的记录），
//  于是这些寄存器**只剩负载没有读者**，综合器删不掉（它们是跨帧保持的时序元件）。
//  今天整块删掉：端口保留、恒 0，省掉约 100 个触发器 + 一组 128 位打包逻辑。
assign smp_bus = 128'd0;
assign smp_win = 1'b0;

endmodule
