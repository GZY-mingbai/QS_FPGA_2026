assign req_mask = (ALIGN_ONLY != 0) ? 4'b0001 :
                  mask_all          ? 4'b1111  : use_mask;   // ★ 影子掩码（出框那拍）

always @(posedge clk or posedge rst) begin
    if (rst) begin
        cur_g <= 21'd0; cur_mask <= 4'd0; cur_vld <= 1'b0;
    end else if (idle_reset) begin
        cur_g <= 21'd0; cur_mask <= 4'd0; cur_vld <= 1'b0;
    end else if (flush_do) begin
        // ★★★ 2026-10-19 修：去掉 `rq_go_eff` ★★★
        //  原来要求"这一拍扫描能推进"才记账。可 `flush_do` 的含义是
        //  "旧组已推出去、当前这个像素属于新组" —— 当前像素是**已知的**
        //  （rq_g/rq_o 都在），这一拍能不能推进无关紧要。
        //  改成只判 `rq_in_box`；若扫描这拍不能推进，下一拍还在同一像素，
        //  会走下面的 `else if` 执行 `cur_mask |= (1<<rq_o)` ——
        //  **同一个位置 1 两次结果不变（幂等）**，不会重复计数。
        //  板上的证据：skip_cnt = 2407/帧，正好是这个分支在丢当前像素的位。
        //  ★ 100M-16：帧末 flush 之后【不再重新装填】（review 问题 2）——
        //    rq_scan_end=1 时扫描已停在最后一个像素，若还按当前像素重新攒组，
        //   下一拍 rq_scan_end 仍为 1 会再 flush 一次 ⇒ 同一个掩码位被推两次
        //   ⇒ 一个字回来两遍 ⇒ pop↔push 计数错位。所以扫停后直接清空。
        // ★ 2026-10-23：补上 `rq_in_range` —— 上一轮加越界检查时漏了这一处。
        //   它是"新组第一个像素"的入口：漏掉它，越界像素会被登记进掩码并发出请求
        //   ⇒ 多回一个字，而显示侧 ds_new 已过滤、不会弹它 ⇒ FIFO 多积一个字
        //   ⇒ 整条流错位 ⇒ 竖条（是否触发取决于 px 的取整 ⇒ "这一帧有下一帧没"）。
        if (rq_in_box && !rq_scan_end) begin
            cur_g    <= rq_g;
            cur_mask <= (4'b0001 << rq_o);
            cur_vld  <= 1'b1;
        end else begin
            cur_vld  <= 1'b0;                // 出框了 / 越界了 / 帧末：推完就空着
        end
    end else if (rq_go_eff && rq_in_box) begin
        if (!cur_vld) begin
            cur_g    <= rq_g;
            cur_mask <= (4'b0001 << rq_o);
            cur_vld  <= 1'b1;
        end else begin
            cur_mask <= cur_mask | (4'b0001 << rq_o);   // 同组：把这一位并进去
        end
    end
end

