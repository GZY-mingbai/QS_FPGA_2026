//
//  【为什么不会误触发】正常通路：50MHz 进 FIFO 2 拍 + 125MHz 侧往返
//  约 15 拍 + 50MHz 同步 2 拍 ≈ 十几拍就回来了；RETRY_AT 取 256 拍
