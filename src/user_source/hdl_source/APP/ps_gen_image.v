// ★ 弹空抑制（2026-10-17 虚线根修，详见文件头/端口注释）★
// ★★ 2026-10-24：改用**真实空标志**（与 HD 层同源）★★
//  pix_count 是跨时钟同步的滞后值（滞后 ~2 拍）：
//    ≈ 两拍内刚到货的字会被误判为“没货”
