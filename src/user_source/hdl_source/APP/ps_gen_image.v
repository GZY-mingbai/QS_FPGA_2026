//      → app_scan_gen 的坐标冻结 → ps_valid = 0
//      → frame_writer 永远收不满 307200 → display_valid 永远 0
//      → 顶层 vout_data = display_valid ? … : 24'd0 → **全屏黑**
//
//  【复现】tb_app_realtex 里给纹理源加"每 1000 个像素丢 1 个"，
//  跑到 rq=41575/ds=41563 就完全冻结（差值 = LEAD=12，请求 FIFO 已空）。
