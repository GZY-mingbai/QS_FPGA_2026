//==============================================================================
//  【问题】纹理读是"一个请求换一个像素"的**严格配对**，而且请求一旦被
//  仲裁器 ack，请求 FIFO 就前进、**绝不会再发第二次**。于是只要掉一个像素
//  （同拍读写被丢 / 跨 owner 串了 / 像素 FIFO 满被丢 / 真 SDRAM 行为差异），
//  显示侧就会**永久**等一个不存在的像素：
