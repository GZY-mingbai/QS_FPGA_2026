//  【阈值为什么取 2047 / 16384】★ 这一步很关键，取小了会误触发 ★
//  正常往返只要十几拍，但**最坏**要等“当前 owner 这一批 + DRAIN”：
//     显示读一轮突发 = BURST_SIZE 256 拍 @125MHz，折算到 50MHz 域约 640 拍，
//     再加跨时钟与往返 → 约 750 拍。所以重发阈值必须明显大于它：取 2047 拍(≈41µs)。
//  【实测踩过的坑】最早取 255 拍，仲裁稍微等久一点就**误重发**，
