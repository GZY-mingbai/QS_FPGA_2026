//==============================================================================
//  ★★★ 2026-10-24 根因修复：s2 级"要字但没字"必须冻结 ★★★
//==============================================================================
//  【实测证据】条纹出现的那一帧：push−pop = +1（数码管左3），
//    同时 dbg_evt = 7 = 空弹 + pop_stall + give_up（左6）。
//  【机制】`pop_stall` 只阻止**新像素进入**（adv_eff=0），但流水线里已经在飞的
//    s1/s2 两个像素仍会随 `pipe_ce` 前进到弹出级。此时 FIFO 空 ⇒ pix_pop=0
//    ⇒ 那一拍的 s2_is_new 被消耗掉、字却没进来 ⇒ 该字永远留在 FIFO
//    ⇒ push−pop = +1 ⇒ 之后每次 pop 都晚一个字 ⇒ 行末取到下一行字 0
//    ⇒ 图像左边那一小段出现在右边缘。
