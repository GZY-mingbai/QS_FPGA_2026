//  ★★★ 2026-10-16 上板修复：重发机制【彻底停用】★★★
//==============================================================================
//  【为什么停用 —— 它是"图片动态花屏"的直接原因】
//  本层是靠"**一次 pop ↔ 一次 ds_new 事件**"的一一对应来对齐两条扫描的：
//  第 k 个"源像素变化"事件必须消费第 k 个推入 FIFO 的像素。这个计数只要被打乱
//  一次，**从那个像素起整幅图永久错位**（直到帧末 flush 才复位）；而每帧错位的
//  起始点还不一样 → 画面上就是**逐帧闪烁的花屏**（上板实测现象）。
//
//  重发正好会打乱这个计数 —— 它**分不清"丢了"和"只是慢"**：
//      慢 → 原请求其实还在路上，重发等于多塞一个像素 → 计数 +1 → 错位；
//      丢 → 重发能补回来。但"丢"这条路**已经不存在了**：
//           真正的丢包根因是 sdr_rd_arb 的"固定 14 拍排空"（数据被错投给显示口，
//           纹理像素凭空消失），那边已改成 `outs==0` 精确排空，
//           从机制上保证了归属正确（见 sdr_rd_arb.v 的证明）。所以这里不需要重发。
//
//  【那"真的丢了"怎么办】纯背压：need_pix 时把场景按在原地等（门控已实现），
//  这是**唯一不会错位**的处理方式。最坏情况由 GIVEUP_AT 兜底 ——
//  代价是这一帧图片上有一段重复，但绝不会永久卡死，更不会持续错位。
//
//  【这个机制历史上的两次反复，记录以免再犯】
//      阈值 255  → 把"慢"误判成"丢"，一致率 99% → 30%
//      阈值 2047 → 仿真里看着好了；但仿真纹理源太快，need_pix 根本不长，
//                  真硬件上"等一批"轻松超过 2047 拍 → 每帧大量重发 → 花屏
//  结论：**只要还需要靠"猜"来区分丢和慢，这个机制就不该存在。**
//==============================================================================
wire retry_req = 1'b0;                                   // ← 已停用（理由见上）

// ★★ 100M-26：自适应超时阈值 ★★
//   【为什么】本帧第一次超时给足 GIVEUP_AT，让"偶发慢"有机会等回来；
//   一旦本帧已经超时过（bp_cnt≠0），说明这一帧供养是"成片断供"，
//   后续每个像素再等 328µs 只会把帧期顶穿（64 次 × 328µs = 21ms ≈ 30fps）。
//   所以后续改用短阈值 41µs：仍然给数据一点回来的机会，但不再拖帧。
//   **只改等待时长，不改"一个 ds_new ↔ 一个字"的对应关系**（重发仍停用）。
reg  [7:0] bp_cnt;                                       // 本帧"像素超时"次数（饱和）
localparam [23:0] GIVEUP_FAST = 24'd2048;                // @50MHz = 41µs
wire [23:0] giveup_th = (bp_cnt != 8'd0) ? GIVEUP_FAST : GIVEUP_AT;
//==============================================================================
//  ★★★ 2026-10-24 根因修复：**帧首（warmed=0）不允许放弃** ★★★
//==============================================================================
//  【上板实测把方向定死了】
//     左6 = 0  ⇒ push_cnt 正好等于"应有字数" ⇒ **请求侧完全正确**
//     左3 = +1 ⇒ push − pop = +1          ⇒ **显示侧少弹了一个字**
//  ⇒ 不是"多写"，是"少弹"。每帧少弹 1 个 ⇒ FIFO 积压 1 个 ⇒ 之后每个 pop 晚一位
//    ⇒ 整幅左移 4px（1 字 = 2 个 RGB565 = 4 个屏幕列 = 320×240 上的 2px），
//      行末补上"下一个字" ⇒ 看起来像"左边那 4px 跑到框最右侧"。
//  【为什么必须是帧首】帧内中间漏弹只会造成"从那一行起错位"；而你看到的是**整幅**
//    左移 ⇒ 错位在第一个像素就存在 ⇒ 漏弹发生在**本帧第一个需要字的时刻**。
//  【为什么帧首会漏】帧首 warmed=0 ⇒ layer_ready 直接报 1（不阻塞）⇒ 扫描开跑，
//    而像素 FIFO 还空（预取刚发出）⇒ s2_hold 冻结等字 —— 这一步是对的。
//    但如果等超过 giveup_th（4096 拍 = 82µs）⇒ give_up ⇒ `s2_hold` 的 `!give_up`
//    让冻结失效 ⇒ 流水线照常推进、字却没取走 ⇒ **这个字的需求永久消失**。
//    平时帧首预取只要几十~几百拍，远小于 82µs，所以只在拥塞帧偶发。
//  【修法】帧首阶段（warmed=0）不给放弃，耐心等预取；另设 4ms 硬超时兜底，
//    防止纹理彻底坏（没插卡）时死等。
//    代价：极少数拥塞帧会多等 ≤4ms（可能掉一帧），但**不再整幅错位**。
//==============================================================================
//==============================================================================
//  ★ 2026-10-27：三处「先使用后声明」提前声明（编译兼容性修复，零语义变化）
//==============================================================================
//  【问题】`warmed`(452 行用/730 声明)、`popw_cnt`(704/957)、`flush_do`(1011/1147)
//    都是先被引用、后才声明。TD 只报 HDL-5373 **WARNING** 并照常综合，
//    但 iverilog 直接报 `Unable to bind wire/reg/memory` 硬失败
//    ⇒ `tb_img_layer` / `tb_viewer` 这些台**早就跑不起来了**（不是本次改动引入）。
//  【做法】只把**声明**搬到这里，赋值语句原地不动 ⇒ 电路完全不变。
//    `flush_do` 原来是 `wire x = expr;`，拆成「提前声明 + 原地 assign」，语义相同。
//------------------------------------------------------------------------------
reg         warmed;                 // 预热完成标志（见第 5 节，赋值在下方原处）
reg  [19:0] popw_cnt;               // 本帧已弹出字数（赋值在下方原处；只剩诊断读者）
reg         popped_any;             // ★ [PGI-SLIM] = (popw_cnt != 0)，ult_giveup 只要这一位
wire        flush_do;               // = flush_now && req_ready（assign 在下方原处）

localparam [23:0] GIVEUP_BOOT = 24'd200000;   // 帧首硬超时 4ms @50MHz（防死锁兜底）
wire give_up   = need_pix && ((warmed && (pix_wait >= giveup_th)) ||
                              (!warmed && (pix_wait >= GIVEUP_BOOT)));

//==============================================================================
//  ★★ 2026-10-18 build F：give_up 不许再"带空 FIFO 继续推进" ★★
//==============================================================================
//  【原来的行为（这段是整条链上最危险的一处）】
//      give_up 时 layer_ready 照旧报 1、pop_stall 因为 `!give_up` 而失效
//      ⇒ adv 继续、pix_pop 在**空 FIFO** 上弹出
//      ⇒ 弹出来的是存储体里的陈旧内容（垃圾像素）
//      ⇒ 而且"一个 ds_new 事件换一个字"的计数照常消费 ⇒ **从那一刻起整帧永久错位**
//      也就是说：原来是用"永久错位"去换"不黑屏"。这恰恰是最不能接受的交换。
//  板上证据（build E 数码管第 1 位一直在变）就是这个：give_up 一旦成立，
//  弹空粘滞位就被置起来，帧末被 flush 清掉，下一帧再置 ⇒ 数码管就是这个闪烁形状。
//  它同时说明**纹理通路出现过 ≥0.8ms 的长时间断供**。
//
//  【100M-25 现在的行为 —— 两级】
//     ① 单个像素超时（pix_wait ≥ GIVEUP_AT）：
//          pix_bypass=1 → layer_ready 报 1、扫描照常走、输出保持 cur_pix、
//          **不弹 FIFO**、这个像素被走过后自动清除。
//          ⇒ 代价只有"1 个像素重复"，不再有整层变透明（白齿）、也不再有 4ms 卡顿。
//     ② 累计超时 ≥ DEAD_AFTER（默认 64 个像素/帧）：
//          layer_dead=1 → 该层本帧全透明（和原来一样），用于"卡没插/纹理没装"这类
//          系统性故障，保证不会永远卡在等待里。
//      下一帧自动恢复。
//  ⇒ 最坏结果：偶发断供 = 几个像素重复；系统性故障 = 这一帧少一张图。
//     **绝不会**花屏、绝不会错位、绝不会连累整屏。
//==============================================================================
reg layer_dead;
wire dead = layer_dead;

assign layer_dead_o = layer_dead;

// 累计多少个像素超时才认定"这一层真拿不到数据"（仅用于诊断读数）
localparam [7:0] DEAD_AFTER = 8'd128;

//==============================================================================
//  ★★ build 100M-33：拆掉【所有】脱钩旁路 —— 本步骤的核心 ★★
//==============================================================================
//  【为什么必须拆】工程自己在上板记录里已经定过案（app_demo_scene.v:316-338）：
//      只要"扫描往前走、图层没走"（layer_ready 被外部强行拉高），
//      从那一刻起图像就**永久错位** ⇒ 内容被画到错位的整行上
//      ⇒ 画面上就是**整行横带**（照片里那些横线）。
//  能让两者脱钩的只剩两条：
//      ① pix_bypass（100M-25 引入：超时后放行扫描、不弹像素）← 本版删除
//      ② layer_dead → layer_ready 恒 1（超时后整层透明、扫描继续）← 本版断开
//  【现在的语义】没数据就**等**，等到有为止。宁可帧变慢，也绝不错位。
//  代价：若某层纹理真的缺失，画面会停住（可恢复），而不是继续画错的（不可恢复）。
//  诊断：`layer_dead_o` 仍保留端口，但恒 0；超时次数看 bp_cnt 的读数。
//==============================================================================
always @(posedge clk or posedge rst) begin
    if (rst)              layer_dead <= 1'b0;
    else if (idle_reset)  layer_dead <= 1'b0;
    // ★ 100M-33：**不再置位**。留这条赋值是为了保留端口与读数，逻辑上恒 0。
    //   （若将来需要"真·整层放弃"，必须同时让 frame_writer 放弃本帧，
    //     而不是让扫描带着停滞的图层继续往前画。）
    // else if (give_up && (bp_cnt >= DEAD_AFTER)) layer_dead <= 1'b1;
end

always @(posedge clk or posedge rst) begin
    if (rst)                                 bp_cnt <= 8'd0;
    else if (idle_reset)                     bp_cnt <= 8'd0;
    else if (give_up && (bp_cnt != 8'hFF))
                                             bp_cnt <= bp_cnt + 8'd1;   // 只做诊断计数
end

