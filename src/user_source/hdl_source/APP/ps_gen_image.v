// ★★ 为什么这里【不能】再带上 `!rq_can_adv`（第一稿踩过）★★
//  带上它以后，rq 被 LEAD 卡住的那一拍会 flush：掩码推出去、cur_vld 清零，
//  **但 rq 并没有前进**（rq_go 需要 rq_can_adv）。下一拍 rq_can_adv 恢复，
//  又从**同一个像素**开始攒 ⇒ 那一位被推了两次 ⇒ 一个像素回来两个字
//  ⇒ 像素 FIFO 里的数据比 `rq_idx - ds_idx` 多 ⇒ ds 反超 rq
//  ⇒ `rq_idx - ds_idx` 的减法回绕成天文数字 ⇒ rq 永久卡死、该层饿死。
