// 只有"要先推出去"的时候才需要等请求队列有空位
// ★★★ 2026-10-24 根因修复：请求扫描**始终**要求 req_ready ★★★
//  【病根】原来只在 flush 时看 req_ready：
//      平时扫描不管队列满没满一路推进 ⇒ 请求队列（128 深）被填满
