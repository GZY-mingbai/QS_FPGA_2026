//==============================================================================
//  ★★★ 2026-10-24：出框 flush 用「影子组号/掩码」，不吃 flush 时序 ★★★
//==============================================================================
//  【病根】`cur_g / cur_mask` 的更新挂在 `flush_do` 上，而
//      flush_do = flush_now && req_ready
//    `req_ready = ~req_wfull` —— 请求队列一满，flush 就被推迟。
//    推迟期间扫描位置可能已经跨过框边界（`rq_g` 变成下一行的组），
//    此时 `cur_g` 仍是"还没推出去的那一组"（**落后**于扫描），
//    等 req_ready 恢复后才补推 —— 如果补推时 `rq_in_box` 已为 0，
//    用的是"上一次成功 flush 时的组"，可能与"最后一个框内像素真正的组"不一致
//    ⇒ 请求到**错误的组** ⇒ 返回的字内容不对 ⇒ 屏幕上那 4 个屏幕列
//      （= 一个字 = 320×240 上的 2px）显示"靠左的某一小段"。
//    只在横向：fx0 每行都会出框（触发 box_exit 路径）；fx1 整行都在框内，从不走这条。
//  【修法】另起一组影子寄存器，**按扫描顺序**累积（组变就重装、同组就 OR），
//    完全不看 flush_do / req_ready。出框那拍用它 ⇒ 一定是"最后一个框内像素"的组。
//    正常（未延迟）时 sb_* 与 cur_* 完全相等 ⇒ 对现有行为零影响。
//==============================================================================
