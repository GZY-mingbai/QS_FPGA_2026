// ★ [PGI-SLIM] committed 直接做成加减计数器（≡ push_w − pop_w mod 2^16，
//   原来 push_w/pop_w 只是 push_cnt/popw_cnt 低 16 位的重复副本 + 一个 16 位减法）
// ★ 2026-11-03 [AREA] 16 → 11 位：真值范围 ⊂ [−1024, 1023]（上界由 ≤496 闸门 + 在飞的
//   少量提交决定；下界 = 帧首 fix_pending 弹掉的残留字，≤ FIFO 深 1024）。在这个范围里
//   "≤ 496" 的判定对 16 位与 11 位补码完全相同（负数都表现为 ≥1024 的大数 ⇒ 不放行）。
reg  [10:0] committed;
// ★★ 100M-41：LEAD 128→512、深度 256→1024、上限 200→900 ★★
//   【实测依据】把 IMG_GATE 置 0（图层不再参与流控 ⇒ **不会有停顿**）后：
//        框外白条**消失**，框内图花掉（预期）。
//   ⇒ 白条 = **图层停顿**的产物。而白条是"固定 x、全高" ⇒ 说明每行都在
//     **同一个 x 上把 FIFO 取空**（预取只有 128 像素，一行要 240 个）。
//   ⇒ 修法：把预取加深到半行以上，让它在那一行不再断货。
//   不变式仍满足：深度 1024 ≥ 2 × LEAD 512。
//  ★ 2026-10-24：500 → **384**。
//    FIFO 深 512（AFIFO_AW=9），原闸门允许 committed 到 496 ⇒ 余量仅 16 个字。
//    一旦"在飞的字"批量落地，像素 FIFO 可能瞬间写满 ⇒ img_afifo 静默拒绝写入
//    ⇒ **物理少一个字** ⇒ 画面整体左移 4px（用户定性：少一个字 = 左移）。
//    384 留 128 字余量。注意：更紧的约束其实是 `rq_ok_ahead = ahead < LEAD(384 像素)`
//    ≈ 96 字，所以这一项平时摸不到，改小不会掉帧。
//  ★ 2026-10-24：384 → **500**（恢复）。
//    收紧到 384 的目的是"给 FIFO 留余量"，但更紧的约束其实是
//    `rq_ok_ahead = ahead < LEAD(384 像素) ≈ 96 字`，它根本摸不到 ⇒ 收紧只会拖慢请求
//    ⇒ 帧耗时变长 ⇒ 双缓冲来不及换页 ⇒ **撕裂**。真正要看的溢出证据是 ovf_w（已上数码管）。
localparam [15:0] COMMIT_MAX = 16'd500;

always @(posedge clk or posedge rst) begin
    if (rst)             committed <= 11'd0;
    else if (idle_reset) committed <= 11'd0;
    else if (req_push || pix_pop)
        committed <= committed + (req_push ? {8'd0, pc_mask} : 11'd0) - (pix_pop ? 11'd1 : 11'd0);
end

// ★ [PGI-SLIM] max(rq−ds,0) < LEAD  ⟺  rq < ds + LEAD（ds+LEAD ≤ NPX+LEAD < 2^20，不溢出）
//   ds_idx 直接以"ds_idx + LEAD"的形式存（ds_lead），省掉一个 20 位比较 + 一个 20 位减法
wire rq_ok_ahead = (rq_idx < ds_lead);
// ★ 100M-16：预留下一次提交的整组空间（review 问题 12）
//   committed 单拍最多 +4（一整个组的掩码位数）。用 "< COMMIT_MAX" 会在 199
//   时放进来到 203；改成 ≤ COMMIT_MAX-4，"像素 FIFO 内容 ≤ committed ≤ 200 < 256"
//   这条证明才严格成立。
// ★★ 100M-28：撤掉 `pix_count <= 224` 这一项 ★★
//   【为什么撤】`phy_1/final_timing.rpt`（20:30 那次布局布线）显示：
//       最差建立路径 slack = +0.122ns
//       起点 u_img0/u_gen/rq_y_reg[1] → 终点 u_img0/u_gen/rq_y_reg[5].ce
//       数据路径 19.598ns / 预算 20.000ns（cell 12.062ns + net 7.536ns）
//   这条路的终点正是"请求扫描要不要前进"的 CE —— `rq_ok_space` 就在上面。
//   而它原本只差 0.12ns 的余量，多一个 9 位比较器就把余量吃光了（还可能是
//   2 个 hold 违例之外的新风险）。
//   【代价】回到只靠 committed 节流。反过来也说明：这条 16 位比较链本身
//   就该被流水化（见文件头 PLAN 的"map_src 乘法 + 节流比较应在同一拍完成"
//   这一隐患），但现在先不做结构改动，只把余量还回去。
//   ★ 另外：真正修丢字要在**写入口**做，不能靠掐请求侧（掐请求 = 掐预热 = 黑屏）。
wire rq_ok_space = (committed <= (COMMIT_MAX[10:0] - 11'd4));

// ★ 100M-16：请求扫描用【屏幕坐标终点】终止（review 问题 2）
//   原来用 rq_idx < NPX 当终点，但 rq_idx 数的是"源像素事件"：小图层（如
//   240×180 框）总数远小于 NPX ⇒ 扫描永远不靠它停，只能等帧结束；末组还
//   要靠 rq_y 回绕出框才 flush。现在显式判"最后一个屏幕像素"，扫到即停；
//   末组由 rq_scan_end 触发 flush（flush_do 与 rq_can_adv 无关，扫停之后
//   攒好的组仍能进请求 FIFO，保证最后一个扫描位置的掩码确实被提交）。
wire rq_at_last = (rq_x == IMG_W - 1) && (rq_y == 16'd0);
reg  rq_scan_end;

//  ★ 2026-10-23：上限不能写死成 NPX(640×480=307200)。
//  【上板踩到的】fx3 的 A 层画框长到 800×600=480000 个位置，而 rq_idx 数的是
//  "本帧框内源像素事件"，撞到 NPX 就 rq_can_adv=0 ⇒ 请求侧停走 ⇒ 显示侧等一个
//  永远不来的像素 ⇒ layer_ready=0 ⇒ 帧收不满 ⇒ 没有 tick ⇒ 状态机卡死在 S_TRANS。
//  真正的终点判据是 rq_scan_end（屏幕扫到最后一个像素），rq_idx 只是防回绕的
//  保险丝，所以放宽到 2^20 就够：任何"框 ≤ 1M 个位置"的几何都不会再被它误停。
wire rq_can_adv  = rq_ok_ahead && rq_ok_space && !rq_scan_end;   // ★ [AREA] 防回绕比较恒真，已删

