//==============================================================================
//  ps_to_rgb24.v —— 输出级：叠加到纯黑图层 + 舍弃 alpha
//==============================================================================
//
//  【它是整条场景图的最后一站】
//
//      场景图像素 {A,R,G,B} ──► [ ps_to_rgb24 ] ──► 24bit {R,G,B} ──► frame_writer
//
//  【做了什么】
//
//      alpha ≠ 0  →  取它的 RGB
//      alpha = 0  →  落在"纯黑图层"上 → 输出 24'h000000
//
//  等价于"用直接叠加把场景叠到一块纯黑底板上，然后丢掉 alpha 通道"。
//  因为场景最底层就是白底矩形（不透明），实际上只有被 offset/scale 挪到屏外、
//  或者场景图本身留空的像素才会露出黑底。
//
//  【为什么不用例化 ps_merge_overlay】
//  功能上完全等价（over 黑色 + 取低 24 位），但那样要多打一拍。
//  这里直接写成组合逻辑，**延迟 0 拍**，并且省掉一级寄存器。
//  （这也让"总延迟 = 1 + 合并级数"这个账更好算。）
//
//==============================================================================

module ps_to_rgb24 (
    input  wire [31:0] pix,             // {A,R,G,B}
    output wire [23:0] rgb24            // {R,G,B}，给 frame_writer.ps_data
);

assign rgb24 = (pix[31:24] != 8'd0) ? pix[23:0] : 24'h000000;

endmodule
