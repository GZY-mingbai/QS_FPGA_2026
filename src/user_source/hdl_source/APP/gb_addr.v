//==============================================================================
//  gb_addr.v —— 字符码 → Flash 字库地址（2 级流水）
//==============================================================================
//
//      字符码 code[15:0] ──► [ gb_addr ] ──► 24 位 Flash 偏移
//
//  【字库是谁】
//  Font/font_gb2312.bin，烧在 W25Q64 的 0x000000，格式见 Font/字库格式说明.md。
//  全部字形统一 16×16 / 32 字节，所以"取一个字"永远是"读 32 字节"。
//
//  【两套寻址】
//
//  ┌────────────┬──────────────────────────────────────────────────────────┐
//  │ ASCII      │ code 高字节 = 0 且低字节 < 0x80                          │
//  │            │ 偏移 = code × 32                                         │
//  │            │ 0x00~0x1F、0x20、0x7F 在字库里本来就是全 0（空白），        │
//  │            │ 所以这里**不需要额外判断可打印字符**，直接算就行。          │
//  ├────────────┼──────────────────────────────────────────────────────────┤
//  │ GB2312     │ code = {qb, wb}（高字节 qb 是区码，低字节 wb 是位码）      │
//  │            │ row  = (qb ≤ 0xA9) ? qb-0xA1 : qb-0xB0+9                 │
//  │            │ 偏移 = 0x1000 + (row × 94 + (wb-0xA1)) × 32              │
//  └────────────┴──────────────────────────────────────────────────────────┘
//
//  【★ row 为什么要那么算（关键）★】
//  GB2312 有 94 个区，但字库只存 81 个**有内容的**区（见说明文档 §3.1）：
//
//      区 1–9   (qb 0xA1–0xA9)  → row  0–8    符号区
//      区 10–15 (qb 0xAA–0xAF)  → 不存储      ← 空
//      区 16–87 (qb 0xB0–0xF7)  → row  9–80   一/二级汉字
//      区 88–94 (qb 0xF8–0xFE)  → 不存储      ← 空
//
//  所以 row 是"重新编号后的行号"，把 6 个空区跳过去了。跳掉空区省下
//  39,104 字节（13.8%），代价只是上面那一个比较器 —— 非常划算。
//
//  【★ row × 94 是常数乘法，不耗 DSP ★】
//  综合器会自动拆成移位相加（94 = 64 + 16 + 8 + 4 + 2），一个 DSP 都不用。
//
//  【★ 空区 / 非法码怎么办 ★】
//  qb 落在 0xAA–0xAF 或 0xF8–0xFE（字库不存储），或者 wb 超出 0xA1–0xFE，
//  或者 ASCII 路径拿到 0x80~0xFF，这些都会算出**越界地址**、读到别人的字形 ——
//  必须兜底。这里统一返回 NULL_ADDR = 0x000000，也就是 ASCII 块里 code 0x00
//  那个槽，它在字库里是 32 个 0x00 → 渲染出来是"什么都没有"，正是我们要的。
//
//  【★ 延迟 = 2 拍（流水线，时序修复）★】
//  旧版是纯组合：比较器 + 两次减法 + ×94 乘法 + ×32 + 加 0x1000 全串在
//  一根组合锥上，实测 ~11.5ns > 10ns 周期（sd_card_clk 100MHz），是
//  final_timing.rpt 里 cur_code → rd_addr_r 违规簇的源头。
//  现在拆成两拍：
//      第 1 拍（stage1）：比较/减法 → 寄存 {row_r, wb_r, wb5_r, is_ascii_r, gb_ok_r}
//      第 2 拍（stage2）：×94、×32、加 0x1000、三分支 mux → 寄存 addr
//  每拍锥都很浅。调用方（osd_font_cache）里 cur_code 在 S_LDCOL 设定，
//  到 S_FREQ 发 Flash 请求中间还隔 ≥5 拍，多出来的 2 拍完全被吸收。
//  ※ 注意：本模块输出相对输入**晚 2 拍**，别当纯组合用。
//
//==============================================================================

module gb_addr #(
    parameter [23:0] NULL_ADDR = 24'h000000   // 非法码 / 空区 → 这个地址（内容是全 0）
)(
    input  wire        clk,             // 采样时钟（与调用方 FSM 同域）
    input  wire [15:0] code,            // 字符码：高字节 0 = ASCII，否则 {qb, wb} = GB2312
    output reg  [23:0] addr             // 该字形在 Flash 里的 24 位起始偏移（晚 code 2 拍）
);

//------------------------------------------------------------------------------
//  第 1 级：拆字节 + 区/位码合法性判断（浅组合）→ 寄存
//------------------------------------------------------------------------------
wire [7:0] qb = code[15:8];         // 区码（GB2312）
wire [7:0] wb = code[7:0];          // 位码（GB2312），或 ASCII 字符本身

//  符号区 0xA1~0xA9 → row 0~8 ；汉字区 0xB0~0xF7 → row 9~80 ；其余不存储。
wire        gb_sym  = (qb >= 8'hA1) && (qb <= 8'hA9);   // 符号区（9 个区）
wire        gb_han  = (qb >= 8'hB0) && (qb <= 8'hF7);   // 汉字区（72 个区）

wire [15:0] row     = gb_sym ? ({8'd0, qb} - 16'h00A1)
                             : ({8'd0, qb} - 16'h00B0 + 16'd9);

// 位码合法性：0xA1 ~ 0xFE
wire        wb_ok   = (wb >= 8'hA1) && (wb <= 8'hFE);

// 该码是不是"字库里真的有"的 GB2312 字符（区码有内容 且 位码在 0xA1~0xFE）
wire        gb_ok   = (gb_sym | gb_han) && wb_ok;

// ASCII：高字节 0 且低字节 < 0x80
wire        is_ascii = (qb == 8'h00) && (wb < 8'h80);

reg  [6:0]  row_r;        // 重编号后的区号 0~80
reg  [7:0]  wb_r;         // 位码 / ASCII 字符本身
reg  [7:0]  wb5_r;        // wb - 0xA1（位码内偏移 0~93）
reg         is_ascii_r;
reg         gb_ok_r;

always @(posedge clk) begin
    row_r      <= row[6:0];
    wb_r       <= wb;
    wb5_r      <= wb - 8'hA1;
    is_ascii_r <= is_ascii;
    gb_ok_r    <= gb_ok;
end

//------------------------------------------------------------------------------
//  第 2 级：乘加寻址（row_r×94 常数乘 = 移位相加）+ 三分支 → 寄存输出
//------------------------------------------------------------------------------
//  GB2312：cell = row×94 + (wb-0xA1)，0~7613，13 bit 够放；
//          偏移 = 0x1000 + cell×32，≤ 0x3C7A0 = 字库末字形，24 bit 内。
//  ASCII ：偏移 = wb×32，≤ 0x7F×32 = 0xFE0。
//------------------------------------------------------------------------------
// ★ 2026-10-30：`row_r * 7'd94` 改成显式移位 —— 之前注释写着"= 移位相加"，
//   但源码里留着 `*`，TD 就老实拉了一个 DSP（本模块唯一乘法，phy 实测 dsp=1）。
//   【为什么要腾】音频 FFT 的复数乘必须落 DSP；LUT 乘法器要 ~200 LUT，
//     这里换掉只多 28 LUT ⇒ 净赚 170+。
//   【为什么拆成 96−2，而不是 128−32−2】两者数学等价，但前者只要 2 个加法器
//     （(row<<6)+(row<<5)−(row<<1)），后者要 3 个。
//   【为什么是逐位等价】94 = 96 − 2；所有中间量都用 **14 位**算（row ≤ 127 时
//     row×96 ≤ 12192，14 位装得下），最后再截到 13 位。原式是在 13 位上下文里
//     算完再截断 —— 模运算对加减法可分配，所以两者对**任意** row 值逐位相同，
//     非法区码（row > 80）也一样。
//------------------------------------------------------------------------------
wire [13:0] row_x96 = ({7'd0, row_r} << 6) + ({7'd0, row_r} << 5);   // row×96
wire [13:0] row_x94 = row_x96 - ({7'd0, row_r} << 1);                 // row×94（row≤80 时 ≤7520）
wire [13:0] cell14  = row_x94 + {7'd0, wb5_r[6:0]};                   // 再 + 位码内偏移
wire [12:0] gb_cell = cell14[12:0];                                   // 截到 13 位（与原式一致）

always @(posedge clk) begin
    if (is_ascii_r)
        addr <= {11'd0, wb_r, 5'd0};                    // wb_r × 32
    else if (gb_ok_r)
        addr <= 24'h001000 + {5'd0, gb_cell, 5'd0};     // 0x1000 + cell×32
    else
        addr <= NULL_ADDR;         // 空区 / 非法码 → 全 0 字形（渲染成空白）
end

endmodule
