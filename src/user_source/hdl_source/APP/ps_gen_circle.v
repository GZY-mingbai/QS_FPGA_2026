//==============================================================================
//  ps_gen_circle.v —— 像素源生成器：圆形
//==============================================================================
//
//      扫描坐标 (x,y) ──► [ ps_gen_circle ] ──► pix {A,R,G,B}
//                                ▲
//                      cfg {CX,CY,R2} + color
//
//  【判定公式】
//
//      dx = x - CX,  dy = y - CY
//      在圆内  ⟺  dx² + dy² ≤ R²
//
//  用平方比较而不是开方：开方又慢又贵；平方比较只要两个乘法器 + 加法 + 比较，
//  而且两边都是整数，**判定是完全精确的**。
//
//  【★ 为什么 cfg 里给的是 R² 而不是 R ★】
//  判定需要的就是 R²。如果给 R，模块里还得算一次 R×R（多一个乘法器）；
//  直接给 R² 就**省掉一个乘法器**。R² 在 app_scene_cfg.v 里由 `R*R` 自动算好，
//  你只需要填半径。想动画半径的话，在动画逻辑里维护 R²（半径变了就平方一次）。
//
//  【★ 关于乘法器和 DSP ★】
//  dx*dx、dy*dy 两个乘法器会映射到 DSP 硬核。DSP 是**组合器件**，本身不带延迟；
//  这里把结果打了一拍，所以时序很宽松。
//
//  【cfg 总线格式】见 app_scene_cfg.v 顶部：
//      cfg   [47:0] = { CX[15:0], CY[15:0], R2[15:0] }
//      color [31:0] = { A[7:0],   R[7:0],  G[7:0],  B[7:0]  }
//
//  【延迟 = 1 拍】，圆外输出透明。
//
//==============================================================================

module ps_gen_circle #(
    parameter integer IMG_W = 640,      // 屏幕宽
    parameter integer IMG_H = 480       // 屏幕高
)(
    input  wire        clk,
    input  wire        rst,
    input  wire [15:0] x,
    input  wire [15:0] y,
    input  wire        valid,
    input  wire [47:0] cfg,             // {CX, CY, R2}
    input  wire [31:0] color,           // {A, R, G, B}
    output reg  [31:0] pix,
    output reg         out_valid
);

//------------------------------------------------------------------------------
//  拆总线
//------------------------------------------------------------------------------
wire [15:0] CX = cfg[47:32];
wire [15:0] CY = cfg[31:16];
wire [15:0] R2 = cfg[15:0];

//------------------------------------------------------------------------------
//  判定（纯组合）
//------------------------------------------------------------------------------
// 【为什么用有符号】dx = x - CX 可能为负。用无符号减法会回绕成大数，
// 平方后就是天文数字，判定必然出错。所以扩成 17 位有符号（够表示 -640~639）。
//------------------------------------------------------------------------------
wire in_bounds = (x < IMG_W) && (y < IMG_H);

wire signed [16:0] dx = $signed({1'b0, x}) - $signed({1'b0, CX});
wire signed [16:0] dy = $signed({1'b0, y}) - $signed({1'b0, CY});

// 17 位 × 17 位 = 34 位有符号
wire signed [33:0] d2  = dx * dx + dy * dy;
wire signed [33:0] R2S = {18'd0, R2};       // 无符号扩展成 34 位正数

wire inside = in_bounds && (d2 <= R2S);

//------------------------------------------------------------------------------
//  输出打一拍
//------------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) begin
        pix       <= 32'h0000_0000;
        out_valid <= 1'b0;
    end else begin
        pix       <= inside ? color : 32'h0000_0000;
        out_valid <= valid;
    end
end

endmodule
