//==============================================================================
//  ps_scale.v —— 像素源坐标变换：缩放（最近邻）
//==============================================================================
//
//  【它是"坐标变换器"，不是"像素处理器"】
//
//      扫描坐标 (x,y) ──► [ ps_scale ] ──► (sx,sy) ──► [ 某个生成器 ] ──► pix
//                             ▲
//                    cfg_pos {CX,CY} + kx/ky
//
//  【最近邻缩放怎么用坐标映射实现】
//
//  输出区域以 (CX,CY) 为中心、TW×TH；源画布是 SW×SH。
//  对输出区域里的每一点 (x,y)，去问源：
//
//      sx = SW/2 + (x - CX) × SW / TW
//      sy = SH/2 + (y - CY) × SH / TH
//
//  "最近邻"就体现在这里——不做插值，直接取映射到的那个源坐标的像素。
//  输出区域之外的点映射出去后会被生成器的边界保护判为屏外 → 透明。
//
//  【★ 除法怎么办 ★】
//  直接写 `(x-CX) * SW / TW` 会引入除法器（很贵）。这里改成**乘以定点倒数**：
//
//      K = 65536 × SW / TW        ← 由 app_scene_cfg.v 预先算好，当输入传进来
//      sx = SW/2 + ((x-CX) * K) >> 16
//
//  【★ 为什么 K 是运行时输入，而 SW/SH 是 parameter ★】
//  SW/SH 只用来算"源画布中心"（一个常数加法），静态最省。
//  K 是动画缩放必须能改的（缩放比变了 K 就变），所以做成输入。
//
//  【★★ 撕裂修复（重要）★★】
//  这一版做了两处改动，专门解决上板时"缩放图形出现竖向白线"的问题：
//
//  ① **收窄位宽**。以前写 `wire signed [16:0] dx` 和 `wire signed [47:0] mx`，
//     综合工具看到 48 位的目标宽度，就会按 48 位去搭那棵乘法加法树，白白多花
//     一倍逻辑、进位链也长得多。而 dx 的真实范围只有 ±320（**11 位有符号**够），
//     乘积也只有 31 位。收窄之后逻辑量约减 40%，进位链短很多。
//
//  ② **输出打一拍（延迟从 0 变成 1）**。以前"常数乘法"和后面的"圆形判定"
//     串在同一个时钟周期里，总延迟 ≈10~14ns，**超过 100MHz 的 10ns 预算**，
//     进位链最长的那几列就会采样出错 → 正好表现为几条竖向白线。
//     打一拍把两段拆到两个周期，每段都 ≤5ns，时序就稳了。
//     （打拍不损失吞吐：还是每拍一个像素。）
//
//  ★ 打了这一拍之后，场景图里的坐标延迟链要相应少延迟一级（缩放支路改用 c5
//    而不是 c6），这样总延迟仍然是 8 拍，frame_writer 的 PIPE 不用改。
//
//  【cfg 总线格式】见 app_scene_cfg.v 顶部：
//      cfg_pos [31:0] = { CX[15:0], CY[15:0] }
//      kx, ky  有符号 20 位 = Q16 定点倒数（|K| ≤ 524287，目标尺寸 ≥80 时够用）
//
//  【延迟 = 1 拍】
//
//==============================================================================

module ps_scale #(
    parameter integer IMG_W = 640,      // 屏幕宽（不使用，仅为接口统一）
    parameter integer IMG_H = 480,      // 屏幕高
    parameter integer SW    = 640,      // 源画布宽（静态，只用来算中心）
    parameter integer SH    = 480       // 源画布高
)(
    input  wire               clk,
    input  wire               rst,
    input  wire [15:0]        x,          // 输出坐标
    input  wire [15:0]        y,
    input  wire               valid,
    input  wire [31:0]        cfg_pos,    // {CX, CY}
    input  wire signed [19:0] kx,         // Q16 定点倒数
    input  wire signed [19:0] ky,
    output reg  [15:0]        sx,         // 源坐标（延迟 1 拍）
    output reg  [15:0]        sy,
    output reg                out_valid
);

//------------------------------------------------------------------------------
//  拆总线 / 常数
//------------------------------------------------------------------------------
wire [15:0] CX = cfg_pos[31:16];
wire [15:0] CY = cfg_pos[15:0];

localparam signed [16:0] HX = SW / 2;   // 源画布中心（常数）
localparam signed [16:0] HY = SH / 2;

//------------------------------------------------------------------------------
//  坐标映射（收窄位宽版）
//------------------------------------------------------------------------------
// dx ∈ [-639, 639] → 11 位有符号（范围 -1024~1023）刚好够。
// 先按 17 位算减法（避免和 CX 相减时出错），再截到 11 位。
//------------------------------------------------------------------------------
wire signed [16:0] dx17 = $signed({1'b0, x}) - $signed({1'b0, CX});
wire signed [16:0] dy17 = $signed({1'b0, y}) - $signed({1'b0, CY});

wire signed [10:0] dx = dx17[10:0];     // 截到 11 位（值域内无损）
wire signed [10:0] dy = dy17[10:0];

// 11 位 × 20 位 = 31 位
wire signed [30:0] mx = dx * kx;
wire signed [30:0] my = dy * ky;

// 算术右移 16 位（负数向下取整），再加源画布中心
wire signed [16:0] sxs = HX + (mx >>> 16);
wire signed [16:0] sys = HY + (my >>> 16);

//------------------------------------------------------------------------------
//  输出打一拍（撕裂修复的关键）
//------------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) begin
        sx        <= 16'd0;
        sy        <= 16'd0;
        out_valid <= 1'b0;
    end else begin
        sx        <= sxs[15:0];        // 负数会回绕成大数 → 被生成器判为屏外
        sy        <= sys[15:0];
        out_valid <= valid;
    end
end

endmodule
