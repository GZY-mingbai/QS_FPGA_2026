//==============================================================================
//  ps_offset.v —— 像素源坐标变换：偏移（offsetX / offsetY）
//==============================================================================
//
//  【它是"坐标变换器"，不是"像素处理器"】
//
//      扫描坐标 (x,y) ──► [ ps_offset ] ──► (ox,oy) ──► [ 某个生成器 ] ──► pix
//                              ▲
//                          cfg {DX,DY}
//
//  它放在**生成器的前面**，只改"生成器看哪个坐标"，不碰像素本身。
//
//  【★ 为什么偏移要做成"坐标重映射"，而不是"挪动像素" ★】
//
//  朴素想法：把源的像素流整体往右挪 dx 个像素。但像素是"每拍一个"流过来的，
//  横向挪动要延迟 dx 拍（还能靠移位寄存器），**纵向挪动就要缓存整行甚至整帧**——
//  那是 BRAM 级别的代价。
//
//  而坐标驱动模型下，偏移只是"让源去查询 (x-dx, y-dy)"，
//  就是两个减法器，**零乘法器、零存储、零延迟**。这是坐标驱动最大的红利。
//
//  【★ DX/DY 是运行时输入 ★】
//  改成输入后**成本完全不变**（还是两个减法器），但动画就能做了——
//  每帧把 DX/DY 改一点，图形就平移了。
//
//  【越界怎么办】
//  x < DX 时，16 位无符号减法会回绕成接近 65535 的大数，
//  生成器内部的 `x < IMG_W` 边界保护会把它判为"屏外"→ 输出透明。正好是我们要的。
//
//  【cfg 总线格式】见 app_scene_cfg.v 顶部：
//      cfg [31:0] = { DX[15:0], DY[15:0] }      正值 = 源向右/向下移
//
//  【延迟 = 0（纯组合）】
//  它在坐标路径上，不改变像素流水线的深度，所以不占"拍数"。
//
//==============================================================================

module ps_offset #(
    parameter integer IMG_W = 640,      // 屏幕宽（本模块不使用，仅为接口统一）
    parameter integer IMG_H = 480       // 屏幕高
)(
    input  wire [15:0] x,               // 扫描坐标
    input  wire [15:0] y,
    input  wire [31:0] cfg,             // {DX, DY}
    output wire [15:0] ox,              // 送给源的查询坐标
    output wire [15:0] oy
);

wire [15:0] DX = cfg[31:16];
wire [15:0] DY = cfg[15:0];

assign ox = x - DX;
assign oy = y - DY;

endmodule
