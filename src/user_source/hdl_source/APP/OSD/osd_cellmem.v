//==============================================================================
//  osd_cellmem.v —— OSD 控件表：几何寄存器阵列 + 属性 BRAM + 并行命中网络
//==============================================================================
//
//  【为什么几何存寄存器、属性存 BRAM】
//  S1 要对全部 NSLOT 个矩形**并行**比较，几何必须同拍可见 ⇒ 只能放寄存器
//  （NSLOT 个 39bit 触发器）。属性（类型/样式/数值）只需要"命中那一条"，
//  按索引读 BRAM 即可（1 拍）。若两者都放 BRAM，双口 RAM 一拍最多读 2 条，
//  根本读不出 NSLOT 组坐标 —— 这是本模块存在的根本原因。
//
//  【优先级 = 索引大者在上】
//  布局引擎按"从底到顶"的顺序写（遮罩→面板→控件→游标），所以命中取
//  最高索引即可，不需要 prio 字段，省掉一整套 16 级优先级编码。
//
//  【写口与读侧的一致性】
//  写只发生在 ps_start 落沿之后的静默窗口（tick），此时 adv=0、S1 不装载；
//  写完 24 条（24 拍）远小于帧间空档 ⇒ 不会出现"半帧新布局"。
//
//==============================================================================
module osd_cellmem #(
    parameter integer NSLOT = 24
)(
    input  wire        clk,
    input  wire        rst,
    // ★★ 2026-10-29：流水推进使能（= pixel_ready）★★
    //   读口的输出寄存器必须跟其它流水级一起冻结，否则背压停顿一次就错一个像素
    //   （上板现象：菜单左侧图标 / logo / 游标框右边缘出现**每帧同一列**的
    //     1px 竖直虚线，虚线位置随该列内容出没）。
    input  wire        ce,

    // ---- 写口（布局引擎，帧间窗口）----
    input  wire        wr_en,
    input  wire [4:0]  wr_idx,
    input  wire [38:0] wr_geo,          // {en, x1[9:0], y1[8:0], x0[9:0], y0[8:0]}
    input  wire [23:0] wr_attr,         // {type,style,rad(4+4+4), mask[1:0], v0[9:0]}

    // ---- 命中（S1，组合）----
    input  wire [9:0]  px,
    input  wire [8:0]  py,
    output wire        hit_v,
    output wire [4:0]  hit_idx,

    // ---- 属性读（S2，同步；地址组合送来，无条件读）----
    input  wire [4:0]  rd_idx,
    output reg  [38:0] rd_geo,
    output reg  [23:0] rd_attr
);

// 属性位宽变了 → 整个条目从 67 位降到 61 位（省 6 位 × NSLOT）
// ★ 2026-10-28：CW/AB 两个打包常量随 cell_r 拆分一起删除（几何 39 + 属性 24 各自成组）

//------------------------------------------------------------------------------
//  1. 几何阵列（寄存器，供并行比较）+ 属性阵列（可推断成 LUTRAM）
//------------------------------------------------------------------------------
// ★★ 2026-10-28：**几何与属性拆成两个数组**（原来合成一个 63 位 cell_r）★★
//
//   【为什么能拆】命中网络只吃几何（en/x1/y1/x0/y0），属性只有 rd_idx 这一处
//   读 —— 也就是说几何是"19 路并行读"，属性是"1 路随机读"。
//   合成一个数组的后果：综合器只能整体实现成「寄存器阵列 + 19 选 1 大 mux」，
//   属性那 24 位白白跟着吃一套 19 选 1（≈120 LUT）。
//   拆开后属性可以落成 LUTRAM/BRAM（4608 bit），mux 由 LUT 内部完成，省一大截。
//
//   【为什么原来会出事故】旧注释记的"属性放 RAM ⇒ 控件画成噪点"不是"不能放 RAM"，
//   而是当时的**写**写成了 `for (wi...) if (wi == wr_idx) attr_r[wi] <= ...`，
//   综合器把属性表推断成 RAM 后只保留循环最后一个分支 ⇒ 每个槽写进去的都是
//   最后一条记录。现在用**变址写**（见第 3 节），该根因不存在。
//
//   【读延迟必须一致】两路仍在同一个 always 块、同一拍出数据
//   （地址组合送入、输出寄存 = 1 拍），与 osd_gfx 的 2 拍流水严格对齐。
// ★★ 2026-10-28：geo_r 拆成两个数组（**行为一位不变**）★★
//  【为什么拆】phy 报 PHY-8023：布线只剩 **1 个**复用冲突，卡在
//      Location: (x19y17_s1beg0),
//      nets: .../u_mem/geo_r[16][3]  .../u_mem/geo_r[18][3]
//    路由器从 2145 个冲突一路清到 1 个，然后 70 次迭代纹丝不动。
//    place.qor 显示 `#slices 9536 / slices 97.31%` ⇒ 全局几乎没有腾挪空间，
//    所以这个点只能靠**改变打包方式**去躲。
//  【为什么按字段边界拆】20 槽 × 39 位是一个大数组，综合器倾向把
//    "同一位、不同槽"的触发器打进同一个 slice（它们共享 wr_geo 的数据/使能），
//    `[16][3]` 和 `[18][3]` 就是这么被摆到一起的。拆成两个数组后打包分组变了，
//    这类同位冲突通常就散开。
//  【拆在哪】按字段边界，跨字段拆会把 x1/y1 切断（y1 是 bit27:19，正好跨 20）：
//      geo_hi[19:0] = wr_geo[38:19] = {en, x1[9:0], y1[8:0]}   20 位
//      geo_lo[18:0] = wr_geo[18:0]  = {x0[9:0],  y0[8:0]}      19 位
//    读的时候直接拼回 39 位，写口同拍写两个数组 ⇒ 语义与拆分前逐位相同。
//    ★ 附带好处：命中比较器每个只读一个数组（x 比 x0/x1、y 比 y0/y1 分开取），
//      综合器布线更自由。
reg [19:0] geo_hi [0:NSLOT-1];      // {en, x1[9:0], y1[8:0]}
reg [18:0] geo_lo [0:NSLOT-1];      // {x0[9:0],  y0[8:0]}

//------------------------------------------------------------------------------
//  1'. 几何读副本：走分布式 RAM（LUTRAM）★ 2026-10-29 [S1]
//------------------------------------------------------------------------------
//  原来读口写的是 `rd_geo <= {geo_hi[rd_idx], geo_lo[rd_idx]}` —— 39 位 × NSLOT
//  选 1 的组合大 mux，而它只服务"命中的那一条"，与命中网络无关。
//  现在同拍留一份副本在 LUTRAM 里，读口变成"RAM 异步读 + 打一拍"，
//  输出仍与 attr_r 同拍（地址组合送、数据下一拍出），像素流水一拍不变。
//
//  ⚠ 三条必须同时满足 TD 才会真的落成 dram（否则会被推成触发器 + mux）：
//    ① 声明处 fehdl 强制；② 写只在**无复位**的时钟块里；③ 初值走 initial。
// ★★ 2026-10-31：几何读副本 + 属性表合并成一张表（LUTRAM，见下面更正）★★
//  原来：geo_rd 强制 dram（只能放 MSlice）+ attr_r 是带异步复位的 8×24 寄存器阵列
//  （192 FF + 24 位 8 选 1 读 mux）。工程卡在 mslice 4909 > 4900。
//  两者的读都是"地址组合送入、ce 门控、1 拍出数"，合并成 {geo[38:0], attr[23:0]}
//  一张 63 位宽表，读写时序逐拍不变；属性不再占 192 FF + 24 位读 mux。
//  属性放低 24 位 ⇒ cell_rd[k][23:0] 就是原来的 attr_r[k]（测试台按此访问）。
//  不再复位：未写过的槽 geo_hi 的 en=0（那边仍复位），根本不会被命中，属性不会被用到。
//  ★ 2026-10-31 更正：TD 对 8 深的表报 SYN-5042「Failed to infer ... as BRAM」，退回成
//    504 个 FF + 63 位 8 选 1 mux（#reg +440）。改成强制 dram（LUTRAM，与原 geo_rd 同写法，
//    TD 接受）：16 个 DRAM16X4，不占 FF；读仍是"异步读 + ce 门控寄存"，时序逐拍不变。
reg [62:0] cell_rd [0:NSLOT-1];     /* fehdl force_ram=1, ram_style="dram" */

integer gr_i;
initial
    for (gr_i = 0; gr_i < NSLOT; gr_i = gr_i + 1)
        cell_rd[gr_i] = 63'd0;

// 写：与 geo_hi/geo_lo 同一拍、同一份 wr_geo / wr_attr
always @(posedge clk) begin
    if (wr_en) cell_rd[wr_idx] <= {wr_geo, wr_attr};
end

//------------------------------------------------------------------------------
//  2. 读口（常开；地址由 S1 的命中结果组合送来，数据下一拍有效）
//------------------------------------------------------------------------------
//  ★★ 2026-10-29：加 `if (ce)` ★★
//    这是整个 OSD 流水线里**唯一**没被 pixel_ready 门控的寄存器。背压停顿
//    一拍时，`s1_px` 保持而 `rd_geo` 继续跟着活地址走 ⇒ 下一拍复用的那个像素
//    是"坐标取自 N、几何取自 N+1"，用错了控件的矩形/样式。
//    对照 `ps_gen_text` 头部那条注释，是同一类问题。
//    两路仍在同一个 always、同一拍出数，**读延迟不变（1 拍）**。
wire [62:0] cell_q = cell_rd[rd_idx];          // 分布式 RAM 异步读
always @(posedge clk) begin
    if (ce) {rd_geo, rd_attr} <= cell_q;        // ce 门控寄存（与原 geo_rd 读口同构）
end

//------------------------------------------------------------------------------
//  3. 写几何 + 属性（同拍同源）
//------------------------------------------------------------------------------
//  ★★★ 关键：写必须用「变址写」attr_r[wr_idx] <= ...，不能写成
//      for (wi...) if (wi == wr_idx) attr_r[wi] <= ...
//      后者在仿真里等价，但综合器容易把 attr_r 推断成 RAM 后只保留循环
//      最后一个分支 ⇒ 属性表全乱（上板现象：每个控件画出来的东西都不一样）。
integer wi;
always @(posedge clk or posedge rst) begin
    if (rst) begin
        // 必须清零：未用槽若保持 X，hit 归约会变 X，整条像素通路被污染
        for (wi = 0; wi < NSLOT; wi = wi + 1) begin
            geo_hi[wi] <= 20'd0;
            geo_lo[wi] <= 19'd0;
        end
    end else if (wr_en) begin
        // ★ 变址写（不是 for 循环比较）：保证属性表被推断成 RAM 时不会丢分支
        geo_hi[wr_idx] <= wr_geo[38:19];
        geo_lo[wr_idx] <= wr_geo[18:0];
    end
end

//------------------------------------------------------------------------------
//  4. 并行命中 + 取最高索引
//------------------------------------------------------------------------------
wire [NSLOT-1:0] hit;

genvar gi;
generate
for (gi = 0; gi < NSLOT; gi = gi + 1) begin : g_hit
    wire        en = geo_hi[gi][19];
    wire [9:0]  x1 = geo_hi[gi][18:9];
    wire [8:0]  y1 = geo_hi[gi][8:0];
    wire [9:0]  x0 = geo_lo[gi][18:9];
    wire [8:0]  y0 = geo_lo[gi][8:0];
    assign hit[gi] = en && (px >= x0) && (px < x1) && (py >= y0) && (py < y1);
end
endgenerate

//------------------------------------------------------------------
//  最高置位索引（16 位一段的 casez 优先编码器，级联 2 段）
//  比 for 循环链短得多：48 深的链在 50MHz 下会逼近 20ns
//------------------------------------------------------------------
function [3:0] pe16;
    input [15:0] v;
    begin
        casez (v)
            16'b1???????????????: pe16 = 4'd15;
            16'b01??????????????: pe16 = 4'd14;
            16'b001?????????????: pe16 = 4'd13;
            16'b0001????????????: pe16 = 4'd12;
            16'b00001???????????: pe16 = 4'd11;
            16'b000001??????????: pe16 = 4'd10;
            16'b0000001?????????: pe16 = 4'd9;
            16'b00000001????????: pe16 = 4'd8;
            16'b000000001???????: pe16 = 4'd7;
            16'b0000000001??????: pe16 = 4'd6;
            16'b00000000001?????: pe16 = 4'd5;
            16'b000000000001????: pe16 = 4'd4;
            16'b0000000000001???: pe16 = 4'd3;
            16'b00000000000001??: pe16 = 4'd2;
            16'b000000000000001?: pe16 = 4'd1;
            16'b0000000000000001: pe16 = 4'd0;
            default:              pe16 = 4'd0;
        endcase
    end
endfunction

// ★ NSLOT 可能小于 16（合并游标槽后 = 15）：两段拆取必须用 generate 分支，
//   直接写 hit[NSLOT-1:16] 在 NSLOT<16 时是**反向空位选**，综合会报错。
wire [15:0] hit_lo;
wire [7:0]  hit_hi;

generate
if (NSLOT >= 16) begin : g_hi
    assign hit_lo = hit[15:0];
    assign hit_hi = (NSLOT > 16) ? hit[NSLOT-1:16] : 8'd0;
end else begin : g_lo
    assign hit_lo = {{(16-NSLOT){1'b0}}, hit[NSLOT-1:0]};
    assign hit_hi = 8'd0;
end
endgenerate

//------------------------------------------------------------------------------
//  ★ 2026-10-27 P1-L3：高位段优先编码改成"按有效位宽"
//------------------------------------------------------------------------------
//  原来：`pe16({8'd0, hit_hi})` —— 把 8 位 hit_hi 塞进 16 路编码器，
//  但 NSLOT=19 ⇒ 只有 hit[18:16] 三位可能为 1，其余 13 路是**恒 0 的输入**
//  ⇒ 白烧一堆 LUT（16 路 casez 的优先级链）。
//  现在：只用 NHI 位做一条 NHI 级的上升沿链（NHI=3 ⇒ 2 级 LUT）。
//  ⚠ 必须"升序扫描、后写覆盖"：这样**最高**的置位索引获胜，与 pe16 语义一致。
//------------------------------------------------------------------------------
localparam integer NHI = (NSLOT > 16) ? (NSLOT - 16) : 0;

wire        any_hi = |hit_hi;
wire [3:0]  pe_lo  = pe16(hit_lo);
reg  [3:0]  pe_hi;
integer     hi_i;
always @(*) begin
    pe_hi = 4'd0;
    for (hi_i = 0; hi_i < NHI; hi_i = hi_i + 1)
        if (hit_hi[hi_i]) pe_hi = hi_i[3:0];
end

assign hit_v   = any_hi | (|hit_lo);
assign hit_idx = any_hi ? (pe_hi + 5'd16)          // 16 + 段内偏移
                        : {1'b0, pe_lo};

endmodule
