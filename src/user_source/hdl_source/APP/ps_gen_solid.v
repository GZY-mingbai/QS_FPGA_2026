//==============================================================================
//  ps_gen_solid.v —— 像素源生成器：满屏纯色
//==============================================================================
//
//      扫描坐标 (x,y) ──► [ ps_gen_solid ] ──► pix {A,R,G,B}
//                                ▲
//                              color
//
//  不管你问它哪个坐标，它都返回同一个颜色。主要用途是当"底色图层"。
//
//  【★ 颜色是运行时输入 ★】做淡入淡出 / 变色动画时直接改 color 即可。
//
//  【cfg 总线格式】见 app_scene_cfg.v 顶部：
//      color [31:0] = { A[7:0], R[7:0], G[7:0], B[7:0] }
//
//  【延迟 = 1 拍】
//
//==============================================================================

module ps_gen_solid #(
    parameter integer IMG_W = 640,      // 屏幕宽（只用它做边界保护）
    parameter integer IMG_H = 480       // 屏幕高
)(
    input  wire        clk,
    input  wire        rst,
    input  wire [15:0] x,
    input  wire [15:0] y,
    input  wire        valid,
    input  wire [31:0] color,           // {A, R, G, B}
    output reg  [31:0] pix,
    output reg         out_valid
);

//------------------------------------------------------------------------------
//  边界保护
//------------------------------------------------------------------------------
// 坐标可能来自 ps_offset / ps_scale 的变换，变换后可能落到屏幕外。
// 这时候输出"透明"，而不是让一个巨大的坐标参与后续判定。
//------------------------------------------------------------------------------
wire in_bounds = (x < IMG_W) && (y < IMG_H);

//------------------------------------------------------------------------------
//  输出打一拍
//------------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) begin
        pix       <= 32'h0000_0000;
        out_valid <= 1'b0;
    end else begin
        pix       <= in_bounds ? color : 32'h0000_0000;
        out_valid <= valid;
    end
end

endmodule
