//==============================================================================
//  tb_ps_gen_text.v —— ps_gen_text 的模块级验证
//==============================================================================
//
//  被测：ps_gen_text.v（多行点阵文字生成器，延迟应为 **2 拍**）
//
//  【怎么跑】
//      cd src/user_source/hdl_source
//      iverilog -g2005 -s tb_ps_gen_text -o tb_ps_gen_text.vvp \
//          APP/tb_ps_gen_text.v APP/ps_gen_text.v
//      vvp tb_ps_gen_text.vvp
//
//  【这个 tb 打的是什么桩】
//  · glyph_row 本来由 osd_font_cache 的 BRAM 提供（地址后 1 拍出数据）。
//    这里用一个"地址打一拍 + 组合读表"的模型来复刻那个时序：
//        always @(posedge clk) ga_d <= glyph_addr;
//        wire [15:0] glyph_row = gmem[ga_d];
//    等价于一个标准同步读 BRAM（1 拍）。
//  · slot_tbl / line_len / line_ready 直接由本 tb 常量驱动。
//
//  【重点验证什么】
//   ① 延迟**恰好** 2 拍（1 拍不算数，且 out_valid 与 pix 同拍）
//   ② 位序 **glyph_row[15-col]**（col=0 → bit15；col=15 → bit0）
//   ③ 多行选择：同一个 x、不同 y 落在不同行，颜色/字形各归各行
//   ④ 边界：x<X0、y 不在任何行带内、超出该行字数 → 全部透明
//   ⑤ line_ready = 0 → 整行透明
//
//==============================================================================

`timescale 1ns/1ps

module tb_ps_gen_text;

//==============================================================================
//  参数
//==============================================================================
localparam integer NL     = 2;
localparam integer MAXLEN = 32;

localparam [15:0] L0_X = 16'd100, L0_Y = 16'd50;    // 第 0 行：起点 (100,50)
localparam [15:0] L1_X = 16'd100, L1_Y = 16'd100;   // 第 1 行：起点 (100,100)
localparam [7:0]  L0_LEN = 8'd8;                    // 第 0 行 8 个字
localparam [7:0]  L1_LEN = 8'd4;                    // 第 1 行 4 个字

// ★ 2026-10-31：ps_gen_text 改成 2 位颜色号（txt_ci）后只剩 3 种固定色，
//   用其中两种区分两行：第 0 行 = 高亮 FFFFFF，第 1 行 = 标题 F0F0F0。
//   （名字沿用 C_RED / C_GREEN，只为少改用例。）
localparam [31:0] C_RED   = 32'hFFFF_FFFF;          // {A,R,G,B}  ci=1 高亮
localparam [31:0] C_GREEN = 32'hFFF0_F0F0;          //             ci=2 标题
localparam [31:0] C_NONE  = 32'h0000_0000;

// 槽位号（0 = 空白槽）
localparam [9:0] S0 = 10'd1;                        // 第 0 行用的槽
localparam [9:0] S1 = 10'd2;                        // 第 1 行用的槽

//==============================================================================
//  时钟与激励
//==============================================================================
reg clk = 0;
reg rst = 1;

reg [15:0] x = 0, y = 0;
reg        valid = 0;

always #5 clk = ~clk;               // 100 MHz

//==============================================================================
//  DUT 端口连线（★ 必须先在 BRAM 模型之前声明，否则会被隐式声明成 1 位线）
//==============================================================================
// 每行 [32*i +: 32] = {Y0, X0}
wire [22*NL-1:0] txt_xy  = { L1_Y[10:0], L1_X[10:0], L0_Y[10:0], L0_X[10:0] };   // 每行 {Y[10:0], X[10:0]}
// 每行 [32*i +: 32] = {A,R,G,B}
wire [ 2*NL-1:0] txt_ci  = { 2'd2, 2'd1 };

// 槽位表：每行每个字符列都指向本行的槽（这里简化为"整行同一个槽"）
reg [10*NL-1:0]  slot_tbl;
// 每行字数
reg [ 8*NL-1:0]  line_len;
// 每行就绪
reg [    NL-1:0] line_ready;

wire [ 8*NL-1:0] slot_col;
wire [13:0]      glyph_addr;
wire [31:0]      pix;
wire             out_valid;

//==============================================================================
//  字形 BRAM 模型（同步读：地址打 1 拍，组合出数据）
//==============================================================================
reg [15:0] gmem [0:16383];
reg [13:0] ga_d;

always @(posedge clk or posedge rst) begin
    if (rst) ga_d <= 14'd0;
    else     ga_d <= glyph_addr;
end

wire [15:0] glyph_row = gmem[ga_d];

//==============================================================================
//  DUT
//==============================================================================
ps_gen_text #(
    .IMG_W (640), .IMG_H (480),
    .NL    (NL),  .MAXLEN (MAXLEN)
) u_dut (
    .clk        (clk),
    .rst        (rst),
    .x          (x),
    .y          (y),
    .valid      (valid),
    .ce(1'b1),
    .txt_xy     (txt_xy),
    .txt_ci     (txt_ci),
    .slot_tbl   (slot_tbl),
    .line_len   (line_len),
    .line_ready (line_ready),
    .glyph_row  (glyph_row),
    .slot_col   (slot_col),
    .glyph_addr (glyph_addr),
    .pix        (pix),
    .out_valid  (out_valid)
);

//==============================================================================
//  逐拍违规计数
//==============================================================================
integer n_err;

//==============================================================================
//  检查任务
//==============================================================================
task run_case;
    input [15:0] tx, ty;
    input        tv;
    input [31:0] texp;
    input        texp_v;
    input [15:0] tid;
    begin
        @(negedge clk);
        x = tx; y = ty; valid = tv;
        @(posedge clk);                 // 第 1 拍：DUT 内部元数据对齐寄存
        @(posedge clk);                 // 第 2 拍：pix 输出寄存
        #1;
        if (pix !== texp) begin
            n_err = n_err + 1;
            $display("  x [%0d] x=%0d y=%0d  pix=%08h  期望 %08h   (glyph_addr=%0d slot_col=%0d)",
                     tid, tx, ty, pix, texp, glyph_addr, slot_col[7:0]);
        end else begin
            $display("    [%0d] x=%0d y=%0d  pix=%08h  OK", tid, tx, ty, pix);
        end
        if (out_valid !== texp_v) begin
            n_err = n_err + 1;
            $display("  x [%0d] out_valid=%b  期望 %b", tid, out_valid, texp_v);
        end
    end
endtask

//==============================================================================
//  主激励
//==============================================================================
integer i;

initial begin
    n_err = 0;

    // ---- 字形表：只填两个槽的第 0、1 行 ----
    for (i = 0; i < 16384; i = i + 1) gmem[i] = 16'd0;

    // 槽 1（第 0 行用）
    gmem[S0*16 + 0] = 16'b1010_0000_0000_0001;   // bit15=col0, bit13=col2, bit0=col15
    gmem[S0*16 + 1] = 16'b0000_0000_0000_0100;   // bit2 =col13
    // 槽 2（第 1 行用）
    gmem[S1*16 + 0] = 16'b1000_0000_0000_0010;   // bit15=col0, bit1 =col14

    slot_tbl   = { S1, S0 };                     // 每行都指向本行自己的槽
    line_len   = { L1_LEN, L0_LEN };
    line_ready = {NL{1'b1}};

    // 复位
    repeat (10) @(posedge clk);
    rst = 0;
    repeat (5)  @(posedge clk);

    $display("");
    $display("============================================================");
    $display("  tb_ps_gen_text —— 多行点阵文字生成器（NL=2, MAXLEN=32）");
    $display("------------------------------------------------------------");
    $display("  第0行: 原点(%0d,%0d) 字数%0d 色=红  槽=%0d", L0_X, L0_Y, L0_LEN, S0);
    $display("  第1行: 原点(%0d,%0d) 字数%0d 色=绿  槽=%0d", L1_X, L1_Y, L1_LEN, S1);
    $display("  槽%0d 第0行点阵 = 1010_0000_0000_0001  -> col 0,2,15 亮", S0);
    $display("  槽%0d 第1行点阵 = 0000_0000_0000_0100  -> col 13    亮", S0);
    $display("  槽%0d 第0行点阵 = 1000_0000_0000_0010  -> col 0,14  亮", S1);
    $display("============================================================");

    //======================================================================
    //  A. 延迟必须**恰好** 2 拍
    //======================================================================
    $display("  --- A. 延迟检查（必须恰好 2 拍）---");
    @(negedge clk); x = 16'd98; y = L0_Y; valid = 1'b1;    // 越界 → 透明（做个干净前置态）
    @(posedge clk); @(posedge clk); #1;
    $display("    前置 pix=%08h (期望 00000000)", pix);

    @(negedge clk); x = L0_X; y = L0_Y; valid = 1'b1;      // 切到"红点"
    @(posedge clk); #1;
    if (pix === C_NONE)
        $display("    第 1 拍 pix 仍为透明  OK（说明没有提前 1 拍输出）");
    else begin
        n_err = n_err + 1;
        $display("  x 第 1 拍 pix=%08h 就已经变了 —— 延迟不足 2 拍！", pix);
    end
    @(posedge clk); #1;
    if (pix === C_RED)
        $display("    第 2 拍 pix=%08h 出现红点  OK（延迟恰好 2 拍）", pix);
    else begin
        n_err = n_err + 1;
        $display("  x 第 2 拍 pix=%08h 期望 %08h —— 延迟不对！", pix, C_RED);
    end

    //======================================================================
    //  B. 位序：col → bit(15-col)
    //======================================================================
    $display("  --- B. 位序 glyph_row[15-col] ---");
    run_case(L0_X + 0,  L0_Y, 1'b1, C_RED,   1'b1, 16'd0);   // col0  → bit15 = 1
    run_case(L0_X + 1,  L0_Y, 1'b1, C_NONE,  1'b1, 16'd1);   // col1  → bit14 = 0
    run_case(L0_X + 2,  L0_Y, 1'b1, C_RED,   1'b1, 16'd2);   // col2  → bit13 = 1
    run_case(L0_X + 15, L0_Y, 1'b1, C_RED,   1'b1, 16'd3);   // col15 → bit0  = 1
    run_case(L0_X + 16, L0_Y, 1'b1, C_RED,   1'b1, 16'd4);   // 第2个字 col0 → 仍亮
    run_case(L0_X + 13, L0_Y + 1, 1'b1, C_RED,  1'b1, 16'd5); // row1 col13 → bit2=1
    run_case(L0_X + 12, L0_Y + 1, 1'b1, C_NONE, 1'b1, 16'd6); // row1 col12 → bit3=0
    run_case(L0_X + 14, L0_Y + 15, 1'b1, C_NONE, 1'b1, 16'd7);// 最后一行没填 → 全 0

    //======================================================================
    //  C. 多行选择
    //======================================================================
    $display("  --- C. 多行选择 ---");
    run_case(L1_X + 0,  L1_Y, 1'b1, C_GREEN, 1'b1, 16'd10);  // 第1行 col0  → 绿
    run_case(L1_X + 14, L1_Y, 1'b1, C_GREEN, 1'b1, 16'd11);  // 第1行 col14 → 绿
    run_case(L1_X + 13, L1_Y, 1'b1, C_NONE,  1'b1, 16'd12);  // 第1行 col13 → 透明

    //======================================================================
    //  D. 边界
    //======================================================================
    $display("  --- D. 边界保护 ---");
    run_case(L0_X - 1,  L0_Y, 1'b1, C_NONE, 1'b1, 16'd20);   // x<X0 → 透明
    run_case(L0_X, L0_Y - 1, 1'b1, C_NONE, 1'b1, 16'd21);    // y 在行带上方 → 透明
    run_case(L0_X, L0_Y + 16, 1'b1, C_NONE, 1'b1, 16'd22);   // y 恰好超出 16 行 → 透明
    run_case(L0_X + L0_LEN*16, L0_Y, 1'b1, C_NONE, 1'b1, 16'd23);      // 超出本行字数 → 透明
    run_case(L0_X + L0_LEN*16 - 1, L0_Y, 1'b1, C_RED, 1'b1, 16'd24);   // 最后一个字的最右列(col15)→亮
    run_case(L1_X + L1_LEN*16, L1_Y, 1'b1, C_NONE, 1'b1, 16'd25);      // 第1行超字数 → 透明

    //======================================================================
    //  E. line_ready = 0 → 整行透明
    //======================================================================
    $display("  --- E. line_ready 门控 ---");
    line_ready = 2'b01;                                       // 第 1 行未就绪
    run_case(L1_X, L1_Y, 1'b1, C_NONE, 1'b1, 16'd30);         // 本来该是绿 → 现在透明
    line_ready = 2'b11;
    run_case(L1_X, L1_Y, 1'b1, C_GREEN, 1'b1, 16'd31);        // 恢复后就绪 → 绿

    //======================================================================
    //  F. 汇总
    //======================================================================
    $display("------------------------------------------------------------");
    $display("  不匹配 = %0d  (期望 0)", n_err);
    if (n_err == 0) $display("  RESULT: PASS");
    else            $display("  RESULT: FAIL");
    $display("============================================================");
    $display("");
    $finish;
end

//==============================================================================
//  看门狗
//==============================================================================
initial begin
    #10_000_000;
    $display("  RESULT: FAIL  (看门狗超时)");
    $finish;
end

endmodule
