//==============================================================================
//  ps_merge_alpha_pp.v —— 逐像素 alpha 合并器（OSD 用）
//==============================================================================
//
//      s1 (前景) ─┐
//                 ├─► [ ps_merge_alpha_pp ] ─► pix
//      s2 (背景) ─┘          ▲
//                            alpha（全层淡入，0~255）
//
//  【与 ps_merge_alpha8 的区别】
//  alpha8 只认"前景透明/不透明"（A!=0），整体不透明度由端口 alpha 给。
//  这里把前景的 A 字节也当**逐像素** alpha 用：
//      a9 = 0                          (A == 0)
//         = alpha（255 时取 256）       (A == 255，与 alpha8 完全一致)
//         = A*alpha/256                (0 < A < 255)
//  所以：
//    · B 图层（A 只有 0/255）⇒ 行为与 ps_merge_alpha8 **逐位相同**；
//    · OSD 层（A = 遮罩 160 / 面板 224 / 文字 255 …）⇒ 得到正确的半透明叠加。
//  公式仍是 (s1*a9 + s2*(256-a9))>>8，乘积 ≤ 255*256，16 位足够。
//
//  【延迟 = 1 拍】（与 alpha8 相同，场景总延迟不变）
//
//==============================================================================
module ps_merge_alpha_pp (
    input  wire        clk,
    input  wire        rst,
    input  wire        ce,

    input  wire [31:0] s1_pix,
    input  wire        s1_valid,
    input  wire [31:0] s2_pix,
    input  wire        s2_valid,

    input  wire [7:0]  alpha,

    output reg  [31:0] pix,
    output reg         out_valid
);

wire [7:0] a1 = s1_pix[31:24];

//==============================================================================
//  ★★ 2026-10-30 [DSP-PIPE]：乘法器**之前**插一级寄存器 ★★
//==============================================================================
//  【为什么要加】布线后最差路径是 `u_merge/add1.mi[0]`（DSP 输入脚）−3.2ns：
//    起点是各层输出寄存器、终点是 DSP 的输入脚，中间 52~66% 是**走线**
//    （95% 占用下 placer 摊不开）。乘法本身不慢，慢在"走不到 DSP 门口"。
//  【做法】把 s1/s2/alpha/valid 先打一拍，再进乘法 ⇒ 一条长路被劈成两段，
//    第二段只是"相邻寄存器 → DSP"，走线短得多。
//  【代价】本模块延迟 1 → 2 拍 ⇒ 顶层 `frame_writer` 的 PIPE 必须 4→5、
//    `viewer_scene` 的 PIPE 也必须 4→5（它的 drain 靠这个数排空）。
//    触发器只用了 54%，这 74 位几乎不花钱，而且不占 LUT。
//  【等价性】纯打拍，数据与 valid 同步延后一拍，权重/算式一个字都没改。
//==============================================================================
reg [31:0] s1_r, s2_r;
reg [7:0]  al_r;
reg        v1_r, v2_r;

always @(posedge clk or posedge rst) begin
    if (rst) begin
        s1_r <= 32'd0; s2_r <= 32'd0; al_r <= 8'd0;
        v1_r <= 1'b0;  v2_r <= 1'b0;
    end else if (ce) begin
        s1_r <= s1_pix;  s2_r <= s2_pix;  al_r <= alpha;
        v1_r <= s1_valid; v2_r <= s2_valid;
    end
end

wire [7:0] a1_r = s1_r[31:24];

//  ★★★ 关键：8×9 乘法必须先落到一个**显式 18 位**的中间量。
//  若直接写成 `wire [8:0] a9 = (a1*alpha)>>8;`，Verilog 的上下文位宽会
//  反向传播进乘法：乘积先被截成 9 位、再右移 8 位 ⇒ 结果恒为 0~1
//  ⇒ 上板表现为"凡是 alpha<255 的像素全透明"（文字/图标恰好是 255 所以正常）。
wire [17:0] mul   = {1'b0, a1_r} * {1'b0, al_r};   // 最大 255*255 = 65025
wire [9:0]  mul_s = mul[17:8];                    // >>8，10 位
wire [8:0]  a9 = (a1_r == 8'd0)   ? 9'd0 :
                 (a1_r == 8'd255) ? ((al_r == 8'd255) ? 9'd256 : {1'b0, al_r}) :
                                  (mul_s > 10'd256) ? 9'd256 : mul_s[8:0];
wire [8:0] i9 = 9'd256 - a9;

// ★★ 2026-11-01：每通道 2 台乘法 → **1 台**（数学恒等，逐位不变）★★
//      x·a + y·(256−a) = y·256 + (x−y)·a
//   y·256 就是左移 8 位（纯连线，0 LUT），所以每通道少一台 8×9 乘法：
//      原来 3 通道 × 2 = 6 台 + a1*alpha 1 台 = 7 台
//      现在 3 通道 × 1 = 3 台 + a1*alpha 1 台 = 4 台（正好塞满 4 个 DSP，
//      其余原本溢出到 LUT 的乘法就没了）
//  位宽：a ∈ 0..256，x−y ∈ −255..255 ⇒ 乘积 ∈ ±65280，和恒 ∈ [0,65280]。
//  ⚠ a9 会等于 **256**（a1=255 且 alpha=255），9 位有符号装不下（-256..255），
//    必须用 10 位有符号，否则 256 会被解释成 -256 —— 这是穷举对拍抓出来的：
//    9 位版本在 a9=256 时输出全错。
wire signed [8:0]  dr = {1'b0, s1_r[23:16]} - {1'b0, s2_r[23:16]};
wire signed [8:0]  dg = {1'b0, s1_r[15:8]}  - {1'b0, s2_r[15:8]};
wire signed [8:0]  db = {1'b0, s1_r[7:0]}   - {1'b0, s2_r[7:0]};
wire signed [9:0]  as10 = {1'b0, a9};                 // 0..256
wire signed [18:0] pr = dr * as10;
wire signed [18:0] pg = dg * as10;
wire signed [18:0] pb = db * as10;
// 用 20 位带符号求和，最后再截回无符号 18 位（真值一定 ≥ 0）
wire signed [19:0] mr_s = $signed({4'b0, s2_r[23:16], 8'd0}) + pr;
wire signed [19:0] mg_s = $signed({4'b0, s2_r[15:8],  8'd0}) + pg;
wire signed [19:0] mb_s = $signed({4'b0, s2_r[7:0],   8'd0}) + pb;
wire [17:0] mr = mr_s[17:0];
wire [17:0] mg = mg_s[17:0];
wire [17:0] mb = mb_s[17:0];

always @(posedge clk or posedge rst) begin
    if (rst) begin
        pix       <= 32'h0000_0000;
        out_valid <= 1'b0;
    end else if (ce) begin
        // 权重和恒 256 ⇒ 加权和 ≤ 255*256 = 65280（16 位），>>8 取 [15:8]
        pix       <= {8'hFF, mr[15:8], mg[15:8], mb[15:8]};
        out_valid <= v1_r & v2_r;
    end
end

endmodule
