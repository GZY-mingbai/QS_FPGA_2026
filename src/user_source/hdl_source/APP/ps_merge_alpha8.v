//==============================================================================
//  ps_merge_alpha8.v —— 8 位透明度合并器（过渡动画用）
//==============================================================================
//
//      s1 (前景，通常 = 新图 B) ─┐
//                                ├─► [ ps_merge_alpha8 ] ─► pix
//      s2 (背景，通常 = 旧图 A) ─┘          ▲
//                                          alpha
//
//  【为什么不用旧的 ps_merge_alpha】
//  旧版只有 4 位 alpha（0~8，共 9 级）。60fps 下 0.5s 的淡入淡出有 32 帧，
//  9 级意味着每 3~4 帧才跳一格 —— 肉眼能看出"台阶"。这里用 8 位（256 级），
//  32 帧每帧 8 级，过渡是连续的。
//
//  【混合公式（带 256 归一化）】
//      a9 = (alpha == 255) ? 256 : alpha      // 9 位，让"全不透明"精确等于前景
//      out = (s1 * a9 + s2 * (256 - a9)) >> 8
//
//  【为什么用 256 而不是 255】
//  255*255 右移 8 位是 254，全不透明时会丢 1 个 LSB（纯白变成 FE）。
//  取 a9 ∈ [0,256]、权重和恒为 256，右移 8 位就是精确的 1.0/0.0。
//  乘积最大 255*256 = 65280 < 65536 ⇒ 16 位够，零 DSP（综合成 LUT 乘法）。
//
//  【透明区怎么办】
//  图层在框外输出 32'h00000000。此时不能参与混合（会把背景冲淡），
//  直接把有效 alpha 压成 0 ⇒ 输出完全等于背景。
//
//  【延迟 = 1 拍】
//
//==============================================================================

module ps_merge_alpha8 (
    input  wire        clk,
    input  wire        rst,
    input  wire        ce,              // 流水线推进使能（= pixel_ready）

    input  wire [31:0] s1_pix,          // 前景 {A,R,G,B}
    input  wire        s1_valid,
    input  wire [31:0] s2_pix,          // 背景 {A,R,G,B}
    input  wire        s2_valid,

    input  wire [7:0]  alpha,           // 前景不透明度 0~255

    output reg  [31:0] pix,
    output reg         out_valid
);

//------------------------------------------------------------------------------
//  有效权重（9 位）：前景透明 ⇒ 0；alpha=255 ⇒ 256（精确不透明）
//------------------------------------------------------------------------------
//  ★ 2026-10-23：**回退"按 valid 门控"**。
//    上一版写成 `p2 = s2_valid ? s2_pix : 0`，结果 HD 页出现**竖直条纹**：
//    HD 层的 `out_valid` 走的是 `img_layer_hd` 里独立的一条有效延迟链
//    （`v1/v2/v3`，与 `p1/p2/p3` 数据链分开），只要两者差一拍，
//    背景就被周期性地清零 ⇒ 一列黑一列图 = 竖条。
//    原来"无条件相信数据"的写法反而稳：图层在框外已经把像素清成 0 了
//    （`pix_raw <= !s2_valid ? 0 : ...`），alpha 字节自然为 0 ⇒ 自动透明。
//------------------------------------------------------------------------------
wire        s1_opaque = (s1_pix[31:24] != 8'd0);
wire [8:0]  a9 = s1_opaque ? ((alpha == 8'd255) ? 9'd256 : {1'b0, alpha}) : 9'd0;
wire [8:0]  i9 = 9'd256 - a9;

//------------------------------------------------------------------------------
//  三通道混合
//------------------------------------------------------------------------------
wire [15:0] mr = s1_pix[23:16] * a9 + s2_pix[23:16] * i9;
wire [15:0] mg = s1_pix[15:8]  * a9 + s2_pix[15:8]  * i9;
wire [15:0] mb = s1_pix[7:0]   * a9 + s2_pix[7:0]   * i9;

always @(posedge clk or posedge rst) begin
    if (rst) begin
        pix       <= 32'h0000_0000;
        out_valid <= 1'b0;
    end else if (ce) begin
        pix       <= {8'hFF, mr[15:8], mg[15:8], mb[15:8]};
        out_valid <= s1_valid & s2_valid;
    end
end

endmodule
