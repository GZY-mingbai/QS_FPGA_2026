//==============================================================================
//  quad_sel.v —— 四宫格坐标适配器（屏幕坐标 → 局部坐标 + 槽基址）
//==============================================================================
//
//  【它在整条链路的哪一环】
//
//      屏幕扫描 (sx,sy)
//          │
//          ▼
//      ┌───────────┐   (lx, ly, base)
//      │ quad_sel  │───────────────► img_layer_ctrl ──► ps_gen_image ──► 像素
//      └───────────┘
//
//  `ps_gen_image` 以为自己在画"一张 160×120 的小图放在 (0,0)"，
//  完全不知道屏幕上有 4 个格子。这样它那一整套预取 / FIFO / 缩放 /
//  包围盒逻辑**一行都不用改**。
//
//  【为什么不在 ps_gen_image 内部改】
//  它是显示链路核心，相册页、高清通路都靠它。改错整个画面没了。
//  放在外层做接口适配，最坏情况把 QUAD_MODE 关掉就回退。
//
//  【为什么一个引擎能画 4 张图】
//  扫描是逐像素的，同一时刻只有一个像素，它只属于一个格子。
//  所以不需要 4 套并行通路，只需要"按当前坐标选对基址"。
//
//  【布局】
//
//      x=208      368 384      544
//        ├──────────┤16├──────────┤
//   y=100├── 格0 ───┤  ├── 格1 ───┤
//   y=220├──────────┴──┴──────────┤
//   y=260├── 格2 ───┤  ├── 格3 ───┤
//   y=380├──────────┴──┴──────────┤
//
//  格子 160×120，列间距 **16**（= 176-160），行间距 40（= 160-120）。
//  名字画在行间距里，所以行距比列距大。
//  这两组数字与 doc/osd_file_page_proto.html 里的 2×2 网格完全一致
//  （原型：left 208 / column-gap 16px / row 高 160）。
//
//  【SDRAM 槽为什么按 2^14 对齐】
//  160×120 565 实际只用 9600 字，按 16384 分配浪费 41%，
//  但换来 `base = SLOT + (region << 14)` —— 纯移位，0 个 LUT 的乘法。
//  SDRAM 空闲 859K 字，这点浪费完全值得。
//
//==============================================================================

module quad_sel #(
    //--------------------------------------------------------------------------
    //  布局（640×480 屏幕）
    //--------------------------------------------------------------------------
    parameter [9:0]  X0        = 10'd208,      // 左列起点
    parameter [9:0]  Y0        = 10'd100,      // 上排起点
    parameter [9:0]  COL_PITCH = 10'd176,      // 列距（160 格宽 + 16 间距）
    parameter [9:0]  ROW_PITCH = 10'd160,      // 行距
    parameter [9:0]  CW        = 10'd160,      // 格子宽
    parameter [9:0]  CH        = 10'd120,      // 格子高
    //--------------------------------------------------------------------------
    //  SDRAM 槽
    //--------------------------------------------------------------------------
    parameter [20:0] SLOT_BASE = 21'd0,        // 槽 0 基址
    parameter integer SLOT_SHIFT = 14          // 槽间距 = 2^14 = 16384 字
)(
    input  wire [9:0]  I_x,                    // 屏幕 x
    input  wire [9:0]  I_y,                    // 屏幕 y
    input  wire        I_en,                   // 1 = 四宫格模式

    output wire [9:0]  O_x,                    // 局部 x（0..159）
    output wire [9:0]  O_y,                    // 局部 y（0..119）
    output wire [20:0] O_base,                 // 该格的 SDRAM 基址
    output wire        O_in,                   // 1 = 落在某个格子里
    output wire [1:0]  O_region                // {row, col}
);

//==============================================================================
//  边界（常量，综合时全部折叠）
//==============================================================================
localparam [9:0] X1 = X0 + COL_PITCH;          // 384
localparam [9:0] X2 = X1 + CW;                 // 544（右边界，开区间）
localparam [9:0] Y1 = Y0 + ROW_PITCH;          // 260
localparam [9:0] Y2 = Y1 + CH;                 // 380

wire in_xl = (I_x >= X0) && (I_x < X0 + CW);   // 208..367
wire in_xr = (I_x >= X1) && (I_x < X2);        // 384..543
wire in_yt = (I_y >= Y0) && (I_y < Y0 + CH);   // 100..219
wire in_yb = (I_y >= Y1) && (I_y < Y2);        // 260..379

wire col = in_xr;
wire row = in_yb;

assign O_region = {row, col};
assign O_in     = I_en && (in_xl || in_xr) && (in_yt || in_yb);

//==============================================================================
//  局部坐标
//==============================================================================
//  不在格子内时 lx/ly 会落在 160..511 区间，超出 cfg_size(160×120) 的包围盒，
//  ps_gen_image 自然输出透明 —— 不需要额外门控。
//==============================================================================
wire [9:0] x_org = col ? X1 : X0;
wire [9:0] y_org = row ? Y1 : Y0;

assign O_x = I_x - x_org;
assign O_y = I_y - y_org;

//==============================================================================
//  基址：SLOT_BASE + (region << SLOT_SHIFT)
//==============================================================================
assign O_base = SLOT_BASE + ({19'd0, O_region} << SLOT_SHIFT);

endmodule
