//==============================================================================
//  ps_merge_alpha.v —— 像素源合并器：透明度叠加（半透明）
//==============================================================================
//
//      s1 (前景) ─┐
//                 ├─► [ ps_merge_alpha ] ─► pix
//      s2 (背景) ─┘        ▲
//                        alpha
//
//  【混合公式】
//
//      设前景不透明度 A（0~8），则：
//
//          out = (s1 * A + s2 * (8 - A)) / 8
//
//      A = 8  →  完全是前景（不透明）
//      A = 4  →  前景背景各一半（半透明）
//      A = 0  →  完全是背景（全透明）
//
//  【★ 为什么用"除以 8"而不是"除以 255" ★】
//  除以 8 就是右移 3 位——**一个移位器，零成本**。
//  如果按 0~255 的 alpha 做 (s1*a + s2*(255-a))/255，就要除以 255，
//  要么引入除法器、要么加一堆近似修正。取 8 级（0~8）既够用（人眼分辨不出
//  9 级透明度的差别），又完全免费。这就是"4 位 alpha 移位版"的含义。
//
//  【★ alpha 是运行时输入 ★】
//  改成输入后成本**完全不变**（还是那几个 8×4 小乘法），但动画就能做淡入淡出了。
//
//  【★ 前景透明处怎么办 ★】
//  s1 在图形外是 32'h00000000。这时候不能做混合（否则透明区会把背景"冲淡"），
//  而是直接透传背景。所以先看 s1 的 alpha：为 0 → 有效 alpha 取 0（= 全透）。
//
//  【延迟 = 1 拍】 【资源】6 个 8×4 小乘法，综合器用 LUT 实现，零 DSP。
//
//==============================================================================

module ps_merge_alpha (
    input  wire        clk,
    input  wire        rst,

    input  wire [31:0] s1_pix,          // 前景像素
    input  wire        s1_valid,
    input  wire [31:0] s2_pix,          // 背景像素
    input  wire        s2_valid,

    input  wire [3:0]  alpha,           // 前景不透明度 0~8（运行时输入）

    output reg  [31:0] pix,             // 混合结果
    output reg         out_valid
);

//------------------------------------------------------------------------------
//  有效不透明度
//------------------------------------------------------------------------------
// 前景透明（alpha=0）→ 有效 alpha = 0 → 输出完全等于背景
wire [3:0] a_eff = (s1_pix[31:24] != 8'd0) ? alpha : 4'd0;
wire [3:0] i_eff = 4'd8 - a_eff;       // 背景保留比例

//------------------------------------------------------------------------------
//  三通道混合（纯组合）
//------------------------------------------------------------------------------
// 最大值 = 255*8 = 2040（11 位），右移 3 位正好落回 0~255。
wire [11:0] mr = s1_pix[23:16] * a_eff + s2_pix[23:16] * i_eff;
wire [11:0] mg = s1_pix[15:8]  * a_eff + s2_pix[15:8]  * i_eff;
wire [11:0] mb = s1_pix[7:0]   * a_eff + s2_pix[7:0]   * i_eff;

always @(posedge clk or posedge rst) begin
    if (rst) begin
        pix       <= 32'h0000_0000;
        out_valid <= 1'b0;
    end else begin
        // 混合后的结果一定是不透明的，alpha 固定给 FF
        pix       <= {8'hFF, mr[10:3], mg[10:3], mb[10:3]};
        out_valid <= s1_valid & s2_valid;
    end
end

endmodule
