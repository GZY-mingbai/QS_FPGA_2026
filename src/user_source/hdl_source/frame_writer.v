//==============================================================================
//  frame_writer.v —— 应用层：往屏幕写一帧的时序控制器
//==============================================================================
//
//  ★★★ 给 C 语言背景的人看的 Verilog 入门 ★★★
//
//  你写 C 的时候，脑子里是「CPU 一条一条执行语句」。Verilog 完全不是这个模型。
//  Verilog 描述的是**一块电路**：里面所有的东西**同时**在工作，没有"执行顺序"这回事。
//
//  下面是几个最容易踩的坑，先看一遍再读代码，会顺很多：
//
//  ┌────────────────────┬──────────────────────┬──────────────────────────────┐
//  │ Verilog            │ C 里像什么            │ 但根本区别在哪                │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ module / endmodule │ struct + 一组函数     │ 端口是**物理导线**，一直连着， │
//  │                    │                      │ 不是调用时把值拷进去           │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ input / output     │ 函数参数 / 返回值     │ 只是"这根线往哪边流"           │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ wire               │ 一根导线             │ 自己存不住值，必须被某个东西驱动│
//  │                    │                      │ （用 assign 或模块的输出口）    │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ reg                │ 一个变量             │ 名字骗人！它**不是**寄存器。   │
//  │                    │                      │ 在 always @(posedge clk) 里赋值 │
//  │                    │                      │ → 综合成 D 触发器（能存住值）   │
//  │                    │                      │ 在 always @(*) 里赋值          │
//  │                    │                      │ → 综合成组合逻辑（存不住值）    │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ always @(posedge   │ 一个每 10ns 自动      │ 所有 always 块**同时**跑，     │
//  │        clk)        │ 醒一次的线程          │ 不存在"谁先谁后"               │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ <= 非阻塞赋值       │ （C 里没有对应的）     │ 见下面「最重要的一节」         │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ =  阻塞赋值         │ a = b;               │ 立即生效。只用在组合逻辑里      │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ for (...)          │ 循环                 │ **不是运行时循环**！编译期展开。│
//  │                    │                      │ 循环 4 次 = 复制出 4 份硬件     │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ {a, b, c}          │ （没有）             │ 位拼接：把几个信号接成一根宽的  │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ a[7:0]             │ （不是数组下标）      │ 位范围：取第 7 位到第 0 位      │
//  ├────────────────────┼──────────────────────┼──────────────────────────────┤
//  │ if / case          │ 一样                 │ 但综合出来是**硬件选择器**，    │
//  │                    │                      │ 两个分支都得有电路，不是跳转    │
//  └────────────────────┴──────────────────────┴──────────────────────────────┘
//
//  ─────────────────────────────────────────────────────────────────────────────
//  【最重要的一节】为什么到处都在写 <= 而不是 =
//  ─────────────────────────────────────────────────────────────────────────────
//
//  先看一个 C 程序员的直觉写法，它是**错的**：
//
//      a = 1;
//      b = a;      // 你会以为 b 得到 1
//
//  在 Verilog 里如果你写成阻塞赋值，确实 b 会是 1（因为 = 是立即生效的）。
//  但如果你写的是两个独立的 always 块：
//
//      always @(posedge clk) a <= 1;
//      always @(posedge clk) b <= a;
//
//  那么 b 得到的是 a **上一拍**的值，不是这一拍刚写进去的 1。
//
//  为什么？因为硬件是这样的：每个触发器（D 触发器）在时钟沿到来时，
//  把「输入端的当前值」采样到「输出端」。所有触发器**同时**采样。
//  采样用的都是"时钟沿到来之前那一瞬间"的输入值。
//
//  用 C 打比方，相当于：
//
//      // 时钟沿来了，先给所有变量拍个快照
//      snapshot_a = a;   snapshot_b = b;   ...
//      // 然后所有赋值都用快照里的值来算
//      a = 1;
//      b = snapshot_a;   // ← 用的是旧值，不是刚写的 1
//
//  这就是 <=（非阻塞赋值）的含义：**"先记下来，等这一拍所有块都算完了再一起生效"**。
//
//  规矩（照做就行，别问为什么，先习惯）：
//    · 在 always @(posedge clk) 里，**一律用 <=**
//    · 在 always @(*) 里（组合逻辑），**一律用 =**
//    · 不要混用
//
//  ─────────────────────────────────────────────────────────────────────────────
//  【第二个坎】这不是"程序"，是"电路"
//  ─────────────────────────────────────────────────────────────────────────────
//
//  你写 `if (state == S_IDLE) ... else ...`，C 里是"满足条件就跳过去执行那一块"。
//  Verilog 里是"搭一个选择器：state 等于 S_IDLE 时选 A 路的输出，否则选 B 路"。
//  两条路**的电路都存在**，只是输出被选哪一条而已。
//
//  同理 `for (pi = 1; pi < PIPE; pi = pi+1)` 不是循环，是"照这个样子复制 PIPE-1 份"。
//  写 `for` 只是省得你手写 PIPE-1 行代码。
//
//  ─────────────────────────────────────────────────────────────────────────────
//  【这个模块干什么】用 C 语言的方式说
//  ─────────────────────────────────────────────────────────────────────────────
//
//  它是"应用层"：负责把一帧画面送上屏幕。但它**不产生像素** ——
//  像素由外部的"像素源"提供（本工程里是 tf_bmp_pixel_source，从 TF 卡读 BMP）。
//
//  职责划分：
//
//      frame_writer（本模块）  = 怎么把一帧"送上去"
//          · 和显存控制器握手（write_req / ack）
//          · 把像素源给的像素按顺序写出去（write_en / write_data）
//          · 管双缓冲指针（写哪块 / 显示哪块）
//          · 整帧写完才切显示（避免撕裂）
//
//      tf_bmp_pixel_source     = 像素"从哪来"
//          · 上电扫描 TF 卡、解析 BMP、响应按键
//          · 输出 ps_data / ps_valid（一个像素一拍）
//
//  两者用一组很简单的信号对接（见下面"像素源接口"）。
//  换成摄像头、测试图案、运算结果，只要按同样的接口产像素，本模块一行都不用改。
//
//  ─────────────────────────────────────────────────────────────────────────────
//  【一次完整的"画一帧"是怎么走的】
//  ─────────────────────────────────────────────────────────────────────────────
//
//      ① 像素源说"我有新的一帧要画"          → ps_new_frame 来一个脉冲
//      ② 本模块发起写请求                     → write_req = 1
//      ③ 显存控制器应答                       → write_req_ack 变 1
//      ④ 本模块撤销请求                       → write_req = 0
//      ⑤ ★等应答也落下去★                     → 这期间下游在清 FIFO，不能发数据
//      ⑥ 本模块通知像素源"开始给数据"          → ps_start 变 1
//      ⑦ 像素源一个像素一拍地给                → ps_valid / ps_data
//      ⑧ 本模块转手写出去                     → write_en / write_data
//      ⑨ 收满 307200 个                       → ps_start = 0，等回执
//      ⑩ 显存说"整帧真的落盘了"               → write_finish_pulse
//      ⑪ ★提交★                              → disp_buf_idx 切过去，屏幕换画面
//
//  ─────────────────────────────────────────────────────────────────────────────
//  【★ 两个必须遵守的时序细节 ★】
//  ─────────────────────────────────────────────────────────────────────────────
//
//  ① 必须等 ack 落下才能让像素源开始给数据。
//     下游 frame_fifo_write 在应答期间会拉高 fifo_aclr 清空写 FIFO。
//     这个窗口里灌进去的数据会被直接冲掉。所以流程必须是：
//         write_req ↑ → 等 ack ↑ → 撤销 write_req → 等 ack ↓ → 才能开始灌数据
//
//  ② 必须等 write_finish_pulse 才能切 disp_buf_idx。
//     write_en 发完只代表数据进了 FIFO，还没落进 SDRAM。
//     这时候切显示会看到"半张新图 + 半张旧图"，俗称撕裂。
//
//  ─────────────────────────────────────────────────────────────────────────────
//  【PIPE 参数怎么设】
//  ─────────────────────────────────────────────────────────────────────────────
//
//  PIPE = 从 ps_data 到 write_data 中间隔了几拍（也就是像素处理链的延迟）。
//      · 像素直通，不做任何处理                      → PIPE = 0
//      · 中间插了一级寄存器                          → PIPE = 1
//      · 中间插了 overlay_layer（固定 2 拍）          → PIPE = 2
//
//  设对了，write_en 和 write_data 自动对齐，一个像素都不会错位。
//
//  ─────────────────────────────────────────────────────────────────────────────
//  【建议的阅读顺序】
//  ─────────────────────────────────────────────────────────────────────────────
//
//  ① 端口列表（module 到 ); 之间）—— 先知道有哪些线进出
//  ② 第 1 节：跨时钟域同步 —— 讲清楚 ack_rise / ack_fall 是怎么来的
//  ③ 第 2 节：双缓冲决策 —— 讲清楚"写哪块"
//  ④ 第 3 节：输出延迟链 —— 讲清楚 PIPE 是干什么的
//  ⑤ 第 4 节：主状态机 —— 核心，对着上面「一次完整的画一帧」看
//
//==============================================================================

module frame_writer #(
    //==========================================================================
    //  #( ... ) 里的东西叫 parameter，相当于 C 的 #define 或 const int，
    //  但是可以在例化的时候被覆盖（像函数的默认参数）。
    //  `integer` 表示这是个整数常量（32 位有符号），不是硬件信号。
    //==========================================================================
    parameter integer IMG_W = 640,             // 画面宽
    parameter integer IMG_H = 480,             // 画面高
    parameter integer NPX   = IMG_W * IMG_H,   // 总像素数 = 307200
    parameter integer PIPE  = 0                // 像素处理链的延迟拍数（见文件头）
)(
    //==========================================================================
    //  端口列表：这些是模块对外的"引脚"，每一条都是一根实际的导线
    //
    //    input  = 信号从外面流进来（你只能读它）
    //    output = 信号从这里流出去（你只能写它）
    //
    //  注意方向是"从本模块的视角看"：
    //    write_req 是 output，因为是本模块主动拉高的
    //    write_req_ack 是 input，因为是下游拉高的
    //==========================================================================

    input  wire        clk,              // 时钟。50 MHz，也就是每 20ns 一个上升沿
                                         // 它是整个模块的"心跳"，所有 always 块都靠它驱动
    input  wire        rst,              // 复位。高电平有效（=1 时把一切清零）

    //--------------------------------------------------------------------------
    //  像素源接口（谁来提供像素）
    //--------------------------------------------------------------------------
    output wire        ps_start,         // 本模块说："开始给这一帧的数据"
                                         // 拉高时机 = 写握手做完之后（第 ⑥ 步）
    input  wire        ps_new_frame,     // 像素源说："我有新的一帧要画"（1 拍脉冲）
                                         // 相当于"按键按下"或"该轮播下一张了"
    input  wire [23:0] ps_data,          // 像素数据 {R, G, B}
    input  wire        ps_valid,         // 这个像素有效（和 ps_data 必须同拍）
                                         // 像素源什么时候给数据由它自己决定
                                         // （TF 卡读得慢就慢点给，本模块会等）
    input  wire        pipe_ce,          // 像素流水线推进使能；低时延迟链保持

    //--------------------------------------------------------------------------
    //  写通道（接显存控制器 frame_read_write 的写侧）
    //--------------------------------------------------------------------------
    output reg         write_req,        // 写请求。本模块拉高它，表示"我要写一帧"
                                         // 注意是 reg 而不是 wire —— 因为在
                                         // always @(posedge clk) 里给它赋值，它得能存住值
    output reg  [1:0]  write_buf_idx,    // 写哪块缓冲（0 = BUF0，1 = BUF1）
    output reg  [20:0] write_len,        // 一帧多少个像素。21 位宽，最大 2097151
                                         // 307200 用 19 位就够，多留几位不碍事
    input  wire        write_req_ack,    // 下游的应答："我准备好了，你可以发数据了"
    output wire        write_en,         // 写使能。每写一个像素就拉高一拍，一帧共 307200 拍
                                         // 是 wire 不是 reg，因为由 assign 驱动（见第 3 节）
    output wire [31:0] write_data,       // 像素数据。32 位 = {R, G, B, 8'b0}

    //--------------------------------------------------------------------------
    //  整帧写完回执
    //--------------------------------------------------------------------------
    input  wire        write_finish_pulse, // 下游说"整帧真的写进 SDRAM 了"
                                           // 注意是 pulse（脉冲），只高 1 拍
                                           // 它从 125 MHz 域同步过来，见 top 里的实现

    //--------------------------------------------------------------------------
    //  提交上屏
    //--------------------------------------------------------------------------
    output reg  [1:0]  disp_buf_idx,     // 显示指针。告诉显示端"现在看哪块缓冲"
                                         // ★ 这一根线就是"上屏"这个动作本身
                                         // ★ 但显示端不再"看到就切"，而是等自己的
                                         //   场边界（vs 下降沿）才采纳 —— 见下面握手
    output reg         display_valid,    // 首图就绪标志。0 = 强制黑屏，1 = 显示真实内容
    // ★ 2026-10-24 诊断：本帧**实际写入的像素数**与 307200 的差
    //   [3:0]=差值（0 = 完美）；[4]=有差异
    //   用来判断"图层 → frame_writer 的一拍握手"是否丢/多了像素。
    output wire [4:0]  px_dbg,
    // ★ 2026-10-24 串口探针：一条 64 位 = 一个像素的上下文
    //   {px[15:0], py[15:0], ps_data[23:0], {take, ps_valid, write_en, pipe_ce, 4'h0}}
    output wire [63:0] fw_smp,
    output wire        fw_win,

    //--------------------------------------------------------------------------
    //  ★ 场同步换页握手（修"边写边显示"造成的滚动横缝/撕裂）★
    //--------------------------------------------------------------------------
    //  【为什么要加这一对信号】
    //  写口 = 16 字/64 拍 = 0.25 字/mem 拍 = 31.25 M 字/s ⇒ 一帧只要 9.83ms
    //  而显示读一帧要 16.7ms。写比读快 1.7 倍，于是写指针转一圈又回来重写
    //  "屏幕正在读"的那一块 ⇒ 屏幕上出现一条从下往上滚动的横缝，缝两侧是
    //  同一动画的两个不同时刻（图形在两处同时出现）。这就是撕裂（tearing）。
    //
    //  【修法：标准双缓冲 + 场同步换页】（每帧一次翻转电平，天然适合跨时钟域）
    //    写侧：整帧写完 → disp_buf_idx 切到新块、并翻转 disp_commit_tgl
    //    显示侧：在**自己的场边界**看到 commit 变了，才把读指针切过去，
    //            并翻转 disp_adopt_tgl 回告"我已经换过去了"
    //    写侧：只有当 disp_adopt 追平 disp_commit 时才允许开下一帧
    //  ⇒ 写侧被节流到 ≤ 显示帧率，**永远不碰显示正在读的那块**。
    //--------------------------------------------------------------------------
    output reg         disp_commit_tgl,  // 每提交一帧翻转一次（写 → 显示，top 里同步）
    input  wire        disp_adopt,       // 显示侧"已换页"的翻转电平（top 里同步好）

    //--------------------------------------------------------------------------
    //  状态
    //--------------------------------------------------------------------------
    output reg         busy,             // 正在画一帧（画完了变 0）
    output reg         done,             // 画完了。1 拍脉冲
    //------------------------------------------------------------------
    //  ★ 上板定位口（不参与功能）★
    //                —— 这拍脉冲是"1 拍宽"的，错过就永远错过，
    //                   于是 frame_writer 会永久卡在 S_WAIT、
    //                   display_valid 永不为 1、整屏黑（数码管 b）。
    //------------------------------------------------------------------

    //--------------------------------------------------------------------------
    //  当前像素的屏幕坐标（给可选的运算/叠加层用）
    //--------------------------------------------------------------------------
    output reg  [15:0] px_x,             // 正在写哪个像素：列（0 ~ 639）
    output reg  [15:0] px_y,             // 正在写哪个像素：行（0 = 屏幕最上面一行）
                                         // ★ 是屏幕坐标，不是"输入流行号"，换算见第 2 节
    output wire [15:0] out_x,            // 和 write_data 完全同步的坐标
    output wire [15:0] out_y             // （px_x/px_y 比 write_data 早 PIPE 拍）
);

//==============================================================================
//  第 0 节：常量定义
//==============================================================================
// localparam 和 parameter 差不多，区别是 localparam 不能被例化时覆盖。
// 用 localparam 是告诉别人"这是内部用的，别改"。
//
// 3'd0 这种写法叫"带位宽的常量"：3 表示 3 位宽，d 表示十进制。
// 其它进制：4'b1010（二进制）、8'hFF（十六进制）、5'o17（八进制）。
// 为什么要写位宽？因为 Verilog 的位宽推断规则很坑，写清楚最保险。
//==============================================================================

localparam S_IDLE   = 3'd0;   // 空闲，等像素源的"要画一帧"请求
localparam S_REQ    = 3'd1;   // write_req 拉高，等 ack 上升
localparam S_ACK    = 3'd2;   // 撤销 req，等 ack 落下（清 FIFO 窗口）
localparam S_STREAM = 3'd3;   // 收 307200 个像素并转手写出去
localparam S_WAIT   = 3'd4;   // 等整帧真正落进 SDRAM

//==============================================================================
//  第 0 节续：内部信号声明
//==============================================================================
// reg  = 需要"存住值"的东西（在 always @(posedge clk) 里赋值的）
// wire = 一根线，值随输入实时变化（用 assign 或模块输出驱动的）
//
// 为什么 state 用 3 位？因为状态编号是 0~4，2 位不够（只能表示 0~3），
// 3 位能表示 0~7，够用。综合器实际会优化，多写一位不要钱。
//==============================================================================

reg [2:0]  state;      // 当前状态（存住值的，所以是 reg）
reg [18:0] cnt;        // 已经收了多少个像素。19 位宽，最大 524287，够装 307200
reg        req_latch;  // "像素源请求画一帧"的暂存位
                       // 【为什么需要它】如果请求来的时候本模块正忙（比如还在
                       // 等上一帧的回执），不能把这个请求丢掉，先记下来。

//==============================================================================
//  第 1 节：跨时钟域同步（把 ack 从 125 MHz 域搬到 50 MHz 域）
//==============================================================================
//
//  【为什么需要这一节】这是个 C 里完全不存在的问题。
//
//  write_req_ack 是下游在 125 MHz 时钟域产生的（每 8ns 变一次）。
//  而本模块跑在 50 MHz（每 20ns 变一次）。
//  两个时钟频率不同、相位毫无关系 —— 这叫"异步时钟域"。
//
//  如果直接拿 125 MHz 的信号到 50 MHz 域里用，会有"亚稳态"风险：
//  想象你在拍一张快速旋转的风扇照片，快门刚好在扇叶边缘时按下，
//  照片上会出现半透明的一团 —— 数字电路里这就是"电压处于 0 和 1 之间的
//  不稳定状态"，后续逻辑拿到它可能算出完全随机的结果。
//
//  标准解法：打两拍（用两个触发器串联），让第一级去"承担风险"，
//  第二级采到的就是稳定值了。这里打了三拍，是为了能安全地做"边沿检测"。
//
//  【下面这行代码在 C 里长什么样】
//
//      ack_sync <= {ack_sync[1:0], write_req_ack};
//
//  等价于 C：
//
//      ack_sync[2] = ack_sync[1];       // 旧值往上挪
//      ack_sync[1] = ack_sync[0];
//      ack_sync[0] = write_req_ack;     // 新值从最低位进来
//
//  {a, b} 是"位拼接"：把 ack_sync[1:0]（2 位）和 write_req_ack（1 位）
//  拼成 3 位，再赋回 ack_sync。整体效果就是左移一位、最低位填新输入。
//
//  这就是个"移位寄存器"，是 Verilog 里最常用的写法之一。
//
//==============================================================================

reg [2:0] ack_sync;    // 3 级同步链。ack_sync[0] 最新，ack_sync[2] 最旧

//------------------------------------------------------------------------------
//  always @(posedge clk or posedge rst)
//
//  逐字拆解：
//    always @(...)          —— "每当括号里的事件发生，就把下面这块跑一遍"
//    posedge clk            —— clk 出现上升沿（0 变 1）时
//    or posedge rst         —— 或者 rst 出现上升沿（也就是按下复位）时
//
//  相当于 C 里注册了一个中断处理函数：
//    on_interrupt(RISING_EDGE_OF(clk) OR RISING_EDGE_OF(rst)) { ... }
//
//  注意：这不是循环！是"事件驱动"。没有时钟沿的时候，这块代码根本不执行。
//
//  ★ 为什么复位要放在敏感列表里、并且用 if (rst) 单独处理？
//    因为复位必须是"立刻生效"的（异步复位），不能等下一个时钟沿。
//    这是硬件设计的惯例，综合工具看到这个模式就知道要生成异步复位的触发器。
//------------------------------------------------------------------------------
always @(posedge clk or posedge rst) begin
    if (rst) begin
        // 复位时把同步链清零
        ack_sync <= 3'b000;
    end else begin
        // 正常工作时，每拍把新输入挤进最低位，老值往高位推
        ack_sync <= {ack_sync[1:0], write_req_ack};
    end
end

//------------------------------------------------------------------------------
//  assign = 连续赋值 = "这根线永远等于右边这个表达式"
//
//  和 C 的赋值完全不同：C 的 a = b 是"执行一次"，assign 是"永远保持相等"。
//  右边任何一个信号变了，左边立刻跟着变（没有延迟，就是一根线）。
//
//  & = 按位与    ~ = 按位取反    | = 按位或    ^ = 按位异或
//  逻辑与用 &&，逻辑或用 ||（和 C 一样）
//
//  这里的写法是"边沿检测"：比较相邻两级同步器的值，找出变化的那一拍。
//
//      ack_sync[2]  ack_sync[1]    含义
//      -----------  -----------    ------------------
//           0            0         一直没应答
//           0            1         ★刚变成应答（上升沿）
//           1            1         应答一直保持
//           1            0         ★应答刚撤销（下降沿）
//
//  所以 ack_rise 只在"应答刚来的那一拍"为 1，ack_fall 只在"应答刚走的那一拍"为 1。
//  都是 1 拍宽的脉冲。
//------------------------------------------------------------------------------
wire ack_rise =  ack_sync[1] & ~ack_sync[2];   // 应答刚来（1 拍脉冲）
wire ack_fall = ~ack_sync[1] &  ack_sync[2];   // 应答刚走（1 拍脉冲）

//==============================================================================
//  第 2 节：双缓冲决策 + 坐标维护
//==============================================================================

//------------------------------------------------------------------------------
//  "这一帧该写到哪块缓冲？"
//
//  规则很简单：**总写"不是正在显示"的那一块**。
//
//      display_valid = 0（还没有任何一帧上屏）
//          → 写 BUF0（第一帧无所谓，随便挑一块）
//      disp_buf_idx = 0（正在显示 BUF0）
//          → 写 BUF1
//      disp_buf_idx = 1（正在显示 BUF1）
//          → 写 BUF0
//
//  这样你写新图的时候，屏幕正在读另一块，互不干扰。
//  整帧写完了再把 disp_buf_idx 切过去，画面就换了。
//
//  三元运算符 ? : 和 C 完全一样。
//------------------------------------------------------------------------------
wire [1:0] next_buf = display_valid ? (disp_buf_idx == 2'd0 ? 2'd1 : 2'd0)
                                    : 2'd0;

//------------------------------------------------------------------------------
//  ★ 场同步换页：写侧必须等显示侧"换过去"了才允许开下一帧 ★
//
//  disp_commit_tgl 是本模块的提交号（每写完一帧翻一次）；
//  disp_adopt     是显示侧的采纳号（top 里同步过来的）。
//      两者相等 ⇒ 显示侧已经采纳了我上一帧提交的画面，正在读的那块
//                 已经不是我要写的那块 ⇒ 可以安全开新帧。
//      两者不等 ⇒ 显示侧还在看我刚写完/还没换过去的那块 ⇒ 等。
//
//  这一等就把写侧节流到 ≤ 显示帧率（60fps），从根上消灭撕裂。
//------------------------------------------------------------------------------
wire buf_free = (disp_commit_tgl == disp_adopt);

//------------------------------------------------------------------------------
//  "本拍是不是要取走一个像素？"
//
//  两个条件同时成立才算：
//      state == S_STREAM  → 本模块处在"收数据"状态
//      ps_valid           → 像素源这一拍确实给了一个有效像素
//      pipe_ce            → 整条像素流水线本拍确实推进
//
//  这就是"流控"：像素源给得快就写得快，给得慢就等着。
//  对 TF 卡这种"读一个扇区要几十微秒、然后一次性吐 512 字节"的突发型数据源，
//  这个机制是必须的。
//------------------------------------------------------------------------------
wire take = (state == S_STREAM) & ps_valid & pipe_ce;

//==============================================================================
//  ★★ 2026-10-24：本帧写入像素数探针 ★★
//==============================================================================
//  【为什么】到目前为止：图层事件全清、写地址行走精确 480 次/帧、
//    读侧线性无行走。三段都干净，那么"行内平移"只能发生在
//    **接受像素的那一拍**：`ps_valid` 与 `ps_data` 相位不对 ⇒
//    帧缓存里多收/少收一个像素 ⇒ 该行后面整体平移。
//    而 `push−pop` 计数**照样配平**（它数的是字，不是写入的像素）。
//  【正常值】307200。差 0 ⇒ 握手完美；差 1 ⇒ 就是它。
//==============================================================================
reg  [18:0] px_cnt, px_snap;
reg         in_stream_d;

always @(posedge clk or posedge rst) begin
    if (rst) begin
        px_cnt      <= 19'd0;
        px_snap     <= 19'd0;
        in_stream_d <= 1'b0;
    end else begin
        in_stream_d <= (state == S_STREAM);
        if (take) px_cnt <= px_cnt + 19'd1;
        if (in_stream_d && (state != S_STREAM)) begin
            px_snap <= px_cnt;          // 本帧快照
            px_cnt  <= 19'd0;
        end
    end
end

wire [18:0] px_err = (px_snap >= 19'd307200) ? (px_snap - 19'd307200)
                                             : (19'd307200 - px_snap);
assign px_dbg = { (px_err != 19'd0),
                  (px_err >= 19'd15) ? 4'd15 : px_err[3:0] };

//------------------------------------------------------------------------------
//  坐标维护
//
//  【为什么要维护坐标】给可选的运算/叠加层用。叠加层需要知道"现在这个像素
//  在屏幕的哪个位置"，才能决定要不要盖上东西。
//
//  ★ 坐标与行的对应关系（最容易搞错的地方）
//
//  写帧时数据是按顺序灌进去的，但 frame_fifo_write 会做行翻转：
//      「输入流第 r 行」被写到「内存第 H-1-r 行」
//  而内存第 s 行就是屏幕第 s 行。两者叠加：
//      输入流第 r 行  ←→  屏幕第 (H-1-r) 行
//
//  所以本模块输出的 px_y 直接是**屏幕行号**（0 = 最上面一行）：
//  一开始 px_y = 479（屏幕最下面一行），每换一行减 1，最后减到 0。
//  这样你在 px_y=0 时画的就是屏幕顶行，不用自己换算。
//
//  ★★ 一个必须遵守的规矩（曾经踩过坑）★★
//  px_x / px_y 只能在这一个 always 块里赋值！
//
//  Verilog 里一个 reg 只能有一个"驱动源"。如果两个 always 块都给 px_x 赋值，
//  综合工具会直接报错：
//      HDL-8007 ERROR: net 'px_x[15]' is constantly driven from multiple places
//  而 iverilog 不会报（它更宽松），所以仿真可能"看起来能跑"，
//  实际是碰巧两个块没有同时赋值而已 —— 那是运气，不是设计。
//
//  所以"新一帧要把坐标归零"这件事，不能由主状态机直接写 px_x，
//  而是用下面这个更简单的办法：**只要不在收数据状态，坐标就一直停在起点**。
//  这样进入 S_STREAM 的第一拍坐标天然就是 (0,479)，不用额外发复位脉冲，
//  也不会出现"复位脉冲和第一个像素撞在同一拍"的边界问题。
//------------------------------------------------------------------------------
wire streaming = (state == S_STREAM);

always @(posedge clk or posedge rst) begin
    if (rst) begin
        px_x <= 16'd0;
        px_y <= IMG_H - 1;      // 屏幕最下面一行（因为第一拍要写的是它）
                                // IMG_H 是 integer 常量，IMG_H-1 = 479
    end else if (!streaming) begin
        // 不在收数据状态（S_IDLE / S_REQ / S_ACK）→ 坐标一直停在起点，
        // 等着 S_STREAM 第一拍来取。
        px_x <= 16'd0;
        px_y <= IMG_H - 1;
    end else if (take) begin
        // 只有"真的取走了一个像素"时才推进坐标 —— 这是关键！
        // 如果按时间推进（每拍都加 1），像素源给得慢的时候坐标就会跑飞。
        if (px_x == IMG_W - 1) begin
            px_x <= 16'd0;              // 一行写完了，回到第 0 列
            px_y <= px_y - 16'd1;       // 屏幕行往上走一行
                                        // 注意是减 1！因为输入流是从屏幕底部往上灌的
        end else begin
            px_x <= px_x + 16'd1;       // 同一行内，列号 +1
        end
    end
end

//==============================================================================
//  第 3 节：输出延迟链（write_en / out_x / out_y 延迟 PIPE 拍）
//==============================================================================
//
//  【要解决的问题】像素处理链（比如叠加层模块）不是瞬间出结果的。
//  比如 overlay_layer 从收到 (px_x,px_y,ps_data) 到输出处理后的像素，中间要过 2 拍。
//  也就是说：第 t 拍取走的像素，第 t+2 拍才拿到处理后的值。
//
//  但 write_en 是"当前这一拍要不要写"的意思。如果它不跟着延迟，
//  就会变成"用第 t 拍的位置去写第 t+2 拍的数据" —— 整幅图横向错位 2 个像素。
//
//  所以要：把 write_en 和坐标也延迟同样拍数，让三者对齐。
//
//  【为什么 write_data 反而不延迟？】
//  因为像素处理链已经延迟过了。ps_data 在经过处理链之后，
//  到达 write_data 的时候已经是"延迟 PIPE 拍"的值了。
//  再延迟一次就多延迟了。所以数据直通，只延迟"使能"和"坐标"。
//
//  ┌──────────────────────────────────────────────────────────────┐
//  │  时间轴：       第 t 拍      第 t+1 拍      第 t+2 拍         │
//  ├──────────────────────────────────────────────────────────────┤
//  │  take           1           0             0                  │
//  │  px_x/px_y      坐标 A      坐标 B         坐标 C             │
//  │  处理链输出     ...         ...           f(坐标 A)          │
//  │  write_en       (延迟链)    0             1  ← 延迟 2 拍      │
//  │  out_x          (延迟链)    ...           坐标 A  ← 延迟 2 拍  │
//  │  write_data     = 处理链输出 ...          f(坐标 A)          │
//  │                                          ↑                   │
//  │                              三者同拍，对齐了 ✓               │
//  └──────────────────────────────────────────────────────────────┘
//
//==============================================================================

//------------------------------------------------------------------------------
//  generate ... endgenerate —— 编译期条件选择，相当于 C 的 #if / #else
//
//  注意：这里的 if (PIPE == 0) 是**编译期**判断（综合工具展开电路时判断一次），
//  不是运行时判断。PIPE 是参数，综合时是常数，所以只有一边会变成硬件。
//  这跟 C 的 #if 一模一样。
//
//  begin : g_nopipe 里的 g_nopipe 是给这个分支起的名字（叫"标签"）。
//  可以省略，但强烈建议写：① 报错时能定位；② 调试时能在波形里找到这些信号。
//------------------------------------------------------------------------------
generate
if (PIPE == 0) begin : g_nopipe

    //--------------------------------------------------------------------
    //  PIPE = 0：像素直通，一拍都不延迟。那就什么都不用做，直接连出去。
    //--------------------------------------------------------------------
    assign write_en = take;           // take 已包含统一推进使能
    assign out_x    = px_x;        // 坐标直通
    assign out_y    = px_y;

end else begin : g_pipe

    //--------------------------------------------------------------------
    //  PIPE >= 1：要延迟 PIPE 拍。
    //
    //  reg en_d [0:PIPE-1];  这是"数组"（Verilog 叫 memory / 数组）。
    //  注意语法和 C 不同：C 是 int en_d[PIPE];  Verilog 是 reg en_d [0:PIPE-1];
    //  位宽写在名字左边，下标范围写在名字右边。别写反了。
    //
    //  这里 en_d[0] 是"延迟 1 拍"，en_d[PIPE-1] 是"延迟 PIPE 拍"。
    //--------------------------------------------------------------------
    reg              en_d  [0:PIPE-1];   // write_en 的延迟链
    reg [15:0]       x_d   [0:PIPE-1];   // 坐标 x 的延迟链
    reg [15:0]       y_d   [0:PIPE-1];   // 坐标 y 的延迟链

    integer pi;    // 循环变量。integer 是 32 位整数，只能用来做循环下标，
                   // 不能当硬件信号用（它不会变成电路）

    always @(posedge clk or posedge rst) begin
        if (rst) begin
            //----------------------------------------------------------
            //  复位：把延迟链里每一级都清零
            //
            //  for 循环在这里的作用是"复制代码"：PIPE=2 时它会展开成
            //      en_d[0] <= 1'b0;  x_d[0] <= 16'd0;  y_d[0] <= 16'd0;
            //      en_d[1] <= 1'b0;  x_d[1] <= 16'd0;  y_d[1] <= 16'd0;
            //  不是"运行时循环两遍"。
            //----------------------------------------------------------
            for (pi = 0; pi < PIPE; pi = pi + 1) begin
                en_d[pi] <= 1'b0;      // 1'b0 = 1 位宽的二进制 0
                x_d[pi]  <= 16'd0;     // 16'd0 = 16 位宽的十进制 0
                y_d[pi]  <= 16'd0;
            end
        end else if (pipe_ce) begin
            //----------------------------------------------------------
            //  第 0 级：从输入端取新值（这一级就是"延迟 1 拍"）
            //----------------------------------------------------------
            en_d[0] <= take;       // 注意：take 是组合信号，每拍都在变
            x_d[0]  <= px_x;
            y_d[0]  <= px_y;

            //----------------------------------------------------------
            //  第 1 ~ PIPE-1 级：每一级把上一级的值接过来
            //
            //  en_d[pi] <= en_d[pi-1] 的意思是：
            //  "这个触发器的输入是上一个触发器的输出"，串起来就是移位寄存器。
            //
            //  注意这里用的是 <=，所以 PIPE=3 时：
            //    en_d[1] 拿到的是 en_d[0] 的**上一拍**值
            //    en_d[2] 拿到的是 en_d[1] 的**上一拍**值
            //  三行代码同时生效，级联起来就是"延迟 3 拍"。
            //  如果这里写成 =（阻塞赋值），三行会变成"同一拍内连续传递"，
            //  结果只延迟 1 拍 —— 这是新手最常犯的错误。
            //----------------------------------------------------------
            for (pi = 1; pi < PIPE; pi = pi + 1) begin
                en_d[pi] <= en_d[pi-1];
                x_d[pi]  <= x_d[pi-1];
                y_d[pi]  <= y_d[pi-1];
            end
        end
    end

    //--------------------------------------------------------------------
    //  输出接延迟链的最后一级
    //--------------------------------------------------------------------
    assign write_en = en_d[PIPE-1] & pipe_ce; // 停顿时不重复写保持的末级像素
    assign out_x    = x_d[PIPE-1];    // 与之同步的坐标
    assign out_y    = y_d[PIPE-1];

end
endgenerate

//------------------------------------------------------------------------------
//  write_data：数据直通，不延迟（理由见上面第 3 节开头）
//
//  {ps_data, 8'h00} 是位拼接：
//      ps_data 是 24 位（R,G,B 各 8 位）
//      8'h00   是 8 位的零
//      拼起来是 32 位，正好对上 write_data 的位宽
//
//  为什么要补 8 个 0？因为 SDRAM 一个存储单元是 32 位，
//  而颜色只需要 24 位。多的 8 位就空着（读出来时直接扔掉 [7:0]）。
//------------------------------------------------------------------------------
assign write_data = {ps_data, 8'h00};

//------------------------------------------------------------------------------
//  ps_start：告诉像素源"开始给数据"
//
//  时机 = 写握手做完之后（进入 S_STREAM 那一刻）。
//  为什么不能更早？因为下游还在清 FIFO（见文件头第 ① 条）。
//
//  它是个组合输出（不是 reg），因为 state 本身是寄存器，
//  (state == S_STREAM) 这个表达式已经足够稳定了。
//------------------------------------------------------------------------------
assign ps_start = (state == S_STREAM);

//==============================================================================
//  ★ 诊断：状态输出 + "完成脉冲漏采"检测 ★
//==============================================================================
//==============================================================================
//  ★ 2026-10-18 根修：完成脉冲先存起来，S_WAIT 再消费 ★
//==============================================================================
//  【为什么必须存】write_finish_pulse 是 sd_card_clk 域里"一拍宽"的边沿，
//  过了就没了。如果它落在 frame_writer 还没进 S_WAIT 的时候（很常见：
//  写引擎把 FIFO 里的数据吐完就报完成，而本模块这才刚发完最后一个像素），
//  这一帧的完成信号就**永久丢失** ⇒ 模块卡在 S_WAIT ⇒ display_valid 永远 0
//  ⇒ 整屏黑（数码管 b），而且再也不会发起下一帧。
//  修法：脉冲来了就置 fin_seen（电平），S_WAIT 看到它就收工；下次开帧再清。
//  这样"来早了"只是把收工提前到进 S_WAIT 的那一拍，逻辑依然正确。
//==============================================================================
reg fin_seen;
always @(posedge clk or posedge rst) begin
    if (rst)
        fin_seen <= 1'b0;
    else if (write_finish_pulse)
        fin_seen <= 1'b1;                       // 来了就记住（电平保持）
    else if ((state == S_WAIT) && fin_seen)
        fin_seen <= 1'b0;                       // 本帧消费掉
    else if (state == S_REQ)
        fin_seen <= 1'b0;                       // 开新帧，清掉陈旧标志
end

//==============================================================================
//  第 4 节：主状态机 ★ 核心 ★
//==============================================================================
//
//  【重要】下面这个 always 块和前面第 1、2、3 节的 always 块是**同时**运行的！
//  不是"先跑完第 1 节再跑第 4 节"。所有电路并行工作，每个时钟沿一起更新。
//
//  它们之间通过信号传递信息：第 1 节算出 ack_rise，第 4 节用 ack_rise 做判断。
//  由于 <= 是"这一拍结束才生效"，第 4 节看到的是 ack_rise 的**当前值**，
//  正好就是第 1 节在这一拍算出来的值。这是硬件设计的标准做法，不用额外同步。
//
//==============================================================================
always @(posedge clk or posedge rst) begin
    if (rst) begin
        //----------------------------------------------------------------------
        //  复位：把所有状态清成初始值
        //
        //  ★ 所有需要"存住值"的信号都必须在这里给初值。
        //    否则上电后它们是未知状态（仿真里显示为 x），会到处传播错误。
        //    C 里局部变量不初始化只是"值是垃圾"，Verilog 里是"整块电路失控"。
        //----------------------------------------------------------------------
        state         <= S_IDLE;
        req_latch     <= 1'b0;
        write_req     <= 1'b0;
        write_buf_idx <= 2'd0;
        write_len     <= NPX[20:0];   // NPX 是 32 位常量，[20:0] 取它的低 21 位
                                      // 因为 write_len 是 21 位宽，位宽要对上
        disp_buf_idx  <= 2'd0;
        disp_commit_tgl <= 1'b0;      // 提交号：与显示侧采纳号一起从 0 开始
        display_valid <= 1'b0;
        busy          <= 1'b0;
        done          <= 1'b0;
        cnt           <= 19'd0;
    end else begin

        //----------------------------------------------------------------------
        //  ★ 默认赋值技巧 ★
        //
        //  done 是个"1 拍脉冲"：只有真正画完的那一拍才是 1，其它时候都是 0。
        //  如果在每个状态里都写一遍 "done <= 1'b0"，代码会很长很啰嗦。
        //
        //  所以这里先无条件写 done <= 0，然后在需要拉高的时候覆盖它。
        //  因为 <= 是"同一拍内后写的生效"，所以下面 S_WAIT 里的 done <= 1'b1
        //  会覆盖掉这一行的 0。
        //
        //  C 类比：相当于在函数开头写 result = 0; 然后中间按需改它。
        //----------------------------------------------------------------------
        done <= 1'b0;

        //----------------------------------------------------------------------
        //  【请求暂存】像素源的"要画一帧"请求可能来得不是时候
        //  （比如本模块还在等上一帧的回执）。先记下来，别丢。
        //
        //  注意这两行的顺序：如果同一拍既收到新请求、又在 S_IDLE 里把它消费掉，
        //  那么后面的 req_latch <= 1'b0（在 case 里）会覆盖这里的 1。
        //  这正是我们想要的行为。
        //----------------------------------------------------------------------
        if (ps_new_frame) req_latch <= 1'b1;

        //----------------------------------------------------------------------
        //  case = C 的 switch。但记住：每个分支都会变成硬件电路，
        //  不是"跳过去执行"。综合工具会把它们做成一个多路选择器。
        //----------------------------------------------------------------------
        case (state)

        //======================================================================
        // S_IDLE：空闲，等像素源说"要画一帧"
        //======================================================================
        S_IDLE: begin
            // ★ buf_free：显示侧还没采纳上一帧时不许开新帧（否则会重写
            //   屏幕正在读的那块 → 撕裂）。新请求会一直留在 req_latch 里。
            if (req_latch && buf_free) begin
                req_latch     <= 1'b0;          // 这个请求被消费掉了
                write_req     <= 1'b1;          // 拉起写请求（第 ② 步）
                write_buf_idx <= next_buf;      // 写哪块：总挑"不是正在显示"的那块
                write_len     <= NPX[20:0];     // 一帧多少个像素
                busy          <= 1'b1;          // 告诉上层"我忙着呢"
                state         <= S_REQ;         // ★ 下一拍进入 S_REQ
            end
            // 注意：如果 req_latch 是 0（或 buf_free 还是 0），什么都不做，
            //      state 保持 S_IDLE
            //      （因为没有写 state <= xxx，state 就保持原值 ——
            //        这就是"寄存器存住值"的含义）
        end

        //======================================================================
        // S_REQ：请求已经发出去了，等下游应答
        //======================================================================
        //  下游要先把请求同步到它自己的时钟域（打 3 拍），所以不会立刻应答。
        //  本模块在这里干等，直到 ack_rise（应答刚来的那一拍）。
        //======================================================================
        S_REQ: begin
            if (ack_rise) begin
                write_req <= 1'b0;              // 第 ④ 步：收到应答，立刻撤销请求
                                                // （下游看到请求撤了，才知道我们收到了）
                state     <= S_ACK;
            end
        end

        //======================================================================
        // S_ACK：请求撤了，等应答也落下去
        //======================================================================
        //  ★★★ 这是整个模块最容易被忽略、但最关键的一步 ★★★
        //
        //  为什么必须等 ack 落下去？
        //  因为下游在"应答期间"正在拉高 fifo_aclr 清空写 FIFO。
        //  这期间如果开始发数据，数据会被清 FIFO 的操作直接冲掉 —— 白写。
        //
        //  ack 落下去 = 下游已经清完 FIFO、进入了搬运状态 = 可以开始灌数据了。
        //  这时候 state 变成 S_STREAM，ps_start 自动拉高，像素源才开始给数据。
        //======================================================================
        S_ACK: begin
            if (ack_fall) begin
                cnt   <= 19'd0;                 // 像素计数器清零
                                                // （坐标不用管：只要不在 S_STREAM，
                                                //   坐标块就自动把它停在起点 (0,479)）
                state <= S_STREAM;              // ★ 可以开始收数据了
            end
        end

        //======================================================================
        // S_STREAM：收 307200 个像素（第 ⑦⑧⑨ 步）
        //======================================================================
        //  这个状态会待多久？**不固定**！取决于像素源给数据的速度。
        //      · 如果像素源每拍都给一个像素 → 307200 拍 = 3.072 ms
        //      · 如果像素源（TF 卡）是突发式的，会慢一些
        //
        //  这就是为什么用 `if (take)` 而不是"每拍无条件推进一步"。
        //  take 已经在第 2 节定义过了：state==S_STREAM 且 ps_valid 同时成立。
        //======================================================================
        S_STREAM: begin
            if (take) begin
                cnt <= cnt + 19'd1;
                if (cnt == NPX - 1)             // 数到 307199（第 307200 个像素）
                    state <= S_WAIT;            // 收满了，转去等回执
                // 注意：这里没有 else，所以没收满时 state 保持 S_STREAM
            end
        end

        //======================================================================
        // S_WAIT：像素收完了，等"整帧真的写进 SDRAM 了"的回执（第 ⑩⑪ 步）
        //======================================================================
        //  ★ 为什么不能马上切显示？
        //    write_en 发完只代表数据进了 FIFO。FIFO 里的数据要等下游慢慢搬进
        //    SDRAM，这中间有好几毫秒。如果这时候就切显示指针，会看到"半张新图
        //    + 半张旧图"，俗称撕裂。
        //
        //  ★ write_finish_pulse 是怎么来的？
        //    下游在 125 MHz 域发出一个脉冲 → 转成"电平翻转" → 本时钟域打 3 拍
        //    同步 → 异或还原成脉冲。这条链在 top_tf_hdmi_audio.v 里实现，
        //    这里只负责用它的结果。
        //======================================================================
        S_WAIT: begin
            if (fin_seen) begin
                disp_buf_idx    <= write_buf_idx; // 提交：告诉显示侧"该看这块了"
                disp_commit_tgl <= ~disp_commit_tgl; // ★ 提交号翻转（显示侧在场边界采纳）
                display_valid   <= 1'b1;          // ★ 解除黑屏
                busy            <= 1'b0;          // 不忙了
                done            <= 1'b1;          // 告诉上层：画完了
                                                // （会覆盖前面那个默认的 done <= 0）
                state           <= S_IDLE;        // 回空闲，准备下一帧
                // ★ 下一帧能不能马上开，取决于显示侧是否已采纳（buf_free）。
                //   如果还没采纳，会停在 S_IDLE 等 —— 这正是节流/防撕裂的关键。
            end
        end

        //======================================================================
        //  兜底：万一 state 变成了没定义的值（比如上电时干扰导致），
        //  就回到空闲状态，别卡死。
        //  这相当于 C 的 switch 里的 default 分支。
        //======================================================================
        default: state <= S_IDLE;

        endcase
    end
end

