//==============================================================================
//  附：几个常见的"从 C 转过来会写错"的地方
//==============================================================================
//
//  1. 想在 always @(posedge clk) 里用 = 写顺序逻辑
//     ❌ 错：a = 1; b = a;   // 你以为 b=1，实际上在时序逻辑里这会造成
//                            // 综合出的电路和你想的不一样（可能只延迟 0 拍）
//     ✅ 对：a <= 1; b <= a; // b 得到 a 的上一拍值
//
//  2. 忘记写 else 分支导致锁存器
//     在 always @(*) 里：
//     ❌ if (x) y = 1;             // x=0 时 y 是多少？没定义 → 综合出"锁存器"
//     ✅ y = 0; if (x) y = 1;      // 先给默认值
//     （在 always @(posedge clk) 里没这个问题，因为触发器天然存值）
//
//  3. 用 for 循环想做"运行时循环"
//     ❌ for (i=0; i<1000; i++) sum += data[i];   // 这不是算法，是复制 1000 份加法器
//     ✅ 硬件里做累加要用状态机：一拍加一个，累加 1000 拍
//
//  4. 位宽不匹配
//     ❌ cnt <= cnt + 1;       // 1 是 32 位的，cnt 是 19 位的，可能出警告
//     ✅ cnt <= cnt + 19'd1;   // 写清楚位宽
//
//  5. 忘了复位
//     ❌ 声明了 reg 但复位时没给初值 → 仿真里是 x，上电后状态随机
//     ✅ 所有 reg 都要在 if (rst) 分支里给初值
//
//  6. 以为 assign 是"执行一次"
//     assign x = a & b;   // 不是"算一次存起来"，是"x 这根线永远等于 a&b"
//                         // a 或 b 一变，x 立刻跟着变
//
//  7. 按时间推进计数器（本模块踩过的坑）
//     ❌ always @(posedge clk) cnt <= cnt + 1;   // 每拍都加，数据来得慢就错位
//     ✅ always @(posedge clk) if (take) cnt <= cnt + 1;   // 只有真取到数据才加
//     数据源不是每拍都有数据时，一定要用"握手有效"来驱动计数。
//
