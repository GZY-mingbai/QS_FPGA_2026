//=============================================================================
// 文件名   : global_def.v
// 作用     : 【全局参数定义头文件】
//            用 `define 定义一批"全局常量"，供 SDRAM 相关模块通过 `include 引用。
//
// 关于 `define 和 `include 的使用要点（初学者注意）
//   · `define 是"文本替换"，不是变量。编译时会把代码里所有 `DATA_WIDTH
//     原样替换成 32。它没有类型、没有作用域 —— 所以要小心重名。
//   · 宏名前面必须带反引号 ` 才能引用（如 `DATA_WIDTH），
//     但定义时反引号后紧跟名字，中间不能有空格。
//   · `include "xxx.v" 是把文件内容原样贴进来（类似 C 语言的 #include）。
//     本工程里 sdram.v 就是这么用的。
//   · 因为不同文件加起来可能重复 include，通常还会配套用
//     `ifndef / `define / `endif 做"防重复包含"（本文件较简单，未做）。
//
// 这些数字怎么选的？
//   看下面的注释 —— 它们对应"2M × 32bit"那颗 SDRAM 芯片的物理规格。
//   ★ 换别的容量/位宽的 SDRAM 时，这几行必须一起改 ★
//=============================================================================


// ---- SDRAM 数据总线与地址总线规格 ----
`define   DATA_WIDTH                        32    // 数据总线宽度：32bit（一次读写 4 个字节）
`define   ADDR_WIDTH                        21    // 地址位宽：2^21 = 2M 个地址；× 32bit = 8MB 容量
`define   DM_WIDTH                          4     // 数据掩码宽度：4bit = 4 个字节各自的写屏蔽位

// ---- SDRAM 行列地址规格 ----
`define   ROW_WIDTH                        11    // 行地址位宽：11bit（行/列地址分时复用在 11 根线上）
`define   BA_WIDTH                        2      // Bank 地址位宽：2bit = 4 个 Bank

// ---- 自刷新相关参数（DRAM 必须定期刷新才不会丢数据）----
// 一个时钟周期是多少纳秒：1e9 / 100e6 = 10ns（对应 SDRAM 控制器时钟 100MHz）
// ★ 2026-10-21 build 100M-18：SDRAM 侧从 125MHz 回退到 100MHz，这一行必须跟着改 ★
//   留 8（125MHz）时 SELF_REFRESH_INTERVAL = 3906 拍 = 31.25us@125MHz；
//   在 100MHz 上就变成 39.06us ⇒ 全阵列 80ms 才刷一遍（> 64ms）⇒ 真的丢数据，
//   而且错法看起来和"位错/花屏"一样。
`define	  SDR_CLK_PERIOD				1000000000/100000000
// 自刷新间隔：标准要求 64ms 内把每一行都刷新一遍。
//   64ms / 周期 / 2^行位宽/2 —— 这里按 64ms 除以行数再除以 2 得到"每一行刷新间隔"
//   （除 2 是留一半余量，工程上的常规做法）
`define   SELF_REFRESH_INTERVAL			64000000/`SDR_CLK_PERIOD/2**(`ROW_WIDTH)
